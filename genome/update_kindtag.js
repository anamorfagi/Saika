// [БЛОК МЕТКИ] Вид персонажа и носитель — это две разные оси, и раньше они были свалены в одну.
//
// Что было сломано: на карточке печаталось genreOf(c). У «ии» и «существа» это совпадало с видом,
// а у обычного персонажа проваливалось в жанр: Питер получал КИНО, Эльза — ПРОЧЕЕ (в словаре жанров
// не было ни «анимации», ни «мультфильма», а Frozen ни под что не подошёл). Человек видит четыре
// категории сверху — Персонажи / Люди / ИИ / Существа — и справедливо ждёт одну из них на карточке,
// а не метку неопределённости.
//
// Что теперь: на карточке ВСЕГДА стоит вид (одна из тех же четырёх категорий), а носитель —
// фильм / мультфильм / сериал / игра / книга / аниме — печатается отдельной приглушённой меткой
// и ТОЛЬКО когда он действительно определён. «Прочее» не печатается никогда: пустая метка честнее
// ложной. Словарь носителей дополнен анимацией, сериалами, книгами и комиксами.
const fs = require("fs");
let t = fs.readFileSync("gs.html", "utf8");
if (t.includes("function kindTag(")) { console.log("метки уже правились"); process.exit(0); }

// 1. Словарь носителей: анимация отдельно от игрового кино, плюс книги и сериалы.
const якорь1 = 'const ЖАНР_ИГРЫ=ЦЕЛИКОМ(';
if (!t.includes(якорь1)) { console.error("нет якоря словаря"); process.exit(1); }
t = t.replace(якорь1,
`const НОСИТЕЛЬ_АНИМ=ЦЕЛИКОМ(["мультфильм","мультсериал","мультик","анимационный","анимация",
  "animation","animated","cartoon","pixar","disney","dreamworks","illumination","ghibli","союзмультфильм"]);
const НОСИТЕЛЬ_СЕРИАЛ=ЦЕЛИКОМ(["сериал","сериала","сериале","series","season","сезон","эпизод","episode","netflix","hbo"]);
const НОСИТЕЛЬ_КНИГА=ЦЕЛИКОМ(["книга","книги","книге","роман","романа","повесть","новелла","novel","book",
  "трилогия","сага","комикс","комиксы","comics","comic","манга","manga"]);
` + якорь1);

// 2. Носитель определяется отдельно от вида и может честно вернуть пустоту.
const якорь2 = 'const GENRE_ORD=';
if (!t.includes(якорь2)) { console.error("нет якоря GENRE_ORD"); process.exit(1); }
t = t.replace(якорь2,
`const ВИД_МЕТКА={"персонаж":"персонаж","человек":"человек","ии":"ии","существо":"существо","синтез":"синтез"};
/* Пятый вид — синтез: персонаж, которого не откуда-то сняли, а собрали прямо в геноме.
   У него нет произведения-первоисточника, и требовать с него улик из фильма бессмысленно. */
function kindOf(c){
  const в=String(c.kind||"").trim();
  if(ВИД_МЕТКА[в])return в;
  if(/персона без модели|синтез|архетип|вручную/.test(String(c.method||"").toLowerCase()))return "синтез";
  return "персонаж"}
function kindTag(c){return ВИД_МЕТКА[kindOf(c)]}
/* 18+ — это возрастной рейтинг, а не вид и не носитель. Он и печатается отдельно,
   маленьким, а не вместо категории персонажа. */
function adultTag(c){
  const s=[c.src,c.desc,c.alias,c.method].map(x=>String(x||"")).join(" · ").toLowerCase();
  return ЖАНР_ВЗРОСЛОЕ.test(s)?"18+":""}
/* Носитель: на чём персонаж вообще существует. Пустая строка — значит не определили,
   и тогда метка не печатается вовсе. Раньше на этом месте появлялось «прочее», что
   ничего не сообщало и выглядело как ошибка разбора — потому что ей и было. */
function mediumTag(c){
  const прямо=String(c.medium||"").toLowerCase().trim();
  if(прямо)return прямо;
  const s=[c.src,c.desc,c.alias,c.method].map(x=>String(x||"")).join(" · ").toLowerCase();
  if(ЖАНР_АНИМЕ.test(s))return "аниме";
  if(НОСИТЕЛЬ_АНИМ.test(s))return "мультфильм";
  if(НОСИТЕЛЬ_СЕРИАЛ.test(s))return "сериал";
  if(ЖАНР_ИГРЫ.test(s))return "игра";
  if(ЖАНР_КИНО.test(s))return "фильм";
  if(НОСИТЕЛЬ_КНИГА.test(s))return "книга";
  return ""}
` + якорь2);

// 3. На карточке: вид всегда, носитель — приглушённо и только если он есть.
const было = '<span class="gtag">${genreOf(c)}</span>';
if (!t.includes(было)) { console.error("нет якоря метки на карточке"); process.exit(1); }
t = t.replace(было, '<span class="gtag">${kindTag(c)}</span>${(m=>m?` · <span class="mtag">${m}</span>`:"")(mediumTag(c))}${(a=>a?` · <span class="atag">${a}</span>`:"")(adultTag(c))}');

// 4. Поиск должен находить и по носителю тоже.
t = t.replace('+" "+genreOf(c)).toLowerCase().includes(KQ)',
              '+" "+kindTag(c)+" "+mediumTag(c)).toLowerCase().includes(KQ)');

// 5. Стиль: вид — золотом, как раньше; носитель — тише, он второстепенный.
t = t.replace('.gtag{color:var(--gold);letter-spacing:.08em}',
              '.gtag{color:var(--gold);letter-spacing:.08em}.mtag{color:var(--dim);letter-spacing:.08em}.atag{color:#7a5560;letter-spacing:.08em}');

// 6. Пятая категория в ряду фильтров и фильтрация по выведенному виду, а не по сырому полю.
const KIND_РЯД = '[["персонаж","Персонажи"],["человек","Люди"],["ии","ИИ-компаньоны"],["существо","Существа"]]';
if (t.includes(KIND_РЯД))
  t = t.replace(KIND_РЯД, '[["персонаж","Персонажи"],["человек","Люди"],["ии","ИИ-компаньоны"],["существо","Существа"],["синтез","Синтез"]]');
else console.error("ПРЕДУПРЕЖДЕНИЕ: ряд категорий не найден, синтез не добавлен в фильтры");
t = t.replace(/CHARS\.filter\(c=>ksel\.has\(c\.kind\|\|"персонаж"\)\)/g, 'CHARS.filter(c=>ksel.has(kindOf(c)))');

fs.writeFileSync("gs.html", t);
console.log("метки: вид всегда, носитель по факту");
