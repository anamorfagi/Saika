def что_есть(чего=""):
    """Проверить, чем машина вообще располагает: пакеты python, программы в PATH.
    Нужно, чтобы не выдумывать: сначала смотрим, есть ли ffmpeg или whisper, потом решаем."""
    import importlib.util, shutil as _sh
    строки = []
    for пакет in ["PIL", "requests", "ddgs", "numpy", "faster_whisper", "whisper", "torch",
                  "soundfile", "librosa", "bs4", "trafilatura", "openpyxl"]:
        строки.append("%-16s %s" % (пакет, "есть" if importlib.util.find_spec(пакет) else "нет"))
    for прога in ["ffmpeg", "ffprobe", "node", "git", "tesseract", "yt-dlp"]:
        путь_ = _sh.which(прога)
        строки.append("%-16s %s" % (прога, путь_ or "нет"))
    if чего:
        строки = [s for s in строки if str(чего).lower() in s.lower()] or ["про «%s» ничего не знаю" % чего]
    return "\n".join(строки)


