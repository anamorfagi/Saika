def картинка(path, ширина=0, обрезка=""):
    """Размер, ужатие и обрезка. Обрезка строкой «слева,сверху,справа,снизу»."""
    from PIL import Image
    f = путь(path)
    im = Image.open(f)
    было = im.size
    if обрезка:
        x0, y0, x1, y1 = [int(v) for v in re.split(r"[,\s]+", str(обрезка).strip())[:4]]
        im = im.crop((x0, y0, x1, y1))
    if ширина:
        k = int(ширина) / im.width
        im = im.resize((int(ширина), max(1, round(im.height * k))))
    if обрезка or ширина:
        im.convert("RGB").save(f if f.suffix.lower() in (".jpg", ".jpeg") else f.with_suffix(".jpg"),
                               "JPEG", quality=92)
        return "было %dx%d, стало %dx%d" % (было[0], было[1], im.width, im.height)
    return "размер %dx%d, формат %s" % (было[0], было[1], im.format)


