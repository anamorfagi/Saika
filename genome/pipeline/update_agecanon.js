// Возраст: канон отдельно, зрелость поведения отдельно.
// Шаг идёт ПОСЛЕ update_age.js, который и заводит индекс зрелости.
//
// Эльзе в карточке стояло «профиль старше типичного (40+)». По геному она и
// правда читается как взрослая — королева под грузом, закрытая, держит себя в
// узде. Но лет ей двадцать один, и подпись со скобками «(40+)» читается как
// возраст, а не как манера держаться.
const fs=require("fs");
let t=fs.readFileSync("gs.html","utf8");
function rep(a,b){if(!t.includes(a)){console.error("нет якоря:",a.slice(0,80));process.exit(1)}t=t.split(a).join(b)}

// 1) подпись без цифр возраста — это зрелость, а не годы
rep(`band:idx>=.3?"профиль старше типичного (40+)":idx<=-.3?"профиль моложе типичного (до 25)":"не определяется"}}`,
    `band:idx>=.3?"держится взрослее сверстников":idx<=-.3?"держится младше сверстников":"как у сверстников"}}`);

// 2) канон впереди, зрелость после — и словами, что это разные вещи
rep(`  if(g)parts.push(\`по геному: <b>\${g.band}</b> — индекс зрелости \${g.idx>0?"+":""}\${g.idx.toFixed(2)} по \${g.n} генам\`);`,
    `  const канон=c.ageStated||(c.voice&&c.voice.age)||"";
  if(канон)parts.push(\`<b>\${канон}</b> — по произведению\`);
  if(g)parts.push(\`манера: <b>\${g.band}</b> (индекс зрелости \${g.idx>0?"+":""}\${g.idx.toFixed(2)} по \${g.n} генам, это не возраст)\`);`);

// 3) не дублировать канон второй раз ниже
rep(`  if(c.ageStated)parts.push(\`корпус · сеть: <b>\${c.ageStated}</b>\`);else if(c.voice&&c.voice.age)parts.push(\`канон: <b>\${c.voice.age}</b>\`);`,
    `  // канон уже выведен первым — второй раз не повторяем`);

fs.writeFileSync("gs.html",t);
console.log("возраст ok");
