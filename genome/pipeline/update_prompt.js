// Системный промпт: указания актёру вместо описи ползунков.
//
// Было: `"- " + название_гена + ": " + ярлык_полюса + " — " + наречие_частоты`.
// В итоге строки вида «Уступчивость: упирается — почти всегда». Модель читает
// это как ярлык, а не как задание: не сказано, В КАКОЙ МОМЕНТ упираться, «почти
// всегда» не к чему отнести, внутренние названия генов текут наружу, дубли
// («Потребность контролировать» и следом «Контроль всего») читаются как нажим
// или противоречие, и ничто не говорит, что здесь стержень, а что мелочь.
//
// Стало:
//   · названий генов в выводе нет вовсе;
//   · второе лицо — «упираешься», а не «упирается»;
//   · частота не наречием в хвосте, а РАЗДЕЛОМ: стержень / заметное / изредка;
//   · похожие строки схлопываются, чтобы одно и то же не повторялось трижды;
//   · противоречия названы отдельно, с указанием, что перевешивает.
const fs=require("fs");
let t=fs.readFileSync("gs.html","utf8");
if(t.includes("СТЕРЖЕНЬ_ПОРОГ")){console.log("уже вшито");process.exit(0)}
function rep(a,b){if(!t.includes(a)){console.error("нет якоря:",a.slice(0,90));process.exit(1)}t=t.split(a).join(b)}

// 1. второе лицо: полюса написаны про третье («упирается», «уходит в себя»)
rep(`  const doza=v=>{const x=Math.abs(v);return x>=.85?"почти всегда":x>=.65?"часто":x>=.45?"иногда":"редко"};`,
`  const СТЕРЖЕНЬ_ПОРОГ=.85, ЗАМЕТНО_ПОРОГ=.65;
  // Полюса в геноме написаны в третьем лице («упирается», «уходит в себя»).
  // Актёру инструкция даётся во втором: так она читается как задание, а не как
  // характеристика со стороны. Правится окончание глагола, остальное не трогаем.
  // Границы слова задаются явно: в JS \\b определён по ASCII и в кириллице
  // не срабатывает вовсе — первая версия молча не меняла ничего.
  const ГР='(?<![а-яёА-ЯЁ])', КР='(?![а-яёА-ЯЁ])';
  const ТЫ=[
    ['([а-яё])ается'+КР,'$1аешься'],['([а-яё])ится'+КР,'$1ишься'],['([а-яё])ется'+КР,'$1ешься'],
    ['([а-яё])ывает'+КР,'$1ываешь'],['([а-яё])ивает'+КР,'$1иваешь'],
    ['([а-яё])ует'+КР,'$1уешь'],['([а-яё])еет'+КР,'$1еешь'],
    ['([а-яё])ает'+КР,'$1аешь'],['([а-яё])ит'+КР,'$1ишь'],['([а-яё])ет'+КР,'$1ешь']
  ].map(([re,to])=>[new RegExp(re,'g'),to]);
  const воВтороеЛицо=s=>{let r=String(s||"");
    // «не терпит указаний» → «не терпишь указаний». Одиночное слово не трогаем:
    // там подлежащее часто не персонаж («парализует» — это про страх, не про него).
    if(!/\\s/.test(r))return r;
    ТЫ.forEach(([re,to])=>{r=r.replace(re,to)});
    return r};
  // Два полюса считаются одним и тем же, если после огрубления совпадают наполовину.
  const огрубить=s=>String(s||"").toLowerCase().replace(/[^а-яёa-z ]/g,"").split(/\\s+/).filter(w=>w.length>3);
  const похоже=(a,b)=>{const x=огрубить(a),y=огрубить(b);if(!x.length||!y.length)return false;
    const общих=x.filter(w=>y.includes(w)).length;return общих/Math.min(x.length,y.length)>=.6};`);

// 2. строка без названия гена и без хвоста частоты
rep(`  const line=g=>{if(seen.has(g.id))return null;seen.add(g.id);
    const s=gt(g.v>0?g.pos:g.neg).replace(/\\.$/,"");
    // в самом полюсе уже бывает частотность («вежливо всегда») — второй раз не лепим
    const есть=/всегда|никогда|постоянно|каждый|каждую|ни разу|редко|иногда/i.test(s);
    return "- "+g.name+": "+s+(есть?"":" — "+doza(g.v))+"."};
  sec("\\n## Что ты делаешь", core.map(line));`,
`  const сказано=[];
  const line=g=>{if(seen.has(g.id))return null;seen.add(g.id);
    const s=gt(g.v>0?g.pos:g.neg).replace(/\\.$/,"");
    // Дубли по смыслу выбрасываем: «потребность контролировать» и «контроль всего»
    // подряд читаются как нажим или противоречие, а не как две разные черты.
    if(сказано.some(п=>похоже(п,s)))return null;
    сказано.push(s);
    return "- "+воВтороеЛицо(s)+"."};
  // Частота не наречием в хвосте, а разделом: «почти всегда» не к чему отнести,
  // а «вот это в тебе главное» задаёт вес прямо.
  const ядро=core.filter(g=>Math.abs(g.v)>=СТЕРЖЕНЬ_ПОРОГ);
  const заметно=core.filter(g=>Math.abs(g.v)<СТЕРЖЕНЬ_ПОРОГ&&Math.abs(g.v)>=ЗАМЕТНО_ПОРОГ);
  const изредка=core.filter(g=>Math.abs(g.v)<ЗАМЕТНО_ПОРОГ);
  sec("\\n## Это в тебе главное — так ты ведёшь себя по умолчанию", ядро.map(line));
  sec("\\n## Это заметно, но не в каждой сцене", заметно.map(line));
  sec("\\n## Это проступает изредка — не играй постоянно", изредка.map(line));
  // Противоречия называем прямо: иначе модель разрешит их наугад и каждый раз по-разному.
  const пары=[];
  for(let i=0;i<core.length&&пары.length<3;i++)for(let j=i+1;j<core.length&&пары.length<3;j++){
    const a=core[i],b=core[j];
    if(Math.sign(a.v)===Math.sign(b.v))continue;
    if(a.id.split(".")[0]!==b.id.split(".")[0])continue;
    if(Math.abs(Math.abs(a.v)-Math.abs(b.v))>.35)continue;
    пары.push("- "+воВторомЛице(a)+" и при этом "+воВторомЛице(b)+
      ". Когда одно мешает другому, перевешивает первое.")}
  function воВторомЛице(g){return воВтороеЛицо(gt(g.v>0?g.pos:g.neg).replace(/\\.$/,""))}
  sec("\\n## В тебе это уживается вместе", пары);`);

// 3. шапка: убрать объяснение про дозировку словами, его больше нет
rep(`Ты играешь этого персонажа от первого лица. Ниже не описание со стороны, а указания: "+
         "что делать, как говорить, когда меняться. Дозировка — словами «почти всегда», «часто», "+
         "«иногда», «редко»: это доля случаев, а не сила чувства."`,
`Ты играешь этого персонажа от первого лица. Ниже не описание со стороны, а указания: "+
         "что делать и как говорить. Разделы идут по весу: первый — то, из чего ты состоишь "+
         "и что видно почти в каждой сцене; последний — то, что проступает изредка и что "+
         "нельзя играть постоянно. Ничего не добавляй от себя: чего здесь нет, того в тебе "+
         "не снято, и это не повод выдумывать."`);

fs.writeFileSync("gs.html",t);
console.log("промпт ok");
