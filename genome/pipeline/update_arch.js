// Архетипы: честное число и правильный род в названии.
//
// Две поломки, обе видны на Питере Паркере:
// 1) NMof смотрел на male() — двухсостоянийный. Пол не задан → ложь → женская
//    форма. Питер получал «Заботливую опекуншу» и «Гордую аристократку», хотя
//    мужские формы для них в данных есть.
// 2) score = raw*cov + .5*(1-cov): неснятые гены считались за половину. При 10%
//    снятого генома число меряло не персонажа, а нашу неосведомлённость — всё
//    сползало к 60–75%. Теперь процент считается ТОЛЬКО по снятым генам,
//    покрытие показывается отдельно, а при малом покрытии процент не даётся.
const fs=require("fs");
let t=fs.readFileSync("gs.html","utf8");
function rep(a,b){if(!t.includes(a)){console.error("нет якоря:",a.slice(0,80));process.exit(1)}t=t.split(a).join(b)}

// --- 1. род в названии: женская форма только для женщин, иначе мужская/словарная
rep(`const NMof=s=>male()&&s.nm?s.nm:s.n;`,
    `const NMof=s=>(SEX==="f")?s.n:(s.nm||s.n);`);

// --- 2. честный счёт
rep(` let score=raw*cov+.5*(1-cov);if(veto)score=Math.min(score,.45);`,
` // Процент — совпадение по СНЯТЫМ генам. Неснятые больше не подмешиваются:
 // они говорят не о персонаже, а о том, чего мы про него не знаем.
 let score=raw;
 // Для сортировки покрытие всё же важно: тип, проверенный по шести генам,
 // надёжнее того же процента, набранного на двух. Корень — чтобы не хоронить
 // редкие типы совсем.
 let вес=raw*Math.sqrt(Math.max(cov,.01));
 const мало=known<3||cov<1/3;
 if(veto){score=Math.min(score,.45);вес=Math.min(вес,.45)}`);

rep(` return {score,raw,rows,known,cov,veto}}`,
` return {score,raw,rows,known,cov,veto,вес,мало}}`);

// сортировка — по весу, а не по проценту
rep(`.sort((a,b)=>b.m.score-a.m.score);const NMof=`,`.sort((a,b)=>b.m.вес-a.m.вес);const NMof=`);

// --- 3. подпись раздела: объяснить новое правило
rep(`применимых архетипов, у каждого — свои параметры (ген → целевой диапазон). Персонаж проецируется на все сразу: попал в диапазон — 1, рядом — частично, далеко — 0, с весом уверенности гена; неснятый параметр считается за 0.5 — ни за, ни против. Отпечаток — какие типы сработали вместе и с какой силой.`,
`применимых архетипов, у каждого — свои параметры (ген → целевой диапазон). Процент считается <b>только по снятым генам</b>: попал в диапазон — 1, рядом — частично, далеко — 0, с весом уверенности гена. Неснятые в процент не входят вовсе — рядом показано, сколько из скольких проверено. Пока проверено меньше трети параметров, процент не показывается: он мерил бы не персонажа, а нехватку данных. Отпечаток — типы, проверенные хотя бы по трети параметров.`);

// --- 4. в списке: «мало данных» вместо выдуманного процента
rep("<span class=\"pc\">${r.m.known?Math.round(r.m.score*100)+\"%\":\"—\"}</span>",
    "<span class=\"pc\">${r.m.мало?(r.m.known?\"мало данных\":\"—\"):Math.round(r.m.score*100)+\"%\"}</span>");

// --- 5. отпечаток: только проверенные типы
rep(`const top=Object.keys(FAM).map(f=>ranked.find(r=>r.s.fam===f)).filter(Boolean).sort((a,b)=>b.m.score-a.m.score);`,
`const top=Object.keys(FAM).map(f=>ranked.find(r=>r.s.fam===f&&!r.m.мало)).filter(Boolean).sort((a,b)=>b.m.score-a.m.score);`);
rep(`const top=SIGS.map(s=>({s,m:sigMatch(s)})).filter(r=>(!r.s.sex||r.s.sex===SEX)&&(!r.s.adult||adultOK)&&r.m.known>=3&&r.m.score>=.6).sort((a,b)=>b.m.score-a.m.score).slice(0,4);`,
`const top=SIGS.map(s=>({s,m:sigMatch(s)})).filter(r=>(!r.s.sex||r.s.sex===SEX)&&(!r.s.adult||adultOK)&&!r.m.мало&&r.m.score>=.6).sort((a,b)=>b.m.вес-a.m.вес).slice(0,4);`);

// --- 6. полоска показывает надёжность (вес), а число — точное совпадение.
// Иначе «100%» при трёх снятых из восьми выглядит увереннее, чем есть.
rep("<span class=\"bar\"><i style=\"width:${Math.round(r.m.score*100)}%;background:${famColor(r.s.fam)}\"></i></span>",
    "<span class=\"bar\" title=\"полоска — надёжность с учётом покрытия\"><i style=\"width:${Math.round(r.m.вес*100)}%;background:${famColor(r.s.fam)}\"></i></span>");

// --- 7. в самом проценте сразу видно, на скольких генах он посчитан
rep("<span class=\"pc\">${r.m.мало?(r.m.known?\"мало данных\":\"—\"):Math.round(r.m.score*100)+\"%\"}</span>",
    "<span class=\"pc\">${r.m.мало?(r.m.known?\"мало данных\":\"—\"):Math.round(r.m.score*100)+\"% по \"+r.m.known}</span>");

fs.writeFileSync("gs.html",t);
console.log("архетипы ok");
