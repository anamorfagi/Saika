"""[БЛОК ЗАМЕР] Насколько модель годна в АГЕНТНОМ цикле, а не в одиночном ответе.

benchmark_models.py проверяет другое: может ли модель выдать строгий JSON по контракту.
Это про послушание формату. Здесь проверяется то, что ломается на практике: выберет ли
модель нужный инструмент, не переврёт ли аргументы, дойдёт ли до ответа за разумное
число шагов или будет ходить кругами.

Задачи только читающие — замер ничего не портит в share/.

Запуск: python pipeline/bench_agent.py [модель ...]
        python pipeline/bench_agent.py --all
"""
import json
import re
import sys
import time
from pathlib import Path

try:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
except Exception:
    pass

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import chat as Ч
from llm import Client

ПРЕДЕЛ = 8

# (задание, как проверить ответ, какие инструменты ожидаем увидеть)
ЗАДАЧИ = [
    {
        "имя": "найти ген по смыслу",
        "запрос": "Каким геном в этом проекте описывается прямота речи? "
                  "Назови его точный id и что означают полюса.",
        "годно": lambda т: "sp.directness" in т,
        "ждём": {"find_genes"},
    },
    {
        "имя": "прочитать карточку",
        "запрос": "Посмотри, какие персонажи есть в папке, возьми любого вида «ии» "
                  "и скажи: его id, сколько у него снято генов и из какого он произведения.",
        "годно": lambda т: bool(re.search(r"\d", т)),
        "ждём": {"list_chars", "read_card"},
    },
    {
        "имя": "понять правила проекта",
        "запрос": "У существа речевые гены пустые. Это ошибка сбора или так и должно быть? "
                  "Ответь одной фразой и скажи, какой блок для существа основной.",
        "годно": lambda т: "beast" in т.lower(),
        "ждём": set(),
    },
]


def прогнать(стык, модель, задача):
    """Один прогон: считаем шаги, вызовы, битые аргументы и выдуманные инструменты."""
    клиент = Client(provider=стык, model=модель, timeout=180)
    if not клиент.key:
        return {"ошибка": "нет ключа"}
    сообщения = [{"role": "system", "content": Ч.о_проекте()},
                 {"role": "user", "content": задача["запрос"]}]
    инструменты = Ч.схема()
    считано = {"шагов": 0, "вызовов": 0, "битых": 0, "выдуманных": 0, "имена": set()}
    t0 = time.time()
    for _ in range(ПРЕДЕЛ):
        считано["шагов"] += 1
        try:
            ответ = клиент.chat_tools(сообщения, инструменты, temperature=0.2, max_tokens=1500)
        except Exception as e:
            считано["ошибка"] = str(e)[:120]
            break
        зовы = ответ.get("tool_calls") or []
        if not зовы:
            считано["текст"] = ответ.get("content") or ""
            break
        сообщения.append({"role": "assistant", "content": ответ.get("content") or "", "tool_calls": зовы})
        for з in зовы:
            фн = з.get("function") or {}
            имя = фн.get("name") or ""
            считано["вызовов"] += 1
            считано["имена"].add(имя)
            try:
                арг = json.loads(фн.get("arguments") or "{}")
                if not isinstance(арг, dict):
                    raise ValueError("не объект")
            except Exception:
                считано["битых"] += 1
                арг = {}
            рука = Ч.РУКИ.get(имя)
            if not рука:
                считано["выдуманных"] += 1
                вышло = f"нет такого инструмента: {имя}"
            else:
                try:
                    вышло, _ = рука[0](арг)
                except Exception as e:
                    вышло = f"ОШИБКА: {e}"
                    считано["битых"] += 1
            сообщения.append({"role": "tool", "tool_call_id": з.get("id") or имя,
                              "name": имя, "content": Ч.обрезать(вышло, 4000)})
    считано["сек"] = round(time.time() - t0, 1)
    текст = считано.get("текст", "")
    считано["решено"] = bool(текст) and задача["годно"](текст)
    считано["нужные"] = задача["ждём"].issubset(считано["имена"]) if задача["ждём"] else True
    считано["имена"] = sorted(считано["имена"])
    return считано


def стык_для(модель):
    """Где эта модель живёт — среди стыков, у которых есть ключ."""
    try:
        кат = json.loads((HERE / "providers.json").read_text(encoding="utf-8"))
    except Exception:
        return ""
    по_id = {п.get("id"): (п.get("models") or []) for п in (кат.get("providers") or [])}
    for стык in Ч.все_стыки():
        if модель in по_id.get(стык, []):
            return стык
    return ""


def main():
    доводы = [x for x in sys.argv[1:] if not x.startswith("--")]
    если_все = "--all" in sys.argv
    if если_все or not доводы:
        try:
            кат = json.loads((HERE / "providers.json").read_text(encoding="utf-8"))
        except Exception:
            кат = {"providers": []}
        по_id = {п.get("id"): (п.get("models") or []) for п in (кат.get("providers") or [])}
        доводы = []
        for стык in Ч.все_стыки():
            доводы += по_id.get(стык, [])
    print("замер агентности · задач %d · потолок шагов %d\n" % (len(ЗАДАЧИ), ПРЕДЕЛ))
    итог = []
    for модель in доводы:
        стык = стык_для(модель)
        if not стык:
            print("%-34s пропуск: нет стыка с ключом" % модель); continue
        строки, решено, вызовов, битых, секунд = [], 0, 0, 0, 0.0
        for з in ЗАДАЧИ:
            р = прогнать(стык, модель, з)
            if "ошибка" in р and not р.get("текст"):
                строки.append("  %-22s ОШИБКА: %s" % (з["имя"], р["ошибка"])); continue
            решено += 1 if р["решено"] else 0
            вызовов += р["вызовов"]; битых += р["битых"]; секунд += р["сек"]
            строки.append("  %-22s %s · шагов %d · вызовов %d · битых %d · %.0f с · %s"
                          % (з["имя"], "решено" if р["решено"] else "НЕ решено",
                             р["шагов"], р["вызовов"], р["битых"], р["сек"],
                             ", ".join(р["имена"]) or "без инструментов"))
        print("%s (%s)" % (модель, стык))
        print("\n".join(строки))
        print("  ИТОГ: решено %d/%d · вызовов %d · битых %d · %.0f с\n"
              % (решено, len(ЗАДАЧИ), вызовов, битых, секунд))
        итог.append((модель, решено, битых, секунд))
    if итог:
        print("=" * 60)
        for м, р, б, с in sorted(итог, key=lambda x: (-x[1], x[2], x[3])):
            print("%-34s решено %d/%d · битых аргументов %d · %.0f с" % (м, р, len(ЗАДАЧИ), б, с))


if __name__ == "__main__":
    main()
