# -*- coding: utf-8 -*-
"""
Лексический оценщик возраста по русскому тексту (транскрипт, переписка, посты).
Часть следователя Genome Studio: канал «текст», улика класса «возраст».

Что делает:
  [1] ищет ПРЯМЫЕ указания возраста («мне 32», «тридцать второй день рождения») — сильнее всего;
  [2] считает МАРКЕРЫ ЖИЗНЕННОГО ЭТАПА по шести возрастным группам (Schwartz et al. 2013 — темы,
      адаптированные под русский), нормируя на 1000 слов;
  [3] считает ГРАММАТИЧЕСКИЕ признаки Пеннебейкера (Pennebaker & Stone 2003): доля «я», доля
      прошедшего времени, доля будущего, положительные/отрицательные слова — с возрастом «я» и
      прошедшее время убывают, будущее и позитив растут;
  [4] выдаёт полосу возраста, уверенность и список улик — чтобы человек видел, ОТКУДА цифра.

Запуск:  python age_lex.py [--year=ГОД_ЗАПИСИ] файл1.txt [файл2.txt ...]   → печать + age_lex_result.json рядом
"""
import re, sys, json, collections

# [БЛОК 1] прямое указание возраста ------------------------------------------------------------
NUM_WORDS = {"восемнадцать":18,"девятнадцать":19,"двадцать":20,"тридцать":30,"сорок":40,"пятьдесят":50,"шестьдесят":60,"семьдесят":70,
             "один":1,"одного":1,"два":2,"две":2,"три":3,"четыре":4,"пять":5,"шесть":6,"семь":7,"восемь":8,"девять":9}
ORD_WORDS = {"первый":1,"второй":2,"третий":3,"четвёртый":4,"четвертый":4,"пятый":5,"шестой":6,"седьмой":7,"восьмой":8,"девятый":9,
             "двадцатый":20,"тридцатый":30,"сороковой":40,"пятидесятый":50}
DIRECT = [
    (r"\bмне\s+(?:уже\s+|скоро\s+|почти\s+|сейчас\s+)?(\d{2})\b", "мне N"),
    (r"\bмне\s+(?:уже\s+|скоро\s+)?(\d{2})\s*(?:лет|года|год)\b", "мне N лет"),
    (r"\bисполнил[оа]сь\s+(\d{2})\b", "исполнилось N"),
    (r"\b(\d{2})[\s-]*(?:й|ый|ой)?\s*день\s+рожден", "N-й день рождения"),
    (r"\bв\s+(?:мои|свои)\s+(\d{2})\b", "в мои N"),
]
def direct_age(text):
    out = []
    for pat, kind in DIRECT:
        for m in re.finditer(pat, text, flags=re.I):
            n = int(m.group(1))
            if 12 <= n <= 90:
                out.append({"возраст": n, "тип": kind, "цитата": text[max(0,m.start()-40):m.end()+20].replace("\n"," ")})
    # словами: «тридцать второй день рождения», «мне тридцать два»
    for m in re.finditer(r"\b(двадцать|тридцать|сорок|пятьдесят|шестьдесят)\s+(\w+?)(?:\s+(?:день\s+рожден|лет|года))", text, flags=re.I):
        tens = NUM_WORDS[m.group(1).lower()]; w = m.group(2).lower().rstrip("йо")  # «второ» из транскрипта
        unit = next((v for k,v in {**ORD_WORDS, **NUM_WORDS}.items() if k.startswith(w[:4]) and v < 10), 0) if w else 0
        out.append({"возраст": tens+unit, "тип": "числом словами", "цитата": text[max(0,m.start()-30):m.end()+25].replace("\n"," ")})
    return out

# [БЛОК 2] маркеры жизненного этапа (слово-основа → группа, вес) ------------------------------
# Основы сопоставляются по началу слова: «школ» ловит школа/школе/школьный. Вес — насколько маркер специфичен группе.
GROUPS = ["13–17","18–22","23–29","30–39","40–54","55+"]
MARKERS = {
 "13–17": {"школ":1,"урок":1,"училк":1.5,"домашк":1.5,"контрольн":1,"физр":1.5,"перемен":.5,"каникул":.5,"егэ":1.5,"огэ":1.5,"родител":.5,
           "тикток":1,"кринж":1,"рофл":1,"зашквар":1,"имба":1,"капец":.5,"го ":.5,"донат":.7,"скин":.7,"мамк":.7,"батя":.5},
 "18–22": {"универ":1.5,"сесси":1.5,"препод":1.5,"общаг":1.5,"пары ":1,"зачёт":1.2,"зачет":1.2,"курсов":1.2,"диплом":1,"стипенд":1.5,
           "первокур":1.5,"вписк":1.5,"тусов":.7,"клуб":.5,"армия":.7,"военком":1,"подработк":.8,"бухать":.7,"бухал":.5,"нахуяр":.3},
 "23–29": {"работ":.6,"начальник":1,"зарплат":1,"офис":1,"коллег":1,"собес":1,"резюме":1.2,"съём":.8,"снимаем квартиру":1,"аренд":.6,
           "свадьб":.8,"девушк":.4,"пацан":.3,"переезд":.6,"командировк":.8,"карьер":.8,"стартап":.8,"новая работа":1.2},
 "30–39": {"жен":.6,"муж ":.6,"жена":1,"ребён":.8,"ребен":.8,"сын":.6,"доч":.6,"садик":1.2,"ипотек":1.2,"ремонт":.6,"кредит":.5,
           "здоровь":.6,"спин":.5,"колен":.5,"режим":.5,"кризис среднего":1.5,"тридцат":.8,"мне 3":.5,"сустав":.7,"метаболизм":.6},
 "40–54": {"подросток":.6,"подростк":.6,"давлен":.6,"дач":.7,"юбиле":.8,"подчинённ":1,"подчиненн":1,"молодёжь":1,"молодежь":1,
           "в наше время":1.2,"сорок":.8,"пятьдесят":.8,"родители болеют":1.2,"кредит":.2,"начальник":.2},
 "55+":   {"пенси":1.5,"внук":1.5,"внучк":1.5,"таблетк":.8,"поликлиник":1,"огород":.8,"в мои годы":1.5,"молодые":.6,"шестьдесят":1,
           "семьдесят":1.2,"давлен":.4,"ветеран":1,"собес ":.5},
}

# [БЛОК 3] грамматика Пеннебейкера ------------------------------------------------------------
POS = ["хорош","классн","круто","кайф","рад","любл","прекрасн","замечательн","счаст","улыб","интересн","добр"]
NEG = ["плох","ужас","грус","больн","страшн","обидн","злой","злюс","ненавиж","тревог","хуёв","хуев","дерьм"]
def grammar(words):
    n = max(1, len(words))
    i_rate  = sum(1 for w in words if w in ("я","мне","меня","мной","мой","моя","моё","мои")) / n * 1000
    past    = sum(1 for w in words if re.search(r"(ла|ли|лся|лась|лись|л)$", w) and len(w) > 3 and not w.endswith(("ель","аль","оль","уль"))) / n * 1000
    future  = sum(1 for w in words if w in ("буду","будет","будем","будешь","будут","завтра","потом","скоро")) / n * 1000
    pos = sum(1 for w in words if any(w.startswith(p) for p in POS)) / n * 1000
    neg = sum(1 for w in words if any(w.startswith(p) for p in NEG)) / n * 1000
    return {"я_на_1000": round(i_rate,1), "прошедшее_на_1000": round(past,1), "будущее_на_1000": round(future,1),
            "позитив_на_1000": round(pos,1), "негатив_на_1000": round(neg,1)}

# [БЛОК 4] сведение -------------------------------------------------------------------------------
def estimate(text, recorded_year=None, now_year=None):
    """recorded_year — год записи корпуса (если известен): прямой возраст переводится в «сейчас»."""
    low = text.lower()
    words = re.findall(r"[а-яё]+", low)
    n = max(1, len(words))
    scores, evid = collections.OrderedDict(), collections.defaultdict(list)
    for g in GROUPS:
        s = 0.0
        for stem, w in MARKERS[g].items():
            c = len(re.findall(r"\b" + re.escape(stem.strip()) + (r"\b" if stem.endswith(" ") else ""), low))
            if c:
                s += w * c; evid[g].append(f"{stem.strip()}×{c}")
        scores[g] = round(s / n * 1000, 2)          # маркеров на 1000 слов, взвешенно
    gr = grammar(words)
    # грамматический сдвиг: много «я» и прошедшего — моложе; много будущего и позитива — старше (Pennebaker & Stone 2003). Слабый вес.
    shift = (-0.4 if gr["я_на_1000"] > 45 else 0.4 if gr["я_на_1000"] < 25 else 0) + (0.3 if gr["позитив_на_1000"] > gr["негатив_на_1000"]*1.5 else 0)
    ranked = sorted(scores.items(), key=lambda kv: -kv[1])
    band, top = ranked[0]
    second = ranked[1][1] if len(ranked) > 1 else 0
    conf = round(min(0.8, (top - second) / (top + 1e-9) * 0.8), 2) if top else 0.0
    d = direct_age(text)
    res = {"слов": n, "полоса_по_маркерам": band, "уверенность_маркеров": conf, "баллы": scores,
           "улики": {g: evid[g] for g in GROUPS if evid[g]}, "грамматика": gr,
           "грамматический_сдвиг": "моложе" if shift < 0 else "старше" if shift > 0 else "нейтрально",
           "прямые_указания": d}
    if d:
        ages = [x["возраст"] for x in d]
        a = f"{min(ages)}–{max(ages)}" if min(ages) != max(ages) else f"{ages[0]}"
        res["итог"] = f"{a} (сказано прямо, на момент записи)"
        res["уверенность_итог"] = 0.9
        if recorded_year and now_year:
            dy = now_year - recorded_year
            res["итог_сейчас"] = f"{min(ages)+dy}–{max(ages)+dy}" if min(ages) != max(ages) else f"{ages[0]+dy}"
            res["итог"] += f" → сейчас ≈{res['итог_сейчас']} (запись {recorded_year})"
    else:
        res["итог"] = f"{band} (по маркерам{', ' + res['грамматический_сдвиг'] if shift else ''})"
        res["уверенность_итог"] = conf
    return res

if __name__ == "__main__":
    import datetime
    args = sys.argv[1:]; ry = None
    if args and args[0].startswith("--year="): ry = int(args[0][7:]); args = args[1:]   # --year=2024 — год записи корпуса
    text = "\n".join(open(f, encoding="utf-8").read() for f in args)
    r = estimate(text, ry, datetime.date.today().year if ry else None)
    print(json.dumps(r, ensure_ascii=False, indent=1))
    json.dump(r, open("age_lex_result.json", "w", encoding="utf-8"), ensure_ascii=False, indent=1)
