    def охота(self):
        имя = self.имена[0] if self.имена else ''
        задача = (f'Персонаж: {имя}. Другие имена: {", ".join(self.имена[1:]) or "нет"}. '
                  f'Произведение: {self.произведение or "не указано"}. ' +
                  (f'Этот персонаж не говорит. Найди сценарий с ремарками действия и разборы '
                   f'создателей о его пластике и поведении.' if self.бессловесный else
                   f'Сначала найди дословную речь из самого произведения — лучше всего полный '
                   f'транскрипт или субтитры целиком. Потом, отдельным каналом, найди интервью '
                   f'или подкаст исполнителя об этой роли.'))
        свод = self.правила or (ПРАВИЛА + "\n\n" + ЗНАНИЕ_О_ПЛОЩАДКАХ)
        if self.правила and not self.бессловесный:
            задача = (f'Персонаж: {имя}. Другие имена: {", ".join(self.имена[1:]) or "нет"}. '
                      f'Произведение: {self.произведение or "не указано"}. Иди по маршруту из правил: '
                      f'добери прямую речь в разных ситуациях там, где она реально есть для этих форм.')
        if self.бессловесный:
            свод = БЕССЛОВЕСНЫЙ + "\n\n" + свод
        сообщения = [
            {"role": "system", "content": свод},
            {"role": "user", "content": задача},
        ]
        if self.урок:
            # Переделка без разбора — тот же бросок теми же костями. Модель должна
            # видеть, что именно не сработало, до первого своего хода.
            self.событие('retry', 'Охота начинается с разбора прошлой неудачи')
            сообщения.append({"role": "user", "content": self.урок})
        if self.заготовка:
            # Первый ход не отдаём на удачу. Тот же Джарвис в одном заходе нашёл
            # транскрипт с 36 репликами, а в следующем — одну цитату, просто
            # потому что модель по-другому сформулировала запрос. Готовые
            # кандидаты со сценарных площадок кладём ей на стол сразу.
            готовое = []
            for r in self.заготовка[:10]:
                if self._мусор(r['url']) and not это_видео(r['url']):
                    continue
                готовое.append({"заголовок": r['title'][:160], "адрес": r['url'],
                                "описание": r['snippet'][:200]})
                self.событие('candidate', r['title'], url=r['url'], snippet=r['snippet'])
            if готовое:
                self.событие('search', f'Охоте выдано {len(готовое)} готовых кандидатов '
                                       'со сценарных площадок — начинает не с пустого места')
                сообщения.append({"role": "user", "content":
                    "Вот страницы, уже найденные по проверенным шаблонам запросов — "
                    "начни с них, читай самые обещающие. Искать своё тоже можно.\n" +
                    json.dumps(готовое, ensure_ascii=False)})
        стол = {"search": lambda a: self.т_искать(a.get("query") or a.get("запрос")),
                "read": lambda a: self.т_прочитать(a.get("url") or a.get("адрес")),
                "take": lambda a: self.т_взять(a.get("url") or a.get("адрес"),
                                               a.get("why") or a.get("почему", ""),
                                               a.get("channel") or a.get("канал", "speech")),
                "browser": lambda a: self.т_пробить(a.get("url") or a.get("адрес")),
                "subs": lambda a: self.т_субтитры(a.get("url") or a.get("адрес"), a.get("lang")),
                "stt": lambda a: self.т_расшифровать(a.get("url") or a.get("адрес"), a.get("lang"))}
        for шаг in range(self.шагов):
            ответ = self.клиент.chat_tools(сообщения, ИНСТРУМЕНТЫ, temperature=0.3, max_tokens=1400)
            мысль = (ответ.get("content") or "").strip()
            вызовы = ответ.get("tool_calls") or []
            if мысль:
                self.событие('think', мысль[:600])
            # content=None у некоторых стыков вызывает 400; пустая строка принимается всеми.
            сообщения.append({"role": "assistant", "content": мысль, "tool_calls": вызовы})
            if not вызовы:
                # Модель заговорила вместо действия — напоминаем, что нужен вызов.
                сообщения.append({"role": "user", "content":
                                  "Действуй инструментом, а не описанием. Если всё собрано — вызови stop."})
                continue
            конец = False
            for вызов in вызовы:
                имя_т = (вызов.get("function") or {}).get("name", "")
                try:
                    доводы = json.loads((вызов.get("function") or {}).get("arguments") or "{}")
                except Exception:
                    доводы = {}
                if имя_т == "stop":
                    self.событие('sources', 'Модель закончила сбор: ' +
                                 str(доводы.get("summary") or доводы.get("итог", ""))[:400])
                    конец = True
                    результат = {"принято": True}
                elif имя_т in стол:
                    результат = стол[имя_т](доводы)
                else:
                    результат = {"ошибка": "нет такого инструмента"}
                сообщения.append({"role": "tool", "tool_call_id": вызов.get("id", ""),
                                  "content": json.dumps(результат, ensure_ascii=False)[:9000]})
            if конец:
                break
            речь_ = [s for s in self.взятое if s['канал'] == 'речь']
            if len(речь_) >= 3 and sum(s['реплик'] for s in речь_) >= 150:
                self.событие('sources', f'Речи достаточно: {sum(s["реплик"] for s in речь_)} реплик из {len(речь_)} источников — охоту останавливаю, деньги не жгу')
                break
            if len([s for s in self.взятое if s['канал'] == 'речь']) >= 5 and len(self.взятое) >= 6:
                self.событие('sources', 'Набрано достаточно: речь и трактовка — сбор остановлен')
                break
        else:
            self.событие('sources', f'Исчерпан лимит шагов ({self.шагов}); работаю с тем, что взято')
        речь = [s for s in self.взятое if s['канал'] == 'речь']
        речи = sum(s['реплик'] for s in речь)
        self.событие('sources', f'Собрано: источников речи {len(речь)} ({речи} реплик), '
                                f'интервью о роли {len(self.взятое) - len(речь)}', replicas=речи)
        return self.взятое
