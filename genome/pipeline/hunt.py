class Охотник:
    """Цикл «модель решает — инструмент отвечает правдой — модель видит ответ».

    Наружу отдаёт список взятых источников. Ничего не выдумывает за модель:
    если она не нашла речи, так и будет записано.
    """

    def __init__(self, клиент, имена, произведение, искать, читать, считать_реплики,
                 мусор, событие, шагов=22, бессловесный=False, заготовка=None, урок='', правила=None):
        self.клиент = клиент
        self.имена = [n for n in имена if n]
        self.произведение = произведение or ''
        self._искать = искать
        self._читать = читать
        self._реплик = считать_реплики
        self._мусор = мусор
        self.событие = событие
        self.шагов = шагов
        self.бессловесный = bool(бессловесный)
        self.заготовка = заготовка or []   # что найдено до начала охоты
        self.урок = str(урок or '')        # разбор прошлой неудачной попытки
        self.правила = правила              # свод под формы произведения (source_map); None — старый «киношный»
        self.прочитано = {}      # адрес -> {'текст','реплик','заголовок'}
        self.взятое = []         # то, что модель приняла осознанно
        self.искалось = set()
        self.пустых_подряд = 0   # сколько поисков подряд не дали ни одной взятой страницы

    # --- инструменты, каждый возвращает настоящий результат, а не обещание ---

    def т_искать(self, запрос):
        запрос = str(запрос or '').strip()
        if not запрос:
            return {"ошибка": "пустой запрос"}
        if запрос.lower() in self.искалось:
            return {"замечание": "такой запрос уже был, переформулируй иначе"}
        self.искалось.add(запрос.lower())
        self.событие('search', 'Модель ищет: ' + запрос, query=запрос)
        try:
            строки = self._искать(запрос)
        except Exception as e:
            return {"ошибка": "поиск не удался: " + str(e)[:200]}
        годные = []
        for r in строки:
            видео = это_видео(r['url'])
            if self._мусор(r['url']) and not видео:
                continue
            запись = {"заголовок": r['title'][:160], "адрес": r['url'],
                      "описание": r['snippet'][:240]}
            if видео:
                запись["это"] = ("видео или подкаст — обычным чтением бесполезен, "
                                 "вызывай subs, а если их нет — stt")
            годные.append(запись)
            self.событие('candidate', r['title'], url=r['url'], snippet=r['snippet'])
        if not годные:
            return {"найдено": 0, "замечание": "вся выдача отсеяна как мусор, смени формулировку"}
        ответ = {"найдено": len(годные), "результаты": годные}
        # Интервью исполнителя может просто не существовать. Десять заходов подряд
        # за ним — это десять шагов, отнятых у речи персонажа: честно говорим об этом.
        self.пустых_подряд += 1
        if self.пустых_подряд >= 4 and self.взятое:
            ответ["замечание"] = ("четыре поиска подряд без единого взятого источника. "
                                  "Если ищешь интервью исполнителя и его не находится — "
                                  "его может не быть вовсе. Не трать на это шаги: либо "
                                  "вернись к речи персонажа, либо вызывай stop.")
        return ответ

    def т_прочитать(self, адрес):
        адрес = str(адрес or '').strip()
        if not адрес.startswith('http'):
            return {"ошибка": "нужен полный адрес из результатов поиска"}
        if адрес in self.прочитано:
            п = self.прочитано[адрес]
            return {"замечание": "уже читали", "символов": len(п['текст']), "реплик": п['реплик']}
        self.событие('fetch', 'Модель читает: ' + адрес, url=адрес)
        try:
            текст = self._читать(адрес)
        except Exception as e:
            self.событие('source_error', str(e)[:200], url=адрес)
            return {"ошибка": "страница не прочиталась: " + str(e)[:160],
                    "совет": "возьми другую ссылку, эта недоступна"}
        if len(текст) < 300:
            self.событие('source_error', 'Пустая оболочка страницы', url=адрес)
            return {"символов": len(текст), "реплик": 0,
                    "замечание": "текста нет — сайт отдаёт пустую оболочку, читать нечего"}
        реплик = self._реплик(текст, self.имена)
        self.прочитано[адрес] = {"текст": текст, "реплик": реплик, "заголовок": адрес}
        self.событие('source', f'Прочитано {len(текст)} символов · прямых реплик {реплик}',
                     url=адрес, chars=len(текст), replicas=реплик)
        if реплик:
            подсказка = "речь есть, можно брать"
        elif self.бессловесный:
            подсказка = ("реплик нет — так и должно быть, он не говорит; "
                         "оценивай по описанным действиям и реакциям")
        else:
            подсказка = "реплик нет — это пересказ, брать не стоит"
        return {"символов": len(текст), "реплик": реплик, "оценка": подсказка,
                "начало": текст[:1500]}

    def т_взять(self, адрес, почему, канал='речь'):
        адрес = str(адрес or '').strip()
        if адрес not in self.прочитано:
            return {"ошибка": "сначала прочитай страницу инструментом read"}
        if any(s['url'] == адрес for s in self.взятое):
            return {"замечание": "этот источник уже взят"}
        канал = 'трактовка' if str(канал) in ('трактовка', 'reading') else 'речь'
        п = self.прочитано[адрес]
        if канал == 'речь' and not п['реплик'] and not self.бессловесный:
            # Иначе пересказ попадёт в первичку и разбор пойдёт по чужим словам.
            return {"отказ": "в этой странице нет ни одной прямой реплики, в канал «речь» она "
                             "не годится. Либо возьми её как «трактовка», если это интервью "
                             "исполнителя о роли, либо ищи дальше."}
        self.взятое.append({"url": адрес, "title": п['заголовок'], "_text": п['текст'],
                            "chars": len(п['текст']), "реплик": п['реплик'], "канал": канал,
                            "status": "read", "почему": str(почему)[:400]})
        подпись = ('реплик ' + str(п['реплик'])) if канал == 'речь' else 'трактовка исполнителя'
        self.пустых_подряд = 0
        self.событие('source', f'Модель взяла источник ({подпись}): ' + str(почему)[:200],
                     url=адрес, chars=len(п['текст']), replicas=п['реплик'], канал=канал)
        речь = [s for s in self.взятое if s['канал'] == 'речь']
        return {"взято": len(self.взятое), "источников_речи": len(речь),
                "всего_реплик": sum(s['реплик'] for s in речь),
                "интервью_о_роли": len(self.взятое) - len(речь)}

    def _принять_текст(self, адрес, текст, откуда):
        """Общая посадка добытого текста: считаем речь и кладём в прочитанное."""
        if len(текст) < 300:
            return {"символов": len(текст), "реплик": 0,
                    "замечание": f"{откуда}: текста почти нет, брать нечего"}
        реплик = self._реплик(текст, self.имена)
        self.прочитано[адрес] = {"текст": текст, "реплик": реплик, "заголовок": адрес}
        self.событие('source', f'{откуда}: {len(текст)} символов · прямых реплик {реплик}',
                     url=адрес, chars=len(текст), replicas=реплик)
        if реплик:
            оценка = "речь есть, можно брать"
        elif self.бессловесный:
            оценка = ("реплик нет — так и должно быть, персонаж бессловесный; "
                      "смотри, есть ли описанные действия и реакции")
        else:
            оценка = ("именных реплик нет; если это сплошная речь без подписи говорящего "
                      "или интервью — всё равно годится, но пометь канал верно")
        return {"символов": len(текст), "реплик": реплик, "источник": откуда,
                "оценка": оценка, "начало": текст[:1500]}

    def т_пробить(self, адрес):
        адрес = str(адрес or '').strip()
        if not адрес.startswith('http'):
            return {"ошибка": "нужен полный адрес"}
        self.событие('fetch', 'Пробиваю браузером: ' + адрес, url=адрес)
        try:
            import tools_web
            текст = tools_web.читать_браузером(адрес)
        except Exception as e:
            self.событие('source_error', 'браузер не справился: ' + str(e)[:180], url=адрес)
            return {"ошибка": "браузером тоже не вышло: " + str(e)[:200],
                    "совет": "ищи другой источник, этот закрыт"}
        return self._принять_текст(адрес, текст or '', 'через браузер')

    def т_субтитры(self, адрес, язык=None):
        адрес = str(адрес or '').strip()
        if not адрес.startswith('http'):
            return {"ошибка": "нужна ссылка на видео"}
        self.событие('fetch', 'Снимаю субтитры: ' + адрес, url=адрес)
        try:
            import tools_web
            готовое = tools_web.субтитры_видео(адрес, язык or 'en')
        except Exception as e:
            self.событие('source_error', 'субтитры не снялись: ' + str(e)[:180], url=адрес)
            return {"ошибка": str(e)[:220], "совет": "попробуй «расшифровать» или другую ссылку"}
        ответ = self._принять_текст(адрес, готовое['текст'], 'субтитры ' + готовое['вид'])
        if готовое['вид'] == 'автоматические':
            ответ["предупреждение"] = ("субтитры автоматические: без знаков препинания и с "
                                       "ошибками в словах. Цитаты сверяй осторожно")
        return ответ

    def т_расшифровать(self, адрес, язык=None):
        адрес = str(адрес or '').strip()
        if not адрес.startswith('http'):
            return {"ошибка": "нужна ссылка"}
        self.событие('fetch', 'Расшифровываю звук: ' + адрес, url=адрес)
        try:
            import tools_web
            готовое = tools_web.расшифровать(адрес, язык)
        except Exception as e:
            self.событие('source_error', 'расшифровка не вышла: ' + str(e)[:180], url=адрес)
            return {"ошибка": str(e)[:220]}
        return self._принять_текст(адрес, готовое['текст'], готовое['вид'])

