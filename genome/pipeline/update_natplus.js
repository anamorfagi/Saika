// Три гена природы агента, которых не хватало для адаптивных систем.
//
// Геном снимал «Карен-при-Питере» и выдавал её ласковость за постоянную черту.
// С другим оператором та же система выглядела бы иначе, а костюм и боевые режимы
// остались бы те же. Нужно различать: что в ней постоянное, а что подобрано под
// конкретного человека; сколько за спокойной работой стоит силы; и кому отдан
// выбор, когда дело касается вреда.
//
// Второй заход: разумный ассистент не становится оружием от смены оператора.
// Он держит в уме, КТО перед ним и что этому человеку можно, учит справляться
// самому и ставит жизнь человека выше выполнения задачи. Тони набивал костюм
// опасными инструментами именно в расчёте на такую Карен, а не вопреки ей.
const fs=require("fs");
let t=fs.readFileSync("gs.html","utf8");
// Сторож проверяет ИМЕННО запись шаблона, а не просто наличие строки в файле:
// после того как описания генов уехали в DESC, «nat.adaptive» стало встречаться
// в html и без вставки — скрипт решал, что уже отработал, и молча пропускал.
if(t.includes('["nat.adaptive"')){console.log("уже вшито");process.exit(0)}
const НОВЫЕ=JSON.parse(fs.readFileSync("/home/claude/work/natplus.json","utf8"));

// Вставляем сразу после гена ограничителя вреда — соседи по смыслу.
// Якорь берём целой записью, чтобы не считать скобки вручную: в прошлый заход
// ручная арифметика по индексам разорвала JSON шаблона.
const якорь='["nat.harm_lock","Ограничитель вреда",0,0,"A",[],"ограничителя нет — вред решается моралью","вред человеку невозможен физически"]';
if(!t.includes(якорь)){console.error("не нашёл запись nat.harm_lock");process.exit(1)}
const добавка=НОВЫЕ.map(g=>JSON.stringify([g.id,g.name,0,0,g.ch,[],g.neg,g.pos])).join(",");
t=t.replace(якорь, якорь+","+добавка);

fs.writeFileSync("gs.html",t);
console.log("гены природы ok · добавлено "+НОВЫЕ.length);
