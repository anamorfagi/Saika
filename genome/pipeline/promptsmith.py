# -*- coding: utf-8 -*-
"""
[БЛОК КОМПИЛЯТОР] Системный промпт персонажа пишет модель, а не шаблон.

Зачем отдельно от компилятора в студии. Шаблон умеет только пересобрать то, что
лежит в данных: ярлык полюса плюс частота. Получается опись ползунков, которую
модель читает как характеристику со стороны, а не как задание актёру. Живой
проход даёт связный текст: поведение в ситуациях, что перевешивает при
столкновении черт, где персонаж ломается.

Вход — карточка .genome.json. Выход — готовый системный промпт, который
кладётся обратно в карточку (meta.prompt) и в файл рядом.

Модель получает три вещи: устройство самого генома, снятые гены с весами и
уликами, и требования к промпту. Ничего сверх снятого она додумывать не должна —
об этом сказано отдельно, иначе при 36 генах из 383 она дофантазирует остальное.
"""
import json
import pathlib
import sys

sys.stdout.reconfigure(encoding="utf-8", errors="replace")
ЗДЕСЬ = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(ЗДЕСЬ))

ГЕНЫ = json.loads((ЗДЕСЬ / "genes.json").read_text(encoding="utf-8"))
ПО_ИДЕНТ = {g["id"]: (g, b) for b in ГЕНЫ for g in b["genes"]}

ЧТО_ТАКОЕ_ГЕНОМ = """Геном персонажа — это набор шкал от −1 до +1, каждая с отдельной
уверенностью от 0 до 1. Значение говорит, где персонаж на шкале; уверенность — насколько
это подтверждено уликами. Шкала не снята, если уверенность 0: это значит «не знаем», а
не «посередине». Снятых генов почти всегда меньше, чем всего, и это нормально.

У каждой шкалы описаны оба полюса человеческим языком. Минус и плюс — не «плохо» и
«хорошо», а две разные манеры."""

ТРЕБОВАНИЯ = """Напиши системный промпт, по которому языковая модель сыграет этого
персонажа. Не описание со стороны — указания изнутри.

Как надо:
- Второе лицо, настоящее время, прямое обращение: «ты делаешь», а не «он делает».
- ПОВЕДЕНИЕ В СИТУАЦИЯХ, а не список черт. Плохо: «уступчивость низкая». Хорошо:
  «уступаешь в мелочах, но упираешься, когда за тебя решают».
- Вес виден по месту и формулировке: сначала то, из чего персонаж состоит и что видно
  почти в каждой сцене, потом то, что проступает изредка.
- Столкновения черт назови прямо и скажи, что перевешивает. Если персонаж и закрытый,
  и заботливый — что он делает, когда забота требует открыться.
- Речь: как строит фразы, что говорит часто, чего не говорит никогда. Если есть образцы
  реплик — покажи, какой у них строй, но НЕ вставляй их дословно: это материал
  исследования, а не текст роли.
- Отдельно: где персонаж ломается, теряет自 форму, ведёт себя не как обычно.

Чего нельзя:
- Названий шкал и внутренних терминов в тексте промпта быть не должно вовсе.
- Не добавляй черт, которых нет в снятом геноме. Чего не снято — того не выдумывай.
  Лучше короткий промпт по десяти шкалам, чем красивый по выдуманным тридцати.
- Никаких «ты — ИИ, играющий роль», никаких пояснений про задачу.
- Без наречий частоты в хвосте строк («— почти всегда»): к чему их относить, непонятно.

Длина — сколько нужно, обычно 40–90 строк. Разметка — markdown, заголовки разделов.
Ответ: ТОЛЬКО текст промпта, без предисловий и без объяснений, что ты сделал."""


def бриф(карта, предел=48):
    """Снятые гены с весами и полюсами — то, из чего пишется промпт."""
    геном = карта.get("genome") or {}
    строки = []
    for ид, зн in геном.items():
        if ид not in ПО_ИДЕНТ:
            continue
        ген, блок = ПО_ИДЕНТ[ид]
        значение, увер = float(зн[0]), float(зн[1])
        if not увер:
            continue
        строки.append({
            "блок": блок["name"],
            "шкала": ген["name"],
            "куда": ген["pos"] if значение > 0 else ген["neg"],
            "насколько": round(abs(значение), 2),
            "уверенность": round(увер, 2),
            "вес": round(abs(значение) * увер, 3),
            "смысл": (ген.get("desc") or "")[:400],
        })
    строки.sort(key=lambda x: -x["вес"])
    return строки[:предел]


def улики(карта, сколько=14):
    """Несколько настоящих реплик: по ним видно строй речи."""
    из = (карта.get("meta") or {}).get("samples") or []
    вышло = []
    for s in из[:сколько]:
        т = (s.get("t") if isinstance(s, dict) else str(s or "")).strip()   # create_card пишет реплики строками
        if len(т) > 12:
            вышло.append(т[:220])
    return вышло


def собрать(файл, провайдер="proxyapi", модель="deepseek/deepseek-v3.2"):
    from llm import Client
    путь = pathlib.Path(файл)
    карта = json.loads(путь.read_text(encoding="utf-8"))
    мета = карта.get("meta") or {}
    шкалы = бриф(карта)
    if len(шкалы) < 4:
        raise SystemExit("снято слишком мало шкал (%d) — промпт писать не из чего" % len(шкалы))

    задача = {
        "имя": мета.get("name", ""),
        "вид": мета.get("kind", "персонаж"),
        "произведение": мета.get("src", ""),
        "что известно": mета_описание(мета),
        "снятые шкалы, сильные первыми": шкалы,
        "снято шкал": len(карта.get("genome") or {}),
        "всего шкал": карта.get("genes_total", 0),
        "образцы речи": улики(карта),
    }
    клиент = Client(provider=провайдер, model=модель, timeout=180)
    текст = клиент.chat(ЧТО_ТАКОЕ_ГЕНОМ + "\n\n" + ТРЕБОВАНИЯ,
                        json.dumps(задача, ensure_ascii=False),
                        temperature=0.6, max_tokens=3000)
    текст = (текст or "").strip()
    if len(текст) < 200:
        raise SystemExit("модель вернула слишком короткий ответ")

    карта.setdefault("meta", {})["prompt"] = текст
    карта["meta"]["prompt_by"] = f"{провайдер} · {модель}"
    путь.write_text(json.dumps(карта, ensure_ascii=False, indent=2), encoding="utf-8")
    рядом = путь.with_suffix("").with_suffix(".prompt.md")
    рядом.write_text(текст, encoding="utf-8")
    print(f"промпт собран: {len(текст)} символов, {текст.count(chr(10))+1} строк")
    print("вшит в карточку и записан в", рядом.name)
    print("\n" + "\n".join(текст.splitlines()[:24]))
    return текст


def mета_описание(мета):
    куски = [мета.get("desc") or ""]
    куски += [str(x) for x in (мета.get("identity") or [])[:5]]
    return " ".join(k for k in куски if k)[:1200]


if __name__ == "__main__":
    if len(sys.argv) < 2:
        print("как звать: promptsmith.py <share/файл.genome.json> [провайдер] [модель]")
        raise SystemExit(2)
    цель = pathlib.Path(sys.argv[1])
    if not цель.is_absolute():
        цель = ЗДЕСЬ.parent / цель
    собрать(цель, *(sys.argv[2:4] or []))
