def статус_для(окт: str | None, паттерны: list | None = None) -> str:
    """Куда двигать СВОЙ статус рядом с этим человеком."""
    ключи = {(п or {}).get("ключ") for п in (паттерны or [])}
    if окт in ("давящий", "властный") or {"обесценивание", "срочность"} & ключи:
        return "поднять"
    if окт in ("покорный", "уступчивый") or "самоуничижение" in ключи:
        return "опустить"
    return "ровно"


# ══════════════════════════════════════════════════════════════════
#  ШУТКА КАК МЕХАНИКА (Грег Дин)
#
#  Шутка у Дина устроена жёстко и повторяемо: есть КОННЕКТОР — одна
#  вещь минимум с двумя толкованиями. Сетап ведёт слушателя к первому,
#  ОЖИДАЕМОМУ толкованию (целевое допущение), панч предъявляет второе.
#  Смех — от переключения между ними, а не от «смешных слов».
#
#  Значит шутку можно СТРОИТЬ, а не ждать вдохновения: найти в только
#  что сказанном слово или ситуацию с двойным дном и договорить второе
#  дно. Это и есть техника, про которую спрашивал владелец.
#
#  ГДЕ НЕ ШУТИТЬ — важнее, чем как. Неудачная шутка не нейтральна: она
#  сообщает «мне не всерьёз», и человек это запоминает дольше, чем
#  удачную.
# ══════════════════════════════════════════════════════════════════
