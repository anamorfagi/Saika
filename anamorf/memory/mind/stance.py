def шутка_уместна(окт: str | None, паттерны: list | None = None) -> bool:
    ключи = {(п or {}).get("ключ") for п in (паттерны or [])}
    if окт in ("давящий",) or {"самоуничижение"} & ключи:
        return False
    return True


# ══════════════════════════════════════════════════════════════════
#  ДИСПЕТЧЕР ИНСТРУКЦИЙ — какой рецепт включён прямо сейчас.
#
#  Раньше блоки просто складывались: советы по октанту, по приёмам, по
#  качелям, ступень лестницы — всё разом. На бумаге полно, на деле
#  модель получала восемь указаний одновременно и выполняла их как
#  список, а не как поведение. Человек так не делает: у него в каждый
#  момент ОДНА линия — «не кормить», «осадить», «дать ему ход», — и
#  остальное подстраивается под неё.
#
#  Поэтому выбирается ОДИН рецепт по приоритету, с именем и причиной.
#  Имя и причина не для красоты: их видно в панели, их можно оспорить,
#  и она сама может сказать вслух, чем сейчас руководствуется, если
#  спросят. Горячая замена — это смена рецепта между ходами, а не
#  подмешивание ещё одного совета к семи прежним.
#
#  ПОРЯДОК ВАЖНЕЕ СПИСКА. Сначала то, что отменяет остальное: если
#  разговор холостой, тонкости стиля уже не работают. Потом защита.
#  Потом коррекция перекоса. В конце — обычная жизнь.
