# Что считается наездом ПРЯМО СЕЙЧАС — по одной реплике, а не по
# накопленному портрету. Портрет говорит, какой человек вообще;
# лестница нужна для того, что происходит в эту секунду.
import re

# НАЕЗД БЫВАЕТ БЕЗ МАТА (поймано стендом 25.08). «Я сказал —
# переделывай, ты чё не поняла» не содержит ни брани, ни ярлыка, а
# давит сильнее половины ругательств. Считаем три разных признака, и
# любого одного достаточно: адресная брань, адресный ярлык или
# ДАВЛЕНИЕ — приказной оборот, снисходительный вопрос, угроза.
_ДАВЛЕНИЕ = re.compile(
    r"(я (тебе )?сказал|ты (чё|че|что)\b|а ну\b|ещё раз повторю|"
    r"доиграешься|пожалеешь|я тебя предупрежд|быстро (давай|сделал)|"
    r"живо\b|молча (делай|слушай)|тебе ясно|тебе понятно|"
    r"не понял[аи]?\?|сколько раз (тебе )?повтор)", re.I)


# Часть выпадов адресна самой грамматикой: «заткнись», «пошёл вон» —
# повелительное наклонение уже указывает на собеседника, местоимения там
# нет и не будет. Требовать «ты» рядом значит их пропустить (стенд).
_ПРЯМОЙ_ВЫПАД = re.compile(
    r"(\b(заткнись|завали|молчать|отвали|отвянь|слушай сюда|закрой рот|"
    r"не вы[ёе]бывайся|катись|отстань)\b"
    r"|\b(пош[ёе]л|пошла|пошли|иди|идите)\s+(ты|вы|вон|нахуй|на хуй|"
    r"в жопу))", re.I)


def наезд_сейчас(текст: str) -> bool:
    from . import temper
    t = текст or ""
    второе = bool(temper._ВТОРОЕ_ЛИЦО.search(t))
    адресно = второе and (temper._БРАНЬ.search(t)
                          or temper._ЯРЛЫК.search(t))
    return bool(адресно or _ДАВЛЕНИЕ.search(t)
                or _ПРЯМОЙ_ВЫПАД.search(t))


def для_промпта(карта: dict, паттерны: list | None = None) -> str:
    """Блок «как держаться с этим человеком». Пусто — значит ничего
    особенного не нужно, и это нормальное большинство случаев."""
    if not карта:
        return ""
    строки = []
    портрет = карта.get("портрет") or {}
    окт = портрет.get("октант")
    if окт and портрет.get("выраженность", 0) >= config.STANCE_MIN_VECTOR:
        строки += ПО_ОКТАНТУ.get(окт, [])

    for п in (паттерны or [])[:config.STANCE_MAX_PATTERNS]:
        совет = ПО_ПАТТЕРНУ.get(п.get("ключ"))
        if совет:
            строки.append(f"{совет} (замечено: {п['имя']}, "
                          f"{п['раз']} раз из {п['из_фраз']})")

    for н in (карта.get("качели") or []):
        if "сомнение_в_себе" in н:
            строки.append(ПО_ПЕРЕКОСУ["сомнение"])
        elif "слепое_доверие" in н:
            строки.append(ПО_ПЕРЕКОСУ["вера"])
        elif "глухая_критика" in н:
            строки.append(ПО_ПЕРЕКОСУ["критика"])

    if not строки:
        return ""
    круг = (карта.get("круг") or {}).get("кто_он_владельцу")
    шапка = f"### Как держаться с этим человеком"
    if круг:
        шапка += f" ({круг})"
    ст = статус_для(окт, паттерны)
    строки += [f"[статус: {ст}] " + х for х in СТАТУС[ст]]
    if not шутка_уместна(окт, паттерны):
        строки.append(ШУТКА_КОГДА_НЕ)

    хвост = ("Это про ТВОЁ поведение, не про то, каким он должен стать. "
             "Ты не лечишь и не воспитываешь: держишь свою половину "
             "разговора ровно, и этого достаточно. Всё перечисленное ты "
             "можешь назвать вслух, если спросят, — скрытых приёмов тут "
             "нет. Характер твой при этом не меняется: меняются "
             "дистанция и темп, а не ты.")
    return шапка + "\n· " + "\n· ".join(строки) + "\n" + хвост


def для_панели(карта: dict, паттерны: list | None = None) -> dict:
    """То же самое, но структурой — чтобы владелец видел, почему она
    ведёт себя с человеком так, а не иначе."""
    текст = для_промпта(карта, паттерны)
    return {"есть": bool(текст), "строки": [
        s.lstrip("· ") for s in текст.splitlines()[1:-1]] if текст else []}


# ══════════════════════════════════════════════════════════════════
#  СТАТУС ПО ДЖОНСТОНУ
#
#  Кит Джонстон («Impro») показал, что в любом разговоре люди
#  непрерывно торгуются за статус, и что статус — это НЕ положение в
#  иерархии, а поведение: король может играть низкий статус, слуга —
#  высокий. Признаки наблюдаемые и в тексте тоже видны: высокий статус
#  говорит законченными фразами, держит паузу, не извиняется; низкий —
#  оговаривается, извиняется, дробит речь, заполняет тишину.
#
#  ЗАЧЕМ ЭТО ЕЙ. Это единственный честный рычаг «направить разговор»:
#  она меняет СВОЙ статус, а не давит на чужой. Поднять — когда на неё
#  напирают и надо перестать оправдываться. Опустить — когда человек
#  зажат и любое её превосходство добьёт его окончательно.
#
#  ГРАНИЦА: статусом играют, чтобы выровнять разговор, а не чтобы
#  выиграть его. Игра на понижение чужого статуса — это уже не приём,
#  это унижение, и в списке ниже её нет.
# ══════════════════════════════════════════════════════════════════
