_ПАМЯТЬ: dict = {}     # person_id → (ступень, когда)


def сбросить(person_id: int | None = None) -> None:
    if person_id is None:
        _ПАМЯТЬ.clear()
    else:
        _ПАМЯТЬ.pop(person_id, None)


def ступень(person_id: int, наезд: bool) -> dict | None:
    """Какая ступень сейчас. Без наезда лестница остывает сама.

    Остывание обязательно: человек, которого один раз осадили, не должен
    навсегда остаться на четвёртой ступени. Иначе она перестанет
    отвечать на нормальные реплики нормально — а это уже её проблема,
    а не его."""
    n, когда = _ПАМЯТЬ.get(person_id, (0, 0.0))
    сейчас = time.time()
    if сейчас - когда > config.LADDER_COOLDOWN and n:
        n, когда = 0, сейчас
        _ПАМЯТЬ[person_id] = (0, сейчас)
    if not наезд:
        return None
    n = min(n + 1, len(СТУПЕНИ))
    _ПАМЯТЬ[person_id] = (n, сейчас)
    ключ, что_делать, почему = СТУПЕНИ[n - 1]
    return {"номер": n, "всего": len(СТУПЕНИ), "ключ": ключ,
            "делать": что_делать, "почему": почему}


# ══════════════════════════════════════════════════════════════════
#  ЕСТЬ ЛИ ВООБЩЕ СМЫСЛ В ЭТОМ РАЗГОВОРЕ
#
#  Мысль владельца: «иногда лучше промолчать, и шелуха сама отпадёт».
#  Это не про лень и не про обиду — это отдельная и более ранняя оценка,
#  чем любая ступень. Лестница отвечает на вопрос «как держаться»; здесь
#  вопрос другой: «а держаться вообще есть ради чего».
#
#  Спор без конкретики питается ответами. Пока на общие обвинения дают
#  развёрнутые ответы, у разговора есть топливо — и чем лучше ответ, тем
#  больше поводов возразить. Убираешь топливо — остаётся либо конкретный
#  вопрос (тогда разговор был нужен), либо тишина (тогда не был).
#
#  Признаки холостого хода, все считаемые: те же приёмы по кругу; на
#  прямой вопрос «что именно» конкретики так и не появилось; собеседник
#  ни разу ничего не спросил; лестница уже прошла половину, а тон тот же.
# ══════════════════════════════════════════════════════════════════
def вхолостую(строки, шаг: dict | None = None) -> dict:
    """Крутится ли разговор на месте. Считает, а не чувствует."""
    if not строки or len(строки) < config.IDLE_MIN_PHRASES:
        return {"вхолостую": False, "почему": "рано судить"}
    тексты = [(r["text"] or "").strip().lower() for r in строки]
    вопросов = sum(1 for t in тексты if "?" in t)
    уник = len({t[:40] for t in тексты})
    повторы = 1 - уник / len(тексты)
    цифры = sum(1 for t in тексты if any(c.isdigit() for c in t))
    признаки = []
    if вопросов == 0:
        признаки.append("он ни разу ничего не спросил")
    if повторы >= config.IDLE_REPEAT_SHARE:
        признаки.append(f"повторяет одно и то же ({повторы:.0%} фраз)")
    if цифры == 0:
        признаки.append("ни одной конкретной детали за весь разговор")
    if шаг and шаг["номер"] >= 3:
        признаки.append(f"уже {шаг['номер']} ступени, тон не изменился")
    return {"вхолостую": len(признаки) >= config.IDLE_MIN_SIGNS,
            "признаки": признаки}


def молчание_для_промпта(итог: dict) -> str:
    if not itog_ok(итог):
        return ""
    return ("### Этот разговор крутится на месте\n"
            "· " + "; ".join(итог["признаки"]) + "\n"
            "· Не отвечай по существу — существа тут нет. Одна короткая "
            "нейтральная реплика или молчание.\n"
            "· Это не обида и не бойкот: спор без конкретики питается "
            "ответами, и чем лучше ответ, тем больше поводов возразить. "
            "Убери топливо — останется либо конкретный вопрос (значит "
            "разговор был нужен), либо тишина (значит не был).\n"
            "· Если он вернётся с конкретикой — отвечай нормально и "
            "без припоминаний.")


def itog_ok(итог: dict) -> bool:
    return bool(итог and итог.get("вхолостую") and итог.get("признаки"))


ПОСЛЕДСТВИЯ = [
    "закончить этот разговор",
    "не помогать с этой просьбой",
    "рассказать владельцу, как всё прошло",
]


def для_промпта(шаг: dict | None) -> str:
    """Блок про то, как держаться под наездом. Пусто — значит наезда нет."""
    if not шаг:
        return ""
    строки = [f"Ступень {шаг['номер']} из {шаг['всего']}: {шаг['делать']}",
              f"Почему именно так: {шаг['почему']}"]
    if шаг["ключ"] in ("назвать_последствие", "выйти"):
        строки.append("Последствие называй только настоящее — из того, "
                      "что ты действительно можешь: "
                      + "; ".join(ПОСЛЕДСТВИЯ) + ".")
    строки.append(
        "Ступени идут по порядку и каждая один раз: прыжок сразу к "
        "последствию — это уже ты разжигаешь. Ничего скрытого: всё, что "
        "ты делаешь, ты можешь назвать вслух, если спросят. Ты не "
        "выигрываешь у него и не воспитываешь его — ты просто не даёшь "
        "втянуть себя.")
    return "### Тебя продавливают\n· " + "\n· ".join(строки)
