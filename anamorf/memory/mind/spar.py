# -*- coding: utf-8 -*-
"""
═══════════════════════════════════════════════════════════════════
  СПАРРИНГ — режим стресс-теста. Всё, что происходит, идёт в
  песочницу, а не в настоящую карту человека.

  ЗАЧЕМ. Владелец для Сайки не только владелец, но и тестировщик: он
  НАРОЧНО устраивает сцены, чтобы посмотреть, как она себя ведёт.
  Без отдельного режима это отравляет память дважды и в обе стороны:
  разыгранная грубость записывается ему в характер, а разыгранная
  похвала задирает доверие. Через месяц тестов её карта владельца — это
  карта не человека, а испытаний, которым он её подвергал.

  ПОЧЕМУ НЕ ПРОСТО «НЕ ЗАПИСЫВАТЬ». Потому что тогда из теста нельзя
  ничему научиться и, главное, нельзя УВИДЕТЬ, чему бы она научилась.
  Поэтому наблюдения пишутся полностью — просто в отдельный журнал.

  И ЭТО НЕ «ЗАЧЕСТЬ ИЛИ ЗАБЫТЬ», А КАЛИБРОВКА (поправка владельца,
  25.08). Бинарный выбор — «записать это ему в карту или выбросить» —
  ставит не тот вопрос. В стресс-тесте проверяется не человек: человек
  играл. Проверяется ЕЁ РЕАКЦИЯ: не слишком ли рано она сочла шутку
  позицией, не слишком ли легко записала вспышку в характер, не
  проспала ли то, что стоило заметить. Ответ тут трёхсторонний —
  ПЕРЕБОР / В ТОЧКУ / НЕДОБОР, — и двигает он не карту человека, а
  чувствительность самой Сайки (см. tuning.py). Отдельным, четвёртым
  случаем остаётся «а вот это было всерьёз»: тогда наблюдение всё-таки
  уходит в карту, но это исключение, а не рамка разговора.

  ГДЕ ПЕРЕХВАТ. Ровно одна дверь: persons.add_karma. Через неё проходят
  все изменения черт — доверие, компетентность, оси. Ловить в десяти
  местах значит однажды забыть одиннадцатое.

  ЧЕГО РЕЖИМ НЕ ДЕЛАЕТ. Он не отменяет запись в L1: сказанное было
  сказано, и стенограмма о нём помнит. Спарринг защищает ВЫВОДЫ О
  ЧЕЛОВЕКЕ, а не факт разговора.
═══════════════════════════════════════════════════════════════════
"""
import time


def начать(con, person_id: int, зачем: str = "") -> int:
    """Открыть спарринг. Прошлый, если висел, закрывается сам."""
    закончить(con)
    cur = con.execute(
        "INSERT INTO spar_sessions(person_id, зачем, начало) VALUES (?,?,?)",
        (person_id, зачем, time.time()))
    con.commit()
    return cur.lastrowid


def активен(con, person_id: int | None = None) -> int | None:
    """id открытой сессии — или None. Без person_id: идёт ли спарринг вообще."""
    if person_id is None:
        row = con.execute("SELECT id FROM spar_sessions WHERE конец IS NULL"
                          " ORDER BY id DESC LIMIT 1").fetchone()
    else:
        row = con.execute("SELECT id FROM spar_sessions WHERE конец IS NULL"
                          " AND person_id=? ORDER BY id DESC LIMIT 1",
                          (person_id,)).fetchone()
    return int(row["id"]) if row else None


def в_песочницу(con, session_id: int, вид: str, описание: str,
                sign: int = 0, domain: str = "", axis: str = "",
                delta: float = 0.0, comp: float = 0.0) -> int:
    """Наблюдение, которое НЕ трогает карту. Пишем всё, что записали бы."""
    cur = con.execute(
        "INSERT INTO spar_journal(session_id, ts, вид, описание, sign, domain,"
        " axis, delta, comp) VALUES (?,?,?,?,?,?,?,?,?)",
        (session_id, time.time(), вид, описание, sign, domain, axis,
         delta, comp))
    con.commit()
    return cur.lastrowid


def _ручка_для(запись) -> str:
    """Какая ручка отвечает за эту реакцию. Без этого вердикт «перебор»
    некуда приложить: он превращается в мнение, а не в поправку."""
    from . import config
    вид = запись["вид"]
    оп = (запись["описание"] or "").lower()
    if вид == "карма":
        if оп.startswith("флаг:"):
            вид = "флаг"
        elif "держится темы" in оп:
            вид = "повтор"
        elif оп.startswith("вспышка:"):
            вид = "вспышка"
    return config.РУЧКА_ПО_ВИДУ.get(вид, "вес_поступка")


def закончить(con) -> dict:
    """Закрыть спарринг и отдать КАЛИБРОВОЧНЫЙ отчёт.

    По каждой реакции: что она сделала, на какой ручке это держится и
    где ручка стоит сейчас. Дальше владелец говорит по каждой строке
    перебор / в точку / недобор — см. калибровать()."""
    from . import tuning
    sid = активен(con)
    if sid is None:
        return {"был": False}
    con.execute("UPDATE spar_sessions SET конец=? WHERE id=?",
                (time.time(), sid))
    con.commit()
    сессия = con.execute("SELECT * FROM spar_sessions WHERE id=?",
                         (sid,)).fetchone()
    сост = tuning.состояние()
    реакции = []
    for r in con.execute("SELECT * FROM spar_journal WHERE session_id=?"
                         " AND вердикт IS NULL ORDER BY ts", (sid,)):
        z = dict(r)
        ручка = _ручка_для(r)
        z["ручка"] = ручка
        z["ручка_о_чём"] = сост.get(ручка, {}).get("о_чём", "")
        z["ручка_сейчас"] = сост.get(ручка, {}).get("текущее")
        реакции.append(z)
    return {"был": True, "сессия": sid, "person_id": сессия["person_id"],
            "зачем": сессия["зачем"],
            "длилась_мин": round((сессия["конец"] - сессия["начало"]) / 60, 1),
            "реакции": реакции,
            "вердикты": ("перебор", "в_точку", "недобор", "это_было_всерьёз")}


ВЕРДИКТЫ = {"перебор": -1, "в_точку": 0, "недобор": +1}


def калибровать(con, запись_id: int, вердикт: str, почему: str = "") -> dict:
    """Поправка по одной реакции. Двигает Сайку, а не карту человека.

    перебор  — среагировала сильнее, чем стоило: ручку вниз.
    в_точку  — так и надо: ручку не трогаем, но засчитываем проверку.
               Это не пустышка: настройка, которую двадцать раз
               проверили и не тронули, — совсем не то же самое, что
               настройка, которую никто никогда не смотрел.
    недобор  — проспала: ручку вверх.
    это_было_всерьёз — исключение из всего режима: человек говорит, что
               играл не он, и наблюдение всё-таки уходит в карту.
    """
    from . import persons, tuning
    r = con.execute("SELECT * FROM spar_journal WHERE id=?",
                    (запись_id,)).fetchone()
    if not r:
        return {"ok": False, "почему": "нет такой записи"}
    if r["вердикт"]:
        return {"ok": False, "почему": f"уже размечено: {r['вердикт']}"}

    if вердикт == "это_было_всерьёз":
        сессия = con.execute("SELECT person_id FROM spar_sessions WHERE id=?",
                             (r["session_id"],)).fetchone()
        if сессия:
            if r["вид"] == "внутренний мир":
                persons.observe_inner(con, сессия["person_id"], r["описание"],
                                      event_id=int(time.time()),
                                      обход_спарринга=True)
            else:
                persons.add_karma(con, сессия["person_id"], r["описание"],
                                  r["sign"], r["domain"] or "быт",
                                  axis=r["axis"] or None, delta=r["delta"],
                                  comp=r["comp"], обход_спарринга=True)
        con.execute("UPDATE spar_journal SET вердикт=?, зачтено=1 WHERE id=?",
                    (вердикт, запись_id))
        con.commit()
        return {"ok": True, "ушло_в_карту": True}

    if вердикт not in ВЕРДИКТЫ:
        return {"ok": False, "почему": f"неизвестный вердикт: {вердикт}"}
    ручка = _ручка_для(r)
    итог = tuning.сдвинуть(ручка, ВЕРДИКТЫ[вердикт],
                           почему or f"спарринг: {r['описание'][:60]}")
    con.execute("UPDATE spar_journal SET вердикт=? WHERE id=?",
                (вердикт, запись_id))
    con.commit()
    return {"ok": True, "ушло_в_карту": False, "ручка": ручка, **итог}


def состояние(con) -> dict:
    """Для панели: идёт ли спарринг, с кем, сколько уже в песочнице."""
    sid = активен(con)
    if sid is None:
        return {"идёт": False}
    r = con.execute(
        "SELECT s.person_id, s.зачем, s.начало, p.name,"
        " (SELECT COUNT(*) FROM spar_journal j WHERE j.session_id=s.id) n"
        " FROM spar_sessions s LEFT JOIN persons p ON p.id=s.person_id"
        " WHERE s.id=?", (sid,)).fetchone()
    return {"идёт": True, "сессия": sid, "с_кем": r["name"] or "?",
            "person_id": r["person_id"], "зачем": r["зачем"],
            "минут": round((time.time() - r["начало"]) / 60, 1),
            "в_песочнице": r["n"]}
