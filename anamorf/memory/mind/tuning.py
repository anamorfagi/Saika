# -*- coding: utf-8 -*-
"""
═══════════════════════════════════════════════════════════════════
  НАСТРОЙКА — то, чему её научили, отдельно от того, с чем родилась.

  РАЗДЕЛЕНИЕ, РАДИ КОТОРОГО ЭТОТ ФАЙЛ И ЕСТЬ. В config.py лежат
  УМОЛЧАНИЯ: с этими числами она приходит из коробки. Здесь лежат
  СДВИГИ: результат того, что владелец её калибровал. Смешивать нельзя
  по двум причинам. Обновление кода перезапишет config.py и сотрёт всё
  нажитое. И, что важнее, без разделения нельзя ответить на вопрос
  «а какой она была изначально» — а этот вопрос однажды понадобится.

  ПОЧЕМУ КАЛИБРОВКА, А НЕ «ЗАЧЕСТЬ ИЛИ ЗАБЫТЬ». Владелец устраивает
  стресс-тест не для того, чтобы решить, записывать ли ему в карту
  разыгранное хамство. Он смотрит НА ЕЁ РЕАКЦИЮ: не слишком ли рано
  она сочла шутку позицией, не слишком ли легко записала вспышку в
  характер. Ответ тут не «да/нет», а «перебор / в точку / недобор» —
  и он двигает не карту человека, а чувствительность самой Сайки.

  ТРИ ПРЕДОХРАНИТЕЛЯ, ЧТОБЫ ЭТО НЕ ПРЕВРАТИЛОСЬ В РАСКАЧКУ

  1. Шаг мелкий. Один тест не имеет права перекрутить ручку: характер,
     который перестраивается с одного разговора, — это не характер.
  2. Пределы жёсткие. Ручку нельзя увести туда, где механика ломается.
  3. Журнал вечный. Каждый сдвиг записан с причиной, и «в точку» тоже:
     подтверждение — такие же данные, как поправка, просто без движения.
═══════════════════════════════════════════════════════════════════
"""
import json
import time
from . import config


def _файл():
    return config.DATA_DIR / "tuning.json"


def _журнал():
    return config.DATA_DIR / "tuning.log"


def _читать() -> dict:
    try:
        return json.loads(_файл().read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {"версия": 1, "ручки": {}}


def _писать(д: dict) -> None:
    config.DATA_DIR.mkdir(parents=True, exist_ok=True)
    _файл().write_text(json.dumps(д, ensure_ascii=False, indent=2),
                       encoding="utf-8")


def _в_журнал(запись: dict) -> None:
    config.DATA_DIR.mkdir(parents=True, exist_ok=True)
    with open(_журнал(), "a", encoding="utf-8") as f:
        f.write(json.dumps(запись, ensure_ascii=False) + "\n")


def родное(имя: str):
    """Значение, с которым она родилась (из config.py)."""
    р = config.РУЧКИ.get(имя)
    return getattr(config, р["конст"]) if р else None


def применить() -> dict:
    """Накатить сохранённые сдвиги поверх умолчаний. Зовётся при старте.

    Отдельным шагом, а не при каждом чтении: константы читаются из
    горячих мест (миндалина трогает их на каждую фразу), и ходить туда
    за файлом было бы честно, но глупо."""
    д = _читать()
    накатано = {}
    for имя, сост in (д.get("ручки") or {}).items():
        р = config.РУЧКИ.get(имя)
        if not р or "значение" not in сост:
            continue
        setattr(config, р["конст"], сост["значение"])
        накатано[имя] = сост["значение"]
    return накатано


def состояние() -> dict:
    """Что где стоит: родное значение, текущее, сколько раз двигали."""
    д = _читать()
    out = {}
    for имя, р in config.РУЧКИ.items():
        сост = (д.get("ручки") or {}).get(имя, {})
        текущее = getattr(config, р["конст"])
        out[имя] = {"о_чём": р["о_чём"], "константа": р["конст"],
                    "текущее": текущее,
                    "родное": сост.get("родное", текущее),
                    "сдвигов": сост.get("сдвигов", 0),
                    "подтверждений": сост.get("подтверждений", 0),
                    "мин": р["мин"], "макс": р["макс"]}
    return out


def сдвинуть(имя: str, направление: int, почему: str = "") -> dict:
    """направление: +1 «реагируй сильнее», −1 «реагируй слабее», 0 «в точку».

    Ноль — не пустышка: он записывает, что ручку проверили и она
    подошла. Настройка, у которой нет подтверждений, отличается от
    настройки, которую двадцать раз проверили и не тронули, — а по
    одному числу их не различить."""
    р = config.РУЧКИ.get(имя)
    if not р:
        return {"ok": False, "почему": f"нет такой ручки: {имя}"}
    д = _читать()
    ручки = д.setdefault("ручки", {})
    сост = ручки.setdefault(имя, {})
    было = getattr(config, р["конст"])
    сост.setdefault("родное", было)

    if направление == 0:
        сост["подтверждений"] = сост.get("подтверждений", 0) + 1
        сост["значение"] = было
        _писать(д)
        _в_журнал({"ts": time.time(), "ручка": имя, "вердикт": "в_точку",
                   "значение": было, "почему": почему})
        return {"ok": True, "двинулось": False, "значение": было,
                "подтверждений": сост["подтверждений"]}

    шаг = р["шаг"] * (1 if направление > 0 else -1) * р["к_сильнее"]
    стало = было + шаг
    стало = max(р["мин"], min(р["макс"], стало))
    стало = round(стало, 4) if isinstance(было, float) else int(round(стало))
    setattr(config, р["конст"], стало)
    сост["значение"] = стало
    сост["сдвигов"] = сост.get("сдвигов", 0) + 1
    _писать(д)
    _в_журнал({"ts": time.time(), "ручка": имя,
               "вердикт": "сильнее" if направление > 0 else "слабее",
               "было": было, "стало": стало, "почему": почему})
    return {"ok": True, "двинулось": стало != было, "было": было,
            "стало": стало, "сдвигов": сост["сдвигов"],
            "упёрлась": стало == было}


def задать(имя: str, значение, почему: str = "") -> dict:
    """Поставить ручку в конкретное значение (ползунки в панели)."""
    р = config.РУЧКИ.get(имя)
    if not р:
        return {"ok": False, "почему": f"нет такой ручки: {имя}"}
    было = getattr(config, р["конст"])
    стало = max(р["мин"], min(р["макс"], float(значение)))
    стало = round(стало, 4) if isinstance(было, float) else int(round(стало))
    д = _читать()
    сост = д.setdefault("ручки", {}).setdefault(имя, {})
    сост.setdefault("родное", было)
    сост["значение"] = стало
    setattr(config, р["конст"], стало)
    _писать(д)
    _в_журнал({"ts": time.time(), "ручка": имя, "вердикт": "задано",
               "было": было, "стало": стало, "почему": почему})
    return {"ok": True, "было": было, "стало": стало}


def сброс(имя: str | None = None) -> dict:
    """Вернуть ручку (или всё) к тому, с чем она родилась.

    Файл не стирается: журнал переживает сброс. Забыть, что калибровка
    была, — значит потерять единственный след того, как её настраивали."""
    д = _читать()
    ручки = д.get("ручки") or {}
    цели = [имя] if имя else list(ручки)
    вернули = {}
    for и in цели:
        р, сост = config.РУЧКИ.get(и), ручки.get(и)
        if not р or not сост:
            continue
        родн = сост.get("родное")
        if родн is None:
            continue
        setattr(config, р["конст"], родн)
        сост["значение"] = родн
        сост["сдвигов"] = 0
        вернули[и] = родн
        _в_журнал({"ts": time.time(), "ручка": и, "вердикт": "сброс",
                   "стало": родн})
    _писать(д)
    return {"ok": True, "вернули": вернули}


def история(последних: int = 40) -> list[dict]:
    try:
        строки = _журнал().read_text(encoding="utf-8").splitlines()
    except OSError:
        return []
    out = []
    for s in строки[-последних:]:
        try:
            out.append(json.loads(s))
        except ValueError:
            continue
    return out
