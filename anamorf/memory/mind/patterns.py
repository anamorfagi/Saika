# -*- coding: utf-8 -*-
"""
═══════════════════════════════════════════════════════════════════
  ПАТТЕРНЫ РЕЧИ — что человек делает В РАЗГОВОРЕ, повторяясь.

  ЧЕГО ЗДЕСЬ НЕТ И НЕ БУДЕТ: ДИАГНОЗОВ.

  Владелец просил «посмотреть, есть ли психологические отклонения».
  Этого файл не делает и делать не должен, и причина не в осторожности,
  а в том, что так не работает. Диагноз ставится очно, по критериям, с
  историей и исключением других причин — по репликам в микрофон его не
  ставит ни один специалист. Зато ярлык, единожды прилипший, меняет всё
  последующее: человека начинают читать через него, и любое его слово
  подтверждает то, что уже решили. Система, которая «видит отклонения»,
  не защищает владельца — она делает его слепым.

  ЧТО ФАЙЛ ДЕЛАЕТ ВМЕСТО ЭТОГО. Считает НАБЛЮДАЕМЫЕ ПРИЁМЫ РЕЧИ. Не
  «он нарцисс», а «в каждой пятой фразе обесценивает собеседника». Не
  «у него расстройство», а «требует срочности и не оставляет времени
  подумать». Разница практическая: приём виден, поддаётся счёту,
  оспаривается и — главное — ПРЕКРАЩАЕТСЯ, если человек передумал.
  Диагноз не прекращается никогда.

  Каждый паттерн несёт: сколько раз, из скольких фраз, пример своими
  словами и что с этим делать в разговоре (см. stance.py).
═══════════════════════════════════════════════════════════════════
"""
import re
from . import config

# (ключ, живое имя, регулярка, что это значит на практике)
ПАТТЕРНЫ = [
    ("обесценивание", "обесценивает",
     r"(ты (не понима|не шариш|не тян)|это (ерунд|фигн|бред|чушь)|"
     r"любой (дурак|идиот)|детский сад|что тут сложного|я же говорил)",
     "принижает собеседника или его слова"),
    ("перекладывание", "переводит стрелки",
     r"(из-за тебя|это ты меня|ты сам виноват|ты меня довёл|ты меня довел|"
     r"я(?: бы)? не (стал|начал) если бы (ты|вы))",
     "свои действия объясняет чужими"),
    ("абсолюты", "говорит абсолютами",
     r"\b(всегда|никогда|все они|никто не|вечно ты|как обычно ты|"
     r"ни разу не)\b",
     "«всегда» и «никогда» вместо конкретного случая"),
    ("срочность", "давит срочностью",
     r"(прямо сейчас|немедленно|срочно|быстро (реши|сделай|отвечай)|"
     r"некогда думать|решай сейчас же)",
     "не оставляет времени подумать"),
    ("идеализация", "идеализирует",
     r"(только ты (меня )?понима|ты лучш(ий|ая)|ты единствен|"
     r"без тебя (я )?никак|ты не такая как)",
     "поднимает собеседника на пьедестал"),
    ("самоуничижение", "принижает себя",
     r"(я (ничтожеств|никчём|никчем|тупой|дурак|бездар)|"
     r"из меня ничего|я вечно всё порчу|я всё порчу|со мной невозможно)",
     "говорит о себе так, как не сказал бы о другом"),
    ("монополия", "не отдаёт ход",
     None,      # считается не словами, а длиной монолога
     "говорит подряд, не оставляя места собеседнику"),
    ("качели_тона", "тон гуляет",
     None,      # считается по разбросу эмоции
     "внутри одного разговора резко меняет настроение"),
]

_СОБРАНО = [(к, имя, re.compile(rx, re.I) if rx else None, что)
            for к, имя, rx, что in ПАТТЕРНЫ]


def найти(строки) -> list[dict]:
    """Приёмы, которые человек повторяет. Единичное не считается: один
    раз сорваться может кто угодно, и называть это приёмом — то же
    самое враньё, что и диагноз, только помельче."""
    if not строки or len(строки) < config.PATTERN_MIN_PHRASES:
        return []
    n = len(строки)
    счёт, примеры = {}, {}
    подряд, лучший_подряд = 0, 0
    эмоции = []
    for r in строки:
        t = r["text"] or ""
        эмоции.append(float(r["emotion"] or 0))
        for к, имя, rx, что in _СОБРАНО:
            if rx and rx.search(t):
                счёт[к] = счёт.get(к, 0) + 1
                примеры.setdefault(к, t[:90])
        # монолог: считаем как «сколько фраз подряд без вопроса»
        if "?" in t:
            подряд = 0
        else:
            подряд += 1
            лучший_подряд = max(лучший_подряд, подряд)

    if лучший_подряд >= config.PATTERN_MONOLOGUE:
        счёт["монополия"] = лучший_подряд
        примеры["монополия"] = f"{лучший_подряд} фраз подряд без вопроса"
    if len(эмоции) > 2:
        ср = sum(эмоции) / len(эмоции)
        разброс = (sum((e - ср) ** 2 for e in эмоции) / len(эмоции)) ** 0.5
        if разброс >= config.PATTERN_MOOD_SWING:
            счёт["качели_тона"] = round(разброс * 100)
            примеры["качели_тона"] = f"разброс заряда {разброс:.2f}"

    out = []
    for к, имя, rx, что in _СОБРАНО:
        c = счёт.get(к, 0)
        if not c:
            continue
        доля = c / n if rx else None
        if rx and доля < config.PATTERN_MIN_SHARE:
            continue                       # разовое — не приём
        out.append({"ключ": к, "имя": имя, "что_это": что, "раз": c,
                    "из_фраз": n,
                    "доля": round(доля, 3) if доля is not None else None,
                    "пример": примеры.get(к, "")})
    out.sort(key=lambda x: -(x["доля"] or 0))
    return out


def сводка(con, person_id: int, окно: int | None = None) -> dict:
    строки = con.execute(
        "SELECT text, emotion FROM raw_events WHERE person_id=?"
        " ORDER BY ts DESC LIMIT ?",
        (person_id, окно or config.PATTERN_WINDOW)).fetchall()
    найдено = найти(строки)
    return {
        "паттерны": найдено,
        "это_не_диагноз":
            "это приёмы речи, а не свойства человека и тем более не "
            "диагноз. Приём можно посчитать, оспорить и прекратить; "
            "диагноз по репликам в микрофон не ставится вообще.",
    }
