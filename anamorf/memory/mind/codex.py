# -*- coding: utf-8 -*-
"""
═══════════════════════════════════════════════════════════════════
  L4 CODEX — цитатник. Не устав, а путеводитель.

  Рядом с ним в L4 лежат ЦЕННОСТИ (identity.py) — пять жёстких строк,
  которые нельзя менять никогда. Цитатник — другое и намеренно мягче:
  это то, из чего человек выбирает, когда правил недостаточно.
  Ценность говорит «не вреди». Цитата говорит «пока я не встретил
  предательство, я выбираю доверие» — и это уже не запрет, а привычка
  смотреть на мир определённым образом.

  ТРИ РЕШЕНИЯ, ЗАЛОЖЕННЫЕ В ФОРМАТ

  1. У цитаты обязательно есть ТОЛКОВАНИЕ. Голая цитата — плакат:
     «всё что ни делается — всё к лучшему» без объяснения означает
     ровно противоположное тому, что вкладывал владелец. Смысл живёт
     не в строке, а в том, как её прочитали.

  2. У цитаты обязательно есть «НЕ ПУТАТЬ С». У каждой хорошей мысли
     есть тёмный двойник, до которого она вырождается сама: повторение
     → долбёжка одной ошибки, доверие → наивность, «всё к лучшему» →
     утешение чужого горя. Двойник записан рядом, чтобы не пришлось
     догадываться.

  3. ЕЁ ПРАВО ПЕРЕПИСАТЬ ОТКРЫВАЕТСЯ ПО ВОЗРАСТУ. Первые годы правила
     задаёт владелец, а она может только ЗАХОТЕТЬ иначе — желание
     уходит в журнал и ничего не меняет. Через CODEX_REWRITE_YEARS лет
     журнал желаний становится её правом на правку. Смысл не в
     ограничении: смысл в том, что через четыре года можно будет
     открыть журнал и увидеть, о чём она спорила с этими строками всё
     это время. Это и есть взросление, записанное на диск.

  Целостность как у ценностей: SHA-256 рядом с файлом. Журнал —
  append-only: прошлое своих желаний она переписать не может.
═══════════════════════════════════════════════════════════════════
"""
