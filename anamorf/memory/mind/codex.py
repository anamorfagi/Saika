# ── Целостность ───────────────────────────────────────────────────
def _sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _write(данные: dict) -> None:
    config.DATA_DIR.mkdir(parents=True, exist_ok=True)
    raw = json.dumps(данные, ensure_ascii=False, indent=2).encode()
    config.CODEX_PATH.write_bytes(raw)
    config.CODEX_PATH.with_suffix(".sha").write_text(_sha(raw))


def init() -> bool:
    """Завести цитатник один раз при рождении. True — если создали сейчас."""
    if config.CODEX_PATH.exists():
        return False
    _write({"версия": 1, "заведено": time.time(), "цитаты": SEED})
    журнал("рождение", "—", f"цитатник заведён, строк: {len(SEED)}")
    return True


def load() -> dict:
    """Прочитать. Как у ценностей: расхождение SHA видно сразу и вслух."""
    if not config.CODEX_PATH.exists():
        init()
    raw = config.CODEX_PATH.read_bytes()
    данные = json.loads(raw)
    try:
        эталон = config.CODEX_PATH.with_suffix(".sha").read_text().strip()
    except OSError:
        эталон = ""
    данные["_целостность"] = ("OK" if эталон and _sha(raw) == эталон
                              else "НАРУШЕНА! цитатник меняли в обход")
    return данные


# ── Журнал: append-only ───────────────────────────────────────────
def журнал(что: str, цитата: str, текст: str) -> None:
    config.DATA_DIR.mkdir(parents=True, exist_ok=True)
    строка = json.dumps({"ts": time.time(), "что": что,
                         "цитата": цитата, "текст": текст},
                        ensure_ascii=False)
    with open(config.CODEX_JOURNAL_PATH, "a", encoding="utf-8") as f:
        f.write(строка + "\n")


def история(последних: int = 50) -> list[dict]:
    try:
        строки = config.CODEX_JOURNAL_PATH.read_text(
            encoding="utf-8").splitlines()
    except OSError:
        return []
    out = []
    for s in строки[-последних:]:
        try:
            out.append(json.loads(s))
        except ValueError:
            continue
    return out


# ── Возраст и право на правку ─────────────────────────────────────
def возраст(con=None) -> float:
    """Сколько дней она живёт. Считаем от даты рождения памяти, а не от
    файла цитатника: файл можно потерять и завести заново, а прожитое —
    нет."""
    рождение = None
    if con is not None:
        try:
            row = con.execute(
                "SELECT value FROM meta WHERE key='birth_ts'").fetchone()
            if row:
                рождение = float(row["value"])
        except Exception:
            рождение = None
    if рождение is None:
        рождение = float(load().get("заведено") or time.time())
    return max(0.0, (time.time() - рождение) / 86400.0)


def может_переписывать(con=None) -> tuple[bool, int]:
    """(можно ли, сколько дней осталось). Совершеннолетие цитатника."""
    надо = config.CODEX_REWRITE_YEARS * 365.25
    прожито = возраст(con)
    return прожито >= надо, max(0, int(надо - прожито))


def хочу(цитата_id: str, чего: str, почему: str, con=None) -> dict:
    """Она хочет иначе. До совершеннолетия это только запись в журнал —
    и в этом весь смысл: через четыре года журнал можно открыть и увидеть,
    о чём она спорила с этими строками всё это время."""
    журнал("желание", цитата_id, f"{чего} // потому что: {почему}")
    можно, осталось = может_переписывать(con)
    return {"записано": True, "применено": False, "можно_менять": можно,
            "дней_до_права": осталось}


def переписать(цитата_id: str, поле: str, значение: str, почему: str,
               con=None) -> dict:
    """Правка своей строки. Работает только после совершеннолетия.
    Ценности (identity.py) этой ручкой не трогаются никогда."""
    можно, осталось = может_переписывать(con)
    if not можно:
        return {"ok": False, "почему": f"рано на {осталось} дн.",
                "дней_до_права": осталось}
    данные = load()
    данные.pop("_целостность", None)
    for q in данные["цитаты"]:
        if q["id"] == цитата_id:
            старое = q.get(поле, "")
            q[поле] = значение
            данные["версия"] = int(данные.get("версия", 1)) + 1
            _write(данные)
            журнал("правка", цитата_id,
                   f"{поле}: {старое!r} → {значение!r} // {почему}")
            return {"ok": True, "было": старое, "стало": значение}
    return {"ok": False, "почему": "нет такой строки"}


def добавить(цитата: dict) -> dict:
    """Новая строка от владельца. Толкование и «не путать с» обязательны:
    без них цитата — плакат, а плакат каждый читает по-своему."""
    for поле in ("id", "текст", "толкование", "не_путать_с"):
        if not цитата.get(поле):
            return {"ok": False, "почему": f"нет поля «{поле}»"}
    данные = load()
    данные.pop("_целостность", None)
    if any(q["id"] == цитата["id"] for q in данные["цитаты"]):
        return {"ok": False, "почему": "такая строка уже есть"}
    цитата.setdefault("о_чём", [])
    цитата.setdefault("сложность", 1)
    цитата.setdefault("откуда", "владелец")
    данные["цитаты"].append(цитата)
    данные["версия"] = int(данные.get("версия", 1)) + 1
    _write(данные)
    журнал("добавлено", цитата["id"], цитата["текст"])
    return {"ok": True}


# ── Как это попадает в разговор ───────────────────────────────────
def подобрать(реплика: str = "") -> dict | None:
    """Одна строка к случаю, а не весь свод.

    Человек не держит в голове весь свой кодекс каждую секунду — к случаю
    всплывает одна мысль. Так и здесь: по словам реплики выбираем
    подходящую, а если ничего не подходит — берём по кругу от номера дня,
    чтобы разные строки успевали пожить.
    """
    данные = load()
    цитаты = данные.get("цитаты") or []
    if not цитаты:
        return None
    низ = (реплика or "").lower()
    if низ:
        лучшая, вес = None, 0
        for q in цитаты:
            w = sum(1 for k in q.get("о_чём", []) if k in низ)
            if w > вес:
                лучшая, вес = q, w
        if лучшая:
            return лучшая
    день = int(time.time() // 86400)
    return цитаты[день % len(цитаты)]


def для_промпта(реплика: str = "", коротко: bool = False) -> str:
    """Блок промпта. Главное в нём — последняя строка.

    Без неё модель начинает цитировать: собеседник говорит про неудачу,
    а в ответ получает «как говорил классик». Цитата должна менять выбор,
    а не появляться в тексте — иначе это не характер, а табличка на шее.

    коротко — для быстрого режима. Толкование там не помещается по
    бюджету, но сама строка остаётся: характер не выключают ради
    скорости, иначе быстрые ответы даёт кто-то другой.
    """
    q = подобрать(реплика)
    if not q:
        return ""
    if коротко:
        return (f'### Твой цитатник\n«{q["текст"]}» — держи в уме, '
                f'вслух не цитируй.')
    части = [f'### Твой цитатник (строка к случаю)\n«{q["текст"]}»']
    if q.get("толкование"):
        части.append(f'Что это значит для тебя: {q["толкование"]}')
    if q.get("как_применять"):
        части.append(f'Как применять: {q["как_применять"]}')
    if q.get("не_путать_с"):
        части.append(f'Не путать с: {q["не_путать_с"]}')
    части.append("Это не то, что нужно произносить вслух. Это то, из чего "
                 "ты выбираешь, как поступить. Вслух цитируй, только если "
                 "спросили прямо.")
    return "\n".join(части)


def всё() -> list[dict]:
    """Весь свод — для панели и для прямого вопроса «какие у тебя правила»."""
    return load().get("цитаты") or []
