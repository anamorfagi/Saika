# Восемь октантов круга Лири, по часовой от «сверху» (чистая агентность).
# Названия нарочно без эвфемизмов. Половина круга — холодная, и если
# её подписать мягко, портрет перестанет отвечать на вопрос, ради
# которого он нужен. По Бёрчнеллу любой полюс бывает и полезной формой,
# и разрушительной: «властный» — это и лидер, и самодур, — поэтому
# октант описывает СТИЛЬ В РАЗГОВОРЕ, а не годность человека.
# ДВА СЛОЯ У КАЖДОГО ОКТАНТА (просьба владельца 25.08: «холодный/тёплый
# звучит не очень»). Термин остаётся ключом — по нему сверяются с
# литературой, спорят и калибруют. Рядом живая формулировка: то, как
# Сайка сказала бы это вслух нормальным языком, а не голосом учебника.
#
# ЧЕГО ЗДЕСЬ НЕТ И НЕ БУДЕТ: ругательного ярлыка. Не из ханжества, а
# потому что метка живёт в памяти месяцами. «Токсик» описывает манеру
# и снимается, когда манера меняется; «долбаёб» описывает человека и
# уже не снимается ничем — это приговор, а вся эта механика построена
# на том, что приговоров она не выносит. Вслух, в моменте, она может
# сказать резко: это разговор. В карту идёт описание.
ОКТАНТЫ = [
    (90,   "властный",   "всегда главный",
     "решает за всех и не спрашивает"),   # см. _живое: бывает «душнила»
    (45,   "уверенный",  "в теме и без душноты",
     "тянет на себя, но слышит других"),
    (0,    "тёплый",     "свой человек",
     "включается в тебя, а не только в разговор"),
    (-45,  "уступчивый", "удобный",
     "гнётся, лишь бы не задеть — им легко пользоваться"),
    (-90,  "покорный",   "его не слышно",
     "не занимает места вообще"),
    (-135, "замкнутый",  "сам по себе",
     "рядом есть, а внутрь не пускает"),
    (180,  "холодный",   "пофигист",
     "собеседник для него мебель"),
    (135,  "давящий",    "токсик",
     "обесценивает и требует разом"),
]

_СЛОВО = re.compile(r"[^\wёЁ]+", re.UNICODE)
_ПОВЕЛИТ = re.compile(r"\b\w{2,}(?:ай|яй|ей|ий|ь|и|йте|ьте)\b", re.I)
_ОБРАЩЕНИЕ = re.compile(r"\b(ты|тебя|тебе|тобой|вы|вас|вам|вами|давай|"
                        r"как думаешь|согласен|согласна)\b", re.I)

# ── БЛОК: враждебность ────────────────────────────────────────────
# НАЙДЕНО ВЛАДЕЛЬЦЕМ 25.08, и это была не дырка, а перевёрнутый знак.
# Тепло мерилось долей обращений к собеседнику — «ты», «тебе», «давай».
# Но оскорбление состоит ровно из них же: «ты тупой» это обращение по
# всем формальным признакам. Матершинник получал ВЫСОКУЮ
# доброжелательность именно за то, что хамит адресно.
#
# Поэтому обращение засчитывается в тепло только во фразе, где нет
# враждебности, а враждебные фразы тянут общность вниз.
#
# ВАЖНОЕ РАЗЛИЧЕНИЕ: брань сама по себе — это манера речи, а не
# отношение. Человек может материться через слово и быть добрейшим;
# другой не выругается ни разу и будет обесценивать в каждой фразе.
# Считается АДРЕСНАЯ агрессия: брань или ярлык рядом со вторым лицом.
# Просто брань уходит в экспрессивность и общности не касается.
_БРАНЬ = re.compile(
    r"(ху[йеё]|пизд|бля|[еёo]б[аеиуын]|сук[аиоу]|мудак|мудил|чмо|уёб|уеб|"
    r"гандон|долбо|пидор|говн|дерьм|срал|нахер|нахуй|похуй)", re.I)
_ЯРЛЫК = re.compile(
    r"\b(туп(ой|ая|ое|ые|ица)|дебил|идиот|кретин|ничтожеств|бездар|"
    r"лох|быдло|днище|уёбок|уебок|дура|дурак|клоун|позор|заткнись|"
    r"завали|пошёл|пошел вон|отвали|бесполезн)", re.I)
_ВТОРОЕ_ЛИЦО = re.compile(r"\b(ты|тебя|тебе|тобой|вы|вас|вам|вами|твой|"
                          r"твоя|твоё|ваш|ваша)\b", re.I)


def _разнообразие(поток: list) -> float:
    """Богатство словаря по СКОЛЬЗЯЩЕМУ ОКНУ, а не по всему тексту.

    Ловушка, которую поймал стенд: доля уникальных слов механически
    падает с объёмом — у болтуна словарь богаче, а число выходит ниже,
    потому что знаменатель растёт быстрее числителя. Разговорчивый
    человек так превращается в «закрытого» ровно за то, что много
    говорил. Окно фиксированной длины эту зависимость снимает."""
    окно = 50
    if len(поток) < окно:
        return round(len(set(поток)) / max(1, len(поток)), 3)
    доли = []
    for i in range(0, len(поток) - окно + 1, окно // 2):
        кусок = поток[i:i + окно]
        доли.append(len(set(кусок)) / окно)
    return round(sum(доли) / len(доли), 3)


def _шкала(x, лево, право) -> float:
    """Сырое число → 0..100, мягко, без обрывов на краях."""
    if право == лево:
        return 50.0
    t = (x - лево) / (право - лево)
    return round(max(0.0, min(1.0, t)) * 100, 1)


def маркеры(строки) -> dict:
    """Наблюдаемые признаки речи. Ничего не толкует — только считает.

    Разделение нарочное: числа здесь можно проверить руками, а
    толкование (какая ось от какого маркера) живёт ниже и потому
    калибруется отдельно от измерения."""
    if not строки:
        return {}
    слов, вопросов, обращений, повелений = [], 0, 0, 0
    брани, адресной, поток, эмоции = 0, 0, [], []
    for r in строки:
        t = r["text"] or ""
        ws = [w for w in _СЛОВО.split(t.lower()) if w]
        слов.append(len(ws))
        поток.extend(ws)
        есть_брань = bool(_БРАНЬ.search(t))
        есть_ярлык = bool(_ЯРЛЫК.search(t))
        в_адрес = bool(_ВТОРОЕ_ЛИЦО.search(t))
        враждебно = (есть_брань or есть_ярлык) and в_адрес
        if есть_брань:
            брани += 1
        if враждебно:
            адресной += 1
        if "?" in t and not враждебно:
            вопросов += 1              # «ты совсем тупой?» — не участие
        if _ОБРАЩЕНИЕ.search(t) and not враждебно:
            обращений += 1             # обращение считается теплом только
                                       # там, где оно не оскорбление
        # Приказ узнаётся по НАЧАЛУ фразы, а не по её длине: «слушай
        # сюда и быстро сделал» — команда, хотя слов много, а «я потом
        # решу, займись сам» — нет, хотя коротко.
        if _ПОВЕЛИТ.search(" ".join(ws[:3])):
            повелений += 1
        эмоции.append(float(r["emotion"] or 0))
    # ── голос: считаем только по тем фразам, где он был измерен ──
    темпы = [float(r["темп"]) for r in строки
             if r.keys().__contains__("темп") and r["темп"]]
    тона = [float(r["тон"]) for r in строки
            if r.keys().__contains__("тон") and r["тон"]]
    паузы = [float(r["пауза"]) for r in строки
             if r.keys().__contains__("пауза") and r["пауза"] is not None]
    n = len(строки)
    ср = sum(слов) / n
    разброс = (math.sqrt(sum((e - sum(эмоции)/n) ** 2 for e in эмоции) / n)
               if n > 1 else 0.0)
    голос = {}
    if len(темпы) >= 5:
        голос["темп_речи"] = round(sum(темпы) / len(темпы), 2)
    if len(тона) >= 5:
        м_тон = sum(тона) / len(тона)
        голос["тон_гц"] = round(м_тон, 1)
        голос["разброс_тона"] = round(
            math.sqrt(sum((t - м_тон) ** 2 for t in тона) / len(тона)), 1)
    if len(паузы) >= 5:
        голос["пауза_с"] = round(sum(паузы) / len(паузы), 2)
    return {"фраз": n, "слов_в_фразе": round(ср, 1), **голос,
            "доля_вопросов": round(вопросов / n, 3),
            "доля_обращений": round(обращений / n, 3),
            "доля_повелений": round(повелений / n, 3),
            "доля_брани": round(брани / n, 3),
            "доля_адресной_агрессии": round(адресной / n, 3),
            "разнообразие": _разнообразие(поток),
            "разброс_эмоции": round(разброс, 3)}


def _оси_из_маркеров(м: dict, добросовестность_извне=None) -> dict:
    """Толкование маркеров в оси. Каждая связка — не выдумка, но и не
    измерение: это разумное приближение, которое надо будет калибровать.
    Границы шкал подобраны по русской разговорной речи и заведомо грубы."""
    if not м:
        return {}
    тепло = _шкала(м["доля_обращений"] * 0.6 + м["доля_вопросов"] * 0.4,
                   0.02, 0.45)
    # Адресная агрессия тянет общность вниз резко и от самого верха:
    # человек, который в каждой пятой фразе обесценивает собеседника,
    # оказывается в холодной половине круга независимо от того, сколько
    # раз он сказал «слушай» и «давай».
    враждебность = min(1.0, м["доля_адресной_агрессии"]
                       / config.TEMPER_HOSTILE_FULL)
    # ГОЛОС УТОЧНЯЕТ ТЕКСТ, А НЕ ЗАМЕНЯЕТ ЕГО. Если темп и тон измерены,
    # они входят в оси с половинным весом: быстрый высокий голос без пауз
    # — это активность, медленный ровный с раздумьем — её отсутствие. Но
    # в чате их не бывает вовсе, и портрет обязан работать без них.
    речь_e = _шкала(м["слов_в_фразе"], 3, 18)
    if "темп_речи" in м:
        речь_e = 0.6 * речь_e + 0.4 * _шкала(м["темп_речи"], 1.4, 4.2)
    if "пауза_с" in м:
        # быстрый ответ — вовлечённость, долгое молчание перед фразой —
        # либо раздумье, либо неохота; в обоих случаях не активность
        речь_e = 0.75 * речь_e + 0.25 * _шкала(20 - м["пауза_с"], 5, 19)
    невроз = _шкала(м["разброс_эмоции"], 0.03, 0.35)
    if "разброс_тона" in м and м.get("тон_гц"):
        невроз = 0.65 * невроз + 0.35 * _шкала(
            м["разброс_тона"] / max(1.0, м["тон_гц"]), 0.05, 0.35)
    оси = {
        # много слов + инициатива в репликах → экстраверсия/агентность
        "экстраверсия": round(речь_e, 1),
        "доброжелательность": round(max(0.0, тепло * (1 - враждебность)
                                        - враждебность * 45), 1),
        # богатство словаря → открытость (самый шаткий из пяти)
        "открытость": _шкала(м["разнообразие"], 0.35, 0.8),
        # скачки заряда и гуляющий тон → нейротизм
        "нейротизм": round(невроз, 1),
    }
    if добросовестность_извне is not None:
        оси["добросовестность"] = добросовестность_извне
    return оси


def _добросовестность(con, person_id: int):
    """Единственная ось, которую видно ПОСТУПКАМИ, а не речью:
    сдержал ли обещание. Она же, по литературе, определяется по тексту
    лучше прочих — ровно потому, что за ней стоит поведение."""
    строки = con.execute(
        "SELECT status FROM promises WHERE person_id=?", (person_id,)).fetchall()
    if len(строки) < 2:
        return None
    сдержал = sum(1 for r in строки if r["status"] in ("закрыто", "выполнено"))
    провалил = sum(1 for r in строки if r["status"] in ("просрочено", "напомнено"))
    если_всего = сдержал + провалил
    if если_всего < 2:
        return None
    return round(сдержал / если_всего * 100, 1)


def уверенность(фраз: int) -> float:
    """Растёт быстро вначале и упирается в потолок: сколько ни слушай,
    речь остаётся косвенным признаком. Потолок стоит НИЖЕ единицы
    намеренно — это оценка, а не факт о человеке."""
    if фраз < config.TEMPER_MIN_PHRASES:
        return 0.0
    x = min(1.0, фраз / config.TEMPER_FULL_PHRASES)
    return round(config.TEMPER_MAX_CONFIDENCE * (1 - math.exp(-2.2 * x)), 3)


def _строки(con, person_id: int, окно: int | None = None):
    return con.execute(
        "SELECT text, emotion, темп, тон, пауза FROM raw_events"
        " WHERE person_id=? ORDER BY ts DESC LIMIT ?",
        (person_id, окно or config.TEMPER_WINDOW)).fetchall()


def пересчитать(con, person_id: int) -> dict:
    """Пересобрать портрет по всему, что человек наговорил. Зовётся ночью."""
    строки = _строки(con, person_id)
    м = маркеры(строки)
    оси = _оси_из_маркеров(м, _добросовестность(con, person_id))
    у = уверенность(м.get("фраз", 0))
    now = time.time()
    for ось, знач in оси.items():
        con.execute(
            "INSERT INTO temper(person_id, ось, значение, уверенность,"
            " наблюдений, обновлено) VALUES (?,?,?,?,?,?)"
            " ON CONFLICT(person_id, ось) DO UPDATE SET"
            " значение=excluded.значение, уверенность=excluded.уверенность,"
            " наблюдений=excluded.наблюдений, обновлено=excluded.обновлено",
            (person_id, ось, знач, у, м.get("фраз", 0), now))
    con.commit()
    return {"маркеры": м, "оси": оси, "уверенность": у}


# ЦЕНТР КРУГА — ДВА РАЗНЫХ ЦЕНТРА, И ПУТАТЬ ИХ НЕЛЬЗЯ.
# «Не хватило наблюдений» и «человек правда без крайностей» дают одну и
# ту же точку посередине, но означают противоположное: в первом случае
# сказать нечего, во втором сказано всё. Первый молчит, второй получает
# имя.
ЦЕНТР_РОВНЫЙ = ("нормис", "без крайностей: ни давит, ни стелется")
ЦЕНТР_ПУСТО = ("пока не читается", "наблюдений мало, круг молчит")


def _октант(агентность: float, общность: float, у: float = 1.0):
    """Угол в круге Лири → название. Центр круга имени не получает:
    «ничего определённого» — честный ответ, и типологии зря его прячут.

    Длина вектора ПРИЖИМАЕТСЯ УВЕРЕННОСТЬЮ (вторая находка стенда).
    Без этого пятьдесят односложных «угу» давали точку на самом краю
    круга с ярлыком «замкнутый» — картинка кричала о выводе, которого
    из полусотни реплик просто нет. Мало данных должно выглядеть как
    середина круга, а не как уверенный край."""
    a, c = агентность - 50, общность - 50
    длина = math.hypot(a, c) / 50.0
    длина *= min(1.0, у / config.TEMPER_MAX_CONFIDENCE)
    if длина < config.TEMPER_MIN_VECTOR:
        # хватило ли данных, чтобы центр означал «ровный», а не «не знаю»
        ровный = у >= config.TEMPER_MAX_CONFIDENCE / 2
        return ("центр" if ровный else None), round(длина, 2), 0.0
    угол = math.degrees(math.atan2(a, c))
    лучший = min(ОКТАНТЫ, key=lambda o: abs(((угол - o[0] + 180) % 360) - 180))
    return лучший, round(min(1.0, длина), 2), round(угол, 1)


def _живое(окт, м: dict) -> tuple[str, str]:
    """Живое слово с одним уточнением по манере.

    ДУШНИЛА — не отдельная точка круга, а оттенок доминирования: человек
    занимает всё место длинными нравоучениями, но никого не оскорбляет.
    От «главного» его отличает не позиция, а форма: длинные фразы,
    вопросов почти нет — говорит В человека, а не С ним. Считается
    отдельно, потому что по одной точке круга эту разницу не увидеть,
    а в жизни она решающая: с главным работают, с душнилой не могут."""
    имя, живое, что = окт[1], окт[2], окт[3]
    длинно = м.get("слов_в_фразе", 0) >= config.DUSHNILA_WORDS
    молча_спрашивает = м.get("доля_вопросов", 1.0) <= config.DUSHNILA_QUESTIONS
    if имя in ("властный", "уверенный") and длинно and молча_спрашивает:
        return "душнила", ("занимает всё место длинными разъяснениями "
                           "и почти не спрашивает")
    return живое, что


# Айзенк в живом переводе: слово «сангвиник» в разговоре звучит как
# кроссворд, а сказать то же самое можно по-человечески.
ЖИВОЙ_ТЕМПЕРАМЕНТ = {
    "холерик": "заводится с полоборота",
    "сангвиник": "лёгкий на подъём",
    "флегматик": "его ничем не пробить",
    "меланхолик": "тихий и всё близко к сердцу",
}


def смесь_темпераментов(экстраверсия: float, нейротизм: float) -> dict:
    """ЧИСТЫХ САНГВИНИКОВ НЕ БЫВАЕТ (поправка владельца 25.08).

    Квадранты Айзенка загоняли человека в одну из четырёх коробок: E и N
    сравнивались с полтинником, и 51 против 49 давало другой ярлык. Это
    не свойство людей, а свойство порога — реальный человек всегда смесь,
    и вопрос только в долях.

    Считаем билинейным разложением точки (E, N) по четырём углам
    квадрата. Метод выбран не за красоту: доли получаются точные, в
    сумме ровно единица, без единого подгоночного коэффициента, а
    середина честно даёт 25/25/25/25 — «всего понемногу», что для
    середины и есть правда.
    """
    e = max(0.0, min(1.0, экстраверсия / 100.0))
    n = max(0.0, min(1.0, нейротизм / 100.0))
    доли = {
        "холерик": e * n,               # активный и заводится
        "сангвиник": e * (1 - n),       # активный и ровный
        "флегматик": (1 - e) * (1 - n),  # спокойный и ровный
        "меланхолик": (1 - e) * n,      # спокойный и всё близко к сердцу
    }
    return {k: round(v * 100, 1) for k, v in доли.items()}


def _темперамент(экстраверсия: float, нейротизм: float) -> str:
    """Преобладающий — только чтобы было как назвать. Настоящий ответ
    отдаёт смесь_темпераментов, и в панели показывается именно она."""
    смесь = смесь_темпераментов(экстраверсия, нейротизм)
    return max(смесь, key=смесь.get)


def профиль(con, person_id: int) -> dict:
    """Портрет для карточки и для панели. Никаких приговоров: если
    данных мало — так и сказано, и это главный ответ, а не заглушка."""
    строки = {r["ось"]: r for r in con.execute(
        "SELECT * FROM temper WHERE person_id=?", (person_id,))}
    if not строки:
        return {"готов": False, "почему": "ещё не слушала этого человека"}
    у = max((r["уверенность"] for r in строки.values()), default=0.0)
    фраз = max((r["наблюдений"] for r in строки.values()), default=0)
    оси = {о: round(строки[о]["значение"], 1) for о in ОСИ if о in строки}
    if у <= 0:
        return {"готов": False, "фраз": фраз,
                "почему": f"нужно хотя бы {config.TEMPER_MIN_PHRASES} фраз, "
                          f"есть {фраз}",
                "оси": оси}

    # АГЕНТНОСТЬ ≠ ЭКСТРАВЕРСИЯ (найдено владельцем 25.08). Первая
    # версия брала вертикаль круга прямо из экстраверсии, то есть по
    # сути из многословности, — и тот, кто хамит короткими приказами,
    # уезжал ВНИЗ, в «замкнутого». Но враждебное доминирование это
    # именно доминирование: человек занимает место в разговоре, просто
    # не словами, а давлением. Вертикаль считается из трёх вещей:
    # приказы, адресная агрессия и объём речи — в таком порядке веса.
    м = на_чём_основано(con, person_id)
    агентность = round(
        0.40 * _шкала(м.get("доля_повелений", 0.0), 0.02, 0.40)
        + 0.25 * _шкала(м.get("доля_адресной_агрессии", 0.0), 0.0, 0.30)
        + 0.35 * оси.get("экстраверсия", 50.0), 1)
    общность = оси.get("доброжелательность", 50.0)
    окт, длина, угол = _октант(агентность, общность, у)
    if окт == "центр":
        окт = (0, "ровный", *ЦЕНТР_РОВНЫЙ)
    живое, что_значит = _живое(окт, м) if окт else ЦЕНТР_ПУСТО
    итог = {
        "готов": True, "фраз": фраз, "уверенность": у, "оси": оси,
        "агрессия": {
            "доля_адресной": м.get("доля_адресной_агрессии", 0.0),
            "доля_брани": м.get("доля_брани", 0.0),
            "как_читать":
                "брань сама по себе — манера речи, а не отношение: можно "
                "материться через слово и быть добрейшим. Считается только "
                "адресная агрессия — брань или ярлык в адрес собеседника."},
        "круг": {"агентность": агентность, "общность": общность,
                 "выраженность": длина, "угол": угол,
                 # термин — ключ для сверки и спора
                 "октант": окт[1] if окт else None,
                 # живое — то, как она скажет это вслух
                 "как_сказать": живое or "ничего определённого",
                 "что_значит": что_значит or
                 "держится ровно посередине — по разговорам не читается"},
        "оговорка": "оценка по речи, не опросник: по литературе такие "
                    "предсказания слабые, экстраверсия и доброжелательность "
                    "хуже прочих. Это гипотеза, которую можно оспорить.",
    }
    # Смесь отдаём ВСЕГДА, даже когда уверенности не хватает на ярлык:
    # доли честно показывают «всего понемногу», а ярлык в этом месте
    # соврал бы, назвав человека одним словом.
    итог["смесь"] = смесь_темпераментов(оси.get("экстраверсия", 50.0),
                                        оси.get("нейротизм", 50.0))
    итог["сейчас"] = сейчас(con, person_id)
    # Античное слово выдаём только при уверенности выше половины
    # потолка. «Холерик» звучит как диагноз и запоминается сильнее, чем
    # любые проценты рядом; повесить его по полусотне реплик — это ровно
    # то, за что типологиям и достаётся.
    if "нейротизм" in оси and у >= config.TEMPER_MAX_CONFIDENCE / 2:
        т = _темперамент(оси.get("экстраверсия", 50), оси["нейротизм"])
        итог["темперамент"] = т
        итог["темперамент_живой"] = ЖИВОЙ_ТЕМПЕРАМЕНТ.get(т, "")
    else:
        итог["темперамент"] = None
        итог["почему_без_темперамента"] = (
            "слишком рано для слова вроде «холерик»: оно звучит как "
            "диагноз и запоминается сильнее любых процентов рядом")
    return итог


def на_чём_основано(con, person_id: int, окно: int | None = None) -> dict:
    """Сырые маркеры — чтобы оценку можно было оспорить, а не только
    прочитать. Портрет без предъявленных оснований это гадание."""
    return маркеры(_строки(con, person_id, окно))


def сейчас(con, person_id: int) -> dict:
    """Портрет ПО ПОСЛЕДНЕМУ РАЗГОВОРУ, а не по всей истории.

    Смысл в разнице. Долгий портрет — какой человек вообще; короткий —
    какой он сегодня. Совпали — значит он такой и есть; разошлись —
    значит сегодня с ним что-то происходит, и это ценнее любого из двух
    портретов по отдельности."""
    м = маркеры(_строки(con, person_id, config.TEMPER_LIVE_WINDOW))
    if not м or м["фраз"] < config.TEMPER_LIVE_MIN:
        return {"готов": False,
                "почему": f"в этом разговоре пока {м.get('фраз', 0)} фраз"}
    оси = _оси_из_маркеров(м, None)
    e = оси.get("экстраверсия", 50.0)
    n = оси.get("нейротизм", 50.0)
    return {"готов": True, "фраз": м["фраз"], "оси": оси,
            "смесь": смесь_темпераментов(e, n), "маркеры": м}
