# -*- coding: utf-8 -*-
"""
═══════════════════════════════════════════════════════════════════
  ОЧКИ — награда за удержание баланса.

  Просьба владельца: держит перекос около нуля (шкала шириной 200
  единиц, от −100 до +100) — +10 за день; не удержала — −5. Копится
  под будущие игровые механики.

  ГЛАВНАЯ ЛОВУШКА, КОТОРУЮ НАДО ОБОЙТИ СРАЗУ

  Система наград учит ровно тому, что измеряет, и находит самый
  дешёвый способ. Если платить только за «перекос близко к нулю»,
  дешевле всего перестать наблюдать: нет улик — нет перекоса — деньги
  идут. Получится память, которая выучилась НЕ ПОМНИТЬ ради очков. Это
  не гипотеза, это обычное поведение любой оптимизации.

  Поэтому три правила:

  1. НЕТ УЛИК ЗА ДЕНЬ — НЕТ ОЧКОВ. Ни плюса, ни минуса: день, в
     который она про человека ничего не узнала, просто не считается.
     Молчание перестаёт быть выигрышной стратегией.
  2. ПЛАТИМ ЗА ДВИЖЕНИЕ, А НЕ ЗА ПОЗУ. Стоять близко к нулю хорошо, но
     подвинуть стрелку к нулю — лучше: это и есть работа.
  3. ОТДЕЛЬНАЯ ПРЕМИЯ ЗА ПРОВЕРКУ. Проверить утверждение — самое
     дорогое действие в системе и единственное, что двигает критику
     вверх честно. Если за него не платить, выгоднее просто меньше
     доверять, а это не баланс, а его имитация.

  Очки — не оценка человека и не оценка отношений. Это оценка ЕЁ
  работы: смотрела ли, проверяла ли, не заваливалась ли в одну
  сторону. Показывать их человеку, о котором они посчитаны, нельзя —
  это её внутренняя кухня, а не отзыв о нём.
═══════════════════════════════════════════════════════════════════
"""
import time
from . import config

СУТКИ = 86400.0


def _день(ts: float | None = None) -> int:
    return int((ts if ts is not None else time.time()) // СУТКИ)


def начислить(con, за_день: int | None = None) -> dict:
    """Посчитать очки за сутки по каждому человеку. Зовётся ночью.

    Идемпотентно: повторный вызов за тот же день ничего не удвоит —
    ночь может сорваться и запуститься снова, и это не повод платить
    дважды."""
    from . import balance
    д = за_день if за_день is not None else _день() - 1
    начало, конец = д * СУТКИ, (д + 1) * СУТКИ
    итог = {"день": д, "начислено": 0, "людей": 0, "строки": []}

    for p in con.execute("SELECT id, name, is_owner, is_creator"
                         " FROM persons").fetchall():
        if p["is_owner"] or p["is_creator"]:
            continue                     # на владельце качелей нет
        улик = con.execute(
            "SELECT COUNT(*) c FROM karma_journal WHERE person_id=?"
            " AND ts>=? AND ts<?", (p["id"], начало, конец)).fetchone()["c"]
        if улик < config.SCORE_MIN_EVIDENCE:
            continue                     # правило 1: день не считается

        было = con.execute(
            "SELECT перекос_конец FROM score WHERE person_id=? AND день<?"
            " ORDER BY день DESC LIMIT 1", (p["id"], д)).fetchone()
        стало = balance.весы(con, p["id"])["перекос"]
        проверок = con.execute(
            "SELECT COUNT(*) c FROM karma_journal WHERE person_id=?"
            " AND ts>=? AND ts<? AND event LIKE '%проверка утверждения%'",
            (p["id"], начало, конец)).fetchone()["c"]

        в_окне = abs(стало) <= config.SCORE_BAND
        очки, почему = 0, []
        if в_окне:
            очки += config.SCORE_HOLD
            почему.append(f"держала в пределах ±{config.SCORE_BAND}")
        else:
            очки += config.SCORE_MISS
            почему.append(f"перекос {стало:+.0f} вышел за ±{config.SCORE_BAND}")
        if было is not None:
            сдвиг = abs(было["перекос_конец"]) - abs(стало)
            if сдвиг >= config.SCORE_MOVE_MIN:
                очки += config.SCORE_MOVE
                почему.append(f"подвинула к центру на {сдвиг:.0f}")
            elif сдвиг <= -config.SCORE_MOVE_MIN:
                очки += config.SCORE_DRIFT
                почему.append(f"уехала от центра на {abs(сдвиг):.0f}")
        if проверок:
            очки += config.SCORE_CHECK * проверок
            почему.append(f"проверок: {проверок}")

        con.execute(
            "INSERT INTO score(день, person_id, перекос_конец, улик,"
            " проверок, очки, почему) VALUES (?,?,?,?,?,?,?)"
            " ON CONFLICT(день, person_id) DO UPDATE SET"
            " перекос_конец=excluded.перекос_конец, улик=excluded.улик,"
            " проверок=excluded.проверок, очки=excluded.очки,"
            " почему=excluded.почему",
            (д, p["id"], стало, улик, проверок, очки, "; ".join(почему)))
        итог["начислено"] += очки
        итог["людей"] += 1
        итог["строки"].append({"кто": p["name"], "перекос": стало,
                               "очки": очки, "почему": "; ".join(почему)})
    con.commit()
    return итог


def всего(con) -> dict:
    """Копилка целиком — для панели и будущих игровых механик."""
    r = con.execute("SELECT COALESCE(SUM(очки),0) s, COUNT(*) n,"
                    " COALESCE(MAX(день),0) d FROM score").fetchone()
    сегодня = con.execute(
        "SELECT COALESCE(SUM(очки),0) s FROM score WHERE день=?",
        (_день() - 1,)).fetchone()["s"]
    # серия: сколько дней подряд не уходила в минус
    подряд = 0
    for row in con.execute("SELECT день, SUM(очки) s FROM score"
                           " GROUP BY день ORDER BY день DESC LIMIT 60"):
        if row["s"] > 0:
            подряд += 1
        else:
            break
    return {"опыт": r["s"], "записей": r["n"], "за_последний_день": сегодня,
            "серия_дней": подряд,
            "это_про_неё": "очки оценивают её работу — смотрела ли, "
                           "проверяла ли, не заваливалась ли в одну "
                           "сторону. Это не оценка людей и не отзыв о них."}


def по_людям(con, дней: int = 14) -> list[dict]:
    порог = _день() - дней
    return [dict(r) for r in con.execute(
        "SELECT p.name кто, SUM(s.очки) очки, COUNT(*) дней,"
        " AVG(s.перекос_конец) средний_перекос"
        " FROM score s LEFT JOIN persons p ON p.id=s.person_id"
        " WHERE s.день>=? GROUP BY s.person_id ORDER BY очки DESC",
        (порог,))]
