def для_промпта(рецепт_ключ: str, максимум: int = 2) -> str:
    """Один-два хода под текущую линию. Больше — это уже сценарий, а по
    сценарию разговаривать нельзя: собеседник живой."""
    ключи = ПО_РЕЦЕПТУ.get(рецепт_ключ, [])[:максимум]
    if not ключи:
        return ""
    куски = []
    for к in ключи:
        имя, что, почему = ХОДЫ[к]
        куски.append(f"{имя}: {что} ({почему})")
    return ("### Ходы, которые тут работают\n· " + "\n· ".join(куски) +
            "\nПроверка на любой ход: сказала бы ты это вслух ему в лицо? "
            "Если да — делай. Если нет — это не ход, а хитрость, и её "
            "здесь нет. Спросят «ты меня обрабатываешь?» — назови ход и "
            "зачем он, прямо.")


