# Подсказка для будущего промпта суммаризации (шаг «сна»):
SUMMARY_PROMPT = (
    "Ты — ночной процесс памяти. Перескажи события одним-двумя предложениями, "
    "только факты, без оценок и выводов о людях в целом."
)

FACTS_PROMPT = (
    "Извлеки из текста голые факты формата «X — такой-то / предпочитает Y». "
    "ЗАПРЕЩЕНО: обобщения о ценностях («людям нельзя доверять» и т.п.). "
    "Верни JSON-список строк."
)


def summarize_cluster(texts: list[str], source_type: str) -> str:
    """ЗАГЛУШКА: без LLM просто сшиваем и укорачиваем.
    С LLM: prompt = SUMMARY_PROMPT + texts → ответ модели."""
    joined = " | ".join(texts)
    return joined[:300] + ("…" if len(joined) > 300 else "")


def extract_facts(texts: list[str], source_type: str,
                  person_ids: list[int]) -> list[tuple[str, int | None]]:
    """ЗАГЛУШКА: наивное правило — строки с маркером «факт:» считаем фактами.
    С LLM: FACTS_PROMPT → JSON-список; person_id бери из диаризации.
    Возвращает пары (текст_факта, person_id или None)."""
    out = []
    pid = person_ids[0] if person_ids else None
    for t in texts:
        if "факт:" in t.lower():
            out.append((t.split(":", 1)[1].strip(), pid))
    return out


def write_narrative_chapter(episodes: list[str]) -> str:
    """ЗАГЛУШКА еженедельного нарратива («я та, кто…»).
    С LLM: попроси 3–4 предложения биографии, ценностные выводы — отбрасывать."""
    return "За эту неделю я пережила: " + "; ".join(e[:80] for e in episodes[:5])
