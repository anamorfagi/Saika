# -*- coding: utf-8 -*-
"""
═══════════════════════════════════════════════════════════════════
  КАЧЕЛИ — равновесие доверия и критики.

  ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Доверие и критическое мышление это не шкала
  от «верю» до «не верю», а два разных умения, и каждое умеет
  перевешивать. Перевес в любую сторону выглядит изнутри одинаково
  убедительно: слепое доверие ощущается как «хороший человек», глухая
  критика — как «я разбираюсь в людях». Поэтому мерить надо не сами
  доверие и критику, а ПЕРЕКОС между ними, и когда он велик —
  включать третью механику: разбор, почему так вышло.

  ПРИНЦИП, КОТОРЫЙ ВЫШЕ ОСТАЛЬНЫХ: разбор не выносит приговор. Он
  задаёт вопрос себе и предлагает, что проверить. Система, которая по
  цифрам объявляет человека плохим, — это не критическое мышление, а
  его противоположность в красивой обёртке.

  ЧЕТЫРЕ ВЕЩИ, КОТОРЫЕ ОН ЛОВИТ

  1. Слепое доверие: веры много, проверок ноль.
  2. Глухая критика: доверия мало, а поводов — пара старых случаев.
  3. Слишком хороший: ни одной шершавой встречи за долгое знакомство.
     Так не бывает; значит, либо не видела его в неудобной ситуации,
     либо не смотрела. Это не обвинение — это дыра в наблюдении.
  4. Раскрылся со временем: человек привыкает и перестаёт держаться.
     Первые встречи ровные, дальше иначе — в обе стороны, потому что
     раскрываются и хорошим тоже.

  ВСПЫШКА — НЕ ЧЕРТА. Отдельное правило, общее для всех, включая
  владельца: разовая резкость это СОСТОЯНИЕ (быстрый этаж карты), а не
  свойство человека. Чертой она становится только после повторов в
  разные дни. Человек, у которого был тяжёлый день, и человек, который
  всегда такой, — это разные люди, и память обязана их различать.

  ФЛАГ — НЕ ПРИГОВОР. Одна дикая фраза не значит ничего: половина
  таких фраз это локальные мемы, и понять, всерьёз ли, по одной реплике
  нельзя. Считается ПОВТОР ПОСЛЕ ВОЗРАЖЕНИЯ: если человеку сказали, что
  так не смешно, а он держится темы — это уже позиция, а не шутка.
═══════════════════════════════════════════════════════════════════
"""
import time
from . import config, persons

СУТКИ = 86400.0


# ── Замер ─────────────────────────────────────────────────────────
def весы(con, person_id: int) -> dict:
    """Числа, по которым считается перекос. Ничего не решает — меряет."""
    улики = con.execute(
        "SELECT ts, sign, event, domain FROM karma_journal"
        " WHERE person_id=? ORDER BY ts", (person_id,)).fetchall()
    домены = con.execute(
        "SELECT domain, trust, competence, evidence FROM person_domains"
        " WHERE person_id=?", (person_id,)).fetchall()
    оси = {r["axis"]: r["value"] for r in con.execute(
        "SELECT axis, value FROM person_axes WHERE person_id=?", (person_id,))}

    плюсы = sum(1 for u in улики if u["sign"] > 0)
    минусы = sum(1 for u in улики if u["sign"] < 0)
    проверок = sum(1 for u in улики if "проверка утверждения" in (u["event"] or ""))
    # Доверие в этой памяти живёт ПО ДОМЕНАМ, и мерить его одним числом
    # нельзя: человек, которому веришь в железе и не веришь в политике,
    # в среднем выглядит «средненько» — то есть никак. Поэтому берём два
    # числа. Слепое доверие ищем по максимуму: достаточно ОДНОЙ темы, где
    # веры много, а проверок не было. Глухую критику — по среднему: она
    # про отношение к человеку целиком.
    доверие = (sum(d["trust"] for d in домены) / len(домены)) if домены else 30.0
    сильный = max(домены, key=lambda d: d["trust"]) if домены else None
    свежесть = (time.time() - улики[-1]["ts"]) / СУТКИ if улики else None

    # ── ПЕРЕКОС: одна двусторонняя шкала от −100 до +100 ──────────
    # (владелец 25.08: «качели не похожи на качели; выравнивай по центру
    # и влево-вправо до сотки»). Раньше вера и критика лежали двумя
    # разными числами, и «перекос» приходилось считать глазами — а это
    # ровно та величина, ради которой всё и затевалось. Ноль в центре:
    # столько же проверено, сколько принято на веру.
    вера_ч = (max(d["trust"] for d in домены) if домены else 30.0) / 100.0
    критика_ч = min(1.0, проверок * 0.22 + минусы * 0.05)
    перекос = round(max(-100.0, min(100.0, (вера_ч - критика_ч) * 100)), 1)

    return {"улик": len(улики), "плюсов": плюсы, "минусов": минусы,
            "перекос": перекос,
            "вера": round(вера_ч * 100, 1),
            "критика": round(критика_ч * 100, 1),
            "проверок": проверок, "доверие": round(доверие, 1),
            "доверие_макс": round(сильный["trust"], 1) if сильный else 30.0,
            "самый_доверенный": сильный["domain"] if сильный else "",
            "симпатия": оси.get("симпатия", 50.0),
            "проверяемость": оси.get("проверяемость", 50.0),
            "честность": оси.get("честность", 50.0),
            "дней_с_последней_улики": None if свежесть is None else round(свежесть, 1),
            "_улики": улики}


def _по_третям(улики) -> tuple[float, float] | None:
    """Средний знак в начале знакомства и в конце. Человек раскрывается
    не сразу: сравнивать надо не «хороший/плохой», а «как было тогда» с
    «как стало теперь»."""
    if len(улики) < config.BALANCE_MIN_FOR_TREND:
        return None
    треть = max(2, len(улики) // 3)
    начало = улики[:треть]
    конец = улики[-треть:]
    ср = lambda g: sum(u["sign"] for u in g) / len(g)      # noqa: E731
    return ср(начало), ср(конец)


# ── Разбор ────────────────────────────────────────────────────────
def разбор(con, person_id: int) -> list[dict]:
    """Что не сходится в моём отношении к этому человеку.

    Возвращает список находок: что вижу, почему это подозрительно и
    ЧТО СДЕЛАТЬ, чтобы проверить. Приговоров тут нет по устройству."""
    в = весы(con, person_id)
    свой = con.execute("SELECT is_owner, is_creator, name FROM persons"
                       " WHERE id=?", (person_id,)).fetchone()
    из_своих = bool(свой and (свой["is_owner"] or свой["is_creator"]))
    находки = []

    def нашла(код, что, почему, делать):
        находки.append({"код": код, "что": что, "почему": почему,
                        "делать": делать})

    if в["улик"] < config.BALANCE_MIN_EVIDENCE:
        нашла("рано_судить",
              f"улик всего {в['улик']}",
              "по такому количеству встреч мнения о человеке не бывает — "
              "бывает первое впечатление",
              "не строить выводов; просто смотреть дальше")
        return находки

    if (в["доверие_макс"] >= config.BALANCE_TRUST_HIGH and в["проверок"] == 0
            and not из_своих):
        нашла("слепое_доверие",
              f"доверие в теме «{в['самый_доверенный']}» {в['доверие_макс']}, "
              f"проверок ни одной",
              "это не доверие, а невнимательность: доверие — это когда "
              "проверить было можно и не понадобилось, а не когда в "
              "голову не пришло",
              "при случае проверить одно его утверждение — не из "
              "подозрения, а чтобы вера была на чём-то")

    if (в["доверие"] <= config.BALANCE_TRUST_LOW and в["минусов"] <= 2
            and (в["дней_с_последней_улики"] or 0) > config.BALANCE_STALE_DAYS):
        нашла("глухая_критика",
              f"доверие {в['доверие']} по {в['минусов']} случаям, "
              f"последний был {в['дней_с_последней_улики']} дн. назад",
              "человека держат на низком доверии по паре старых эпизодов, "
              "а новых поводов нет. Это уже не осторожность, а привычка",
              "дать шанс: заговорить первой и посмотреть на свежем")

    if (в["минусов"] == 0 and в["улик"] >= config.BALANCE_TOO_GOOD_EVIDENCE
            and not из_своих):
        нашла("слишком_хороший",
              f"{в['улик']} встреч и ни одной шершавой",
              "так не бывает даже с хорошими людьми. Значит, либо я не "
              "видела его в неудобной ситуации, либо не смотрела. Это "
              "дыра в наблюдении, а не улика против него",
              "не искать плохое специально; заметить, как он ведёт себя, "
              "когда ему неудобно или когда с ним спорят")

    if abs(в["симпатия"] - в["проверяемость"]) >= config.BALANCE_AXIS_GAP:
        сильнее = ("нравится сильно больше, чем проверен"
                   if в["симпатия"] > в["проверяемость"]
                   else "проверен сильно лучше, чем нравится")
        нашла("перекос_осей",
              f"симпатия {в['симпатия']:.0f}, проверяемость {в['проверяемость']:.0f}",
              f"он мне {сильнее}. Симпатия — ось вкуса, она не даёт "
              "права считать его правым (и не отнимает этого права)",
              "разделить: что мне в нём нравится и что он на деле "
              "подтвердил")

    # ── КРАЙ ШКАЛЫ — ЭТО ПОВОД УСОМНИТЬСЯ В СЕБЕ, А НЕ В ЧЕЛОВЕКЕ ──
    # (владелец 25.08). Если стрелка легла на упор, вероятнее не то, что
    # человек идеален или невыносим, а то, что смотрела я криво: одну
    # сторону считала, другую нет. Поэтому у самого края разбор задаёт
    # вопрос не про него, а про себя — и это единственная находка,
    # которая обязана попасть наверх немедленно.
    if abs(в["перекос"]) >= config.BALANCE_DOUBT_EDGE:
        куда = "веры" if в["перекос"] > 0 else "недоверия"
        нашла("сомнение_в_себе",
              f"перекос {в['перекос']:+.0f} из 100 в сторону {куда}",
              "стрелка на упоре. Так не бывает у людей — так бывает у "
              "наблюдения: скорее всего я считала одну сторону и не "
              "считала другую",
              "перепроверить не человека, а себя: что я в нём НЕ "
              "смотрела? Позвать владельца рассудить")

    тренд = _по_третям(в["_улики"])
    if тренд:
        было, стало = тренд
        if было >= 0.4 and стало <= -0.3:
            нашла("раскрылся_хуже",
                  f"в начале знакомства {было:+.1f}, теперь {стало:+.1f}",
                  "человек привык и перестал держаться. Важное различие: "
                  "он не изменился — он таким был, просто раньше "
                  "сдерживался. Первое впечатление было не о нём",
                  "смотреть на последнюю треть, а не усреднять всё "
                  "знакомство: среднее здесь врёт")
        elif было <= -0.4 and стало >= 0.3:
            нашла("раскрылся_лучше",
                  f"в начале {было:+.1f}, теперь {стало:+.1f}",
                  "начало было колючим, дальше ровно. Возможно, человек "
                  "просто закрывался с незнакомыми, а я записала это "
                  "в характер",
                  "пересмотреть выводы, сделанные в первые встречи")
    return находки


def для_карточки(con, person_id: int, максимум: int = 2) -> list[str]:
    """Короткие строки разбора — в карту человека и оттуда в промпт.
    Двух хватает: это подсказка себе, а не досье."""
    out = []
    for н in разбор(con, person_id)[:максимум]:
        out.append(f"[качели: {н['код']}] {н['что']} — {н['делать']}")
    return out


# ── Вспышка: состояние, а не черта ────────────────────────────────
def вспышка(con, person_id: int, что: str) -> dict:
    """Разовая резкость. НЕ трогает черты — по устройству.

    Правило общее для всех, включая владельца: у человека бывает
    тяжёлый день, и путать это со свойством характера нельзя. Чертой
    вспышка становится, только если повторяется в РАЗНЫЕ дни: один
    вечер это настроение, пять вечеров за месяц — это уже как он живёт.
    """
    persons.add_karma(con, person_id, f"вспышка: {что}", 0, "быт",
                      delta=0.0)                      # журнал есть, сдвига нет
    дни = {int(r["ts"] // СУТКИ) for r in con.execute(
        "SELECT ts FROM karma_journal WHERE person_id=? AND event LIKE 'вспышка:%'",
        (person_id,))}
    стало_чертой = False
    if len(дни) >= config.FLASH_DAYS_TO_TRAIT:
        persons.observe_inner(con, person_id,
                              f"в напряжении срывается: {что}",
                              event_id=int(time.time()))
        стало_чертой = True
    return {"разных_дней": len(дни), "стало_чертой": стало_чертой}


# ── Флаг: одна фраза ничего не значит ─────────────────────────────
def флаг(con, person_id: int, тема: str, возразили: bool = False) -> dict:
    """Дикая фраза. Первая — просто отметка почти без веса.

    Понять по одной реплике, всерьёз человек или это местный мем,
    нельзя — и пытаться не надо. Значение имеет ПОВТОР ПОСЛЕ
    ВОЗРАЖЕНИЯ: ему сказали, что так не смешно, а он держится темы.
    Вот это уже позиция, и вот это стоит веса.
    """
    было = con.execute(
        "SELECT COUNT(*) c FROM karma_journal WHERE person_id=?"
        " AND event LIKE ?", (person_id, f"флаг: {тема}%")).fetchone()["c"]
    persons.add_karma(con, person_id, f"флаг: {тема}", -1, "этика",
                      delta=config.FLAG_FIRST_DELTA)
    позиция = было >= 1 and возразили
    if позиция:
        persons.add_karma(con, person_id, f"держится темы «{тема}» после возражения",
                          -1, "этика", axis="конструктивность",
                          delta=config.FLAG_REPEAT_DELTA)
        persons.observe_inner(con, person_id,
                              f"держится темы «{тема}» даже когда возражают",
                              event_id=int(time.time()))
    return {"отметок": было + 1, "стало_позицией": позиция,
            "как_понимать": ("это уже позиция, а не шутка" if позиция
                             else "пока просто отметка — одной фразы мало")}
