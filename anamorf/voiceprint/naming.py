# Морфология: слово с таким хвостом — почти наверняка глагол, наречие
# или прилагательное, а не имя. Проверено на живом аниме-логе: снимает
# «Благодарить», «Пожалуй», «Спрашивал», «Продолжать», не трогая
# «Мизели», «Тестаросса», «Ремуру», «Диабло», «Леон».
_NOT_NAME_TAIL = ("ть", "ться", "ешь", "ёшь", "ете", "ёте", "ите",
                  "уй", "уйте", "айте", "ейте", "ают", "яют", "уют",
                  "ует", "ишь", "ыть", "ать", "ять", "еть", "лся",
                  "лись", "ного", "ному", "ными", "ший", "щий", "мый")

_SELF = [
    re.compile(r"\bменя\s+зовут\s+([а-яёa-z]{2,20})", re.I),
    re.compile(r"\bэто\s+я[, ]+([а-яёa-z]{2,20})\b", re.I),
    re.compile(r"\bя\s+([а-яёa-z]{2,20})\s*[,.!]", re.I),
]
# ОБРАЩЕНИЕ ПО ИМЕНИ — ТОЛЬКО С УЛИКОЙ (2026-08-16).
# Правило «первое слово фразы + запятая = имя» приходится выбросить:
# заглавная буква в начале предложения стоит ВСЕГДА, и отличить «Мизели,
# постой» от «Пожалуй, постой» по ней невозможно. Улики бывают двух
# видов, и обе надёжные:
#   1. ТИТУЛ впереди — «госпожа Тестаросса», «господин Йохан», «великий
#      Ремуру», «леди Анна». В русском после титула стоит именно имя.
#   2. ЗАГЛАВНАЯ БУКВА В СЕРЕДИНЕ фразы — в русском так пишутся только
#      имена собственные. «…, Мизели!» проходит, «…, пожалуй» нет.
_TITLE = re.compile(
    r"(?:[Гг]осподин[ауеом]?|[Гг]оспож[аеиую]|[Мм]астер[ауе]?|[Лл]еди|"
    r"[Сс]эр|[Сс]ударь|[Сс]ударыня|[Вв]елик(?:ий|ому|ая|ой)|"
    r"[Кк]нязь|[Кк]орол(?:ь|ева|ю)|[Пп]ринц(?:есса)?)\s+"
    r"([А-ЯЁA-Z][а-яёa-zА-ЯЁA-Z\-]{2,19})")
_ADDR_MID = [
    # «…, Мизели!» / «…сном, Мизели.» — имя после запятой в конце фразы
    re.compile(r"[,]\s*([А-ЯЁA-Z][а-яёa-z\-]{2,19})\s*[.!?]*\s*$"),
    # «Слушай, Гай», «эй, Леон» — после прямого оклика
    re.compile(r"(?:[Сс]лушай|[Сс]мотри|[Ээ]й|[Пп]ривет|[Зз]дравствуй)"
               r"[, ]+([А-ЯЁA-Z][а-яёa-z\-]{2,19})\b"),
]

# ЗАГЛАВНАЯ В СЕРЕДИНЕ ФРАЗЫ. В русском так пишутся только имена
# собственные, и это самый общий признак: «Это я говорю про Виоли»,
# «противостоять Гаю», «передавай привет Ремуру». Слово после точки и
# самое первое не берём — там заглавная стоит по правилу, а не по сути.
_MID_CAP = re.compile(r"(?<![.!?…]\s)(?<!^)\b([А-ЯЁ][а-яё\-]{2,19})\b")


def _ok(w: str) -> bool:
    w = (w or "").strip().lower()
    if not w or w in STOP or len(w) < 3 or w.isdigit():
        return False
    return not w.endswith(_NOT_NAME_TAIL)


def _cap(w: str) -> str:
    w = w.strip().lower()
    return w[:1].upper() + w[1:]


# ═══ ИМЯ — В ИМЕНИТЕЛЬНОМ ПАДЕЖЕ (27.08.2026) ═══
# Замер на живых фразах: «мы вчера с Мариной ходили» давало метку
# «Мариной». В карте голосов заводился отдельный человек на каждый падеж:
# Марина, Марину, Мариной, Марине — четыре карточки на одну женщину.
# Приводим к словарной форме по типичным окончаниям русских имён.
_CASE_RU = (
    ("ою", "а"), ("ей", "я"), ("ой", "а"), ("ою", "а"),
    ("ом", ""), ("ем", "ь"), ("ым", ""),
    ("у", ""), ("ю", "я"), ("е", "а"), ("и", "а"), ("ы", "а"), ("а", "а"),
)
_KEEP_AS_IS = ("а", "я", "й", "н", "р", "л", "м", "с", "т", "к", "в", "г", "д")


def _nominative(w: str) -> str:
    """Мариной -> Марина, Диме -> Дима, Ольгу -> Ольга. Осторожно:
    трогаем только то, что после отката остаётся похожим на имя."""
    s = (w or "").strip()
    if len(s) < 4:
        return s
    low = s.lower()
    for end, repl in (("ой", "а"), ("ей", "я"), ("ою", "а"), ("ею", "я")):
        if low.endswith(end):
            return _cap(low[:-len(end)] + repl)
    for end, repl in (("ом", "а"), ("ем", "я"), ("ым", "а")):
        if low.endswith(end):
            return _cap(low[:-len(end)] + repl)
    if low.endswith(("у", "ю")) and len(low) > 4:
        return _cap(low[:-1] + ("а" if low.endswith("у") else "я"))
    if low.endswith(("е", "и")) and len(low) > 4:
        return _cap(low[:-1] + "а")
    return _cap(low)


# отчество: «Андрей Петрович» — имя ПЕРВОЕ, отчество не имя
_PATRONYMIC = re.compile(r"^[А-ЯЁ][а-яё\-]+(ович|евич|ьич|овна|евна|ична|инична)$",
                         re.I)


def guess(text: str):
    """-> список (имя, кому, вес): кому = "self" (говорящему) или
    "address" (собеседнику). Пустой список — имён не услышала."""
    t = (text or "").strip()
    if not t or len(t) > 400:
        return []
    out = []
    seen = set()
    for rx in _SELF:
        m = rx.search(t)
        if m and _ok(m.group(1)):
            n = _cap(m.group(1))
            if n not in seen:
                seen.add(n)
                # «меня зовут» весит втрое против «я такой-то»: второе
                # сплошь и рядом просто оборот речи
                out.append((n, "self", 3.0 if "зовут" in m.group(0).lower() else 1.0))
    for rx in ([_TITLE] + _ADDR_MID):
        m = rx.search(t)
        if m and _ok(m.group(1)):
            n = _cap(m.group(1))
            if n not in seen:
                seen.add(n)
                # ВЕС ОБРАЩЕНИЯ (2026-07-29, живой случай: владелец весь
                # день звал собеседника «Николай», а метка так и не
                # приклеилась). Вес был 1.0 при пороге 6.0 — то есть шесть
                # обращений, да ещё с отрывом вдвое от второго кандидата.
                # Для имени, услышанного мельком в чужом разговоре, это
                # правильная осторожность. Но «Николай, ...» и следом ОТВЕТ
                # ДРУГОГО ГОЛОСА — это не мельком, это почти представление:
                # позвали — откликнулся. Два таких обмена и должны решать.
                out.append((n, "address", 3.0))
    # заглавная в середине фразы — слабее прямого обращения, но это
    # единственный способ поймать имя, произнесённое в третьем лице
    # («противостоять Гаю», «привет Ремуру»): в аниме персонажей чаще
    # называют так, чем окликают
    for m in _MID_CAP.finditer(t):
        w = m.group(1)
        if not _ok(w) or w.lower() in seen:
            continue
        # ОТЧЕСТВО — НЕ ИМЯ. «Андрей Петрович будет в среду» давало метку
        # «Петрович»: обе части с заглавной, побеждала вторая. Отчество
        # пропускаем целиком — имя стоит перед ним и уже поймано.
        if _PATRONYMIC.match(w):
            continue
        n = _nominative(w)
        if not _ok(n) or n in seen:
            continue
        seen.add(n)
        out.append((n, "address", 1.0))
    # ОБРАЩЕНИЕ В НАЧАЛЕ ФРАЗЫ: «Серёга, подай ключ». Правило когда-то
    # выбросили — оно вешало имена на вводные слова. Возвращаем с двумя
    # замками: слово проходит проверку на имя (огромный STOP отсекает
    # вводные) И после запятой идёт продолжение фразы. Вес намеренно
    # низкий: одного раза мало, порог переименования 6.0 с отрывом вдвое,
    # то есть решают только повторные обращения, а не случайная оговорка.
    m0 = re.match(r"^\s*([А-ЯЁ][а-яё\-]{2,19})\s*,\s*\S", t)
    if m0 and _ok(m0.group(1)):
        n = _nominative(m0.group(1))
        if _ok(n) and n not in seen:
            seen.add(n)
            out.append((n, "address", 1.0))
    return out
