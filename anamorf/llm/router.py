"""Быстрое мышление: какой моделью думать НАД ЭТОЙ репликой (2026-07-27).

ИДЕЯ (владельца). Локальная модель на своём llama-server отвечает за доли
секунды — но она маленькая. Облачная умная — но платит секунды за prefill и
деньги за токены. Живому компаньону нужно и то и другое: болтовня и быстрые
реакции — молниеносно локально, а когда человек приносит настоящую задачу
(разбор, код, документ, расчёт) — незаметно подключается тяжёлая голова.

Это НЕ вторая LLM-классификация (она бы сама стоила задержку). Это «быстрое
мышление» в буквальном смысле: дешёвые признаки по самой фразе, доли
миллисекунды. Ошибка не фатальна в обе стороны: локальная модель на сложном
вопросе честно старается (как и раньше), облако на простом — просто дороже.

Маршрут выбирается НА ОДИН ХОД, конфиг не трогается: llm.backend остаётся
какой был, а выбор уезжает в chat_stream(prefer=...). Фолбэк прежний: облако
упало — тот же ход договаривает локальная, человек видит это в подписи под
сообщением (мы не скрываем, КТО отвечал, — мы скрываем ПАУЗУ).

Включение: llm.router.enabled (по умолчанию false — облако может быть
платным, решение за владельцем).
"""
import logging
import re

from anamorf.config import CFG

log = logging.getLogger("saika.router")

# Признаки НАСТОЯЩЕЙ ЗАДАЧИ — за каждый начисляются очки.
# Слова подбирались по реальным диалогам из логов, а не из головы.
_HEAVY = (
    # анализ и рассуждение
    r"проанализ|разбер[иё]|сравн[иы]|объясни подробн|почему .{12,}|"
    r"докажи|обоснуй|стратег|спланируй|продумай|архитектур|"
    # код и математика
    r"код|функци|скрипт|программ|отладь|почини|рефактор|"
    r"посчитай|вычисли|уравнен|формул|"
    # документы и длинные тексты
    r"документ|договор|статья|отч[её]т|резюме|переведи|перескажи|"
    r"напиши (статью|письмо|текст|пост|доклад)|"
    # исследование
    r"исследуй|изучи|найди вс[её]|собери информац"
)
# Признаки болтовни — очки в минус (локальная справится блестяще и мгновенно)
_LIGHT = (
    r"^(привет|здаров|хай|йоу|ку|добр(ое|ый))|как (дела|ты|жизнь)|"
    r"что делаешь|скучала|спасибо|молодец|умница|люблю|погод|"
    r"расскажи (шутку|анекдот)|спой|похвали"
)


def pick(user_text: str) -> tuple:
    """('local'|'cloud', причина). Дёшево: одна прогонка регексов."""
    if not CFG.get("llm.router.enabled", False):
        return "local", "маршрутизатор выключен"
    c = CFG.get("llm.cloud", {}) or {}
    if not (c.get("enabled") and c.get("model")):
        return "local", "облако не настроено"
    t = (user_text or "").strip().lower()
    if not t:
        return "local", "пустая фраза"

    score = 0
    reasons = []
    if re.search(_HEAVY, t):
        score += 2
        reasons.append("похоже на задачу")
    if re.search(_LIGHT, t):
        score -= 2
        reasons.append("похоже на болтовню")
    # длинная фраза = человек принёс контекст, а не реплику
    if len(t) > int(CFG.get("llm.router.long_chars", 220)):
        score += 1
        reasons.append("длинная фраза")
    # код/данные прямо в сообщении
    if "```" in t or re.search(r"[{};=]{2,}|def |class |select .+ from", t):
        score += 2
        reasons.append("в фразе код/данные")
    # короткие фразы без признаков задачи — всегда локально: реактивность
    # для них важнее ума, и именно они составляют 90% живого диалога
    if len(t) < 40 and score <= 0:
        return "local", "короткая реплика"

    need = int(CFG.get("llm.router.cloud_score", 2))
    if score >= need:
        why = ", ".join(reasons) or "набрала очки"
        log.info("Быстрое мышление: облако (%s, очки %d)", why, score)
        return "cloud", why
    return "local", ", ".join(reasons) or "обычный разговор"
