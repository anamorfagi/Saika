"""МОЗГИ — модели, лестница выбора и инструменты.

Лестница (`brains.py`): локальная модель ведёт разговор и держит руки,
облачные подключаются на сложное и страхуют, когда локальная занята или
сломалась. Выбор не случайный: у каждой модели есть паспорт (`passport.py`)
и паспорт умений (`skills.py`), снятые пробами, а не заявленные в описании.

Отдельное правило, купленное дорого: модель, которая инструменты только
ИЗОБРАЖАЕТ словами («Пробую открыть YouTube» — и ничего не вызывает),
рук не получает. Проверка живёт в `anamorf/capabilities.py`, лестница её
обязана уважать.

Кто есть кто:

* `manager.py`     — бэкенды (Ollama, LM Studio, свой llama.cpp),
                     переключение, автофоллбэк, выгрузка под давлением.
* `brains.py`      — лестница: кому думать, кому держать руки.
* `llamacpp.py`    — свой движок: нативный llama-server с CUDA.
* `locallm.py`     — воркер «своей» LLM без Ollama и LM Studio.
* `dreampc.py`     — воркер диффузионной LLaDA-8B.
* `train_manager.py` — воркер дообучения.
* `passport.py`    — авто-профилирование модели при первом знакомстве.
* `skills.py`      — что модель умеет и насколько хорошо.
* `router.py`      — какой моделью думать НАД ЭТОЙ репликой.
* `free_tiers.py`  — каталог облачных моделей с бесплатным тиром.
* `autoconnect.py` — поднять всё, до чего дотянемся, без ручной настройки.
* `guard.py`       — обрыв зависшей генерации (лупы).
* `tools.py`       — клиент HandsPC: «руки» как внешний сервис.

Настройки: `llm.*` в `config.json`, разбор — в `CONFIG.md`.
"""
