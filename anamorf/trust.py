"""Доверие: когда Сайка делает молча, а когда сперва спрашивает.

ЗАЧЕМ. Как только у неё появились руки в системе, вопрос «спрашивать или
делать» перестал быть вопросом вкуса. Владелец сформулировал так: на очень
умной модели и высоком доверии она делает длинные цепочки сама; если модель
мелкая, а доверия мало — под присмотром.

ФОРМУЛА. Одна ручка в интерфейсе (trust.level, 1..10) задаёт базу, а
модель за рулём сдвигает её в обе стороны. Отдельно крутить «доверие к
каждой модели» — путь в ад настроек: моделей у владельца три десятка.

  запас = доверие + сдвиг_модели        (-2 глупая … +1 очень толковая)

Из запаса вытекает ровно две вещи:
  1. какой риск действий она берёт на себя без вопроса;
  2. сколько шагов подряд делает, прежде чем отчитаться.

РАЗОВОЕ ПОВЫШЕНИЕ. «Делай как знаешь», «сама разберись», «не спрашивай» в
начале фразы поднимают планку на этот ход. Обратное («спроси меня»,
«осторожно») — опускают. Это ближе к живому разговору, чем лазать в
настройки ради одной просьбы.

ЧЕГО ФОРМУЛА НЕ РЕШАЕТ. Есть действия, которые не спрашивают разрешения у
арифметики: снять процесс, стереть файл, выключить компьютер. Для них
подтверждение нужно всегда, кроме максимального запаса — и даже тогда
Сайка обязана сказать, что именно делает.
"""
