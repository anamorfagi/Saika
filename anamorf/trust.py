DEFAULT_RISK = 3

# Разовые оговорки в начале фразы. Ловим начало, а не любое вхождение:
# «сделай как знаешь» в середине рассказа — это не разрешение.
_FREE = re.compile(
    r"^\W*(?:ну\s+)?(?:давай\s+)?(?:делай|действуй|поступай|решай|разбирайся|"
    r"сделай)?\s*(?:как\s+знаешь|как\s+считаешь|сама|сам[аи]?\s+реши|"
    r"на\s+сво[её]\s+усмотрение|не\s+спрашивай|без\s+вопросов)", re.I)
_CAREFUL = re.compile(
    r"^\W*(?:осторожн|аккуратн|спроси|уточни|сначала\s+спроси|"
    r"только\s+с\s+моего)", re.I)


def level() -> int:
    return max(1, min(10, int(CFG.get("trust.level", 5) or 5)))


def model_smart() -> int:
    """Насколько модель ЗАСЛУЖИВАЕТ доверия, 1..10.

    2026-07-26, поправка владельца: «4b высоко в рейтинге только потому,
    что бодро отвечает, но она часто ошибалась или не делала под видом что
    сделала — доверие к ней на самом деле низкое». Это разные оси, и здесь
    нужна вторая. Рейтинг скорости (ratings) сюда больше не заходит вообще
    — надёжность ведёт отдельное досье (anamorf/model_dossier.py): ручная
    оценка владельца, пойманные «сказала, что сделала», ошибки
    инструментов, чистые ходы.
    """
    model = CFG.get("llm.model", "") or ""
    if not model:
        return 3
    try:
        from anamorf import model_dossier
        return model_dossier.reliability(model)
    except Exception as e:
        log.debug("досье моделей недоступно: %s", e)
    # запасной путь, если досье почему-то не читается
    base = 6 if CFG.get("llm.backend") == "cloud" else 4
    if model in set(CFG.get("llm.tools_broken", [])):
        base = min(base, 3)
    return base


def budget(user_text: str = "") -> int:
    """Итоговый запас доверия на этот ход, 1..10.

    2026-07-26: было level×smart/10 — и это душило. При ползунке 5 даже
    самая толковая облачная модель получала 5, а средняя локальная — 4;
    планка «сколько тебе доверяют» физически не могла подняться выше
    положения ползунка. Теперь ползунок задаёт БАЗУ, а модель сдвигает её
    в обе стороны: глупая отнимает, умная добавляет. Так «доверие 7»
    действительно означает семь, а не «семь, если повезёт с моделью».
    """
    smart = model_smart()
    shift = -2 if smart <= 2 else -1 if smart <= 4 else 0 if smart <= 7 else 1
    b = level() + shift
    t = user_text or ""
    if _FREE.search(t):
        b += 3
    if _CAREFUL.search(t):
        b -= 4
    return max(1, min(10, b))


def max_risk(b: int) -> int:
    """Какой риск она берёт на себя без вопроса при таком запасе."""
    if b <= 2:
        return 1          # только смотреть
    if b <= 4:
        return 2          # плюс обратимое: запуск, окна, звук, папки
    if b <= 6:
        return 3          # плюс создание файлов и закрытие окон
    if b <= 8:
        return 4          # плюс переносы и переименования
    return 5              # всё, но вслух


def max_chain(b: int) -> int:
    """Сколько действий подряд без отчёта. Мелкая модель на низком доверии
    делает один шаг и показывается — иначе она уедет в свою фантазию на
    десять вызовов, и разгребать это будет человек."""
    return {1: 1, 2: 1, 3: 2, 4: 2, 5: 3, 6: 4, 7: 5, 8: 6, 9: 8, 10: 10}[b]


def allowed(tool: str, user_text: str = "") -> tuple[bool, str]:
    """Можно ли выполнить этот инструмент прямо сейчас.
    Возвращает (можно, причина-для-модели)."""
    if not CFG.get("pc.enabled", True):
        return False, ("управление компьютером выключено владельцем "
                       "в настройках")
    b = budget(user_text)
    r = RISK.get(tool, DEFAULT_RISK)
    if r <= max_risk(b):
        return True, ""
    # ПРЯМАЯ ПРОСЬБА = УЖЕ ДАННОЕ ПОДТВЕРЖДЕНИЕ (2026-07-28, реальный
    # случай: «на первом экране открыта папка X — закрой её» упёрлось в
    # «опиши и дождись да». Человек ПОПРОСИЛ закрыть — ждать «да» на
    # собственную просьбу абсурдно, доверие тут вообще ни при чём: оно
    # придумано против САМОДЕЯТЕЛЬНОСТИ модели, а не против исполнения
    # приказов. Если в фразе человека есть намерение ровно этого действия
    # (та же карта, что у предохранителя _intent_ok) — пускаем.
    import re as _re
    try:
        from anamorf.llm import tools as _tls          # ленивый, без цикла
        pat = _tls._MUTATING_INTENT.get(tool)
        if pat and _re.search(pat, user_text or "", _re.I):
            return True, ""
    except Exception:
        pass
    # короткое чистое согласие («да», «давай») после ЕЁ ЖЕ вопроса —
    # это и есть то самое «дождись да», ради которого отказ и писался
    if _re.fullmatch(r"\s*(да+[\s,!.-]*)+|\s*(давай|ага|угу|конечно|ок|"
                     r"окей|хорошо|можно|валяй|делай|попробуй)[\s!.]*",
                     (user_text or "").lower()):
        return True, ""
    return False, (
        f"это действие требует подтверждения: доверия сейчас {b} из 10, "
        f"а «{tool}» относится к риску {r}. Опиши человеку ОДНОЙ фразой, "
        "что собираешься сделать, и дождись «да». Если он скажет «делай как "
        "знаешь» — планка поднимется сама.")


def describe() -> dict:
    """Для интерфейса: что означает текущая настройка на человеческом."""
    b = budget()
    r, c = max_risk(b), max_chain(b)
    what = {1: "только смотреть", 2: "смотреть и поправлять обратимое",
            3: "запускать программы и создавать файлы",
            4: "ещё и закрывать окна",
            5: "всё, включая снятие процессов — но вслух"}[r]
    return {"level": level(), "model": CFG.get("llm.model", ""),
            "model_smart": model_smart(), "budget": b,
            "max_risk": r, "max_chain": c,
            "summary": f"{what}; до {c} действий подряд без отчёта"}
