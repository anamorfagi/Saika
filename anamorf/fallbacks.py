# ЗАПАСНОЙ НЕ ИМЕЕТ ПРАВА ДЕЛАТЬ БОЛЬШЕ ИСХОДНОГО (2026-08-15, поймано
# через час после того, как я это написал). Живой лог: агентный цикл
# дёргает folder_list, предохранитель его блокирует, запасной путь
# честно «спасает» — и открывает на экране проводник. Владелец в это
# время просто разговаривал: «Мне показалось, или ты папку открыла?».
# Открыла. Правило: подменять можно только РАВНОЕ по последствиям.
# Чтение подменяется чтением; открыть окно, запустить программу, нажать
# клавишу — это действия, у них запасных быть не может: не вышло —
# скажи, что не вышло. Ошибка была ровно в паре folder_list <-> open_folder:
# первый читает, второй лезет на экран.

# что чинить в фоне, если этот инструмент лёг
REPAIR = {
    "look_screen": "vision",
    "screen_read": "ui_hands",
    "web_search": "browser",
    "web_research": "browser",
    "web_list": "browser",
}


_TOLD = {}          # о чём уже доложили — чтобы не долбить одним и тем же


def _repair_bg(part: str, tool: str, why: str) -> None:
    """Починка уезжает в фон: дело от неё не зависит и её не ждёт.

    Ремонт тут не «переустановить всё», а две честные вещи: записать
    грабли (чтобы следующий раз этот путь не выбирался вслепую) и один
    раз сказать вслух, что узел лёг — молчаливых поломок у нас нет
    (PHILOSOPHY §0.5).
    """
    import time as _t

    def run():
        try:
            from anamorf import recipes
            recipes.remember_fail("узел " + part, tool, {}, why[:300])
        except Exception as e:
            log.debug("грабли не записались: %s", e)
        last = _TOLD.get(part, 0)
        if _t.time() - last < 600:
            return
        _TOLD[part] = _t.time()
        try:
            from anamorf.main import report_problem
            report_problem(part, "«%s» не отработал: %s" % (tool, why[:160]),
                           "задачу доделала запасным путём; посмотри этот "
                           "узел, когда будет минута")
        except Exception as e:
            log.debug("доложить о %s не вышло: %s", part, e)
    threading.Thread(target=run, daemon=True,
                     name="repair:" + part[:12]).start()


def rescue(name: str, arguments, failed_result: str, run) -> str:
    """Вызывается, когда инструмент вернул неудачу.

    run(имя, аргументы) — как выполнить запасной (передаёт вызывающий,
    чтобы не тащить сюда весь диспетчер и не ловить круговой импорт).
    Возвращает результат запасного или исходную неудачу, если не помог
    никто.
    """
    alts = CHAIN.get(name) or []
    part = REPAIR.get(name)
    if part:
        _repair_bg(part, name, failed_result)
    for alt in alts:
        try:
            res = str(run(alt, arguments) or "")
        except Exception as e:
            log.debug("запасной %s тоже упал: %s", alt, e)
            continue
        if not res:
            continue
        from anamorf.llm.tools import _FAIL_RE
        if _FAIL_RE.match(res):
            continue
        log.info("«%s» не вышло — сделала через «%s», задачу не бросаю",
                 name, alt)
        return (res + "\n(основной путь «%s» сейчас не работает, сделала "
                "через «%s» — результат выше настоящий)" % (name, alt))
    return failed_result
