"""ПАСПОРТ МИКРОФОНА — знание о первом сенсоре системы (2026-08-15).

ЗАМЫСЕЛ ВЛАДЕЛЬЦА, дословно: «система должна правильно идентифицировать
микро — какая плата, есть ли у неё потенциальные дефекты, что нужно
сделать, чтобы получать чистый звук для транскриба и меток».

Микрофон — первый элемент всей сенсорики: любой дефект в нём протекает во
ВСЁ (VAD, движки, отпечаток, метки). Паспорт складывается из двух половин:

  КТО ОН — имя устройства из браузера (владелец выбирает его в меню 🎙;
  по имени видно тракт: «USB», «Realtek» — встройка материнки, «Bluetooth
  Hands-Free» — телефонный профиль с полосой 8 кГц, худший случай);

  ЧЕМ БОЛЕЕТ — диагнозы по живому звуку, каждый с советом:
    - клиппинг: сэмплы бьются в потолок — усиление велико, движки слышат
      треск вместо согласных;
    - наводка 50/100 Гц: узкий горб в спектре шума — земля/питание;
    - высокий шумовой пол: постоянное шипение — дешёвый тракт или
      задранный gain; тихий голос будет тонуть;
    - обрезанная полоса: энергия кончается до 6-7 кГц — тракт режет верха
      (Bluetooth HFP!), «с» и «ц» неразличимы для движка;
    - постоянное смещение (DC): плата с дефектом связи по постоянному
      току — ест динамический диапазон;
    - провалы: очередь роняла куски — виноват не микрофон, а конвейер.

Копится из живого звука мимоходом (окно раз в несколько секунд), отчёт
по запросу: /api/mic. Ничего не пишется на диск — паспорт живёт сеанс.
"""
import logging
import threading
import time

import numpy as np

from anamorf.config import CFG

log = logging.getLogger("saika.mic")

SR = 16000

_lock = threading.Lock()
S = {"device": "", "set_at": 0.0,
     "n": 0, "clip": 0, "dc": 0.0, "floor": 1.0,
     "hum50": 0.0, "band_top": 0.0, "ts": 0.0}


def set_device(label: str):
    with _lock:
        S["device"] = (label or "")[:120]
        S["set_at"] = time.time()
    log.info("Микрофон: паспорт заведён на «%s»", S["device"])


def feed(pcm16: np.ndarray):
    """Кусок из горячего цикла. Меряем не чаще раза в 3с — этого хватает,
    а конвейеру и так есть чем заняться."""
    now = time.time()
    if now - S["ts"] < 3.0:
        return
    try:
        x = np.asarray(pcm16, dtype=np.float32).ravel()
        if x.size < SR // 10:
            return
        with _lock:
            S["ts"] = now
            S["n"] += 1
            # клиппинг: доля сэмплов у потолка
            S["clip"] = 0.95 * S["clip"] + 0.05 * float(
                np.mean(np.abs(x) >= 32300))
            # смещение нуля
            S["dc"] = 0.95 * S["dc"] + 0.05 * float(np.mean(x)) / 32768.0
            xf = x / 32768.0
            rms = float(np.sqrt(np.mean(xf ** 2)))
            # шумовой пол: минимум RMS из виденного (медленно всплывает)
            S["floor"] = min(S["floor"] * 1.01, max(S["floor"] * 0.5, rms)) \
                if rms < S["floor"] else S["floor"] * 1.001
            spec = np.abs(np.fft.rfft(xf * np.hanning(len(xf))))
            fr = np.fft.rfftfreq(len(xf), 1.0 / SR)
            tot = float(spec.sum()) + 1e-9
            # наводка: узкие пики на 50 и 100 Гц против соседей
            for f0 in (50.0, 100.0):
                band = spec[(fr > f0 - 3) & (fr < f0 + 3)]
                near = spec[(fr > f0 - 15) & (fr < f0 + 15)]
                if band.size and near.size:
                    r = float(band.max() / (near.mean() + 1e-9))
                    S["hum50"] = max(S["hum50"] * 0.98, min(r, 30.0))
            # верх полосы: где кончаются 99% энергии
            cum = np.cumsum(spec) / tot
            idx = int(np.searchsorted(cum, 0.99))
            top = float(fr[min(idx, len(fr) - 1)])
            S["band_top"] = max(S["band_top"] * 0.995, top)
    except Exception as e:
        log.debug("паспорт микрофона: %s", e)


def report() -> dict:
    """Диагнозы + советы. Каждый порог можно назвать вслух."""
    with _lock:
        d = dict(S)
    problems, advice = [], []
    dev = d["device"].lower()
    if "bluetooth" in dev or "hands-free" in dev or "headset" in dev:
        problems.append("Bluetooth-гарнитура: в режиме разговора полоса "
                        "режется до ~8 кГц и хуже")
        advice.append("для транскриба подключи проводной/USB микрофон или "
                      "используй BT только как наушники (A2DP), а микро — "
                      "другой")
    if d["clip"] > 0.001:
        problems.append(f"клиппинг: {d['clip']*100:.2f}% сэмплов бьются в "
                        "потолок — согласные превращаются в треск")
        advice.append("убери усиление в микшере Windows на 10-20%")
    if d["hum50"] > 8:
        problems.append("наводка 50/100 Гц (гул земли/питания): узкий горб "
                        f"в {d['hum50']:.0f} раз выше соседей")
        advice.append("другой USB-порт (лучше сзади корпуса), не тот же "
                      "удлинитель, что у блока питания; шумодав gate её "
                      "приглушит")
    if d["floor"] > 0.012:
        problems.append(f"высокий шумовой пол ({d['floor']:.3f} RMS): "
                        "постоянное шипение, тихий голос тонет")
        advice.append("если gain задран — опусти; если это сам тракт — "
                      "шумодав wiener честно помогает именно тут")
    if 0 < d["band_top"] < 6000 and d["n"] > 20:
        problems.append(f"полоса кончается на ~{d['band_top']:.0f} Гц — "
                        "«с»/«ц»/«ф» для движка неразличимы")
        advice.append("проверь, что в Windows у микрофона формат 16 бит "
                      "48000 Гц, а не «телефонное качество»")
    if abs(d["dc"]) > 0.01:
        problems.append(f"смещение нуля {d['dc']*100:.1f}% — плата ест "
                        "динамический диапазон")
        advice.append("обычно лечится другим входом/платой; не критично, "
                      "но паспорту положено об этом знать")
    return {"device": d["device"] or "(браузер ещё не сообщил)",
            "windows_seen": d["n"],
            "noise_floor_rms": round(d["floor"], 4),
            "clip_pct": round(d["clip"] * 100, 3),
            "hum_peak_x": round(d["hum50"], 1),
            "band_top_hz": round(d["band_top"]),
            "problems": problems or ["дефектов не вижу — тракт чистый"],
            "advice": advice or ["ничего не трогай, звук для транскриба "
                                 "пригодный"]}
