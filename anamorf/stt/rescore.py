"""МОЗГ В УХЕ — переслушивание текста смыслом, а не звуком.

ЗАМЫСЕЛ ВЛАДЕЛЬЦА, дословно: «на уровне уха человека, и встроить в него
мозг, который также сможет определять логику в звуках, словах, фразах,
предложениях, целых абзацах, пении, искажении тональности одного и того
же голоса».

ПОЧЕМУ У НИХ «ПОЧТИ ИДЕАЛЬНО», А У НАС НЕТ. Владелец спросил прямо: как
у Gemini и Grok транскриб пишет почти без ошибок. Ответ не в микрофоне и
не в шумодаве. У них распознавание делает МУЛЬТИМОДАЛЬНАЯ ЯЗЫКОВАЯ
МОДЕЛЬ: языковое знание участвует в самом декодировании. У нас GigaAM —
чистая акустическая модель (RNNT), языкового приора в ней почти нет.
Поэтому на плохом звуке она честно выдаёт то, что похоже ПО ЗВУКУ, без
оглядки на смысл: «Монстро кайранга», «Тестеросова», «стемпису».

Человеческое ухо работает иначе, и это ровно то, что просит владелец. Мы
не слышим каждый звук отдельно: мозг непрерывно достраивает услышанное
из контекста. В шумном баре разбираешь фразу целиком, хотя половина
согласных до уха не дошла. Это называется фонематическим восстановлением,
и это не украшение слуха, а его часть.

ЗНАЧИТ, НУЖЕН ВТОРОЙ ПРОХОД — ПО СМЫСЛУ. Акустика уже сказала своё; над
ней встаёт языковая модель и правит то, что звучит похоже, но в этом
разговоре быть не могло. Модель у нас есть, служебный канал к ней тоже
(llm.chat_once — специально не тот мозг, что ведёт беседу, чтобы не
объедать разговор).

ЧЕТЫРЕ ПРЕДОХРАНИТЕЛЯ, потому что модель охотно сочиняет:

  1. ЗОВЁМ НЕ ВСЕГДА. Только когда есть ПРИЗНАК беды: движок сам не
     уверен, звук был тихий, в тексте нерусские буквы, повторы или
     обрубки. Чистая фраза уходит как есть — и бесплатно, и без риска.

  2. ПРАВКА ОГРАНИЧЕНА ПО РАЗМЕРУ. Считаем расстояние Левенштейна: если
     модель переписала больше трети фразы, это уже не «расслышала», это
     сочинение. Отвергаем и оставляем исходный текст.

  3. ДЛИНА НЕ РАСТЁТ. Ответ длиннее исходника на четверть — отказ. Так
     отсекается любимое «дополню-ка я мысль».

  4. ВСЁ ВИДНО. Правка уезжает в интерфейс отдельным событием: было —
     стало. Владелец в любой момент видит, что именно домыслено, и может
     выключить одной ручкой.

ЦЕНА. Один короткий запрос (полсотни токенов ответа) на подозрительную
фразу, в фоновом потоке. Разговор не задерживает: текст в чате уже стоит,
правка приезжает следом и заменяет его на месте.
"""
import logging
import re
import threading

from anamorf.config import CFG

log = logging.getLogger("saika.rescore")

# слова, которых в русской речи не бывает, но движок их любит рожать на
# плохом звуке: латиница вперемешку с кириллицей, тройные согласные
_LATIN = re.compile(r"[A-Za-z]{2,}")
_ODD = re.compile(r"[бвгджзйклмнпрстфхцчшщ]{4,}", re.I)


def suspicious(r: dict) -> tuple:
    """Стоит ли переспрашивать эту фразу -> (да/нет, почему).

    Признаки намеренно грубые и дешёвые: это фильтр, а не диагноз."""
    t = (r.get("text") or "").strip()
    # КОРОТКОЕ НЕ ПЕРЕСПРАШИВАЕМ. На «Смотри.» контекста нет, а цена
    # ошибки максимальна: заменится всё слово целиком (2026-08-16).
    if len(t) < int(CFG.get("stt.rescore.min_len", 18)):
        return False, ""
    why = []
    if r.get("shaky"):
        why.append("движок сам засомневался")
    db = r.get("in_dbfs")
    if db is not None and float(db) <= float(
            CFG.get("stt.rescore.quiet_dbfs", -34.0)):
        why.append(f"тихо ({db} dBFS)")
    if _LATIN.search(t):
        why.append("латиница в русской фразе")
    if _ODD.search(t):
        why.append("нечитаемое стечение согласных")
    # пословные вероятности даёт whisper; если есть — верим им
    ws = r.get("words") or []
    low = [w for w in ws if isinstance(w, dict) and (w.get("p") or 1) < 0.5]
    if len(low) >= 2:
        why.append(f"{len(low)} слов расслышаны неуверенно")
    # повтор одного слова подряд — почти всегда сбой декодера
    parts = t.lower().split()
    if any(parts[i] == parts[i + 1] and len(parts[i]) > 2
           for i in range(len(parts) - 1)):
        why.append("слово повторено дважды")
    # ═══ «ТИХО» В ОДИНОЧКУ — НЕ ПОВОД ═══ (2026-08-16, владелец: «есть
    # подвисания, как будто не успевает»). На системном звуке в −52 dBFS
    # тихими оказываются ВСЕ фразы подряд, и переспрос уходил в модель на
    # каждую — по запросу в секунду, все последовательно через служебный
    # канал. Отсюда и подвисания: очередь к модели длиннее, чем сам
    # разговор. Тихий звук — это фон источника, а не улика против
    # конкретной строки. Нужна вторая причина: сомнение движка, латиница,
    # повтор, нечитаемое стечение согласных.
    hard = [w for w in why if not w.startswith("тихо")]
    if not hard:
        return False, ""
    return True, "; ".join(why)


def _lev(a: str, b: str) -> int:
    """Расстояние Левенштейна — сколько правок отделяет одну строку от
    другой. Нужно, чтобы отличить «расслышала иначе» от «сочинила»."""
    if a == b:
        return 0
    if not a or not b:
        return max(len(a), len(b))
    prev = list(range(len(b) + 1))
    for i, ca in enumerate(a, 1):
        cur = [i]
        for j, cb in enumerate(b, 1):
            cur.append(min(prev[j] + 1, cur[j - 1] + 1,
                           prev[j - 1] + (ca != cb)))
        prev = cur
    return prev[-1]


_PROMPT = (
    "Ты — слуховая кора: правишь ОШИБКИ РАСПОЗНАВАНИЯ речи, а не текст.\n"
    "Тебе дают строку от акустического движка. Он слышит звук и не знает "
    "смысла, поэтому путает похоже звучащие слова.\n\n"
    "ПРАВИЛА, НАРУШАТЬ НЕЛЬЗЯ:\n"
    "1. Меняй ТОЛЬКО слова, которые звучат похоже на правильные, но в "
    "этом разговоре быть не могли.\n"
    "2. Ничего не дописывай, не продолжай мысль, не отвечай на неё.\n"
    "3. Не исправляй стиль, мат, обрывы и разговорность — так и было "
    "сказано.\n"
    "4. Не уверен — верни строку без изменений.\n"
    "5. В ответе ТОЛЬКО исправленная строка, без кавычек и пояснений.\n"
)


def fix(text: str, context=None, hint: str = "") -> str:
    """Переспросить строку у языковой модели. Возвращает исходник, если
    правка не прошла предохранители."""
    t = (text or "").strip()
    if not t or not CFG.get("stt.rescore.enabled", True):
        return t
    try:
        from anamorf.llm.manager import chat_once
        ctx = "\n".join(f"- {c}" for c in (context or [])[-6:] if c)
        user = ""
        if ctx:
            user += f"Предыдущие реплики этого разговора:\n{ctx}\n\n"
        if hint:
            user += f"Почему строка под подозрением: {hint}\n"
        user += f"Строка от движка:\n{t}"
        out = (chat_once([{"role": "system", "content": _PROMPT},
                          {"role": "user", "content": user}],
                         max_len=600) or "").strip()
    except Exception as e:
        log.debug("переспрос не удался: %s", e)
        return t
    if not out:
        return t
    out = out.strip().strip('"').strip("«»").strip()
    if out == t:
        return t
    # ═══ ПРЕДОХРАНИТЕЛИ ═══
    if len(out) > len(t) * float(CFG.get("stt.rescore.max_grow", 1.25)) + 4:
        log.info("Переспрос отвергнут (дописала лишнее): %r -> %r",
                 t[:50], out[:50])
        return t
    # ═══ ГЛАВНЫЙ ПРЕДОХРАНИТЕЛЬ — ЗВУЧАТЬ ДОЛЖНО ТАК ЖЕ ═══
    # (2026-08-16, живой прокол через десять минут после выкатки.
    # Владелец прислал: «Смотри» превратилось в «Сдохни», «Это мой
    # кинжал» — в «Это мой нож». Первое поменяло смысл на противоположный,
    # второе исправило слово, которое было верным.
    #
    # Почему прошло: у коротких строк я разрешал «хотя бы три правки», а
    # три правки на слове из шести букв — это уже другое слово. Числа тут
    # не помогут в принципе: правильная мера не «сколько букв изменилось»,
    # а ЗВУЧИТ ЛИ ЗАМЕНА ТАК ЖЕ. Движок ошибается только в похожем по
    # звуку — если замена звучит иначе, это не исправление ослышки, это
    # сочинение, чем бы модель его ни объясняла.
    #
    # Фонетический ключ уже есть в misheard.py: он оглушает согласные и
    # сводит безударные гласные, то есть оставляет ровно тот скелет,
    # который слышит движок. «смотри» и «сдохни» по нему далеки, а
    # «тестеросова» и «тестаросса» — почти одно.)
    try:
        from anamorf import misheard as _mh
        # ПРОВЕРЯЕМ ПОСЛОВНО, А НЕ ФРАЗУ ЦЕЛИКОМ (2026-08-16, второй
        # прокол подряд: «появилась гробница» стало «появилась груша».
        # Фраза длинная, общий лимит правок большой — и одно слово внутри
        # можно было заменить на что угодно, ключ фразы почти не менялся.
        # Правильная единица тут слово: движок ослышивается в СЛОВЕ, и
        # каждая замена обязана звучать похоже сама по себе.
        wa, wb = t.split(), out.split()
        if len(wa) != len(wb):
            # разное число слов — сравнить пословно нельзя, а значит и
            # проверить нечем. Отказываем: слова не появляются и не
            # исчезают при ослышке, только заменяются.
            log.info("Переспрос отвергнут (изменилось число слов %d -> %d): "
                     "%r -> %r", len(wa), len(wb), t[:50], out[:50])
            return t
        klim = float(CFG.get("stt.rescore.max_sound_edit", 0.34))
        for a, b in zip(wa, wb):
            if a == b:
                continue
            ka, kb = _mh.key(a), _mh.key(b)
            if not ka or not kb:
                return t
            kd = _lev(ka, kb)
            if kd > max(1, int(len(ka) * klim)):
                log.info("Переспрос отвергнут (слово звучит иначе: %r -> %r, "
                         "ключи %r/%r, правок %d): %r", a, b, ka, kb, kd,
                         t[:50])
                return t
    except Exception as e:
        log.debug("фонетическая проверка недоступна: %s", e)
        return t                      # нет проверки — нет и правки
    d = _lev(t.lower(), out.lower())
    lim = float(CFG.get("stt.rescore.max_edit", 0.30))
    if d > max(1, int(len(t) * lim)):
        log.info("Переспрос отвергнут (переписала %d из %d символов): "
                 "%r -> %r", d, len(t), t[:50], out[:50])
        return t
    log.info("Слух переспросил смыслом: %r -> %r (правок %d, повод: %s)",
             t[:60], out[:60], d, hint or "—")
    return out


_GATE = {"busy": False, "ts": 0.0}


def fix_async(r: dict, context, emit):
    """Фоновый переспрос: текст в чате уже стоит, правка приезжает следом.

    emit(new_text) зовётся ТОЛЬКО если правка прошла предохранители."""
    ok, why = suspicious(r)
    if not ok:
        return False
    # ОДИН ПЕРЕСПРОС ЗА РАЗ. Служебный канал к модели последовательный:
    # два запроса встанут в очередь, третий — за ними, и разговор начнёт
    # ждать переспросов. Пока один в работе — остальные пропускаем: текст
    # в чате уже стоит, а неисправленная строка лучше подвисшего слуха.
    import time as _t
    if _GATE["busy"] or _t.monotonic() - _GATE["ts"] < float(
            CFG.get("stt.rescore.min_gap_s", 2.0)):
        return False
    _GATE["busy"] = True
    _GATE["ts"] = _t.monotonic()
    src = r.get("text") or ""

    def _bg():
        try:
            out = fix(src, context, why)
            if out and out != src:
                emit(out, why)
        except Exception as e:
            log.debug("фоновый переспрос: %s", e)
        finally:
            _GATE["busy"] = False
            _GATE["ts"] = _t.monotonic()

    threading.Thread(target=_bg, daemon=True, name="rescore").start()
    return True
