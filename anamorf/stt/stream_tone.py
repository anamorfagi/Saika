# ЖИВОЙ ПОТОК: свой поток исполнения, чтобы не тормозить звук
# ═══════════════════════════════════════════════════════════════════════
# Аудиоцикл обязан успевать за реальным временем любой ценой — всё, что
# он делает, стоит миллисекунды. Семнадцать миллисекунд на прогон модели
# для него уже много. Поэтому цикл только КЛАДЁТ кусок в очередь и идёт
# дальше, а модель крутится здесь, отдельно.
#
# Очередь короткая нарочно: если мы не успеваем, надо ронять СТАРОЕ, а не
# копить. Живой текст, отставший на секунду, не живой.
import queue as _q

_Q: "_q.Queue" = _q.Queue(maxsize=24)
_TH = {"t": None}
on_text = None          # сюда main вешает отправку в интерфейс
_LAST = {"txt": "", "ts": 0.0}
_MARKS: dict = {}   # src -> [(позиция в тексте, цвет, Гц)]


def push(pcm16, src: str = "sys"):
    """Отдать кусок звука потоковому слуху. Никогда не блокирует."""
    if not enabled() or not STATE.get("ready"):
        return
    try:
        _Q.put_nowait((src, np.asarray(pcm16, np.int16).copy()))
    except _q.Full:
        try:                       # ронять старое, а не новое
            _Q.get_nowait()
            _Q.put_nowait((src, np.asarray(pcm16, np.int16).copy()))
        except Exception:
            pass


def _lane_stream(src: str, lid: int):
    """Поток нужной дорожки, с моделью от общего. Модель у T-one одна на
    всех: она без состояния сама по себе, состояние живёт в потоке, —
    значит второй экземпляр грузить незачем, это лишние 71 млн весов в
    памяти на ровном месте."""
    st = stream("%s#%d" % (src, lid))
    if st._model is None:
        st._model = stream("sys")._model
    return st


def _worker():
    """═══ ПОТОК ЧИТАЕТ ЦЕЛЬНЫЙ ЗВУК. ТОЧКА. (06.09.2026) ═══

    Здесь была моя ошибка, и ровно та же, что я перед этим измерил на
    чистовике: я делил звук по дорожкам и каждой скармливал кусок, где
    чужие кадры занулены. Замер на чистовике сказал прямо — дыры хуже
    смеси (46.9% слов эталона против 53.1%), потому что модель опирается
    на контекст вокруг звука. В потоке это вышло ещё злее: T-one на
    дырявой тишине замолчал совсем — 620 кадров прошло, текста ноль.

    Поэтому: движок всегда получает ВЕСЬ звук. Маршрутизатор при этом
    продолжает работать — он дешёвый и нужен для другого: сказать, ЧЕЙ
    голос звучит прямо сейчас. Это метка поверх текста, а не нож по
    звуку. Разделять надо ответственность, а не сигнал."""
    while True:
        try:
            src, pcm = _Q.get()
            if pcm is None:
                break
            s = stream(src)
            if s._model is None:
                s._model = stream("sys")._model or s._model
                if s._model is None:
                    continue
            # ТИШИНУ НЕ ЧИТАЕМ (2026-10-09, замер /api/diag/threads: поток
            # «tone» + пул ONNX ели 2.5 ядра в тишине — модель разбирала
            # пустой звук каждые 300 мс). Кусок тише порога пропускаем:
            # букв в нём нет, а ядра нужны мозгу и человеку.
            try:
                _a = np.asarray(pcm, dtype=np.float32)
                if _a.size and np.abs(_a).max() > 1.5:      # int16 -> доли
                    _a = _a / 32768.0
                if _a.size and float(np.sqrt(np.mean(_a * _a))) < float(
                        CFG.get("stt.tone.min_rms", 0.004)):
                    continue
            except Exception:
                pass
            # кто говорит сейчас — считаем, но звук не трогаем
            act_hz, act_col = 0, ""
            try:
                if int(CFG.get("stt.tone.lanes", 2) or 1) > 1:
                    r = router(src)
                    r.split(pcm)                      # только разметка дорожек
                    for l in r.lanes:
                        if l["id"] == r.active:
                            act_hz = int(round(110.0 * (2.0 ** (l["f0"] / 12.0))))
                            act_col = l.get("color", "")
            except Exception as e:
                log.debug("разметка дорожек: %s", e)
            txt = s.feed(pcm)
            if txt is None:
                txt = s.preview()
            if txt is None:
                continue
            # ЦВЕТ ХВОСТА. Текст один, но кусок, дописанный сейчас,
            # принадлежит тому, кто сейчас говорит. Запоминаем границу —
            # по ней вкладка красит хвост в цвет его голоса.
            try:
                m = _MARKS.setdefault(src, [])
                if not m or m[-1][1] != act_col:
                    m.append((len(txt), act_col, act_hz))
                    del m[:-24]
            except Exception:
                pass
            now = time.time()
            if now - _LAST["ts"] < float(
                    CFG.get("stt.tone.emit_every_s", 0.05) or 0.05):
                continue
            _LAST["ts"], _LAST["txt"] = now, txt
            if on_text:
                try:
                    on_text(txt, src)
                except Exception as e:
                    log.debug("показ потока: %s", e)
        except Exception as e:
            log.debug("поток слуха: %s", e)
            time.sleep(0.05)


