# ═══════════════════════════════════════════════════════════════════════
# Владелец: «он должен по тембру угадывать, чьи это слова, всех быстро
# определяя», «у разных людей свой цвет».
#
# ПОЧЕМУ НЕ РЕЖЕМ ЗВУК. Я сначала попробовал развести смесь на две
# дорожки по тону и читать порознь — и замерил, что стало ХУЖЕ: смесь
# даёт 53.1% слов эталона, две дорожки вместе 46.9%. Причина понятна
# задним числом: движок опирается на контекст вокруг слова, а в дорожке
# с зануленными чужими кадрами контекста нет, и он теряет даже то, что
# слышал в смеси. Рвать звук нельзя.
#
# Поэтому здесь наоборот: движок читает смесь целиком и даёт максимум
# слов, а тембр отвечает на отдельный вопрос — КОМУ каждое слово
# принадлежит. Разметка не может испортить текст, потому что текста не
# касается.
#
# ПОЧЕМУ НЕ ОДНА ВЫСОТА. Тот же замер показал: две женщины на близких
# нотах попадают в одну группу, а деление по высоте разводит «низ против
# всего остального» (центры вышли 132 и 312 Гц — на 132 Гц женщин не
# бывает, туда ушла музыка). Поэтому в признак идёт не только высота, но
# и огибающая спектра: две женщины на одной ноте различаются формантами,
# и считаются они из того же БПФ, что уже крутится, — то есть даром.
#
# ЧЕСТНАЯ ГРАНИЦА. Границы слов у движка нет, поэтому слова
# раскладываются по времени пропорционально длине. Это приближение: на
# длинной фразе одного человека оно безошибочно, на быстрой перепалке
# может сдвинуть слово на соседа. Приближение названо, а не спрятано.

def _lpc(x: np.ndarray, order: int) -> np.ndarray:
    """Коэффициенты линейного предсказания (автокорреляция + Левинсон)."""
    r = np.correlate(x, x, "full")[len(x) - 1:len(x) + order]
    if r[0] <= 1e-9:
        return None
    a = np.zeros(order + 1); a[0] = 1.0; e = r[0]
    for i in range(1, order + 1):
        acc = r[i] + np.dot(a[1:i], r[i - 1:0:-1])
        k = -acc / e
        a[1:i] = a[1:i] + k * a[i - 1:0:-1]
        a[i] = k
        e *= (1.0 - k * k)
        if e <= 1e-12:
            break
    return a


def _formants(w: np.ndarray, sr: int = SR_IN, order: int = 14):
    """Первые три форманты кадра (Гц) по LPC; None — не нашлись."""
    x = np.asarray(w, np.float64)
    x = x - x.mean()
    if np.abs(x).max() < 1e-4:
        return None
    x = np.append(x[0], x[1:] - 0.97 * x[:-1]) * np.hamming(len(x))   # преэмфаза
    a = _lpc(x, order)
    if a is None:
        return None
    rts = np.roots(a)
    rts = rts[np.imag(rts) >= 0.01]
    if rts.size < 3:
        return None
    ang = np.arctan2(np.imag(rts), np.real(rts))
    fr = ang * sr / (2 * np.pi)
    bw = -0.5 * (sr / (2 * np.pi)) * np.log(np.abs(rts) + 1e-12)
    keep = np.sort(fr[(fr > 90) & (fr < sr / 2 - 100) & (bw < 400)])
    if keep.size < 3:
        return None
    return keep[:3]


def _vtl_cm(f1, f2, f3) -> float:
    """Длина голосового тракта из формант: для трубы Fn = (2n-1)c/4L.
    Берём среднее по F1..F3 — так меньше влияет гласная."""
    c = 35000.0
    Ls = [(2 * n - 1) * c / (4.0 * f) for n, f in ((1, f1), (2, f2), (3, f3)) if f > 0]
    return float(np.mean(Ls)) if Ls else 0.0


def vocal_tract(pcm16, sr: int = SR_IN):
    """Медианная длина тракта по куску (см) и доля кадров, где нашлись
    форманты. Мужчины ~16.5-18.5, женщины ~13.5-15.5, дети <13.
    Это ФИЗИОЛОГИЯ, её криком или пародией не спрятать: высота тона
    прыгает на октаву, а тракт остаётся своей длины (2026-09-06, идея
    владельца: «друг меняет голос — а мы по тракту понимаем, что это он»)."""
    a = np.asarray(pcm16, np.int16).ravel().astype(np.float32)   # _f0_and_tilt ждёт масштаб int16
    if sr and int(sr) != SR_IN:
        k = float(SR_IN) / float(sr)
        idx = (np.arange(int(a.size * k)) / k).astype(np.int64)
        a = a[idx[idx < a.size]]
    n = _WIN
    Ls = []
    total = 0
    for i in range(0, len(a) - n, n // 2):
        w = a[i:i + n]
        f0, _t, rms, _d = _f0_and_tilt(w)
        if f0 <= 0 or rms < 0.004:
            continue
        total += 1
        fm = _formants(w / 32768.0)
        if fm is None or fm[0] > 1100 or fm[1] < 700 or fm[2] < 1500:
            continue
        L = _vtl_cm(fm[0], fm[1], fm[2])
        if 9.0 < L < 24.0:
            Ls.append(L)
    if len(Ls) < 4:
        return 0.0, 0.0
    return float(np.median(Ls)), len(Ls) / max(1, total)


def _frame_feats(a: np.ndarray, sr: int = SR_IN):
    """Признак кадра: [полутоны, наклон, 6 полос огибающей]."""
    n = int(sr * FRAME_S)
    nf = max(0, len(a) // n)
    F, ok = [], []
    edges = [(150, 400), (400, 800), (800, 1500), (1500, 2500),
             (2500, 4000), (4000, 7000)]
    win = np.hanning(n)
    for i in range(nf):
        w = np.asarray(a[i * n:(i + 1) * n], np.float32)
        f0, tilt, rms, _d = _f0_and_tilt(w)
        if f0 <= 0:
            F.append(None); ok.append(False); continue
        sp = np.fft.rfft((w - w.mean()) * win, 1024)
        pw = sp.real ** 2 + sp.imag ** 2
        hz = np.fft.rfftfreq(1024, 1.0 / sr)
        b = np.array([pw[(hz >= lo) & (hz < hi)].sum() + 1e-9
                      for lo, hi in edges], np.float32)
        b = np.log(b / (b.sum() + 1e-9))          # форма спектра, без громкости
        F.append(np.concatenate([[12 * np.log2(f0 / 110.0), tilt], b]))
        ok.append(True)
    return F, np.array(ok, bool)


def word_owners(pcm16, sr: int, text: str, max_people: int = 2,
                times=None) -> list:
    """Вернуть [(слово, Гц, цвет), ...] — кому принадлежит каждое слово."""
    words = [w for w in (text or "").split() if w]
    if not words:
        return []
    try:
        a = np.asarray(pcm16, np.int16).ravel()
        if sr and int(sr) != SR_IN:
            k = float(SR_IN) / float(sr)
            idx = (np.arange(int(a.size * k)) / k).astype(np.int64)
            a = a[idx[idx < a.size]]
        F, ok = _frame_feats(a)
        nf = len(F)
        if nf < 4 or ok.sum() < 4:
            return []
        X = np.stack([F[i] for i in range(nf) if ok[i]]).astype(np.float32)
        # ВЕС ПРИЗНАКОВ. Высота — главный, но не единственный: без
        # огибающей два женских голоса сливаются (проверено замером).
        X[:, 0] *= 1.0; X[:, 1] *= 1.5; X[:, 2:] *= 0.9
        lab_v = np.zeros(len(X), np.int8)
        if len(X) >= 12 and max_people > 1:
            c1 = X[np.argmin(X[:, 0])].copy()
            c2 = X[np.argmax(X[:, 0])].copy()
            for _ in range(20):
                d1 = ((X - c1) ** 2).sum(1); d2 = ((X - c2) ** 2).sum(1)
                m = d1 <= d2
                if m.any(): c1 = X[m].mean(0)
                if (~m).any(): c2 = X[~m].mean(0)
            lab_v = np.where(m, 0, 1).astype(np.int8)
            # если группы почти совпали — человек один, не выдумываем второго
            # ОДИН ГОЛОС НЕ ДЕЛИМ НАДВОЕ. В замере вышли «два человека»
            # на 314 и 333 Гц — это меньше полутора полутонов, то есть
            # один голос, разрезанный дрожанием признака. Требуем и
            # разницу по высоте, и разницу по огибающей: одно без
            # другого обманывает.
            if abs(c1[0] - c2[0]) < 2.5 or float(np.abs(c1[2:] - c2[2:]).max()) < 0.45:
                lab_v[:] = 0
            else:
                # ДВА ГОЛОСА — ЭТО РАЗРЫВ, А НЕ РАЗБРОС (2026-09-06). Владелец:
                # Снейл один орёт «Да набейте ебальники…», а слова покрашены в
                # два цвета. Крик одного человека гуляет по высоте на 4-6
                # полутонов НЕПРЕРЫВНО; k-средних всё равно режет его пополам.
                # У двух людей между их высотами есть ПУСТОТА. Нет пустоты
                # хотя бы в полтора полутона — это один голос.
                lo = X[m][:, 0]; hi = X[~m][:, 0]
                if lo.size and hi.size:
                    gap = float(np.percentile(hi, 10)) - float(np.percentile(lo, 90))
                    if gap < float(CFG.get("stt.tone.owner_gap_st", 1.5)):
                        lab_v[:] = 0
        lab = np.full(nf, -1, np.int8)
        lab[np.where(ok)[0]] = lab_v
        # ═══ ВЛАДЕЛЕЦ НЕ МЕНЯЕТСЯ ЧАЩЕ, ЧЕМ ЛЮДИ ПЕРЕБИВАЮТ (06.09) ═══
        # Замер на живом куске дал вот такую строку:
        #     А(372) ты,(222) а(372) ты(372) своей(222)
        # Владельцы чередуются пословно, а в жизни так не бывает: человек
        # произносит подряд хотя бы несколько слов. Значит это не смена
        # говорящего, а дрожание признака на границах кадров.
        # Лечим медианой по окну: короткие всплески гасятся, настоящая
        # смена (полсекунды и дольше) проходит насквозь.
        try:
            k = int(float(CFG.get("stt.tone.owner_smooth", 9)))
            if k >= 3 and nf > k:
                sm = lab.copy()
                for i in range(nf):
                    a0 = max(0, i - k // 2); b0 = min(nf, i + k // 2 + 1)
                    v = [int(x) for x in lab[a0:b0] if x >= 0]
                    if v:
                        sm[i] = max(set(v), key=v.count)
                lab = sm
        except Exception:
            pass
        # медианная высота каждой группы — для цвета и подписи
        hzs = {}
        for g in (0, 1):
            v = [F[i][0] for i in range(nf) if ok[i] and lab[i] == g]
            if v:
                hzs[g] = float(110.0 * 2 ** (float(np.median(v)) / 12.0))
        if not hzs:
            return []
        order = sorted(hzs, key=lambda g: hzs[g])
        col = {g: _lane_color(hzs[g], k) for k, g in enumerate(order)}
        # слова по времени — пропорционально длине (границ слов у движка нет)
        # ВРЕМЯ СЛОВА — ОТ ДВИЖКА, А НЕ ПО ДОЛЕ БУКВ (06.09.2026). CTC даёт
        # начало/конец каждого слова с шагом 40 мс (engines.LAST_WORDS);
        # раньше место слова считалось по числу букв — на крике с паузами
        # это промахивалось на слово-два, и владелец слова уезжали к соседу.
        tmap = {}
        if times:
            for tw, t0, t1, *_c in times:
                tmap.setdefault(tw.strip(".,!?…").lower(), []).append((t0 + t1) / 2)
        tot = sum(len(w) for w in words) or 1
        out, pos = [], 0.0
        for w in words:
            share = len(w) / tot
            mid = (pos + share / 2) * nf
            _key = w.strip(".,!?…").lower()
            if tmap.get(_key):
                mid = tmap[_key].pop(0) / FRAME_S
            i = int(min(nf - 1, max(0, mid)))
            j = i
            while j < nf and lab[j] < 0:
                j += 1
            if j >= nf:
                j = i
                while j >= 0 and lab[j] < 0:
                    j -= 1
            g = int(lab[j]) if 0 <= j < nf and lab[j] >= 0 else order[0]
            out.append((w, int(round(hzs.get(g, 0))), col.get(g, "")))
            pos += share
        return out
    except Exception as e:
        log.debug("разметка слов по тембру: %s", e)
        return []
