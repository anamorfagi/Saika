def warm(tag: str = "sys"):
    """Поднять модель в фоне, не задерживая звук."""
    s = stream(tag)
    if s._model is not None or STATE["loading"] or not enabled():
        return
    def _go():
        try:
            s.load()
        except Exception:
            pass
    threading.Thread(target=_go, daemon=True, name="tone-warm").start()


