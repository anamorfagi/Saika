# ДВЕ ДОРОЖКИ ПО ТЕМБРУ (06.09.2026)
# ═══════════════════════════════════════════════════════════════════════
# Владелец: «если звуковая система в мгновение слышит два разных тембра,
# подрубает транскрибирование в два потока от разных людей по тембру и
# пишет две дорожки с их словами, вычленяя транскриб от каждого».
#
# ЧТО ЭТО НА САМОМ ДЕЛЕ И ЧЕГО НЕ ДЕЛАЕТ. Разделения источников тут нет и
# быть не может дёшево: развод смеси мы уже мерили — 5.6× реального
# времени, очередь взрывалась, выключили. Здесь другое и честное:
# МАРШРУТИЗАЦИЯ. Кадр в 30 мс почти всегда принадлежит одному голосу —
# люди перебивают друг друга, но редко звучат хором. Значит достаточно
# для каждого кадра решить, ЧЕЙ он, и отдать его в поток этого человека,
# а остальным в этот момент подсунуть тишину. Тайминг сохраняется, текст
# каждой дорожки собирается из своих кадров.
# Там, где двое действительно говорят одновременно, кадр уходит тому,
# кто громче. Это ограничение, а не недоделка: без развода смеси иначе
# не бывает.
#
# ПО ЧЕМУ РАЗЛИЧАЕМ. Основной тон — за один период волны, то есть за
# миллисекунды; отпечатку тембра для того же нужны секунды речи. Плюс
# наклон спектра: он ловит разницу там, где тон совпал (мужчина и
# мужчина в одной октаве различаются формантами, а не высотой).
# Расстояние считаем в ПОЛУТОНАХ — так порог не зависит от того, низкий
# голос или высокий: полтона у баса и у сопрано это одна и та же на слух
# разница, а в герцах — втрое разная.

_LANE_HZ = (80.0, 400.0)          # где вообще ищем голос
_WIN = int(SR_IN * FRAME_S)       # 480 отсчётов = 30 мс на 16 кГц


def _f0_and_tilt(w: np.ndarray):
    """Тон, наклон спектра, громкость и ВТОРОЙ тон одного кадра.
    Возвращает (f0, tilt, rms, f0_второй); f0 = 0, если высоты нет
    (шум, согласный, тишина); f0_второй > 0 — в кадре звучат два голоса.

    Тон ищем автокорреляцией через спектр — это то же самое, что прямой
    перебор задержек, только вместо ста восьмидесяти сверток один БПФ на
    512 точек. Цена кадра выходит меньше десяти микросекунд, то есть
    триста кадров в секунду стоят треть процента ядра."""
    a = np.asarray(w, np.float32)
    if a.size < 128:
        return 0.0, 0.0, 0.0, 0.0
    a = a - a.mean()
    rms = float(np.sqrt((a * a).mean())) / 32768.0
    if rms < 1e-4:
        return 0.0, 0.0, rms, 0.0
    n = 1024
    sp = np.fft.rfft(a * np.hanning(a.size), n)
    pw = (sp.real ** 2 + sp.imag ** 2)
    # наклон: сколько энергии сверху относительно низа. Отношение, а не
    # разность, чтобы громкость не влияла.
    hz = np.fft.rfftfreq(n, 1.0 / SR_IN)
    lo = float(pw[(hz >= 120) & (hz < 900)].sum()) + 1e-9
    hi = float(pw[(hz >= 900) & (hz < 4000)].sum()) + 1e-9
    tilt = float(np.log2(hi / lo))
    # автокорреляция = обратный БПФ спектра мощности
    ac = np.fft.irfft(pw, n)[:n // 2]
    if ac[0] <= 0:
        return 0.0, tilt, rms, 0.0
    ac = ac / ac[0]
    lo_lag = int(SR_IN / _LANE_HZ[1])
    hi_lag = int(SR_IN / _LANE_HZ[0])
    hi_lag = min(hi_lag, ac.size - 1)
    if hi_lag <= lo_lag:
        return 0.0, tilt, rms, 0.0
    seg = ac[lo_lag:hi_lag].copy()
    k = int(np.argmax(seg))
    # порог на силу периодичности: без него шум даёт «тон» на случайной
    # задержке, и дорожки начинают плодиться на согласных
    if seg[k] < 0.30:
        return 0.0, tilt, rms, 0.0
    f0 = float(SR_IN) / (lo_lag + k)
    # ═══ ВТОРОЙ ТОН В ТОМ ЖЕ КАДРЕ (06.09.2026) ═══
    # Владелец: «а они бывают одновременно говорить». Разделить смесь мы
    # не можем — это дорого, мерили. Но ЗАМЕТИТЬ смесь можно даром:
    # если в автокорреляции есть второй сильный пик на задержке, которая
    # не кратна первой (то есть это не обертон того же голоса, а другая
    # высота), — значит в кадре два голоса разом.
    # Врать про такой кадр нельзя: он уйдёт громкому, но помечен будет
    # честно, и в показе видно, где система слышала хор, а не одного.
    peak2 = 0.0
    try:
        m = seg.copy()
        lag0 = lo_lag + k
        for mult in (0.5, 1.0, 2.0, 3.0):
            c = int(round(lag0 * mult)) - lo_lag
            w = max(2, int(0.06 * abs(c) + 2))
            m[max(0, c - w):c + w] = 0.0
        k2 = int(np.argmax(m))
        if m[k2] >= 0.30:
            peak2 = float(SR_IN) / (lo_lag + k2)
    except Exception:
        peak2 = 0.0
    return f0, tilt, rms, peak2


# Цвет закрепляем ЗА ДОРОЖКОЙ, а не за полосой частот (06.09.2026).
# Владелец: «когда в потоке две девушки говорят, система не успела их
# распределить — сменим цвет хотя бы». Он прав дважды. Во-первых, цвет
# по полосе (мужской/женский/высокий) двум женщинам даёт ОДИН цвет —
# именно то, что он и увидел. Во-вторых, цвет должен держаться за
# человеком, а не за высотой: высота у одного и того же голоса гуляет
# на треть октавы, и он бы мигал.
# Тёплые — женские, холодные — мужские (06.09, просьба владельца: «давай
# голоса будем по цветам разделять, женские тёплые оттенки, мужские
# холодные, для наглядности»). Граница 165 Гц: мужской голос 85-155,
# женский 165-255. Внутри своей половины оттенки идут по кругу, чтобы
# двое мужчин не слились в один цвет.
_WARM = ["#f06292", "#ffb74d", "#ff8a65", "#ffd54f", "#ce93d8"]
_COOL = ["#5a96ff", "#4dd0e1", "#9fa8da", "#4db6ac", "#81c784"]
_LANE_COLORS = _WARM + _COOL


_NEUTRAL = ["#b39ddb", "#bcaaa4", "#a5d6a7", "#e6ee9c", "#90caf9"]


def _lane_color(hz: float, nth: int) -> str:
    """Ниже 165 Гц — точно мужской (холодный). Выше — высота пола НЕ
    доказывает (крик мужчины идёт на 330 Гц): нейтральная палитра, пока
    пол не подтверждён трактом (2026-09-06)."""
    pal = _COOL if hz < 165 else _NEUTRAL
    return pal[nth % len(pal)]


class _Router:
    """Кому какой кадр. Держит до N живых дорожек, каждая со своим
    средним тоном и наклоном; кадр уходит ближайшей, а если ни одна не
    подходит и есть место — заводится новая."""

    def __init__(self):
        self.lanes: list = []
        self._next = 0
        self.active = -1
        self._last = 0.0          # когда был последний кадр С ГОЛОСОМ

    def _cfg(self, k, d):
        return CFG.get("stt.tone." + k, d)

    def _retire(self, now):
        idle = float(self._cfg("lane_idle_s", 4.0) or 4.0)
        self.lanes = [l for l in self.lanes if now - l["seen"] < idle]

    def assign(self, f0, tilt, now, dual=False):
        """Вернуть id дорожки для кадра или -1, если кадр без голоса."""
        if f0 <= 0:
            return -1
        st = 12.0 * np.log2(f0 / 110.0)          # полутоны от ля большой октавы
        tol = float(self._cfg("lane_semitones", 3.0) or 3.0)
        wt = float(self._cfg("lane_tilt_w", 2.5) or 2.5)
        cap = int(self._cfg("lanes", 3) or 3)
        # ═══ ПАУЗА — ЭТО ШАНС РАЗДЕЛИТЬ, И ЕГО НАДО БРАТЬ ═══
        # Владелец: «они явно для слуха успели остановиться между
        # словами». Верно: смена говорящего почти всегда идёт через
        # паузу, пусть в доли секунды. Внутри слитной речи мы обязаны
        # быть консервативны — иначе дорожка рвётся на каждом обертоне.
        # А сразу ПОСЛЕ паузы наоборот: порог ужимаем, и голос, который
        # раньше «дотягивался» до чужой дорожки, теперь заводит свою.
        gap = now - self._last if self._last else 9.9
        self._last = now
        if gap >= float(self._cfg("lane_gap_s", 0.22) or 0.22):
            tol *= float(self._cfg("lane_gap_strict", 0.55) or 0.55)
        self._retire(now)
        best, bd = None, 1e9
        for l in self.lanes:
            d = abs(st - l["f0"]) + wt * abs(tilt - l["tilt"])
            if d < bd:
                best, bd = l, d
        if best is None or (bd > tol and len(self.lanes) < cap):
            _same = sum(1 for x in self.lanes
                        if (110.0 * (2.0 ** (x["f0"] / 12.0)) >= 165) == (f0 >= 165))
            l = {"f0": st, "tilt": tilt, "seen": now, "id": self._next,
                 "n": 1, "dual": 0, "tot": 1,
                 "color": _lane_color(f0, _same)}
            self._next += 1
            self.lanes.append(l)
            self.active = l["id"]
            return l["id"]
        # ═══ ЦЕНТР ДОРОЖКИ ПЕРЕСТАЁТ ПОЛЗТИ, КОГДА ОН УЖЕ ЗНАЕТ ГОЛОС ═══
        # Раньше центр подтягивался к каждому кадру с одним и тем же
        # шагом. На двух похожих голосах это и есть механизм слияния:
        # дорожка первой женщины за секунду переползала на вторую и
        # проглатывала её. Пока кадров мало — тянемся быстро (надо же
        # где-то встать), дальше шаг падает почти до нуля: голос гуляет
        # в пределах терпимости, а на чужого уже не съезжает.
        l = best
        l["n"] += 1
        l["tot"] += 1
        if dual:
            l["dual"] += 1
        warm = int(self._cfg("lane_warm_frames", 40) or 40)
        k = 0.15 if l["n"] < warm else 0.015
        l["f0"] += k * (st - l["f0"])
        l["tilt"] += k * (tilt - l["tilt"])
        l["seen"] = now
        self.active = l["id"]
        return l["id"]

    def split(self, pcm16, now=None):
        """Разложить кусок 16 кГц по дорожкам. Каждая получает кусок той
        же длины: свои кадры как есть, чужие — тишиной. Так у каждой
        дорожки сохраняется настоящее время, и пауза остаётся паузой."""
        a = np.asarray(pcm16, np.int16).ravel()
        if not a.size:
            return {}
        now = now or time.time()
        nf = max(1, a.size // _WIN)
        ids = np.full(nf, -1, np.int32)
        for i in range(nf):
            w = a[i * _WIN:(i + 1) * _WIN]
            f0, tilt, rms, f0b = _f0_and_tilt(w)
            ids[i] = self.assign(f0, tilt, now + i * FRAME_S, dual=f0b > 0)
        live = [int(x) for x in np.unique(ids) if x >= 0]
        if not live:
            return {}
        # ОДИН ГОЛОС — ОДНА ДОРОЖКА, БЕЗ ЛИШНЕЙ РАБОТЫ. Если все кадры
        # ушли одному, второй поток гонять незачем: это ровно тот случай,
        # когда владелец говорит «тут один человек, а система рисует
        # миллион оттенков».
        if len(live) == 1:
            return {live[0]: a}
        out = {}
        for lid in live:
            b = np.zeros_like(a)
            for i in range(nf):
                if ids[i] == lid:
                    b[i * _WIN:(i + 1) * _WIN] = a[i * _WIN:(i + 1) * _WIN]
            if a.size > nf * _WIN and ids[nf - 1] == lid:
                b[nf * _WIN:] = a[nf * _WIN:]
            out[lid] = b
        return out


def classify(pcm16, sr: int, src: str = "sys") -> dict:
    """ЧЕЙ ЭТО КУСОК — ПО ТЕМБРУ, НЕ ТРОГАЯ ЖИВЫЕ ДОРОЖКИ (06.09.2026).

    Владелец ткнул в реплику «Друг на друге...»: сказал её другой
    человек, а подписана она «Голос 5», и добавил — «хотя тембр явно
    отличается». Он прав, и вот почему так вышло. Живая разметка по
    тембру работала ТОЛЬКО в бледной строке; закрытую фразу подписывал
    отпечаток, а у него эталон «Голос 5» — солянка (плотность 0.59 при
    3400 срабатываниях), которая тянет к себе всех подряд и отвечает
    «100%».

    Здесь мы считаем тембр самого куска и говорим, на какую живую
    дорожку он похож. Ответ read-only: центры дорожек не двигаем и
    новых не заводим — иначе разбор задним числом портил бы разметку
    того, что звучит прямо сейчас.

    Берём МЕДИАНУ по кадрам с голосом, а не среднее: в куске есть
    согласные и придыхания со случайной высотой, и одно такое значение
    утащило бы среднее на полтона."""
    try:
        a = np.asarray(pcm16, np.int16).ravel()
        if a.size < _WIN * 4:
            return {}
        if sr and int(sr) != SR_IN:                  # приводим к 16 кГц
            k = float(SR_IN) / float(sr)
            idx = (np.arange(int(a.size * k)) / k).astype(np.int64)
            idx = idx[idx < a.size]
            a = a[idx]
        nf = a.size // _WIN
        f0s, tilts, dual = [], [], 0
        for i in range(nf):
            f0, tilt, rms, f0b = _f0_and_tilt(a[i * _WIN:(i + 1) * _WIN])
            if f0 > 0:
                f0s.append(f0)
                tilts.append(tilt)
                if f0b > 0:
                    dual += 1
        if len(f0s) < 4:
            return {}
        hz = float(np.median(f0s))
        tl = float(np.median(tilts))
        out = {"tone_hz": int(round(hz)),
               "tone_dual": round(dual / max(1, len(f0s)), 2)}
        try:
            vtl, vshare = vocal_tract(a, SR_IN)
            if vtl > 0:
                out["vtl_cm"] = round(vtl, 1)
                out["vtl_share"] = round(vshare, 2)
                # порог между женским и мужским трактом; высота — только
                # если тракт не определился уверенно
                thr = float(CFG.get("stt.tone.vtl_male_cm", 15.8))
                out["sex"] = "м" if vtl >= thr else "ж"
                # УВЕРЕННОСТЬ, А НЕ ГАДАНИЕ: тракт дальше сантиметра от границы
                # и найден в половине кадров — иначе пол не утверждаем
                out["sex_sure"] = bool(abs(vtl - thr) >= 1.0 and vshare >= 0.5)
        except Exception:
            pass
        r = _ROUTERS.get(src)
        if r is not None and r.lanes:
            st = 12.0 * np.log2(hz / 110.0)
            wt = float(CFG.get("stt.tone.lane_tilt_w", 2.5) or 2.5)
            best, bd = None, 1e9
            for l in r.lanes:
                d = abs(st - l["f0"]) + wt * abs(tl - l["tilt"])
                if d < bd:
                    best, bd = l, d
            if best is not None:
                out["tone_lane"] = int(best["id"])
                out["tone_color"] = best.get("color", "")
        if "tone_color" not in out:
            # дорожка могла уже закрыться по молчанию — цвет всё равно
            # должен быть стабильным для одной и той же высоты
            out["tone_lane"] = int(hz // 20)
            out["tone_color"] = _lane_color(hz, int(hz) // 20)
        return out
    except Exception:
        return {}


_ROUTERS: dict = {}


def router(src: str = "sys") -> _Router:
    r = _ROUTERS.get(src)
    if r is None:
        r = _ROUTERS[src] = _Router()
    return r


def lanes(src: str = "sys") -> list:
    """Живые дорожки с их текстом — для показа."""
    out = []
    r = _ROUTERS.get(src)
    if r is None:
        return out
    now = time.time()
    st = stream(src)          # текст один: движок читает цельный звук
    for l in sorted(r.lanes, key=lambda x: x["f0"]):
        hz = 110.0 * (2.0 ** (l["f0"] / 12.0))
        tot = max(1, int(l.get("tot", 1)))
        out.append({"id": l["id"], "hz": round(hz),
                    # ТЕКСТА В ДОРОЖКАХ БОЛЬШЕ НЕТ (06.09). Владелец:
                    # «слова начали прыгать вверх-вниз в этих строках».
                    # Так и было: текст показывался у того, кто говорит
                    # сейчас, и при каждой смене говорящего перескакивал
                    # на соседнюю строку. Читать это невозможно.
                    # Лента одна — значит и строка одна; дорожки остаются
                    # индикатором «кто здесь», а людей внутри строки
                    # различает цвет (см. marks).
                    "text": "",
                    "active": bool(l["id"] == r.active),
                    "on": bool(now - l["seen"] < 0.8),
                    "color": l.get("color", ""),
                    # доля кадров, где в звуке слышно ДВА тона разом:
                    # честная метка «здесь говорили поверх друг друга»
                    "dual": round(int(l.get("dual", 0)) / tot, 2),
                    # ВЫСОТА — НЕ ПОЛ (2026-09-06): крик мужчины идёт на 330 Гц,
                    # подпись «женский» по герцам была враньём. Пишем высоту.
                    "band": ("низкий" if hz < 160 else
                             "средний" if hz < 260 else "высокий")})
    return out


def live_text(src: str = "sys") -> dict:
    """Живой текст одной лентой + куда в нём меняется говорящий.

    Метки ставит рабочий поток на каждой смене активной дорожки:
    (позиция в тексте, цвет, Гц). Вкладка режет строку по этим позициям
    и красит куски — получается одна нескачущая строка, в которой видно,
    где один человек сменился другим."""
    st = stream(src)
    t = st.text or ""
    marks = []
    try:
        base = len(st.text or "") - len(t)
        for pos, col, hz in (_MARKS.get(src) or []):
            p = pos - base
            if 0 <= p <= len(t):
                marks.append([p, col, hz])
    except Exception:
        marks = []
    return {"t": t[-400:], "marks": marks[-12:]}


