# -*- coding: utf-8 -*-
"""ПОТОКОВЫЙ СЛУХ: буквы по мере речи (06.09.2026).

═══ ЗАЧЕМ ═══
Владелец, дословно: «нужно чтобы движок буквы писать начал буквально из
звуков микрофона в реальном времени», «если я захочу затянуть нооооо —
он должен прописать ровно столько о, сколько я тяну звук по времени».

Прежний слух этого не мог ПРИНЦИПИАЛЬНО, и дело было не в настройках.
GigaAM работает по готовому куску: нарезка ждёт паузы, отдаёт фразу
целиком, движок думает, текст появляется разом. Между «сказал» и
«увидел» лежит вся фраза плюс время разбора. Никакая настройка этого не
уберёт — у модели нет потокового режима.

═══ ЧТО ЗДЕСЬ ═══
T-one (Т-Банк, Apache 2.0) — Conformer-CTC с НАСТОЯЩИМ потоком:
состояние переносится между кусками, кусок 300 мс, кадр 30 мс, 71 млн
параметров, работает на процессоре (видеокарта остаётся под большую
модель и игру).

Но её штатный конвейер отдаёт ГОТОВЫЕ ФРАЗЫ — то есть ту же беду, только
покороче. Поэтому мы идём на уровень ниже: берём у модели сырые
логарифмы вероятностей ПОКАДРОВО и декодируем сами, каждые 300 мс, весь
накопленный кусок заново. Отсюда оба нужных свойства:
  • буквы появляются через 300 мс после того, как прозвучали;
  • уже написанное САМО ИСПРАВЛЯЕТСЯ, когда подъезжает контекст, —
    потому что это не дописка, а новое чтение всего куска целиком.

═══ ПРО РАСТЯЖКУ ═══
CTC схлопывает повторы: «ноооо» и «но» дают один и тот же ответ, потому
что декодер выбрасывает подряд идущие одинаковые метки. Это правильно
для обычной речи и неправильно для песни и для крика.
Но у нас есть то, чего нет у обычного декодера: ВЫРАВНИВАНИЕ ПО КАДРАМ.
Каждый кадр — 30 мс, и если «о» держится двадцать кадров, значит его
тянули шестьсот миллисекунд. Считаем длину каждого прогона и повторяем
гласную ровно по времени. Это не украшательство: длительность — часть
смысла, и владелец просит именно её.

═══ ЧЕГО ЗДЕСЬ НЕТ ═══
Точности GigaAM. T-one учили на телефонии (8 кГц), на широкой полосе он
слабее. Поэтому он тут НЕ ЗАМЕНА, а передний край: пишет мгновенно и
начерно, а закрытую фразу перечитывает GigaAM и заменяет своим текстом.
Быстрый спереди, точный сзади — так устроены все живые субтитры.
"""
from __future__ import annotations

import logging
import threading
import time

import numpy as np

from anamorf.config import CFG

log = logging.getLogger("saika.tone")

SR_IN = 16000          # чем живёт весь остальной слух
SR = 8000              # чего требует модель
CHUNK = 2400           # 300 мс при 8 кГц — её единица потока
FRAME_S = 0.03         # один кадр логарифмов = 30 мс
LABELS = "абвгдеёжзийклмнопрстуфхцчшщъыьэюя "
BLANK = len(LABELS)    # 35-я метка — пустая
VOWELS = set("аеёиоуыэюя")

STATE = {"ready": False, "loading": False, "err": "", "frames": 0, "ms": 0.0}


def enabled() -> bool:
    return bool(CFG.get("stt.tone.enabled", True))


def status() -> dict:
    d = dict(STATE)
    d["enabled"] = enabled()
    return d


class ToneStream:
    """Один поток речи: свой буфер, своё состояние модели, свой текст."""

    def __init__(self, tag: str = ""):
        self.tag = tag
        self._model = None
        self._state = None
        self._tail = np.zeros(0, np.int32)   # недобранное до 2400
        self._prev_at = 0                    # на какой длине хвоста был предпросмотр
        self._frames: list = []              # логарифмы текущей фразы
        self._lock = threading.Lock()
        self.text = ""                       # что видно сейчас
        self.since = 0.0                     # когда фраза началась

    # ---------------------------------------------------------------- модель
    def load(self):
        if self._model is not None:
            return
        STATE["loading"] = True
        try:
            from tone import StreamingCTCModel
            t0 = time.monotonic()
            self._model = StreamingCTCModel.from_hugging_face()
            STATE["ready"] = True
            STATE["err"] = ""
            log.info("Поток T-one поднят за %.1fс (кусок %d мс, кадр %d мс)",
                     time.monotonic() - t0, int(CHUNK / SR * 1000),
                     int(FRAME_S * 1000))
        except Exception as e:
            STATE["err"] = repr(e)[:200]
            log.warning("Поток T-one не поднялся: %s", STATE["err"])
            raise
        finally:
            STATE["loading"] = False

    # ------------------------------------------------------------ пересчёт
    @staticmethod
    def _to8k(pcm16: np.ndarray) -> np.ndarray:
        """16 кГц -> 8 кГц. Простое прореживание даёт зеркальные помехи
        (алиасинг): всё, что выше 4 кГц, отражается вниз и портит шипящие.
        Усредняем пары — это полуполосный фильтр беднейшего вида, но он
        честно давит верх перед прореживанием и стоит копейки."""
        a = np.asarray(pcm16, np.float32).ravel()
        if a.size % 2:
            a = a[:-1]
        if not a.size:
            return np.zeros(0, np.int32)
        return ((a[0::2] + a[1::2]) * 0.5).astype(np.int32)

    # ------------------------------------------------------------- растяжка
    @staticmethod
    def _decode(frames: list, final: bool = False) -> str:
        """Жадное декодирование С СОХРАНЕНИЕМ ДЛИТЕЛЬНОСТИ.

        Обычный жадный декодер делает groupby и выбрасывает повторы. Мы
        повторы СЧИТАЕМ: длина прогона одной метки — это время звучания.
        Гласную, которую тянули дольше порога, повторяем — по одной букве
        на каждый шаг растяжки, но не больше потолка, чтобы «а-а-а» не
        превратилось в простыню."""
        if not frames:
            return ""
        lp = np.concatenate(frames, axis=0)
        toks = lp.argmax(axis=-1)
        # ═══ ДВА ТЕКСТА ИЗ ОДНОГО ЗВУКА (06.09.2026) ═══
        # Владелец: «если человек не специально тянет — мы можем в тексте
        # еле заметно это отобразить, но в готовом тексте нормально
        # построить слово».
        #
        # Разница между «тянет» и «просто произносит» — это длительность,
        # и она измерима. Обычная ударная гласная в русской речи держится
        # 60-150 мс. Всё, что заметно дольше, человек тянет НАМЕРЕННО:
        # поёт, кричит, растягивает для смысла.
        #
        # Отсюда два порога вместо одного:
        #   ЖИВОЙ текст (черновик)  — порог низкий: видно, как звук
        #       держится, буквы дышат вместе с голосом. Это подсказка
        #       глазу, а не документ.
        #   ГОТОВЫЙ текст            — порог высокий: естественная
        #       протяжка схлопывается в одну букву, слово выглядит как
        #       слово. Переживает только НАМЕРЕННАЯ растяжка, и та
        #       ограничена по числу букв, чтобы строка осталась читаемой.
        if final:
            step = float(CFG.get("stt.tone.stretch_final_s", 0.35))
            cap = int(CFG.get("stt.tone.stretch_final_max", 4) or 4)
            floor = step          # короче порога — вообще не растягиваем
        else:
            step = float(CFG.get("stt.tone.stretch_step_s", 0.14))
            cap = int(CFG.get("stt.tone.stretch_max", 8) or 8)
            floor = step
        out = []
        i, n = 0, len(toks)
        while i < n:
            t = int(toks[i])
            j = i
            while j < n and int(toks[j]) == t:
                j += 1
            run = j - i
            i = j
            if t >= len(LABELS):        # пустая метка
                continue
            ch = LABELS[t]
            rep = 1
            if ch in VOWELS and step > 0:
                held = run * FRAME_S
                if held >= floor:
                    rep = max(1, min(cap, int(held / step)))
            out.append(ch * rep)
        return "".join(out).strip()

    # ---------------------------------------------------------------- поток
    def feed(self, pcm16: np.ndarray) -> str | None:
        """Скормить кусок звука 16 кГц. Вернёт текущий текст, если он
        изменился, иначе None. Ничего не блокирует дольше одного куска."""
        if self._model is None:
            return None
        with self._lock:
            a = self._to8k(pcm16)
            if a.size:
                self._tail = np.concatenate([self._tail, a]) \
                    if self._tail.size else a
            grew = False
            while self._tail.size >= CHUNK:
                chunk = self._tail[:CHUNK]
                self._tail = self._tail[CHUNK:]
                self._prev_at = 0
                t0 = time.monotonic()
                try:
                    # модель ждёт (партия, отсчёты, 1) — так её зовёт и
                    # штатный конвейер: audio_chunk[None, :, None]
                    lp, self._state = self._model.forward(
                        chunk[None, :, None], self._state)
                except Exception as e:
                    log.debug("поток T-one споткнулся: %s", e)
                    continue
                STATE["ms"] = round((time.monotonic() - t0) * 1000, 1)
                lp = np.asarray(lp, np.float32)
                if lp.ndim == 3:
                    lp = lp[0]
                self._frames.append(lp)
                STATE["frames"] += len(lp)
                grew = True
            if not grew:
                return None
            # держим в памяти столько, сколько имеет смысл читать разом
            keep = int(float(CFG.get("stt.tone.window_s", 12.0) or 12.0)
                       / FRAME_S)
            tot = sum(len(f) for f in self._frames)
            # СТАРЫЕ КАДРЫ НЕ ВЫБРАСЫВАЕМ, А ЗАКРЕПЛЯЕМ (2026-09-06, владелец:
            # «строчка должна писать слова последовательно, а она буквы на
            # месте перебирает»). Раньше окно уезжало — и вся строка
            # пересчитывалась заново, буквы ползли. Теперь всё, что вышло
            # за окно, один раз декодируется и приклеивается к готовому
            # началу строки; меняется только хвост.
            popped = []
            while tot > keep and len(self._frames) > 1:
                f = self._frames.pop(0)
                tot -= len(f)
                popped.append(f)
            if popped:
                head = self._decode(popped, final=True)
                if head:
                    done = getattr(self, "_done", "")
                    if done and head and done[-1:] == head[:1]:
                        head = head[1:]            # шов: одна буква на границе дважды
                    self._done = (done + " " + head).strip()[-600:]
            txt = self._decode(self._frames)
            done = getattr(self, "_done", "")
            if done:
                txt = (done + " " + txt).strip()
            if txt == self.text:
                return None
            if not self.text:
                self.since = time.time()
            self.text = txt
            return txt

    # ═══ ПРЕДПРОСМОТР КАЖДЫЕ 30 МС (06.09.2026) ═══
    # Владелец: «300 мс нужно в сто раз быстрее, чтобы звук за 30 мс уже
    # вписался в транскриб, проявя букву».
    #
    # Замер на его машине: один прогон куска 300 мс стоит 17 мс (худший
    # 25). То есть модель тратит 5.7% реального времени — запас в 18 раз.
    # Значит шаг в 30 мс по деньгам проходит: десять прогонов на те же
    # 300 мс звука = 170 мс из 300, чуть больше половины одного ядра.
    #
    # Механика. У модели вход жёстко 2400 отсчётов и состояние, которое
    # двигается на целый кусок за вызов. Двигать его по 30 мс нельзя —
    # развалится. Поэтому делим на два хода:
    #   • ЧИСТОВОЙ ход — раз в 300 мс, двигает настоящее состояние и
    #     копит кадры (см. feed);
    #   • ПРЕДПРОСМОТР — каждые 30 мс, на КОПИИ состояния, недобранный
    #     хвост дополняется тишиной до 2400. Настоящее состояние он не
    #     трогает вовсе, поэтому испортить поток не может.
    # Из предпросмотра берём только кадры, которым соответствует
    # настоящий звук: дополненная тишина в текст не идёт.
    #
    # Честная граница: 30 мс — это шаг ПОКАЗА. Сама модель смотрит окно
    # в 300 мс, и звук, прозвучавший миллисекунду назад, ещё не пойман
    # ни одной моделью в мире — ей нужен хотя бы слог, чтобы понять,
    # какая это буква. Мы отдаём букву настолько рано, насколько её
    # вообще возможно узнать.
    def preview(self) -> str | None:
        if self._model is None or not self._tail.size:
            return None
        step = int(float(CFG.get("stt.tone.preview_step_s", 0.03) or 0.03) * SR)
        if self._tail.size - self._prev_at < step:
            return None
        with self._lock:
            self._prev_at = self._tail.size
            pad = np.zeros(CHUNK, np.int32)
            n = min(CHUNK, self._tail.size)
            pad[:n] = self._tail[-n:] if self._tail.size > CHUNK else self._tail[:n]
            try:
                st = self._state
                st_copy = None if st is None else np.array(st, copy=True)
                lp, _ = self._model.forward(pad[None, :, None], st_copy)
            except Exception as e:
                log.debug("предпросмотр T-one споткнулся: %s", e)
                return None
            lp = np.asarray(lp, np.float32)
            if lp.ndim == 3:
                lp = lp[0]
            # кадров, покрытых НАСТОЯЩИМ звуком (остальное — дополненная тишина)
            live = max(1, int(round(n / (SR * FRAME_S))))
            txt = self._decode(self._frames + [lp[:live]])
            done = getattr(self, "_done", "")
            if done:
                txt = (done + " " + txt).strip()
            if txt == self.text:
                return None
            if not self.text:
                self.since = time.time()
            self.text = txt
            return txt

    def close(self) -> str:
        """Фраза кончилась: отдать ГОТОВЫЙ текст и начать с чистого листа.

        Готовый — это перечитанные те же кадры со строгим порогом
        растяжки: естественная протяжка схлопывается, намеренная
        остаётся. Состояние модели НЕ сбрасываем — поток непрерывный, и
        обнулять его значит терять контекст на каждой паузе."""
        with self._lock:
            txt = self._decode(self._frames, final=True) or self.text
            done = getattr(self, "_done", "")
            if done:
                txt = (done + " " + txt).strip()
            self._frames = []
            self._done = ""
            self.text = ""
            self.since = 0.0
            return txt


