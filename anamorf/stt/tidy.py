"""ЧИСТЫЙ ТЕКСТ ФРАЗЫ — ДО ТОГО, КАК ЕГО КТО-ТО ПРОЧИТАЕТ (06.09.2026).

Владелец: «есть слова, которые он пишет не совсем корректно, но главное —
в облачко диалога, который нейронка будет получать, должен идти чистый
правильный диалог».

Здесь ДЕТЕРМИНИРОВАННАЯ уборка и только она: ничего не додумывается,
ничего не переписывается по смыслу. Всё, что чинится тут, чинится по
правилу, которое можно проверить глазами. Смысловая правка — отдельный,
осторожный проход (stt/rescore.py), у него свои предохранители.

Требование владельца, которое здесь главнее красоты: «правильное
количество слов, ровно то, что сказал человек, а не то, что потенциально
заглючила модель». Поэтому убираем только то, чего человек ТОЧНО не
говорил: шов между кусками, который создали мы сами, и вырожденные
повторы декодера.
"""
from __future__ import annotations

import logging
import re

log = logging.getLogger("saika.tidy")

_SP = re.compile(r"[ \t ]+")
_BEFORE_PUNCT = re.compile(r"\s+([,.!?;:…])")
_MULTI_PUNCT = re.compile(r"([,.!?;:])\1{1,}")
_TAIL = {}          # канал -> последние слова прошлой фразы


def _words(t: str):
    return [w for w in t.split() if w]


def _norm(w: str) -> str:
    return re.sub(r"[^\w]+", "", w.lower(), flags=re.UNICODE)


def unseam(text: str, src: str = "sys", max_overlap: int = 6) -> str:
    """Убрать шов между кусками, который сделали мы сами.

    При резе по потолку мы нарочно переносим последние 260 мс звука в
    начало следующего куска — иначе слово на стыке гибнет целиком (его
    половины не звучат словом ни там, ни там). Плата за это — что слово
    (иногда два) звучит в обоих кусках и оказывается в тексте дважды.

    Ищем самое длинное совпадение хвоста прошлой фразы с началом новой и
    срезаем его. Сравниваем по «голым» словам, без падежей регистра и
    знаков: движок на разных кусках ставит запятые по-разному.
    """
    ws = _words(text)
    prev = _TAIL.get(src) or []
    if ws and prev:
        best = 0
        for k in range(min(max_overlap, len(ws), len(prev)), 0, -1):
            if [_norm(x) for x in prev[-k:]] == [_norm(x) for x in ws[:k]]:
                best = k
                break
        if best:
            ws = ws[best:]
    if ws:
        _TAIL[src] = ws[-max_overlap:]
    return " ".join(ws)


def _derepeat(ws: list) -> list:
    """Три и более одинаковых слова подряд — это сбой декодера, а не речь.

    Порог намеренно щадящий. Человек ДЕЙСТВИТЕЛЬНО говорит «да, да» и
    «нет, нет» — вычищать двойные повторы значит править человека, а не
    модель. А вот «то то то то» подряд живой речью не бывает.
    """
    # ВЕЧНЫЙ ЦИКЛ НА ГОЛОМ ЗНАКЕ (2026-09-06, найдено сэмплером стеков:
    # поток stt минуту сидел в _derepeat, слух встал, очередь кадров
    # упёрлась в 300). Токен вроде «—» или «…» после _norm пуст, внутренний
    # цикл не делал ни шага, j == i, и i не двигался. CTC-декодер такие
    # токены выдаёт постоянно, RNNT почти никогда — потому вылезло только
    # после смены движка. Пустой токен — просто пропускаем вперёд.
    out, i, n = [], 0, len(ws)
    while i < n:
        key = _norm(ws[i])
        if not key:
            out.append(ws[i])
            i += 1
            continue
        j = i
        while j < n and _norm(ws[j]) == key:
            j += 1
        run = j - i
        out.extend(ws[i:i + (2 if run > 2 else run)])
        i = j
    return out


def polish(text: str, src: str = "sys", seam: bool = True) -> str:
    """Полная уборка одной фразы."""
    t = (text or "").strip()
    if not t:
        return ""
    if seam:
        t = unseam(t, src)
    t = " ".join(_derepeat(_words(t)))
    t = _SP.sub(" ", t)
    t = _BEFORE_PUNCT.sub(r"\1", t)
    t = _MULTI_PUNCT.sub(r"\1", t)
    t = t.strip()
    if not t:
        return ""
    # заглавная в начале и точка в конце: облачко читает человек, а следом
    # его читает модель — обоим нужна граница предложения
    if t[0].islower():
        t = t[0].upper() + t[1:]
    if t[-1] not in ".!?…":
        t += "."
    return t


def forget(src: str = ""):
    """Забыть хвост (перезапуск канала, смена источника)."""
    if src:
        _TAIL.pop(src, None)
    else:
        _TAIL.clear()
