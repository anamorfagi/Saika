"""СМЕНА ГОВОРЯЩЕГО ВНУТРИ ОДНОЙ ФРАЗЫ — разрезание перед распознаванием.

(2026-08-15, задача владельца: «включу аниме на фон, будем смотреть, как он
будет определять голоса персонажей… чтобы мог определить по тембру, даже
если два человека вместе говорят».)

ЧТО ЭТО ЧИНИТ. Нарезка по паузам считает фразой всё от тишины до тишины.
Живой диалог — аниме, спор, перебивание — пауз между репликами не имеет:
«Ты куда пошёл?Я в магазин.Купи молока» приезжает ОДНИМ куском, движок
пишет его одной строкой, отпечаток вешает на кусок ОДНОГО говорящего —
второй персонаж исчезает из стенограммы как человек.

КАК РЕЖЕМ. По тембру, тем же энкодером, что узнаёт голоса (ECAPA из
voiceprint — он уже в памяти, ничего нового не грузится): скользящим окном
~1.2с с шагом 0.4с считаем эмбеддинги, между соседними окнами — косинус.
Провал ниже порога = в этом месте сменился голос. Режем по центру провала,
куски короче 0.8с не рождаем (это не реплика, это придыхание).

ЧЕСТНОСТЬ ГРАНИЦ. Метод ловит СМЕНУ голоса, а не наложение: когда двое
говорят строго одновременно, эмбеддинг смеси не похож ни на кого — такие
куски помечаются crowd=True («несколько голосов разом»), и это правда,
которую мы знаем, а не выдумка. Полное разделение наложенной речи — это
source separation, отдельная тяжёлая модель; пометка честнее плохой догадки.

ЦЕНА. Эмбеддинг окна — миллисекунды на GPU и десятки на CPU; окон в фразе
единицы. Живёт в потоке распознавания, горячий цикл слуха не трогает.
Выключается: stt.turns = false.
"""
import logging

import numpy as np

from anamorf.config import CFG

log = logging.getLogger("saika.turns")

SR = 16000
WIN_S = 1.2          # окно эмбеддинга
HOP_S = 0.4          # шаг
# КОРОЧЕ — НЕ РЕПЛИКА. Полторы секунды, а не 0.8 (2026-08-16): обрывок
# в секунду движок дослышивает до случайного слова, и в ленте появляются
# «Огромный.» и «Ра!» вместо целых фраз. Ручка: stt.turns_min_part_s.
MIN_PART_S = 1.5


def _cos(a, b):
    na, nb = np.linalg.norm(a), np.linalg.norm(b)
    if na < 1e-9 or nb < 1e-9:
        return 0.0
    return float(np.dot(a, b) / (na * nb))


def _f0(win_x, sr):
    """Основная частота окна -> Гц или 0 (не тон).

    ДВА ФОКУСА РАДИ СКОРОСТИ, и оба обязательны (2026-08-16, мой прокол,
    пойманный владельцем через минуту после выкатки: в логе поехало
    «Слух не успевает: уронила 1001 чанков — движок медленнее реального
    времени»). Первая версия считала np.correlate(w, w, "full") по 6400
    отсчётам: это честные 40 миллионов умножений НА КАЖДОЕ окно, восемь
    окон на фразу — и конвейер захлебнулся.

      1. ПРОРЕЖИВАЕМ ВЧЕТВЕРО. Тон живого голоса лежит в 65-320 Гц; для
         него хватает 4 кГц частоты дискретизации, а данных становится
         вчетверо меньше.
      2. АВТОКОРРЕЛЯЦИЯ ЧЕРЕЗ ФУРЬЕ. Прямая свёртка — O(n²), через
         спектр — O(n log n). На этих длинах это разница в сотни раз.

    Итог: доли миллисекунды на окно вместо десятков."""
    m = len(win_x)
    if m < int(sr * 0.2):
        return 0.0
    c = m // 2
    half = min(c, int(sr * 0.2))
    w = win_x[c - half:c + half]
    dec = max(1, int(sr // 4000))
    if dec > 1:                       # 16к -> 4к: тону этого с запасом
        cut = (len(w) // dec) * dec
        w = w[:cut].reshape(-1, dec).mean(1)
    srd = sr / dec
    nw = len(w)
    if nw < 64:
        return 0.0
    w = w - float(np.mean(w))
    if float(np.sqrt(np.mean(w ** 2))) < 1e-4:
        return 0.0
    nfft = 1 << int(np.ceil(np.log2(2 * nw)))
    sp = np.fft.rfft(w, nfft)
    ac = np.fft.irfft(sp * np.conj(sp), nfft)[:nw]
    lo, hi = int(srd / 320), int(srd / 65)
    if hi >= len(ac) or lo >= hi or lo < 1:
        return 0.0
    k = lo + int(np.argmax(ac[lo:hi]))
    if ac[0] <= 0 or ac[k] < 0.30 * ac[0]:
        return 0.0                      # непериодично — шипящая или шум
    # ОКТАВНАЯ ОШИБКА — БОЛЕЗНЬ ВСЕХ АВТОКОРРЕЛЯЦИЙ: пик на удвоенном
    # периоде почти так же высок, и женский голос в 260 Гц уезжает в 130.
    # Для нас это критично: на этом тоне строится развод по людям.
    # Если половинный период почти так же хорош — берём его.
    if k // 2 >= lo and ac[k // 2] >= 0.85 * ac[k]:
        k = k // 2
    return float(srd) / k


def _jump(a, b):
    """Относительный скачок тона между соседними окнами (0 — нет)."""
    if not a or not b:
        return 0.0
    return abs(a - b) / max(a, b)


def _encoder():
    """Боевой энкодер тембра из voiceprint. Нет его (выключен, не встал) —
    разрезание молча выключается: слух работает как работал."""
    try:
        from anamorf import voiceprint as vp
        enc = getattr(vp.S, "enc", None)
        if enc is not None and hasattr(enc, "encode"):
            return enc
    except Exception:
        pass
    return None


def _dna_cuts(pcm16, sr, min_gap_s):
    """Границы смены голоса по ГОЛОСОВОЙ ДНК — окном в полсекунды.

    ЗАЧЕМ ВТОРОЙ МЕТОД (2026-08-16, разбор аниме-лога владельца: «есть
    моменты, где говорят разные люди, видно по частотам, но записывается
    в одни облачка»). Разрез по ECAPA считает окном 1.2 секунды. В аниме
    реплики короче: «Есть!», «Да не может быть!», «Как так?» — окно
    накрывает СРАЗУ ДВОИХ, эмбеддинг выходит химерой, косинус между
    такими химерами ничего не проваливает, и двое уезжают в один пузырь.
    Уменьшить окно у ECAPA нельзя: на полсекунды он врёт.

    А отпечаток из voice_dna можно: он считается по мел-огибающей за
    доли миллисекунды и на полсекунде речи уже устойчив (проверено — от
    высоты тона и от слов не зависит). Поэтому здесь второй проход,
    мелкой сеткой: окно 0.5с, шаг 0.15с. Он ловит быструю перепалку,
    которую крупная сетка физически не видит.
    """
    try:
        from anamorf.stt import voice_dna as vd
    except Exception:
        return []
    win = int(sr * float(CFG.get("stt.turns_dna_win_s", 0.5)))
    hop = int(sr * float(CFG.get("stt.turns_dna_hop_s", 0.15)))
    n = len(pcm16)
    if n < win * 3:
        return []
    embs, marks = [], []
    for i in range(0, n - win, hop):
        e = vd.envelope(pcm16[i:i + win], sr)
        if e is not None:
            embs.append(e)
            marks.append(i + win // 2)
    if len(embs) < 4:
        return []
    thr = float(CFG.get("stt.turns_dna_cos", 0.82))
    sims = [_cos(embs[k], embs[k + 1]) for k in range(len(embs) - 1)]
    cuts = []
    for k in range(len(sims)):
        if sims[k] >= thr:
            continue
        # локальный минимум: одна смена даёт 2-3 низких пары подряд
        if (k == 0 or sims[k] <= sims[k - 1]) and \
           (k == len(sims) - 1 or sims[k] <= sims[k + 1]):
            cut = (marks[k] + marks[k + 1]) // 2
            if not cuts or cut - cuts[-1] >= int(min_gap_s * sr):
                cuts.append(cut)
    # проверка группами: слева и справа от реза средние отпечатки тоже
    # обязаны быть непохожи — иначе это был чих, а не смена человека
    kept = []
    for cut in cuts:
        L = [e for e, m in zip(embs, marks) if m < cut]
        R = [e for e, m in zip(embs, marks) if m >= cut]
        if not L or not R:
            continue
        cl, cr = np.mean(np.stack(L), 0), np.mean(np.stack(R), 0)
        if _cos(cl, cr) < thr + 0.06:
            kept.append(cut)
    return kept


def split(pcm16: np.ndarray, sr: int = SR, encoder=None):
    """-> [ {start, end, crowd} ] в сэмплах. Один говорящий -> один кусок.

    encoder пробрасывается только стендом (tools/hear_lab.py) — в бою он
    берётся из voiceprint сам."""
    n = len(pcm16)
    whole = [{"start": 0, "end": n, "crowd": False}]
    if not CFG.get("stt.turns", True):
        return whole
    win, hop = int(WIN_S * sr), int(HOP_S * sr)
    min_part = float(CFG.get("stt.turns_min_part_s", MIN_PART_S))
    # КОРОТКУЮ ФРАЗУ НЕ ТРОГАЕМ (2026-08-15, живой прокол в первый же час:
    # «Твоя задача определить, сколько человек в аниме» — хвост «в аниме»
    # отрезало и ослышало как «Да». В двух секундах речи смене голоса
    # взяться неоткуда, а вреда от ложного разреза много: обрезок в
    # полсекунды движок дослышивает до случайного слова.)
    if n < int(float(CFG.get("stt.turns_min_s", 2.5)) * sr):
        return whole
    if n < win + hop:               # короче двух окон — резать нечего
        return whole
    enc = encoder or _encoder()
    if enc is None:
        return whole
    try:
        # ТИХОЕ ОКНО НЕ ЭМБЕДДИТСЯ (баг пойман стендом tools/hear_lab:
        # окно на хвостовой тишине даёт мусорный вектор, косинус с ним
        # проваливается — и «смена голоса» рисовалась там, где человек
        # просто ЗАМОЛЧАЛ). Эмбеддинг тембра имеет смысл только на речи.
        x = np.asarray(pcm16, np.float32) / 32768.0
        peak_rms = 0.0
        rms_of = {}
        i = 0
        while i + win <= n:
            r = float(np.sqrt(np.mean(x[i:i + win] ** 2)))
            rms_of[i] = r
            peak_rms = max(peak_rms, r)
            i += hop
        floor = peak_rms * 0.2
        # ═══ ТОН — ПЕРВЫМ, ТЕМБР — ВТОРЫМ (2026-08-16) ═══
        # Владелец: «нужно ускорять обработку, точность и улучшать
        # логичность разделения; обе технологии должны работать друг на
        # друга — и на основе логики, и на основе частоты».
        #
        # Тон и тембр — два независимых свидетеля, и у каждого своя
        # сильная сторона. Тон считается автокорреляцией за микросекунды
        # и не врёт грубо; тембр (ECAPA) видит тонкие различия, но стоит
        # на два порядка дороже и на коротком окне капризен.
        #
        # Поэтому порядок такой: СНАЧАЛА дешёвый тон по всем окнам. Если
        # он ровный по всей фразе — говорил один человек, и эмбеддинги
        # можно не считать вовсе (это и есть обещанное ускорение: чаще
        # всего фраза именно такая). Если тон где-то прыгнул — зовём
        # тембр и дальше решаем ВДВОЁМ: неоспоримый провал косинуса режет
        # сам; спорный — только если в том же месте прыгнул и тон.
        pitches, pmarks = [], []
        i = 0
        while i + win <= n:
            if rms_of.get(i, 0.0) >= floor:
                pitches.append(_f0(x[i:i + win], sr))
                pmarks.append(i + win // 2)
            i += hop
        vp_ = [p for p in pitches if p]
        pj_thr = float(CFG.get("stt.turns_pitch_jump", 0.16))
        if len(vp_) >= 2:
            spread = (max(vp_) - min(vp_)) / max(vp_)
            if spread < pj_thr * 0.6:
                # тон ровный на всю фразу — тембру тут делать нечего
                return whole
        embs, marks = [], []
        i = 0
        while i + win <= n:
            if rms_of.get(i, 0.0) < floor:
                i += hop
                continue
            e = enc.encode(pcm16[i:i + win])
            # боевой encode отдаёт (vec, pitch); стендовый может отдать vec
            vec = e[0] if isinstance(e, tuple) else e
            if vec is None:
                return whole
            embs.append(np.asarray(vec, dtype=np.float32))
            marks.append(i + win // 2)          # центр окна
            i += hop
        if len(embs) < 3:
            return whole
        # ПОРОГ 0.35, А НЕ 0.60 (2026-08-15, тот же прокол). ECAPA-косинус
        # ОДНОГО человека между соседними окнами гуляет 0.5-0.8 — порог
        # 0.60 резал монологи. Разные голоса дают 0.1-0.4. Режем только
        # там, где непохожесть НЕОСПОРИМА; спорные места пусть живут одной
        # фразой — это дешевле, чем осколки со случайными словами.
        thr = float(CFG.get("stt.turns_cos", 0.35))
        # косинус соседних окон; провал = смена голоса. Ищем ЛОКАЛЬНЫЕ
        # минимумы ниже порога, а не все подряд: одна смена даёт 2-3
        # низких пары подряд (окна перекрывают границу), резать надо раз.
        sims = [_cos(embs[k], embs[k + 1]) for k in range(len(embs) - 1)]
        # тон в тех же точках, что и тембр: pmarks считались по тем же
        # окнам, поэтому просто берём по позиции
        pit = {m: p for m, p in zip(pmarks, pitches)}
        jumps = [_jump(pit.get(marks[k], 0.0), pit.get(marks[k + 1], 0.0))
                 for k in range(len(marks) - 1)]
        cuts = []
        for k in range(len(sims)):
            # ОКНА СМОТРЯТ В РАЗНЫЕ ТОЧКИ, И ЭТО НАДО УЧЕСТЬ. Эмбеддинг
            # берётся со всего окна в 1.2с, поэтому меняется УЖЕ тогда,
            # когда новый голос занял его половину; тон считается по
            # центральным 400мс и меняется на шаг позже. На стенде это
            # видно буквально: провал косинуса на индексе 2, прыжок тона
            # на индексе 3. Поэтому свидетелей сверяем с допуском в один
            # шаг — иначе они всё время «не встречаются».
            jmp = max(jumps[max(0, k - 1):min(len(jumps), k + 2)] or [0.0])
            # ДВА СВИДЕТЕЛЯ. Неоспоримый провал тембра режет сам; спорный
            # (до порога не дотянул, но близко) — только если в этом же
            # месте прыгнул тон. И наоборот: очень большой прыжок тона
            # (голос ушёл больше чем на треть) — повод резать, даже если
            # тембр мнётся: так ловится мужчина/женщина, взрослый/ребёнок,
            # где ECAPA на коротком окне часто нерешителен.
            # ПРАВИЛО «БОЛЬШОЙ ПРЫЖОК ТОНА РЕЖЕТ САМ» УБРАНО (2026-08-16,
            # через час после введения). Владелец на аниме: «он не совсем
            # корректно прописывает слова, друг сказал „огромный пенис“, а
            # он просто не прописал». Смотрю в чат: одна фраза «Как бы
            # тяжело ни продолжать бороться за Розенхей» разорвана надвое,
            # а между кусками вклинился обрывок «Огромный.» на 141 Гц.
            # Это и есть тот самый прыжок тона: у диктора голос ушёл вниз
            # на слове, музыка добавила своего — и я резал посреди мысли,
            # теряя слова на стыке.
            #
            # Тон остаётся ПОДДЕРЖКОЙ, а не самостоятельным основанием:
            # он помогает дожать спорный провал тембра (soft) и не более.
            # Резать по одному тону — значит резать по интонации.
            hard = sims[k] < thr
            soft = sims[k] < thr + 0.12 and jmp >= pj_thr
            if not (hard or soft):
                continue
            # ДЛИНА КУСКА ЗАВИСИТ ОТ СИЛЫ УЛИКИ (2026-08-16, разбор
            # аниме-лога владельца: «есть моменты, где говорят разные
            # люди, видно по частотам, но записывается в одни облачка»).
            # Полторы секунды я поставил, чтобы не рождались обрывки
            # «Огромный.» — и заодно запретил резать короткие реплики,
            # а в аниме почти вся перепалка короче: «Есть!», «Да!»,
            # «Как так?». Правило точнее: когда тембр провалился
            # НЕОСПОРИМО, короткий кусок — это не обрывок, это реплика.
            _mp = min_part if not hard else float(
                CFG.get("stt.turns_min_part_hard_s", 0.8))
            if (k == 0 or sims[k] <= sims[k - 1]) and \
               (k == len(sims) - 1 or sims[k] <= sims[k + 1]) or soft:
                cut = (marks[k] + marks[k + 1]) // 2
                if not cuts or cut - cuts[-1] >= int(_mp * sr):
                    cuts.append(cut)
        # ВТОРОЙ ПРОХОД, МЕЛКОЙ СЕТКОЙ: то, что крупное окно ECAPA
        # физически не видит (реплики короче секунды). Границы обоих
        # методов складываем и чистим от близнецов.
        try:
            _dc = _dna_cuts(pcm16, sr, float(
                CFG.get("stt.turns_min_part_hard_s", 0.8)))
            if _dc:
                _all = sorted(set(cuts) | set(_dc))
                _mg = int(float(CFG.get("stt.turns_min_part_hard_s", 0.8)) * sr)
                cuts = []
                for c in _all:
                    if not cuts or c - cuts[-1] >= _mg:
                        cuts.append(c)
        except Exception as _e:
            log.debug("разрез по ДНК пропущен: %s", _e)
        if not cuts:
            return whole
        # ПРОВЕРКА КАЖДОГО РАЗРЕЗА ПО ГРУППАМ (2026-08-15). Пара соседних
        # окон — слишком шаткое основание: одно кашлянутое окно роняет
        # косинус. Разрез остаётся, только если СРЕДНИЕ тембры слева и
        # справа от него тоже непохожи — то есть голос сменился надолго,
        # а не мигнул на полсекунды.
        kept = []
        for cut in cuts:
            left = [e for e, m in zip(embs, marks) if m < cut]
            right = [e for e, m in zip(embs, marks) if m >= cut]
            if len(left) >= 1 and len(right) >= 1:
                cl = np.mean(np.stack(left), axis=0)
                cr = np.mean(np.stack(right), axis=0)
                # групповая проверка тоже слушает обоих свидетелей: если
                # средний тон слева и справа разошёлся уверенно, разрез
                # выживает даже при мягком косинусе
                pl = [p for m, p in zip(marks, [pit.get(m, 0.0) for m in marks])
                      if m < cut and p]
                pr = [p for m, p in zip(marks, [pit.get(m, 0.0) for m in marks])
                      if m >= cut and p]
                gj = _jump(float(np.median(pl)) if pl else 0.0,
                           float(np.median(pr)) if pr else 0.0)
                if _cos(cl, cr) < thr + 0.1 or \
                        (gj >= pj_thr and _cos(cl, cr) < thr + 0.25):
                    kept.append(cut)
        cuts = kept
        if not cuts:
            return whole
        # РАЗНОБОЙ ВНУТРИ КУСКА = НЕСКОЛЬКО ГОЛОСОВ РАЗОМ. Если окна и
        # ПОСЛЕ разреза не похожи друг на друга, это не смена — это смесь:
        # честная пометка вместо уверенной подписи одним именем.
        parts = []
        edges = [0] + cuts + [n]
        wi = 0
        for s0, s1 in zip(edges[:-1], edges[1:]):
            _mp_lo = float(CFG.get("stt.turns_min_part_hard_s", 0.8))
            if s1 - s0 < int(_mp_lo * sr):
                # слишком короткий — приклеиваем к соседу
                if parts:
                    parts[-1]["end"] = s1
                    continue
                s1 = min(n, s0 + int(_mp_lo * sr))
            ws = [e for e, m in zip(embs, marks) if s0 <= m < s1]
            crowd = False
            if len(ws) >= 2:
                inner = [_cos(ws[k], ws[k + 1]) for k in range(len(ws) - 1)]
                crowd = (float(np.mean(inner)) < thr)
                # ВТОРОЙ ПРИЗНАК СМЕСИ — ДЁРГАНЫЙ ТОН. У одного человека
                # тон внутри реплики плывёт плавно; когда в куске звучат
                # двое разом, автокорреляция цепляется то за один голос,
                # то за другой, и трек прыгает туда-обратно. Считаем долю
                # больших скачков: больше трети — это смесь.
                pp = [pit.get(m, 0.0) for m in marks if s0 <= m < s1]
                pp = [p for p in pp if p]
                if len(pp) >= 3:
                    jj = [_jump(pp[k], pp[k + 1]) for k in range(len(pp) - 1)]
                    if sum(1 for j in jj if j >= pj_thr) / len(jj) > 0.34:
                        crowd = True
            # НАХЛЁСТ НА НАЧАЛЕ КУСКА (2026-08-16). Рез приходится на
            # середину провала косинуса, а не на тишину, — и слово,
            # начавшееся прямо на границе, теряет свою атаку: движок
            # получает «енис» вместо «пенис» и честно молчит. Отступаем
            # назад на десятую секунды: начало слова возвращается в кусок,
            # а лишний хвост предыдущего голоса такой длины движку не
            # мешает — это меньше одного слога.
            # НАХЛЁСТ ТЕПЕРЬ С ОБЕИХ СТОРОН (2026-08-16, владелец: «бывают
            # пропуски слов в фразах»). Отступ назад спасал начало слова у
            # ПРАВОГО куска, но у ЛЕВОГО ровно то же слово по-прежнему
            # обрывалось на середине — и движок его просто не писал. Слово
            # на границе должно целиком попасть в ОБА куска: тогда каждый
            # движок видит его полностью, а лишний повтор снимается уже по
            # тексту (склейка стыков в main.py::_join_parts) — по словам
            # это надёжнее, чем по сэмплам.
            _ov = int(float(CFG.get("stt.turns_overlap_ms", 120)) / 1000 * sr)
            parts.append({"start": int(max(0, s0 - (_ov if s0 else 0))),
                          "end": int(min(n, s1 + (_ov if s1 < n else 0))),
                          "crowd": crowd})
            wi += 1
        if len(parts) > 1:
            log.info("Смена голоса внутри фразы: режу на %d куска(ов) "
                     "(пороговый косинус %.2f)", len(parts), thr)
        return parts or whole
    except Exception as e:
        log.debug("разрезание по голосам пропущено: %s", e)
        return whole


def who_emb(pcm16: np.ndarray, sr: int = SR):
    """То же, что who(), но ОТДАЁТ И САМ ВЕКТОР (2026-08-31).

    ПОВОД — замер горячего пути. На каждый результат ECAPA кодировала
    ОДИН И ТОТ ЖЕ кусок ДВАЖДЫ: здесь — чтобы назвать говорящего, и
    следом в main.py — чтобы положить отпечаток в r["_env"] для
    пересборки дорожек. Два прогона модели на GPU вместо одного, на
    каждую фразу, в самом узком месте конвейера. Отдаём вектор наружу —
    второй прогон становится не нужен, а смысл не меняется: это ровно
    тот же эмбеддинг того же куска.
    """
    try:
        from anamorf import voiceprint as vp
        enc = getattr(vp.S, "enc", None)
        reg = getattr(vp.S, "reg", None)
        if enc is None or reg is None:
            return "", 0.0, None
        e = enc.encode(pcm16)
        vec = e[0] if isinstance(e, tuple) else e
        if vec is None:
            return "", 0.0, None
        name, _sim, conf, _near = reg.match(vec)
        return name, float(conf), vec
    except Exception:
        return "", 0.0, None


def who(pcm16: np.ndarray, sr: int = SR):
    """Чей это кусок: имя из карты голосов + уверенность, или ("", 0).
    Для подписи разрезанных кусков: who_now() тут не годится — он про
    «прямо сейчас в комнате», а кусок мог прозвучать три секунды назад."""
    n, c, _ = who_emb(pcm16, sr)
    return n, c
