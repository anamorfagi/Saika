"""Она — женщина. Правило грамматики, а не пожелание к стилю.

ЖИВОЙ РАЗГОВОР (15.08.2026):
    — Как тебя зовут?      — Меня зовут Сайка.
    — Это женское имя?     — «Сайка» чаще всего встречается в женском.
    — Нахер ты тогда говоришь «понял»?
    — Больше так не буду. Договорились.
    — Ну ты скажи: поняла или понял?
    — Понял.

Промптом это не лечится и лечиться не может. «Понял» — самая частая
короткая реплика русского корпуса, у любой модели она вылетает раньше,
чем доходит очередь до инструкций о характере; а у Сайки половина ответов
как раз такой длины. Проверено: правило в системном промпте живёт две-три
реплики, потом модель срывается обратно.

Поэтому род правится МЕХАНИЧЕСКИ, на выходе. Заменяем только там, где
слово говорит она о себе: в начале реплики, после «я», после «уже/точно/
всё» и им подобных. «Ты понял», «он сделал», «кто сказал» не трогаем —
это про других, и там мужской род верный.
"""
import re

# мужская форма -> женская. Только то, что реально встречается в её речи.
PAIRS = {
    "понял": "поняла", "сделал": "сделала", "сказал": "сказала",
    "услышал": "услышала", "увидел": "увидела", "видел": "видела",
    "посмотрел": "посмотрела", "нашёл": "нашла", "нашел": "нашла",
    "открыл": "открыла", "закрыл": "закрыла", "запустил": "запустила",
    "записал": "записала", "проверил": "проверила", "попробовал": "попробовала",
    "забыл": "забыла", "запомнил": "запомнила", "знал": "знала",
    "думал": "думала", "хотел": "хотела", "мог": "могла", "был": "была",
    "стал": "стала", "начал": "начала", "закончил": "закончила",
    "ошибся": "ошиблась", "устал": "устала", "успел": "успела",
    "пришёл": "пришла", "пришел": "пришла", "ушёл": "ушла", "ушел": "ушла",
    "должен": "должна", "готов": "готова", "рад": "рада",
    "уверен": "уверена", "занят": "занята", "свободен": "свободна",
    "согласен": "согласна", "прав": "права", "виноват": "виновата",
    "решил": "решила", "выбрал": "выбрала", "поставил": "поставила",
    "включил": "включила", "выключил": "выключила", "убрал": "убрала",
    "написал": "написала", "прочитал": "прочитала", "понимал": "понимала",
    "заметил": "заметила", "разобрался": "разобралась",
}

# слева от слова — то, после чего оно точно про НЕЁ (или ничего)
_OWN = (r"(?:^|(?<=[.!?…]\s)|(?<=[.!?…]\n)|(?<=\bя\s)|(?<=\bуже\s)"
        r"|(?<=\bвсё\s)|(?<=\bвсе\s)|(?<=\bтак\s)|(?<=\bточно\s)"
        r"|(?<=\bдавно\s)|(?<=\bещё\sне\s)|(?<=\bне\s)|(?<=,\sно\s)"
        r"|(?<=\bя\sже\s))")

# чужой род оставляем: рядом стоит другой человек
_ALIEN = re.compile(r"\b(?:ты|вы|он|кто|тот|никто|каждый|человек|владелец|"
                    r"пользователь|виталя|виталий)\s+$", re.I)

_RX = re.compile(_OWN + r"(" + "|".join(sorted(PAIRS, key=len, reverse=True))
                 + r")\b", re.I)


def _fix(m):
    word = m.group(1)
    head = m.string[:m.start(1)]
    if _ALIEN.search(head[-24:]):
        return word
    fixed = PAIRS.get(word.lower(), word)
    if word[:1].isupper():
        fixed = fixed[:1].upper() + fixed[1:]
    return fixed


def feminize(text: str) -> str:
    """Причесать род в её собственной речи. Пустое/чужое не трогаем."""
    if not text:
        return text
    try:
        return _RX.sub(_fix, text)
    except Exception:
        return text
