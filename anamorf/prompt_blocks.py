"""Порядок блоков в промпте (2026-07-26).

ЗАЧЕМ. Динамика хода (`dyn_parts` в main.py) копилась плоским списком и
уезжала в промпт в том порядке, в котором написан код. Блоков стало много —
тон, память, лорбук, дев-доска, поиск, картинка, зрение, заметки автора — и
порядок начал значить: у языковых моделей ближе к концу промпта инструкция
весит больше, чем в середине. То есть «указание на сейчас» должно идти
последним, а справочный контекст — первым, иначе свежая инструкция тонет.

Идея разложить промпт на именованные блоки с настраиваемым порядком взята
из разбора Soul of Waifu (workshop/SOW_vs_SAIKA.md); реализация своя, у него
код под GPL-3.0 и брать оттуда строки нельзя.

ПОЧЕМУ КЛАСС-СПИСОК, А НЕ НОВЫЙ API. В main.py около двадцати мест зовут
`dyn_parts.append(text)`. Переписывать каждое — двадцать шансов опечататься
в файле на 3000 строк, который перезапускается руками. Поэтому Blocks ведёт
себя как обычный список: `append` работает как раньше, а имя блока
определяется по заголовку `### …`, который у этих кусков и так есть. Где
нужна точность — `add("имя", text)`.
"""
import logging
import re

from anamorf.config import CFG

log = logging.getLogger("saika.prompt")

# Порядок по умолчанию. Сначала справочное (кто, что помним, что в мире),
# потом добытые факты (поиск, картинка, кадр с экрана), потом правила
# поведения, и в самом конце — указание владельца на сейчас: оно должно
# перебивать всё выше, поэтому стоит ближе всех к реплике человека.
DEFAULT_ORDER = [
    "lore",        # лорбук: факты о мире, всплывшие по упоминанию
    "memory",      # долгая память по теме
    "devboard",    # дев-доска, если спросили про разработку
    "search",      # результаты поиска
    "image",       # присланная картинка
    "vision",      # то, что она увидела своими глазами
    "tone",        # метка тона: как себя вести с этой фразой
    "tools",       # правила инструментов
    "models",      # чем она думает и что есть в запасе
    "psyche",      # самочувствие и вера в свои силы
    "browser",     # напоминание про открытое окно браузера
    "other",       # всё, что не опознали
    "notes",       # заметки автора — последними, они главнее
]

# Опознание блока по заголовку. Ключ — что искать в первых 200 символах.
# Список проверяется СВЕРХУ ВНИЗ, первое совпадение выигрывает, поэтому
# более специфичные признаки должны идти раньше общих.
_SIGNS = [
    ("notes",    r"указание от владельца"),
    ("vision",   r"посмотрела своими глазами|кадр (?:экрана|вебки)|"
                 r"глаза выключены|режиме наблюдения|чёрного списка|"
                 r"открыть глаз|разобрала vision-модель"),
    ("image",    r"прислал\w* картинку|прикрепил\w* картинку|"
                 r"одолжила глаза|модель без зрения"),
    ("search",   r"результаты тво\w+ поиска|поиск в интернете за тебя"),
    ("memory",   r"тво\w+ память"),
    ("devboard", r"дев-доск|карта разработки"),
    ("lore",     r"что ты знаешь об этом мире|из твоего лорбука"),
    ("browser",  r"окно браузера|браузер (?:открыт|остался)"),
    ("tone",     r"как себя вести|тон реплики|человек (?:хамит|провоцирует|"
                 r"флиртует|хвалит)"),
    ("tools",    r"инструмент"),
]
_SIGNS = [(name, re.compile(pat, re.I)) for name, pat in _SIGNS]


def order() -> list:
    """Порядок из конфига, дополненный забытыми именами."""
    cfg = CFG.get("prompt.order", None)
    if not isinstance(cfg, list) or not cfg:
        return list(DEFAULT_ORDER)
    out = [x for x in cfg if x in DEFAULT_ORDER]
    if not out:
        return list(DEFAULT_ORDER)
    # Блок, которого нет в настройке, не должен пропадать молча. Ставим его
    # ПЕРЕД последним блоком из настройки: последняя позиция — самая весомая
    # (модель сильнее слушает конец промпта), владелец выбрал её осознанно, и
    # новый блок не должен эту позицию отбирать. Правило предсказуемое:
    # «незнакомое едет перед тем, что ты поставил последним».
    tail = [x for x in DEFAULT_ORDER if x not in out]
    if not tail:
        return out
    return out[:-1] + tail + out[-1:]


def classify(text: str) -> str:
    head = (text or "")[:220]
    for name, pat in _SIGNS:
        if pat.search(head):
            return name
    return "other"


class Blocks(list):
    """Список кусков промпта, который умеет собрать себя в нужном порядке.

    Совместим с обычным списком: `append`, `if dyn_parts:`, `len()` — всё
    как было. Дополнительно помнит, к какому блоку относится каждый кусок.
    """

    def __init__(self):
        super().__init__()
        self._tags = []

    def append(self, text, name=None):
        if not text:
            return
        super().append(text)
        self._tags.append(name or classify(text))

    def add(self, name, text):
        """Явно указать блок — когда заголовок не говорит сам за себя."""
        self.append(text, name)

    def render(self, sep="\n\n") -> str:
        """Собрать в порядке из настроек. Внутри блока — порядок добавления."""
        want = order()
        buckets = {}
        for text, name in zip(self, self._tags):
            buckets.setdefault(name, []).append(text)
        out = []
        for name in want:
            out.extend(buckets.pop(name, []))
        for name, items in buckets.items():        # неизвестные имена — в конец
            out.extend(items)
        return sep.join(out)

    def sizes(self) -> str:
        """Для логов: сколько символов съел каждый блок. Без этого «промпт
        16 тысяч символов» ничего не объясняет — непонятно, память это
        разрослась, лорбук или заметки владельца."""
        acc = {}
        for text, name in zip(self, self._tags):
            acc[name] = acc.get(name, 0) + len(text)
        if not acc:
            return "пусто"
        return " ".join(f"{n}:{v}" for n, v in
                        sorted(acc.items(), key=lambda kv: -kv[1]))

    def report(self) -> str:
        """Для логов: какие блоки собрались и в каком порядке."""
        want = order()
        present = [n for n in want if n in set(self._tags)]
        return " → ".join(present) if present else "пусто"
