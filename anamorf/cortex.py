"""СЛУХОВАЯ КОРА — один поток восприятия из всех моделей слуха (2026-08-15).

ЗАМЫСЕЛ ВЛАДЕЛЬЦА, дословно: «нужно получить подобие обработки звука
настоящим мозгом, то есть мультимодельная система распознавания,
сортировки и фильтрации».

К вечеру этого дня у Сайки уже есть все «отделы» слуховой системы, какие
есть у человека, — и каждый работает сам по себе:
    улитка/ствол  — нейро-VAD (речь или нет, 32мс);
    зона Вернике  — GigaAM/whisper (слова);
    правая кора   — отпечаток голоса (КТО), просодия (КАК);
    вторичная кора— PANNs + CLAP (ЧТО звучит), битбокс-транскриб (ритм);
    рефлексы      — стоп-слово, «будь здоров».
Не хватало того, что делает мозг МОЗГОМ: единого места, где всё это
сливается, сортируется по ВАЖНОСТИ и фильтруется ПРИВЫКАНИЕМ. Это оно.

ТРИ ПРИНЦИПА, честно взятые у нейрофизиологии:

1. САЛИЕНС (важность) — не громкость. Обращение по имени важнее любого
   грохота; речь важнее шума; новое важнее длящегося; хозяин важнее
   незнакомца. Каждый перцепт получает балл по этим осям.

2. ПРИВЫКАНИЕ (habituation). Мозг перестаёт слышать холодильник через
   минуту — не потому что тот стих, а потому что он ПРЕДСКАЗУЕМ. Повтор
   одинакового перцепта экспоненциально гасит его салиенс; изменение —
   мгновенно возвращает (дизабитуация).

3. ЭХОИЧЕСКАЯ ПАМЯТЬ. Последние ~30 секунд восприятия живут единой
   лентой, из которой читают ВСЕ потребители: промпт модели, панель,
   «что ты сейчас слышала?». Один источник правды вместо шести.

Кора ничего не считает сама — она СЛИВАЕТ уже посчитанное, поэтому её
цена — микросекунды на словарях. Отделы продолжают работать как работали
(правило «новое рядом»): кора подписана на их выходы, а не встроена в них.
"""
import logging
import threading
import time
from collections import deque

from anamorf.config import CFG

log = logging.getLogger("saika.cortex")

# базовый салиенс по типу перцепта: во сколько мозг ценит сам ФАКТ
_BASE = {
    "stop":     1.00,   # стоп-слово — рефлекс, выше всего
    "name":     0.95,   # обращение по имени
    "speech":   0.80,   # распознанная речь
    "event":    0.60,   # чих, крик, дверь — разовые события
    "beat":     0.50,   # ритм/битбокс
    "voice":    0.45,   # смена говорящего в комнате
    "sound":    0.30,   # метка звука (музыка, клавиатура...)
    "ambient":  0.15,   # фон: дистанция, темп печати
}

_lock = threading.Lock()
_tape = deque(maxlen=200)        # эхоическая память: перцепты за ~30с
_habit = {}                       # ключ привыкания -> {"n", "ts"}


def _salience(kind: str, key: str, novel_boost: float) -> float:
    base = _BASE.get(kind, 0.2)
    h = _habit.get(key)
    now = time.time()
    if h is None or now - h["ts"] > float(CFG.get("cortex.forget_s", 45)):
        _habit[key] = {"n": 1, "ts": now}
        return min(1.0, base + novel_boost)         # новое — ярче
    h["n"] += 1
    h["ts"] = now
    # привыкание: каждый повтор гасит вдвое слабее, пол — четверть базы
    return max(base * 0.25, base * (0.82 ** (h["n"] - 1)))


def feel(kind: str, text: str, who: str = "", extra: dict = None):
    """Один перцепт от любого отдела. kind — тип из _BASE, text — суть
    по-человечески («речь: привет», «звук: клавиатура», «ритм: пу тс»)."""
    try:
        key = f"{kind}:{(text or '')[:40]}"
        novel = 0.15 if kind in ("sound", "event") else 0.05
        sal = _salience(kind, key, novel)
        with _lock:
            _tape.append({"ts": time.time(), "kind": kind, "sal": round(sal, 2),
                          "text": (text or "")[:160], "who": who,
                          **(extra or {})})
    except Exception as e:
        log.debug("кора споткнулась: %s", e)


def tape(seconds: float = 30.0, min_sal: float = 0.0) -> list:
    """Лента восприятия за окно, свежее — последним."""
    now = time.time()
    with _lock:
        return [p for p in _tape
                if now - p["ts"] <= seconds and p["sal"] >= min_sal]


def context_line(budget: int = 420) -> str:
    """Строка для промпта: чем сейчас живёт слух, по убыванию важности.
    Замена шести разрозненных строк одним взглядом коры. Привыкшее
    (салиенс упал ниже 0.2) в промпт не попадает — как и у человека
    холодильник не попадает в мысли."""
    ps = tape(20.0, 0.2)
    if not ps:
        return ""
    # схлопываем одинаковое, свежее и важное — вперёд
    seen, rows = set(), []
    for p in sorted(ps, key=lambda x: (-x["sal"], -x["ts"])):
        k = f'{p["kind"]}:{p["text"][:30]}'
        if k in seen:
            continue
        seen.add(k)
        who = f' ({p["who"]})' if p.get("who") else ""
        rows.append(f'{p["text"]}{who}')
        if sum(len(r) for r in rows) > budget:
            break
    return "; ".join(rows)


def status() -> dict:
    """Для панели: что в коре прямо сейчас, с баллами важности."""
    return {"tape": tape(30.0)[-25:],
            "habituated": sorted(
                (k for k, v in _habit.items() if v["n"] >= 4),
                key=lambda k: -_habit[k]["n"])[:10]}
