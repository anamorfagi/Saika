"""ЧТО СЕЙЧАС НА СТОЛЕ: состояние разговора (2026-08-14).

Владелец, посмотрев на поиск «дай его»: «мне кажется, тут какой то глупый
механизм — что именно гуглит, она буквально не понимает контекст», и следом:
«попробуй проанализировать свой же анализ — как ты понимаешь контекст, как
догадываешься, о чём всё-таки речь».

РАЗБОР. Человек, читающий «Попробуй загуглить, дай его», не разбирает эту
фразу. Он держит состояние разговора и читает фразу как ОБНОВЛЕНИЕ к нему.
В состоянии лежит четыре вещи:

  1. НЕЗАКРЫТАЯ ЗАДАЧА. Пять реплик подряд одна цель — открыть канал
     Snailkick. Она не выполнена. Пока цель висит, двусмысленная фраза
     читается как шаг к ней, а не как новая тема.
  2. ПРЕДМЕТЫ НА СТОЛЕ. Snailkick, YouTube, Chrome — с давностью. «Его»
     ищет кандидата среди них, а не в словаре.
  3. ПРОВЕРКА НА АБСУРД. Стал бы человек гуглить «дай его»? Таких запросов
     не бывает. Абсурдный разбор — признак ошибки РАЗБОРА, а не оговорки
     человека.
  4. ЧТО МЕШАЕТ. Фокус окна не отдавался — значит ввод не сработал, и
     следующая реплика читается на этом фоне.

У Сайки не было ни одного из четырёх: каждая фраза приходила голой, как
первая в жизни. Отсюда «Второй открой» -> «открываю второй пункт» и ноль
действий, «Догадайся» -> «уточни, пожалуйста», «дай его» -> мемы в TikTok.
Это не три разных бага, это одно отсутствующее.

Модуль дешёвый нарочно: никаких лишних вызовов модели, всё считается по
тексту реплик и по тому, что вернули инструменты. Состояние живёт в памяти
процесса и стареет само — разговор через час это уже другой разговор.
"""
import logging
import re
import time

log = logging.getLogger("saika.focus")

STATE = {
    "goal": "",          # незакрытая задача словами человека
    "goal_ts": 0.0,
    "objects": [],       # [{"name": str, "ts": float}] — предметы на столе
    "blocked": "",       # что помешало в прошлый раз
    "blocked_ts": 0.0,
}

LIFE_S = 1800.0          # полчаса без упоминания — предмет уходит со стола
GOAL_LIFE_S = 900.0      # цель живёт 15 минут: дольше — это уже другой день

# имя собственное: латиница или слово с заглавной НЕ в начале предложения
_NAME = re.compile(r"[A-Za-z][A-Za-z0-9._\-]{2,}")
_STOP_NAME = {"youtube", "google", "chrome", "windows", "http", "https",
              "www", "com", "org", "enter", "esc", "ok"}

# просьба, а не болтовня: с неё начинается задача
_TASK = re.compile(
    r"\b(открой|запусти|включи|найди|поищи|загугли|покажи|поставь|сделай|"
    r"закрой|сверни|переключись|перенеси|впиши|введи|набери|напиши|"
    r"отправь|нажми|кликни|прокрути|скачай)\b", re.I)

# признаки, что задача закрыта
_DONE = re.compile(r"\b(спасибо|отлично|супер|готово|получилось|"
                   r"да[,\s]*всё|хватит|забудь|ладно|проехали)\b", re.I)

# человек говорит, что НЕ получилось — цель остаётся висеть
_FAILED = re.compile(r"\b(не\s+получилось|не\s+вышло|ничего\s+не|"
                     r"не\s+работает|не\s+сделал\w*|не\s+открыл\w*|"
                     r"неправильно|не\s+то|мимо|туплю|тупишь)\b", re.I)

# местоимения, за которыми прячется предмет со стола
PRONOUN = re.compile(r"\b(его|её|ее|их|это|этого|эту|этот|эти|там|туда|"
                     r"тот|та|те|он|она|они)\b", re.I)


def _fresh(items, life):
    now = time.time()
    return [i for i in items if now - i["ts"] < life]


def note_user(text: str):
    """Реплика человека: обновляем стол и цель."""
    t = (text or "").strip()
    if not t:
        return
    now = time.time()
    # предметы: имена собственные из фразы
    names = []
    for sent in re.split(r"[.!?]+", t):
        words = sent.split()
        for i, w in enumerate(words):
            cw = w.strip("«»\"'(),:;-—")
            if len(cw) < 3 or cw.lower() in _STOP_NAME:
                continue
            if _NAME.fullmatch(cw) or (cw[:1].isupper() and i > 0):
                names.append(cw)
    objs = _fresh(STATE["objects"], LIFE_S)
    for n in names:
        objs = [o for o in objs if o["name"].lower() != n.lower()]
        objs.append({"name": n, "ts": now})
    STATE["objects"] = objs[-8:]

    # цель: просьба ставит её, благодарность снимает, жалоба продлевает
    if _DONE.search(t) and not _TASK.search(t):
        if STATE["goal"]:
            log.info("Задача закрыта человеком: %r", STATE["goal"])
        STATE["goal"] = ""
        STATE["blocked"] = ""
        return
    if _TASK.search(t) and len(t.split()) >= 2:
        STATE["goal"] = t[:160]
        STATE["goal_ts"] = now
    elif _FAILED.search(t) and STATE["goal"]:
        STATE["goal_ts"] = now          # не вышло — цель всё ещё висит


def note_result(tool: str, result: str):
    """Чем кончился инструмент: отказ или «не нашла» — это помеха, о
    которой она обязана помнить в следующей реплике."""
    r = str(result or "")
    if not r:
        return
    bad = ("отказ" in r[:30].lower() or "не нашла" in r.lower()
           or "не вышло" in r.lower() or "не даёт" in r.lower()
           or "НЕТ" in r[:60])
    if bad:
        STATE["blocked"] = f"{tool}: {r[:140]}"
        STATE["blocked_ts"] = time.time()
    elif tool and STATE["blocked"].startswith(tool + ":"):
        STATE["blocked"] = ""           # тот же инструмент теперь сработал


def objects() -> list:
    STATE["objects"] = _fresh(STATE["objects"], LIFE_S)
    return [o["name"] for o in STATE["objects"]]


def subject() -> str:
    """Кто/что скрывается за «его», «это», «там» — последний предмет."""
    o = objects()
    return o[-1] if o else ""


def goal() -> str:
    if STATE["goal"] and time.time() - STATE["goal_ts"] < GOAL_LIFE_S:
        return STATE["goal"]
    return ""


def block() -> str:
    """Состояние разговора для промпта. Пусто — значит стол чистый."""
    parts = []
    g = goal()
    if g:
        parts.append(f"НЕЗАКРЫТАЯ ЗАДАЧА (её просил человек, она ещё не "
                     f"выполнена): «{g}». Пока она висит, короткие и "
                     "непонятные реплики человека — это про НЕЁ, а не новая "
                     "тема.")
    objs = objects()
    if objs:
        parts.append("НА СТОЛЕ (о чём шла речь, свежее — правее): "
                     + ", ".join(objs)
                     + ". Местоимения человека («его», «это», «там», "
                       "«второй») относятся к чему-то отсюда — подставь сама "
                       "и действуй, а не переспрашивай.")
    if STATE["blocked"] and time.time() - STATE["blocked_ts"] < 600:
        parts.append("ЧТО ПОМЕШАЛО В ПРОШЛЫЙ РАЗ — " + STATE["blocked"]
                     + ". Не повторяй тот же шаг вслепую: либо обойди, либо "
                       "скажи человеку прямо.")
    if not parts:
        return ""
    return ("### Состояние разговора (факт)\n" + "\n".join(parts)
            + "\nПроверка на абсурд: если из твоего разбора получается "
              "бессмыслица (искать «дай его», закрыть окно «Открой на "
              "YouTube…»), значит ошиблась ТЫ при разборе, а не человек "
              "при просьбе. Перечитай стол и разбери заново.")


def reset():
    STATE.update(goal="", goal_ts=0.0, objects=[], blocked="", blocked_ts=0.0)
