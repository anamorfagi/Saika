"""СЛУХОВАЯ СЦЕНА — одно честное состояние слуха на всех уровнях.

Просьба владельца 05.09.2026, дословно: «просто сделай мне нормальную
качественную транскрибцию наподобие человеческого слуха… для ЛЛМ нужно
его правильно выводить логично, а для человека, кто смотрит в чат,
написать визуал так, чтобы он понимал, что где и как работает».

═══ ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ ═══

До этого «слух» существовал как набор не связанных между собой правд:
уровень звука жил в одном месте, теги окружения во втором, дорожки
голосов в третьем, распознанный текст в четвёртом, а решение «отвечать
или нет» принималось в пятом и нигде не записывалось. Снаружи это давало
худший из возможных ответов на вопрос «почему она не расслышала»:
зелёная точка «слух: готов» и никаких подробностей. Владелец при этом
видел в чате «сферы не окно нам студию» и делал единственно возможный
вывод — «вообще нерабочий ИИ».

Здесь всё это собрано в ОДНО состояние, разложенное по уровням так же,
как разложен слух у человека. Уровень — это не красивая метафора: у
каждого своя цена, свой масштаб времени и свой вид отказа, и когда они
свалены в кучу, отказ одного выглядит как отказ всего.

═══ УРОВНИ И ЧТО ЗА НИМИ СТОИТ ═══

0. ЗАХВАТ. Что физически пришло с устройства: уровень, клиппинг, тишина.
   Отказ здесь выглядит как «она глухая», а на деле выбран не тот вход.

1. ВОРОТА (речь или не речь). У человека это не порог громкости:
   улитка — банк фильтров, и решение принимается по огибающей в полосах,
   по модуляции 2–8 Гц и по гармоничности (Elliott & Theunissen 2009 —
   пик разборчивости речи именно на 4–5 Гц модуляции). Широкополосный
   RMS — плохой детектор речи по построению: комнатный шум живёт на
   низах, где разборчивости нет, а тихая фрикативная «с» информативнее
   громкого гула холодильника.

2. ОКРУЖЕНИЕ. Что это за сцена вообще: тишина, живая речь, музыка,
   телевизор, шум. Человек не транскрибирует фон — и это не экономия, а
   устройство внимания. Здесь же живёт умный фильтр, который не пускает
   музыку в дорогой тракт распознавания.

3. ДОРОЖКИ. Единица восприятия — не кадр и не частота, а ПОТОК
   (Bregman, Auditory Scene Analysis, 1990): непрерывный объект, который
   ведут во времени по общему началу, общему F0, когерентности огибающих
   и совпадению направления. Пофреймовые метки — это не слух.

4. СЛОВА. Что распознано, каким движком, с какой уверенностью и что
   ДОСТРОЕНО. Разделение «услышала» и «достроила» принципиально: человек
   тоже достраивает (фонемное восстановление, Warren 1970), но знает,
   что достроил, и откатывает догадку при новых данных. Достроить молча
   — это и есть «угадала», а угадывать в необратимых действиях нельзя.

5. АДРЕСАТ. Кому это сказано. Внимание выбирает ОБЪЕКТ, а не канал
   (Shinn-Cunningham 2008), и фильтр не бинарный, а градиентный
   (Treisman 1960): фон ослаблен, но своё имя и «стоп» пробивают
   ослабление всегда.

═══ ДВА ВЫВОДА ИЗ ОДНОГО СОСТОЯНИЯ ═══

`for_llm()` — сжатый логичный блок для промпта: только то, что меняет
ответ, и ни одной цифры ради цифры. Модели не нужен уровень в децибелах,
ей нужно знать, что рядом играет музыка, что фразу слышно наполовину и
что говорит не владелец.

`snapshot()` — полная картина для человека: все шесть уровней с
числами и причинами, чтобы одним взглядом было видно, ЧТО где сломалось.

Модуль ничего не считает сам. Он только собирает то, что уже посчитано
в конвейере, и хранит короткую историю. Ноль моделей, ноль видеопамяти.
"""
import threading
import time

_LOCK = threading.Lock()

# сколько последних событий помним на каждом уровне
_KEEP = 40

# ЕДИНОЕ СОСТОЯНИЕ. Каждый уровень пишется своим местом конвейера через
# note_*(), и ни одно место не пишет в чужой уровень — иначе через месяц
# никто не скажет, откуда взялось число.
S = {
    "capture": {"device": "", "rms_dbfs": None, "peak": 0.0, "clip": False,
                "ts": 0.0, "src": ""},
    "gate": {"open": False, "speech_p": 0.0, "why": "", "ts": 0.0,
             "seen": 0, "passed": 0, "gated": 0},
    "scene": {"kind": "тишина", "tags": [], "conf": 0.0, "ts": 0.0,
              "music": 0.0, "speech": 0.0},
    "tracks": [],          # [{id, who, conf, f0, last, owner}]
    "words": [],           # [{ts, who, text, engine, conf, ms, sec, low}]
    "address": {"to": "", "why": "", "ts": 0.0},
    "drops": [],           # [{ts, why, text}] — что НЕ пошло в разговор
}


def _now():
    return time.time()


# ───────────────────────────────────────────────── запись уровней
def note_capture(src="", rms_dbfs=None, peak=0.0, device=""):
    with _LOCK:
        c = S["capture"]
        c.update(ts=_now(), src=src or c["src"])
        if device:
            c["device"] = device
        if rms_dbfs is not None:
            c["rms_dbfs"] = round(float(rms_dbfs), 1)
        if peak:
            c["peak"] = round(float(peak), 3)
            c["clip"] = float(peak) > 0.985


def note_gate(open_: bool, speech_p=0.0, why=""):
    """Ворота речи. Считаем И ПРОПУЩЕННОЕ, И ЗАДЕРЖАННОЕ: без второго
    числа «она меня не слышит» неотличимо от «она молчит»."""
    with _LOCK:
        g = S["gate"]
        g.update(open=bool(open_), speech_p=round(float(speech_p or 0), 2),
                 why=why or g["why"], ts=_now())
        g["seen"] += 1
        if open_:
            g["passed"] += 1
        else:
            g["gated"] += 1


def note_scene(kind="", tags=None, speech=0.0, music=0.0, conf=0.0):
    with _LOCK:
        S["scene"].update(ts=_now(), speech=round(float(speech or 0), 2),
                          music=round(float(music or 0), 2),
                          conf=round(float(conf or 0), 2))
        if kind:
            S["scene"]["kind"] = kind
        if tags is not None:
            S["scene"]["tags"] = [(str(n), round(float(p), 2))
                                  for n, p in list(tags)[:6]]


def note_tracks(rows):
    """rows: [{id, who, conf, f0, last, owner}] — дорожки-объекты."""
    with _LOCK:
        S["tracks"] = list(rows or [])[:8]


def note_words(text, who="", engine="", conf=None, ms=0, sec=0.0, low=False):
    with _LOCK:
        S["words"].append({"ts": _now(), "text": (text or "")[:400],
                           "who": who or "", "engine": engine or "",
                           "conf": None if conf is None else round(
                               float(conf), 2),
                           "ms": int(ms or 0), "sec": round(float(sec or 0), 2),
                           "low": bool(low)})
        del S["words"][:-_KEEP]


def note_address(to="", why=""):
    with _LOCK:
        S["address"].update(to=to or "", why=why or "", ts=_now())


def note_drop(why, text=""):
    """Что НЕ поехало в разговор и почему. Самая полезная строка из всех:
    именно её отсутствие превращало «отфильтровала эхо» в «она меня
    игнорирует»."""
    with _LOCK:
        S["drops"].append({"ts": _now(), "why": str(why)[:60],
                           "text": (text or "")[:160]})
        del S["drops"][:-_KEEP]


# ───────────────────────────────────────────────── чтение
def _fresh(ts, within):
    return ts and (_now() - ts) < within


def snapshot() -> dict:
    """Полная картина для человека — шесть уровней с числами и причинами."""
    with _LOCK:
        g, sc, c = S["gate"], S["scene"], S["capture"]
        seen = max(1, g["seen"])
        return {
            "ts": _now(),
            "levels": [
                {"n": 0, "name": "Захват",
                 "ok": _fresh(c["ts"], 5) and not c["clip"],
                 "head": (("%.0f дБ" % c["rms_dbfs"])
                          if c["rms_dbfs"] is not None else "—"),
                 "note": ("перегруз — уменьши усиление входа" if c["clip"]
                          else (c["device"] or c["src"] or "—")),
                 "raw": dict(c)},
                {"n": 1, "name": "Ворота речи", "ok": _fresh(g["ts"], 10),
                 "head": "%d%% пропущено" % round(100 * g["passed"] / seen),
                 "note": g["why"] or ("речь %.2f" % g["speech_p"]),
                 "raw": dict(g)},
                {"n": 2, "name": "Окружение", "ok": _fresh(sc["ts"], 10),
                 "head": sc["kind"],
                 "note": ", ".join("%s %.0f%%" % (n, p * 100)
                                   for n, p in sc["tags"][:3]) or "—",
                 "raw": dict(sc)},
                {"n": 3, "name": "Дорожки", "ok": bool(S["tracks"]),
                 "head": "%d" % len(S["tracks"]),
                 "note": ", ".join(
                     "%s%s" % (t.get("who") or "не узнан",
                               " ✓" if t.get("owner") else "")
                     for t in S["tracks"][:3]) or "тихо",
                 "raw": list(S["tracks"])},
                {"n": 4, "name": "Слова", "ok": bool(S["words"]),
                 "head": (S["words"][-1]["engine"] if S["words"] else "—"),
                 "note": (S["words"][-1]["text"][:60] if S["words"] else "—"),
                 "raw": list(S["words"][-12:])},
                {"n": 5, "name": "Кому сказано",
                 "ok": _fresh(S["address"]["ts"], 30),
                 "head": S["address"]["to"] or "—",
                 "note": S["address"]["why"] or "—",
                 "raw": dict(S["address"])},
            ],
            "drops": list(S["drops"][-12:]),
        }


def for_llm(max_chars=420) -> str:
    """Блок для промпта. ТОЛЬКО ТО, ЧТО МЕНЯЕТ ОТВЕТ.

    Модели не нужен уровень в децибелах и не нужна статистика ворот — от
    этого ответ не изменится ни на слово, а токены и внимание она съест.
    Ей нужно ровно три вещи, и все три меняют поведение:
      * что за сцена вокруг — от этого зависит, уместно ли сейчас
        говорить и стоит ли переспрашивать;
      * кто говорит — владелец, кто-то ещё или неизвестно;
      * насколько уверенно расслышано — потому что на плохо расслышанном
        нельзя делать необратимое, надо переспросить.

    Пустая строка — законный ответ: тишина не нуждается в описании."""
    with _LOCK:
        sc, tr = S["scene"], list(S["tracks"])
        last = S["words"][-1] if S["words"] else None
    parts = []
    if _fresh(sc["ts"], 20) and sc["kind"] not in ("", "тишина"):
        t = ", ".join(n for n, _p in sc["tags"][:2])
        parts.append("вокруг %s%s" % (sc["kind"], (" (%s)" % t) if t else ""))
    known = [t for t in tr if t.get("who")]
    if len(tr) > 1:
        parts.append("голосов рядом %d" % len(tr))
    if known and not any(t.get("owner") for t in known):
        parts.append("говорит не владелец (%s)" % known[0]["who"])
    if last and last.get("low"):
        parts.append("последнюю фразу расслышала плохо — "
                     "лучше переспросить, чем угадывать")
    if not parts:
        return ""
    return ("Слух: " + "; ".join(parts) + ".")[:max_chars]


def reset_counters():
    with _LOCK:
        S["gate"].update(seen=0, passed=0, gated=0)
