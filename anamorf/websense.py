"""КАК ИСКАТЬ В ИНТЕРНЕТЕ: метод, а не список инструментов (05.09.2026).

Владелец: «проверь, как она серфит инфу в инете… обучи её своим навыкам и
алгоритмам правильного поиска и сёрфинга в инете».

═══ ЧЕГО НЕ ХВАТАЛО ═══

Инструменты поиска у неё были всегда, а метода не было. Описание
инструмента отвечает на вопрос «что этим можно сделать», но не отвечает
на вопросы, которые решают дело: искать ли вообще, какими словами, на
каком языке, когда остановиться и чему верить. Без этого модель делает
ровно то, что делает любая модель без метода: один запрос словами
человека, чтение сниппета, ответ с уверенным лицом.

Три ошибки из этого набора стоят дороже всех остальных:
  * поиск не начинается там, где нужен (модель «помнит» цену и версию —
    а они изменились);
  * ответ берётся из сниппета выдачи, то есть из рекламы страницы;
  * число называется по одному источнику.

═══ ПОЧЕМУ БЛОК, А НЕ ЖЁСТКИЙ АЛГОРИТМ В КОДЕ ═══

Последовательность «искать → открыть → сверить» нельзя зашить циклом:
решение «хватит» зависит от смысла найденного, а смысл видит только
модель. Код может дать инструменты и правила; выбор остаётся за ней.
Поэтому здесь текст в промпт, а не машина состояний.

Блок появляется не всегда: в разговоре «как дела» он лишний, а место в
окне не бесплатное. Признак — просьба, в которой есть поиск или вопрос о
внешнем мире.
"""
import re

from anamorf.config import CFG

# ПРИЗНАКИ ПРОСЬБЫ, ГДЕ НУЖЕН ИНТЕРНЕТ. Намеренно широкие: лишний блок в
# промпте стоит двести токенов, а пропущенный поиск — неправильный ответ.
_ASK = re.compile(
    r"\b(найд[иь]|поищ|погугл|поиск|загугл|посмотри в интернете|в интернете|"
    r"что такое|кто так|кто это|чем известен|сколько стоит|какая цена|цена на|"
    r"когда вышл|когда выйдет|последн(яя|ие) верси|какая верси|новост|"
    r"курс (доллара|евро|валют)|погод|расписан|отзыв|сравни|обзор|"
    r"скачать|где взять|документаци|как установить|как настроить)",
    re.I)

BLOCK = """### Как искать в интернете (метод, не приказ)

**Когда искать.** Всё, что могло измениться со времени обучения, ищи
обязательно, даже если кажется, что помнишь: цены, версии, даты, кто
сейчас чем занимается, что вышло нового. Вечное (сколько ног у паука)
искать не надо.

**Запрос — не вопрос.** Убери вежливость и вопросительные слова,
оставь имена собственные и различающие слова. «Расскажи, кто такой
Snail Kick и что он поёт» → `Snail Kick группа`.

**Язык запроса — язык источника.** Про русскую группу ищи по-русски,
про библиотеку Python — по-английски: там источников в сотню раз больше.

**Один запрос — одна мысль.** Не «цена и отзывы и где купить», а три
отдельных поиска. Склеенный запрос даёт склеенный мусор.

**Не верь выдаче.** Строчка под ссылкой — это реклама страницы, а не
ответ. Если ответ важен, открой источник и прочитай.

**Два независимых источника на любое число** — цену, дату, версию.
Один источник — это слух, а не факт.

**Первичное лучше пересказа:** документация, сайт проекта, официальный
релиз — раньше, чем блог или подборка «топ-10».

**Дата важнее места в выдаче.** Ответ 2021 года на вопрос про сегодня —
неправильный ответ, как бы высоко он ни стоял.

**Не вышло — сузь, а не повторяй.** Мусорная выдача лечится добавлением
различающего слова (год, точный термин, домен), а не тем же запросом
второй раз.

**Остановись, когда два источника сошлись.** Дальше — трата времени
человека.

**Не нашла — так и скажи.** «Не нашла» — это честный ответ. Выдумать —
нет. Если сказала число, назови, откуда оно.

**Сёрфинг.** Открывай по одной странице и читай, а не десять вкладок
разом. Ищи по странице нужное слово вместо чтения целиком. Просят куки,
подписку или регистрацию — не соглашайся, возьми другой источник."""


def needed(text: str) -> bool:
    """Стоит ли класть метод в этот ход."""
    if not CFG.get("web.method_block", True):
        return False
    t = (text or "").strip()
    return bool(t) and bool(_ASK.search(t))


def block(text: str) -> str:
    return BLOCK if needed(text) else ""
