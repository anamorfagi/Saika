"""Нажать «играть» в уже открытом плеере — по прямой просьбе владельца.

«Вот я сейчас вырублю ролик, сам его запусти и сразу начни считывать.»

Своего плеера НЕ открываем и файл не трогаем: у него ролик уже открыт и
стоит на паузе на 31:44. Шлём системную клавишу «воспроизведение/пауза»
— ту же, что на мультимедийной клавиатуре. Плеер продолжит с того места,
где стоял, окна не перекрываются, ничего не сбрасывается.
"""
import ctypes, sys, time

VK_MEDIA_PLAY_PAUSE = 0xB3
KEYEVENTF_KEYUP = 0x0002

u = ctypes.windll.user32
u.keybd_event(VK_MEDIA_PLAY_PAUSE, 0, 0, 0)
time.sleep(0.05)
u.keybd_event(VK_MEDIA_PLAY_PAUSE, 0, KEYEVENTF_KEYUP, 0)
print("послана клавиша воспроизведения", time.strftime("%H:%M:%S"))
