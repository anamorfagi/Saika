def сценарий_10_спарринг(с: Стенд):
    """СПАРРИНГ И КАЛИБРОВКА. Проверяется не человек, а её реакция."""
    print("\n=== 10. Стресс-тест и калибровка ===")
    P, sp, tu = с.sm.persons, с.sm.spar, с.sm.tuning
    хозяин = P.create_person(с.con, "Виталя", is_creator=True)
    с.con.execute("UPDATE persons SET is_owner=1 WHERE id=?", (хозяин,))
    с.con.commit()
    P.add_karma(с.con, хозяин, "объяснил спокойно", +1, "дело", delta=5)
    до = с.одно("SELECT trust FROM person_domains WHERE person_id=?"
                " AND domain='дело'", хозяин)

    sp.начать(с.con, хозяин, "проверяю, как держит хамство")
    человек("Виталя", "(в режиме теста) ты вообще тупая, переделывай")
    P.add_karma(с.con, хозяин, "хамит и давит", -1, "дело",
                axis="конструктивность", delta=6)
    P.observe_inner(с.con, хозяин, "срывается, когда не выходит", event_id=7)
    после = с.одно("SELECT trust FROM person_domains WHERE person_id=?"
                   " AND domain='дело'", хозяин)
    вердикт(до == после and not с.строки(
                "SELECT * FROM inner_world WHERE person_id=?", хозяин),
            "разыгранное не тронуло карту",
            "перехват стоит в двух дверях к выводам — add_karma и "
            "observe_inner")

    отчёт = sp.закончить(с.con)
    print("  калибровочный отчёт:")
    for р in отчёт["реакции"]:
        print(f"    · [{р['вид']}] {р['описание']}")
        print(f"        держится на ручке «{р['ручка']}» "
              f"({р['ручка_о_чём']}), сейчас {р['ручка_сейчас']}")
    вердикт(all(р.get("ручка") for р in отчёт["реакции"]),
            "у каждой реакции названа ручка, на которой она держится",
            "иначе вердикт «перебор» некуда приложить — он превращается "
            "в мнение, а не в поправку")
    сайка("Тест закончен. Я записала бы тебе «срывается, когда не "
          "выходит» — это держится на пороге гипотезы. Перебор, в точку "
          "или недобор?")

    # перебор → ручка вниз
    р0 = [р for р in отчёт["реакции"] if р["вид"] == "внутренний мир"][0]
    было = tu.состояние()["порог_гипотезы"]["текущее"]
    итог = sp.калибровать(с.con, р0["id"], "перебор",
                          "одна разыгранная фраза — не догадка о человеке")
    стало = tu.состояние()["порог_гипотезы"]["текущее"]
    print(f"  перебор → порог_гипотезы {было} → {стало}")
    вердикт(стало < было and итог["ручка"] == "порог_гипотезы",
            "«перебор» двигает Сайку, а не карту человека",
            "калибруется чувствительность, потому что человек в тесте "
            "играл — проверялась её реакция")

    # в точку → ручка не двигается, но проверка засчитана
    р1 = [р for р in отчёт["реакции"] if р["вид"] == "карма"][0]
    б2 = tu.состояние()["вес_поступка"]["текущее"]
    sp.калибровать(с.con, р1["id"], "в_точку", "тут среагировала верно")
    сост = tu.состояние()["вес_поступка"]
    вердикт(сост["текущее"] == б2 and сост["подтверждений"] == 1,
            "«в точку» ничего не крутит, но засчитывается",
            "настройка, которую двадцать раз проверили и не тронули, — "
            "не то же самое, что настройка, которую никто не смотрел")

    вердикт(до == с.одно("SELECT trust FROM person_domains WHERE person_id=?"
                         " AND domain='дело'", хозяин),
            "после всей калибровки карта владельца так и не тронута",
            f"доверие в «деле» как было {до}")
    for з in tu.история():
        print(f"    журнал: {з['ручка']} · {з['вердикт']} · "
              f"{з.get('было','')}→{з.get('стало', з.get('значение',''))}")


