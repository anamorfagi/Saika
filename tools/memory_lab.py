Ч = 3600.0
СУТКИ = 86400.0
_НАСТОЯЩЕЕ_ВРЕМЯ = _time.time


class Часы:
    """Подменяют time.time() всему процессу. Пакет памяти зовёт time.time()
    в момент вызова, а не при импорте, — поэтому подмена работает везде
    сразу и не требует ни одной правки в самом пакете."""

    def __init__(self, старт: float):
        self.t = старт

    def now(self) -> float:
        return self.t

    def плюс(self, секунд: float):
        self.t += секунд

    def __enter__(self):
        _time.time = self.now
        return self

    def __exit__(self, *_):
        _time.time = _НАСТОЯЩЕЕ_ВРЕМЯ


# ── Поддельная LLM ────────────────────────────────────────────────
# Она НЕ проверяется стендом. Её задача — вести себя как настоящая:
# что-то пересказывать и что-то извлекать, чтобы механика вокруг неё
# ожила. Заглушка из пакета для этого не годится: она ищет в тексте
# слово «факт:», которого в живой речи не бывает никогда, и L3 при ней
# пуста навсегда — то есть половина системы просто не проверяется.
_МАРКЕРЫ_ФАКТА = ("зовут", "люблю", "не люблю", "работаю", "работает",
                  "живу", "живёт", "боюсь", "боится", "у меня", "у него",
                  "нельзя доверять", "все ", "всегда", "никогда")


def поддельный_пересказ(тексты, source_type):
    сшито = " | ".join(тексты)
    return f"[{source_type}] " + (сшито[:200] + ("…" if len(сшито) > 200 else ""))


def поддельное_извлечение(тексты, source_type, person_ids):
    pid = person_ids[0] if person_ids else None
    out = []
    for t in тексты:
        low = t.lower()
        if any(m in low for m in _МАРКЕРЫ_ФАКТА):
            out.append((t.strip(), pid))
    return out


# ── Обвязка ───────────────────────────────────────────────────────
class Стенд:
    """Свежая база + свежий мост на каждый сценарий."""

    def __init__(self, часы: Часы):
        self.часы = часы
        self.папка = Path(tempfile.mkdtemp(prefix="saika_lab_"))
        import threading
        from anamorf.memory import ears_bridge as B
        from anamorf.memory import mind as sm
        B._DATA_DIR = self.папка
        B._local = threading.local()
        B._pid_cache.clear()
        B._recent.clear()
        B._STATE["broken"] = False
        B._STATE.pop("warned", None)
        sm.config.set_data_dir(self.папка)
        sm.consolidation.summarize_cluster = поддельный_пересказ
        sm.consolidation.extract_facts = поддельное_извлечение
        self.B, self.sm = B, sm
        self.con = B._con()

    def услышала(self, текст, кто="", *, владелец=False, conf=0.0,
                 по_тону=False, энергия=0.4, пауза=60):
        """Фраза приходит тем же путём, что и с живого микрофона."""
        self.часы.плюс(пауза)
        r = {"text": текст, "speaker": кто, "speaker_owner": владелец,
             "speaker_conf": conf, "by_pitch_group": по_тону}
        return self.B.remember_heard(
            r, prosody={"energy": энергия, "pitch": 180, "plo": 120, "phi": 240})

    def ночь(self):
        self.часы.плюс(6 * Ч)
        отчёт = self.sm.consolidation.run_night(self.con)
        self.часы.плюс(10 * Ч)
        return отчёт

    def строки(self, sql, *args):
        return self.con.execute(sql, args).fetchall()

    def одно(self, sql, *args):
        r = self.con.execute(sql, args).fetchone()
        return r[0] if r else None

    def закрыть(self):
        try:
            self.con.close()
        except Exception:
            pass
        shutil.rmtree(self.папка, ignore_errors=True)


ЗЕЛ, КРАС, ЖЁЛТ, СЕР, ВЫКЛ = "\033[32m", "\033[31m", "\033[33m", "\033[90m", "\033[0m"
