def сценарий_6_передумала(с: Стенд):
    """ЛЮДИ МЕНЯЮТСЯ. Факт обязан уметь деградировать обратно в гипотезу."""
    print("\n=== 6. Гипотеза → факт → и обратно ===")
    pid = с.sm.persons.create_person(с.con, "Николай")
    for n in range(1, 6):
        с.sm.persons.observe_inner(с.con, pid, "не любит созвоны", event_id=n)
    r = с.строки("SELECT * FROM inner_world WHERE person_id=?", pid)[0]
    print(f"  после 5 независимых наблюдений: {r['status']} {r['confidence']:.2f}")
    вердикт(r["status"] == "fact", "пять подтверждений превращают догадку в факт")
    for _ in range(3):
        с.sm.persons.observe_inner(с.con, pid, "не любит созвоны", event_id=5)
    r2 = с.строки("SELECT * FROM inner_world WHERE person_id=?", pid)[0]
    вердикт(abs(r2["confidence"] - r["confidence"]) < 1e-9,
            "повтор одного события не считается подтверждением",
            "защита от «сам себя убедил» (last_event_id)")
    # А умеет ли внутренний мир падать обратно?
    было = r2["confidence"]
    упало = getattr(с.sm.persons, "contradict_inner", lambda *a: False)(
        с.con, pid, "не любит созвоны")
    r3 = с.строки("SELECT * FROM inner_world WHERE person_id=?", pid)[0]
    вердикт(упало and r3["confidence"] < было,
            "наблюдение против факта роняет уверенность",
            f"{было:.2f} → {r3['confidence']:.2f}, статус {r3['status']}. "
            "Люди меняются; память, которая этого не умеет, лепит из "
            "человека его прошлую версию.")
    человек("Николай", "(сам предложил созвон)")
