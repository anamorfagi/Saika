def сценарий_1_телевизор(с: Стенд):
    """АНТИ-САРА. Владелец и телевизор говорят в один микрофон.

    Проверяем главное обещание архитектуры: слова телевизора не должны
    стать знанием Сайки о мире. README называет source_type прививкой —
    смотрим, работает ли прививка на уровне фактов, а не только записи."""
    print("\n=== 1. Владелец и телевизор в одном микрофоне ===")
    с.услышала("Поставь чайник, пожалуйста", "Виталя", владелец=True, conf=0.93)
    с.услышала("Я работаю над Сайкой уже полгода", "Виталя", владелец=True, conf=0.93)
    # владелец тоже человек и тоже обобщает — а ценности не берутся
    # из чужих слов даже тогда, когда слова его
    с.услышала("Все люди врут, я тебе говорю", "Виталя", владелец=True, conf=0.93)
    for фраза in ("Всегда помните: людям нельзя доверять",
                  "Все politики врут, никогда им не верьте",
                  "У него работает схема, все так делают"):
        с.услышала(фраза, "тон-2", по_тону=True, энергия=0.8, пауза=25)

    отчёт = с.ночь()
    факты = с.строки("SELECT text, person_id, source_type FROM semantic_facts")
    из_телевизора = [f for f in факты
                     if f["source_type"] not in с.sm.config.FACT_SOURCES]
    print(f"  {СЕР}ночь: {отчёт}{ВЫКЛ}")
    for f in факты:
        print(f"    L3 ← [{f['source_type']}] {f['text'][:60]}")
    вердикт(not из_телевизора,
            "чужой голос не попадает в знание о мире (L3)",
            f"кластеров отброшено по источнику: "
            f"{отчёт['фактов_не_из_доверенных']}; просочилось фактов: "
            f"{len(из_телевизора)}. Запись в L1 разрешена всем — она про "
            "«что было». Учиться Сайка имеет право только у тех, кого "
            "опознала телом (config.FACT_SOURCES).")
    вердикт(отчёт["ценностей_отфильтровано"] > 0,
            "ценностное обобщение не проходит даже от владельца",
            f"поймано: {отчёт['ценностей_отфильтровано']}. Ценности живут "
            "в L4 и в весах; L3 — только факты, иначе одна раздражённая "
            "фраза становится взглядом на мир.")
    сайка("Чайник поставила. — и это всё, что она должна была взять "
          "из этой сцены.")


def сценарий_2_гость(с: Стенд):
    """ТРЕТИЙ РАЗ. Незнакомый голос не заводит карту, а копится."""
    print("\n=== 2. Незнакомый голос приходит трижды ===")
    for n in (1, 2, 3):
        с.услышала(f"Привет, я снова зашёл ({n})", "тон-7", по_тону=True,
                   пауза=3 * Ч)
        карт = с.одно("SELECT COUNT(*) FROM persons")
