def вердикт(ок, заголовок, пояснение=""):
    знак = f"{ЗЕЛ}так и надо{ВЫКЛ}" if ок else f"{КРАС}ДЫРА{ВЫКЛ}"
    print(f"  [{знак}] {заголовок}")
    if пояснение:
        print(f"          {СЕР}{пояснение}{ВЫКЛ}")
    if not ок:
        _НАХОДКИ.append(заголовок)


def сайка(реплика):
    print(f"  {ЖЁЛТ}Сайка:{ВЫКЛ} {реплика}")


def человек(кто, реплика):
    print(f"  {СЕР}{кто}:{ВЫКЛ} {реплика}")


