"""СТЕНД ПАМЯТИ — автозапуск мозга Сайки без микрофона, моделей и видеокарты.

    python tools/memory_lab.py            все сценарии
    python tools/memory_lab.py 3          только третий
    python tools/memory_lab.py --list     список

Зачем он есть. Память — единственная часть Сайки, где ошибка не падает,
а тихо копится: неправильное затухание видно не в логе, а через месяц
пустой базой; дырка в фильтре источников видна не сегодня, а когда она
однажды повторит за телевизором. Проверять такое можно только временем,
а времени ждать нельзя — значит, время надо подделать.

Стенд подделывает три вещи и больше ничего:
  ЧАСЫ    — `Часы` подменяет time.time(), день проматывается за миллисекунду;
  LLM     — вместо модели простые правила (модель тут не проверяется);
  СЛУХ    — фразы подаются в тот же ears_bridge.remember_heard, что и живьём.

Всё остальное — настоящее: та же схема базы, та же миндалина, та же ночь.
База каждый раз временная и стирается за собой: боевую он не трогает.
"""
