"""ЖУРНАЛ ЭФФЕКТА: цифры должны быть честными, иначе они хуже, чем их нет.

Владелец 20.08.2026, про идею стащить чужую практику: «сделай что полезно
потенциально и следи, реально ли это нам поможет в будущем».

Инструмент, который говорит «стало лучше», когда стало просто тише, —
это не измеритель, а самоуспокоение. Здесь проверяется ровно это.
"""
import io
import os
import tempfile


LOG = """\
2026-08-01 10:00:00,000 saika INFO handle_text: стартую диалог для 'раз'
2026-08-01 10:00:01,000 saika WARNING Модель x заявила о действии, которого не делала: 'y'
2026-08-01 10:00:02,000 saika INFO handle_text: стартую диалог для 'два'
2026-08-01 10:00:03,000 saika WARNING Модель x заявила о действии, которого не делала: 'y'
2026-08-01 10:00:04,000 saika INFO Тайминги: итого до 1-го токена 4000мс
2026-08-01 10:00:05,000 saika.locallm INFO locallm: запускаю воркер: ...
2026-08-02 10:00:00,000 saika INFO handle_text: стартую диалог для 'раз'
2026-08-02 10:00:01,000 saika WARNING Модель x заявила о действии, которого не делала: 'y'
2026-08-02 10:00:02,000 saika INFO Тайминги: итого до 1-го токена 2000мс
2026-08-02 10:00:03,000 saika.reflex INFO Рефлекс: window_place(...) -> ок
"""


def run():
    rows = []
    sys_path = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    import importlib.util as iu
    spec = iu.spec_from_file_location(
        "effect", os.path.join(sys_path, "tools", "effect.py"))
    ef = iu.module_from_spec(spec)
    spec.loader.exec_module(ef)

    path = os.path.join(tempfile.gettempdir(), "saika_effect_test.log")
    io.open(path, "w", encoding="utf-8", newline="\n").write(LOG)
    days, lat = ef.scan(path)

    # 1. Считаем то, что есть, а не то, что хочется увидеть.
    d1 = days["2026-08-01"]
    rows.append(("события считаются по дням",
                 d1["команд"] == 2 and d1["врёт"] == 2
                 and d1["второй движок"] == 1,
                 f"команд {d1['команд']}, врёт {d1['врёт']}"))

    # 2. ГЛАВНОЕ. Первого числа два вранья на две команды, второго — одно
    #    на одну. В абсолюте «стало вдвое меньше»; на сто команд — РОВНО
    #    СТОЛЬКО ЖЕ. Инструмент обязан показывать второе, иначе он будет
    #    хвалить нас за то, что в этот день меньше разговаривали.
    a = ef.fold(days, lat, ["2026-08-01"])
    b = ef.fold(days, lat, ["2026-08-02"])
    rows.append(("нормировано на сто команд, а не в штуках",
                 a["врёт"] == 2 and b["врёт"] == 1
                 and a["врёт/100"] == b["врёт/100"] == 100.0,
                 f"штук {a['врёт']} -> {b['врёт']}, "
                 f"на сто {a['врёт/100']} -> {b['врёт/100']}"))

    # 3. Задержка — медиана, а не среднее: один пятиминутный прогрев
    #    модели не должен решать за все остальные ответы.
    rows.append(("ответ считается медианой",
                 a["ответ, с"] == 4.0 and b["ответ, с"] == 2.0,
                 f"{a['ответ, с']}с -> {b['ответ, с']}с"))

    # 4. Сравнивать не с чем — так и говорим, а не рисуем «стало лучше».
    only = {k: v for k, v in days.items() if k == "2026-08-01"}
    got = []
    try:
        import contextlib
        buf = io.StringIO()
        with contextlib.redirect_stdout(buf):
            ef.show_split(only, lat, "2026-08-01")
        got = buf.getvalue()
    except Exception as e:
        got = f"упал: {e}"
    rows.append(("нет данных — честно говорим, а не выдумываем",
                 "нужны дни" in str(got), str(got).strip()[:60]))

    try:
        os.remove(path)
    except Exception:
        pass
    return rows
