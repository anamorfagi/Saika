"""МОИ СЕРВИСЫ: «включи музыку» у каждого человека своё.

Владелец 20.08.2026: «включи музыку — можно делать запуск сервиса у
человека. У них это Спотик, у меня это Яндекс.Музыка… у меня Яндекс.Музыка
в браузере Яндекса с моим аккаунтом, у некоторых есть прям приложение, у
того же друга на компе Спотифай есть как прога. То есть она должна
уточнить, где именно находится музыка».

Правило: не знаю — спроси ОДИН раз, знаю — делай молча.
"""


def run():
    rows = []
    from anamorf import reflex, services as sv

    # 1. «Включи музыку» — это привычка, а не площадка и не папка.
    #    До правки уходило в go_to и открывало пустую системную папку
    #    «Музыка»: слово «включи» стояло в правиле про папки.
    table = {
        "включи музыку": "service_open",
        "Сайка, поставь музычку": "service_open",
        "открой почту": "service_open",
        # площадку назвали — тот же путь: разбор сам увидит место в
        # просьбе, откроет его и привычку НЕ перепишет
        "включи музыку на ютубе": "service_open",
        "включи музыку в папке музыка на компе": "service_open",
        # тип файла назвали — это диск
        "включи какой-нибудь трек из железного человека": "find_here",
    }
    bad = []
    for phrase, want in table.items():
        hit = reflex.match(phrase)
        if not hit or hit[0] != want:
            bad.append(f"{phrase} -> {hit}")
    rows.append(("«включи музыку» != площадка и != папка", not bad,
                 f"{len(table)} фраз" if not bad else "; ".join(bad)))

    # 2. Ответ человека разбирается во ВСЕХ трёх формах, которые он назвал.
    cases = {
        # сайт + КОНКРЕТНЫЙ браузер: аккаунт живёт именно там
        "яндекс музыка в браузере яндекса с моим аккаунтом":
            {"how": "site", "browser": "browser", "title": "яндекс музыка"},
        # программа на компьютере — как у друга
        "у меня спотифай есть как прога":
            {"how": "app", "app": "спотифай"},
        "спотик прогой": {"how": "app", "app": "спотик"},
        # падежи: «в оперЕ», «музыкУ» — морфологии нет, хватает основы
        "в опере яндекс музыку":
            {"how": "site", "browser": "opera", "title": "яндекс музыка"},
        # незнакомое имя — считаем программой, а не гадаем сайт
        "аимп": {"how": "app", "app": "аимп"},
    }
    bad = []
    for answer, want in cases.items():
        got = sv.parse("музыка", answer)
        if any(got.get(k) != v for k, v in want.items()):
            bad.append(f"{answer} -> {got}")
    rows.append(("ответ человека разбирается верно", not bad,
                 f"{len(cases)} ответов" if not bad else "; ".join(bad)))

    # 2б. НОСИТЕЛЬ — ЛЮБОЙ. Владелец: «думай не просто логикой „ага,
    #     запрос про музыку“, а пиши универсальные алгоритмы… что будет,
    #     если я попрошу открыть музыку в папке Музыка на самом компе;
    #     или вообще в текущем окне браузера сайт или прогу типа ТГ с
    #     каналом, где я обычно смотрю кинчик».
    carriers = {
        "включи музыку на ютубе": ("site", "ютуб"),
        "включи музыку в спотифае": ("site", "спотифай"),
        "включи музыку в папке музыка на компе": ("folder", None),
        "открой видео в тг с каналом кинчик": ("app", "тг"),
        "в текущем окне браузера": ("window", None),
    }
    bad = []
    for phrase, (how, title) in carriers.items():
        got = sv.parse("видео" if "видео" in phrase else "музыка", phrase)
        if got.get("how") != how or (title and got.get("title") != title):
            bad.append(f"{phrase} -> {got}")
    rows.append(("носитель любой: сайт, прога, папка, открытое окно",
                 not bad, f"{len(carriers)} фраз" if not bad
                 else "; ".join(bad)))

    # 2в. «ТГ с каналом кинчик»: имя носителя и место ВНУТРИ него — разные
    #     поля. Открыть Телеграм и остановиться — это не то, что просили.
    got = sv.parse("видео", "открой видео в тг с каналом кинчик")
    rows.append(("что внутри носителя — отдельно от него",
                 got.get("app") == "тг" and got.get("inside") == "кинчик",
                 f"носитель={got.get('app')!r} внутри={got.get('inside')!r}"))

    # 2г. Названное в просьбе место — на ОДИН раз. «Сегодня из папки» не
    #     значит «отныне всегда из папки»; переписывает только «запомни».
    rows.append(("сегодня так != всегда так",
                 not sv.forever("включи музыку из папки Музыка")
                 and sv.forever("запомни: музыку всегда из папки Музыка"),
                 "переписывает только явное «запомни/всегда»"))

    # 3. Не знаем — спрашиваем, а не угадываем. Открыть чужому человеку
    #    Spotify, когда подписка у него на Яндексе, — не помощь.
    real = sv._load
    try:
        sv._load = lambda: {}
        sv.ASK.update(on=False)
        q = sv.open_it("музыка", "Виталя")
        rows.append(("не знаю — спрашиваю один раз",
                     "где" in q.lower() and bool(sv.waiting()),
                     q[:70]))

        # 4. Привычка живёт ПРИ ГОЛОСЕ: у друга за тем же компьютером
        #    «включи музыку» откроет его сервис, а не чужой.
        store = {"Виталя": {"музыка": {"how": "site", "title": "яндекс музыка"}},
                 "Друг": {"музыка": {"how": "app", "app": "спотифай"}}}
        sv._load = lambda: store
        rows.append(("у каждого своя музыка",
                     sv.get("музыка", "Виталя").get("title") == "яндекс музыка"
                     and sv.get("музыка", "Друг").get("app") == "спотифай",
                     "Виталя -> яндекс, Друг -> спотифай"))

        # 5. Голос не узнан — берём общую запись, а не первую попавшуюся.
        store[""] = {"музыка": {"how": "app", "app": "общий плеер"}}
        rows.append(("голос не узнан — общая запись",
                     sv.get("музыка", "Незнакомец").get("app") == "общий плеер",
                     "падаем в запись «на всех»"))
    finally:
        sv._load = real
        sv.ASK.update(on=False)
    return rows
