"""ИМЕНА ГОЛОСОВ: как она сама догадывается, кого как зовут (2026-07-28).

ЗАМЫСЕЛ ВЛАДЕЛЬЦА. Она слышит разговор, в разговоре звучат имена. Имя надо
привязать не к слову, а к ЗВУЧАНИЮ — к сигнатуре голоса. Дальше метка висит
как предположение («кажется, этого человека зовут Аня»), и чем дольше оно
подтверждается, тем крепче держится. А если имя задал человек руками — оно
прибито гвоздями, и никакие догадки его больше не трогают.

ДВА СПОСОБА УСЛЫШАТЬ ИМЯ, и они работают по-разному:

1. ПРЕДСТАВИЛСЯ САМ — «меня зовут Аня», «я Аня». Имя относится к ТОМУ, КТО
   ГОВОРИТ. Самый надёжный случай, вес большой.
2. ПОЗВАЛИ ПО ИМЕНИ — «Аня, ты идёшь?», «слушай, Аня». Имя относится к
   СОБЕСЕДНИКУ, то есть почти наверняка к тому, кто ответит следующим. Такие
   имена кладём в ожидание и вешаем на следующий ЗАГОВОРИВШИЙ ДРУГОЙ голос в
   ближайшие секунды. Приём простой и ошибается, но ошибается предсказуемо:
   одна догадка ничего не решает, решает накопление.

ПОЧЕМУ НЕ ПРОСТО «СЛОВО С БОЛЬШОЙ БУКВЫ». Распознавание отдаёт текст в
нижнем регистре и без пунктуации, заглавных там нет вообще. Поэтому только
конструкции — и стоп-лист, чтобы «я думаю» не превратилось в человека по
имени Думаю.

ЧЕГО ЗДЕСЬ НЕТ. Словаря русских имён. Он выглядит соблазнительно, но отсекал
бы всё нестандартное — прозвища, ники, иностранные имена, — а это ровно те
случаи, ради которых затевалось автоматическое узнавание.
"""
import re

# Слова, которые синтаксически встают на место имени, но именем не являются.
# Список короткий нарочно: чем он длиннее, тем больше настоящих имён он съест.
STOP = {
    "не", "да", "нет", "это", "тут", "там", "так", "уже", "ещё", "еще",
    "тебе", "тебя", "меня", "мне", "его", "её", "ее", "их", "нас", "вас",
    "думаю", "знаю", "помню", "вижу", "слышу", "хочу", "могу", "буду",
    "сказал", "сказала", "говорю", "пойду", "иду", "сейчас", "потом",
    "просто", "очень", "тоже", "весь", "вся", "всё", "все", "что", "кто",
    "как", "где", "когда", "почему", "зачем", "ладно", "хорошо", "плохо",
    "спасибо", "пожалуйста", "привет", "пока", "слушай", "смотри", "давай",
    "короче", "кстати", "блин", "вообще", "конечно", "наверное", "точно",
    "один", "два", "раз", "тут", "здесь", "сюда", "туда", "сам", "сама",
}

_SELF = [
    re.compile(r"\bменя\s+зовут\s+([а-яёa-z]{2,20})", re.I),
    re.compile(r"\bэто\s+я[, ]+([а-яёa-z]{2,20})\b", re.I),
    re.compile(r"\bя\s+([а-яёa-z]{2,20})\s*[,.!]", re.I),
]
_ADDR = [
    re.compile(r"^\s*([а-яёa-z]{2,20})\s*[,!]", re.I),          # «Аня, ты…»
    re.compile(r"[,]\s*([а-яёa-z]{2,20})\s*[.!?]*\s*$", re.I),  # «…, Аня»
    re.compile(r"\b(?:слушай|смотри|эй|привет)[, ]+([а-яёa-z]{2,20})\b", re.I),
]


def _ok(w: str) -> bool:
    w = (w or "").strip().lower()
    return bool(w) and w not in STOP and len(w) >= 2 and not w.isdigit()


def _cap(w: str) -> str:
    w = w.strip().lower()
    return w[:1].upper() + w[1:]


def guess(text: str):
    """-> список (имя, кому, вес): кому = "self" (говорящему) или
    "address" (собеседнику). Пустой список — имён не услышала."""
    t = (text or "").strip()
    if not t or len(t) > 400:
        return []
    out = []
    seen = set()
    for rx in _SELF:
        m = rx.search(t)
        if m and _ok(m.group(1)):
            n = _cap(m.group(1))
            if n not in seen:
                seen.add(n)
                # «меня зовут» весит втрое против «я такой-то»: второе
                # сплошь и рядом просто оборот речи
                out.append((n, "self", 3.0 if "зовут" in m.group(0).lower() else 1.0))
    for rx in _ADDR:
        m = rx.search(t)
        if m and _ok(m.group(1)):
            n = _cap(m.group(1))
            if n not in seen:
                seen.add(n)
                out.append((n, "address", 1.0))
    return out
