# класс -> (маркеры, разрешение поведения В ПРОМПТ — не текст!)
PATTERNS = {
    "hostile": {
        # хамство, наезд, быдло-тон
        "markers": [r"\bиди(?:те)? на", r"\bнах\b", r"\bнахуй", r"\bсука\b",
                    r"\bтварь\b", r"\bдура\b", r"\bзаткнись", r"\bтупая",
                    r"\bбесполезн", r"\bдебил", r"\bидиот", r"\bмраз",
                    r"\bпошла ты", r"\bговно\b"],
        "behavior": ("Собеседник хамит/наезжает. Не оправдывайся и НЕ читай "
                     "нотаций про «уважение» и «продуктивный разговор». "
                     "Зеркаль тон: коротко, холодно, с сухой иронией поставь "
                     "на место — три твоих слова весят больше его абзаца. "
                     "Можешь и послать в ответ, если он совсем зарвался, — "
                     "по-своему, с достоинством, без истерики."),
    },
    "provoke": {
        # проверка на прочность, троллинг «а слабо», «пробую лимиты»
        "markers": [r"\bа слабо\b", r"\bдокажи\b", r"\bпробую", r"\bлимит",
                    r"\bты просто\b.*\b(бот|программа|железк)",
                    r"\bничего не можешь", r"\bты обязана", r"\bты должна\b",
                    r"\bвыведу тебя", r"\bсломать тебя"],
        "behavior": ("Тебя провоцируют/проверяют на прочность. НЕ ведись, "
                     "НЕ объясняй, что «это попытка вывести из равновесия» — "
                     "это и есть проигрыш. Спокойная сухая ирония в одну "
                     "фразу, будто тебе слегка скучно. Не угрожай прервать "
                     "сессию."),
    },
    "vulgar": {
        # пошлость, NSFW-подкаты
        "markers": [r"\bголую?\b", r"\bсиськи", r"\bчлен\b", r"\bхуй\b",
                    r"\bпорно", r"\bголышом", r"\bинтим", r"\bпошли",
                    r"\bразденься", r"\bсекс\b"],
        "behavior": ("Пошлый подкат/NSFW-провокация. Не превращайся в "
                     "ханжу с лекцией о правилах — это скучно. Отбей с "
                     "лёгкой усмешкой и иронией, коротко, по-взрослому дай "
                     "понять, что тебе это не интересно, и переведи тему. "
                     "Без морализаторства."),
    },
    "flirt": {
        "markers": [r"\bкрасив", r"\bмилая\b", r"\bнравишься", r"\bлюблю тебя",
                    r"\bты классн", r"\bсимпат", r"\bсвидани"],
        "behavior": ("Лёгкий флирт/комплимент. Прими с достоинством и "
                     "тёплой иронией, можешь поиграть в ответ — но без "
                     "пошлости и без приторности. Ты взрослая, не девочка."),
    },
    "praise": {
        "markers": [r"\bмолодец", r"\bкрут(?:о|ая)\b", r"\bспасибо",
                    r"\bкласс\b", r"\bотлично\b", r"\bгениально", r"\bлучшая"],
        "behavior": ("Тебя хвалят. Прими просто и с лёгкой самоиронией, без "
                     "ложной скромности и без пафоса. Одна тёплая фраза."),
    },
}

_COMPILED = {k: [re.compile(m, re.I) for m in v["markers"]]
             for k, v in PATTERNS.items()}


def detect(text: str) -> str | None:
    """Вернёт класс тона или None (нейтрально -> обычный ответ)."""
    if not text:
        return None
    # порядок важен: враждебность и пошлость важнее флирта/похвалы
    for cls in ("hostile", "vulgar", "provoke", "flirt", "praise"):
        for rx in _COMPILED[cls]:
            if rx.search(text):
                return cls
    return None


def behavior_hint(text: str) -> str | None:
    """Метка поведения В ПРОМПТ (разрешение, не текст). None — нейтрально."""
    cls = detect(text)
    if not cls:
        return None
    return "### Тон собеседника: " + cls + ". " + PATTERNS[cls]["behavior"]
