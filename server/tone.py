"""Детектор тона реплики -> метка поведения для Сайки.

Философия (как сформулировал владелец): ОБОЛОЧКА даёт метку и разрешение,
ОСТРОУМИЕ рождает модель. Мы НЕ пишем ей реплики — мы вешаем ярлык
состояния собеседника и рамку допустимого поведения, а слова она подбирает
сама. Чем умнее модель, тем лучше отыграет метку.

Детект быстрый — по ключевым маркерам, без обращения к LLM (мгновенно,
до генерации). Неоднозначное остаётся neutral — тогда просто обычный ответ.
"""
