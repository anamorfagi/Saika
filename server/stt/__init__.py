"""СЛУХ — распознавание речи со сменными движками.

Правило пакета: движок — деталь, а не фундамент. Любой из шести
(`gigaam`, `faster_whisper`, `whispercpp`, `vosk`, `tone`, внешний
процесс) реализует один интерфейс из `base.py`, поэтому менеджер может
переключиться посреди разговора, если активный сломался, — и чинить
сломанный в фоне, не прерывая слух.

Порядок обработки одной фразы:

    микрофон -> neuro_vad (где речь) -> turns (не сменился ли говорящий)
             -> unmix (разделить наложенные голоса)
             -> frontend (мастеринг: усиление, ресемпл, обрезка тишины)
             -> engines/external (слова)
             -> rescore (переслушать смыслом, если звучало шатко)

Кто есть кто:

* `manager.py`   — сегментация по VAD, выбор движка, автофоллбэк.
* `base.py`      — интерфейс, который обязан выполнить любой движок.
* `engines.py`   — шесть встроенных движков под русский.
* `external.py`  — движок в отдельном процессе со своим venv (когда
                   зависимости движка несовместимы с основным окружением).
* `neuro_vad.py` — Silero VAD: речь или не речь.
* `frontend.py`  — подготовка звука перед движком.
* `turns.py`     — смена говорящего ВНУТРИ фразы, разрез до распознавания.
* `unmix.py`     — две дорожки из одного микрофона.
* `voice_dna.py` — узнавание по строению голоса.
* `rescore.py`   — модель переслушивает текст смыслом, а не звуком.

Настройки: `stt.*` в `config.json`, разбор — в `CONFIG.md`.
Живые разборы слуха: `docs/HEARING.md`.
"""
