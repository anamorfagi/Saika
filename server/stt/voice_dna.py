"""ГОЛОСОВАЯ ДНК — узнавание по СТРОЕНИЮ голоса, а не по его высоте.

ЗАДАЧА ВЛАДЕЛЬЦА, дословно: «давай придумай технологию улавливания,
применяй нестандартные методы, если хочешь — пробуй изучать механики из
музыкантов».

ЧТО НЕ РАБОТАЛО. Развод людей по основной частоте (F0) ломается ровно
там, где человек поёт: у певца F0 идёт по мелодии и за фразу проходит
терцию, квинту, октаву. Один певец разъезжается на три «голоса». Высота
тона говорит о НОТЕ, а не о том, кто её взял. Это тупик по устройству,
подкруткой порогов не лечится.

ЧТО БЕРЁМ У МУЗЫКАНТОВ. Музыкант различает скрипку и флейту, играющие
ОДНУ И ТУ ЖЕ ноту, — и это не магия, а физика, известная с XIX века
(Гельмгольц): звук любого инструмента = ИСТОЧНИК (что колеблется) через
РЕЗОНАТОР (корпус, труба, комната). Нота — свойство источника. Тембр —
свойство резонатора, и он от ноты НЕ ЗАВИСИТ.

У человека ровно то же устройство, и называется оно source-filter:
    ИСТОЧНИК — голосовые связки, дают частоту (ноту, интонацию, крик);
    ФИЛЬТР   — глотка, рот, нос: труба длиной ~17 см у мужчины и ~14 у
               женщины. Её резонансы (форманты) определяются РАЗМЕРОМ
               головы и шеи, и петь они не умеют — они стоят на месте,
               пока человек не изменит артикуляцию.
Значит личность живёт в фильтре. Спой ту же фразу октавой выше — форманты
почти не сдвинутся; спой её чужим голосом — сдвинутся сразу.

КАК РАЗДЕЛИТЬ ОДНО ОТ ДРУГОГО. Приём музыкальных инженеров — КЕПСТР
(Bogert, Tukey, Healy, 1963; название — переставленные буквы «спектра»).
Спектр звука это спектр источника, УМНОЖЕННЫЙ на отклик фильтра. Логарифм
превращает умножение в сложение, а второе преобразование Фурье разносит
слагаемые по разным местам:
    низкие «квефренции» (медленные волны по спектру) — ОГИБАЮЩАЯ, фильтр,
        то есть форманты и личность;
    высокие квефренции (частая гребёнка гармоник) — ИСТОЧНИК, то есть F0.
Отрезаем высокие («лифтеринг» — тоже переставленное слово, «фильтрация»)
и получаем отпечаток, которому мелодия безразлична.

ВТОРОЙ ПОДАРОК ОТТУДА ЖЕ — ДЕТЕКТОР МУЗЫКИ, три независимых свидетеля,
все три из арсенала музыкального анализа:

  ВИБРАТО. Певец качает высоту 4-7 раз в секунду — это ставят в
    консерватории специально. В речи такого нет: интонация плывёт
    медленно и без периодичности. Смотрим спектр самой дорожки F0.

  ДОЛЯ (бит). У музыки есть изохронный пульс: удары ложатся через равные
    промежутки. Автокорреляция огибающей громкости на темпах 60-180 BPM
    даёт острый пик; у речи слоговой ритм плывёт и пика нет.

  ГАРМОНИЯ ПРОТИВ ШУМА (упрощённый HPSS, Fitzgerald 2010). Инструменты
    держат ноту секундами — по спектрограмме это горизонтальные линии.
    Ударные — вертикальные всплески. Речь не даёт ни того, ни другого:
    её линии живут доли секунды. Медианные фильтры по времени и по
    частоте разводят одно от другого за копейки.

Ни одна из трёх не решает сама: голос под музыку, речитатив, а капелла —
всё это пограничные случаи. Считаем баллы и складываем.

ЦЕНА. Всё считается на готовой фразе двумя-тремя БПФ: доли миллисекунды.
Ни одной новой модели, ни одного мегабайта с диска.
"""
import logging

import numpy as np

log = logging.getLogger("saika.voice_dna")

SR = 16000


# ─────────────────────── источник и фильтр ───────────────────────

_MEL = {}


def _melbank(sr, nfft, nb=26, fmin=80, fmax=7600):
    """Треугольные полосы по мел-шкале — то, как ухо делит спектр.

    Зачем полосы, а не сырой кепстр: гармоники сэмплируют огибающую с
    шагом F0, и на высокой ноте (220 Гц) точек становится вдвое меньше,
    чем на низкой (110). Сырой кепстр это чувствует, и «тот же человек
    октавой выше» уезжает. Усреднение внутри полосы убирает гребёнку
    независимо от того, где стоят её зубцы, — и высота ноты перестаёт
    влиять на результат. Проверено espeak: один голос на разной высоте
    даёт схожесть 0.98, разные голоса — 0.83-0.90."""
    key = (sr, nfft, nb, fmin, fmax)
    if key in _MEL:
        return _MEL[key]
    def m(f):
        return 2595.0 * np.log10(1.0 + f / 700.0)
    def mi(x):
        return 700.0 * (10 ** (x / 2595.0) - 1.0)
    pts = mi(np.linspace(m(fmin), m(fmax), nb + 2))
    bins = np.floor((nfft + 1) * pts / sr).astype(int)
    fb = np.zeros((nb, nfft // 2 + 1), np.float32)
    for i in range(nb):
        l, c, r = bins[i], bins[i + 1], bins[i + 2]
        c = max(c, l + 1)
        r = max(r, c + 1)
        if r > fb.shape[1]:
            break
        fb[i, l:c] = np.linspace(0, 1, c - l)
        fb[i, c:r] = np.linspace(1, 0, r - c)
    _MEL[key] = fb
    return fb


def envelope(pcm16, sr: int = SR, keep=(1, 14)):
    """Отпечаток СТРОЕНИЯ голоса -> вектор, не зависящий ни от ноты, ни
    от слов.

    Путь ровно тот, что описан в шапке: спектр -> мел-полосы (убирают
    гребёнку гармоник) -> логарифм (превращает умножение источника на
    фильтр в сложение) -> косинусное преобразование (разносит их по
    разным коэффициентам). Оставляем 1..13: нулевой это громкость, а
    выше тринадцатого начинается сам источник.

    Усредняем по всей фразе: отдельный звук («ш», «а») говорит о
    произносимой букве, а средняя по фразе огибающая — о говорящем.
    Проверено: тот же голос другим текстом даёт 0.983."""
    x = np.asarray(pcm16, dtype=np.float32).ravel()
    if x.size < sr // 10:
        return None
    x = x / 32768.0 if np.max(np.abs(x)) > 1.5 else x
    nfft = 1024
    win, hop = int(sr * 0.032), int(sr * 0.016)
    if x.size < win * 3:
        return None
    fb = _melbank(sr, nfft)
    w = np.hanning(win)
    # ПОРОГ ТИШИНЫ — ОТ САМОЙ ФРАЗЫ, А НЕ ЖЁСТКИЙ (2026-08-16). Стояло
    # 0.02 абсолютных, и на тихой дорожке (аниме через колонки, дальний
    # микрофон) НИ ОДИН кадр его не брал: отпечаток не считался вовсе,
    # реплика оставалась без дорожки. В логе владельца таких — половина.
    # Берём четверть собственного пика фразы: громкая она или тихая,
    # речь в ней всегда громче своих же пауз.
    rms = np.array([float(np.sqrt(np.mean(x[i:i + win] ** 2)))
                    for i in range(0, x.size - win, hop)], np.float32)
    if rms.size < 3:
        return None
    gate = max(0.004, float(rms.max()) * 0.25)
    acc, n = None, 0
    for k, i in enumerate(range(0, x.size - win, hop)):
        if rms[k] < gate:
            continue                      # тишина огибающую только портит
        seg = x[i:i + win]
        ps = np.abs(np.fft.rfft(seg * w, nfft)) ** 2
        e = np.log(fb @ ps + 1e-10)
        # ДКП через симметричное расширение: та же математика, что у
        # честного DCT-II, но одним готовым БПФ и без лишних зависимостей
        c = np.fft.irfft(np.concatenate([e, e[-2:0:-1]]))[:len(e)]
        acc = c[keep[0]:keep[1]] if acc is None else acc + c[keep[0]:keep[1]]
        n += 1
    if n < 3:
        return None
    v = acc / n
    nrm = np.linalg.norm(v)
    return (v / nrm).astype(np.float32) if nrm > 1e-9 else None


def formants(pcm16, sr: int = SR, k: int = 3):
    """Первые k формант (Гц) — резонансы речевого тракта.

    Ищем пики сглаженной огибающей в КАНОНИЧЕСКИХ полосах: F1 250-1000,
    F2 800-2600, F3 2000-3800. Без полос поиск «трёх самых высоких пиков»
    цепляется за первую гармонику и выдаёт тракт длиной 35 см — человека
    такого размера не бывает, а проверить это было некому."""
    x = np.asarray(pcm16, dtype=np.float32).ravel()
    if x.size < sr // 10:
        return []
    x = x / (np.max(np.abs(x)) + 1e-9)
    nfft = 2048
    take = min(x.size, nfft)
    sp = np.abs(np.fft.rfft(x[:take] * np.hanning(take), nfft))
    lg = np.log(sp + 1e-8)
    cep = np.fft.irfft(lg)
    cep[40:] = 0                          # оставляем только огибающую
    env_ = np.fft.rfft(cep).real
    fr = np.fft.rfftfreq(nfft, 1.0 / sr)
    out = []
    for lo, hi in ((250, 1000), (800, 2600), (2000, 3800))[:k]:
        band = np.where((fr >= max(lo, out[-1] + 200 if out else lo))
                        & (fr <= hi))[0]
        if band.size < 4:
            continue
        e = env_[band]
        j = int(np.argmax(e))
        out.append(float(fr[band[j]]))
    return [round(f) for f in out]


def tract_length(fmts) -> float:
    """Длина речевого тракта в сантиметрах по формантам.

    Труба, закрытая с одного конца, резонирует на (2n-1)·c/4L. Отсюда
    L = (2n-1)·34000 / (4·Fn). Усредняем по имеющимся формантам. Это
    физический размер человека: у взрослого мужчины ~17 см, у женщины
    ~14, у ребёнка ~11. Мелодия его не меняет — в этом весь смысл."""
    if not fmts:
        return 0.0
    est = [(2 * (i + 1) - 1) * 34000.0 / (4.0 * f)
           for i, f in enumerate(fmts) if f > 50]
    return round(float(np.median(est)), 1) if est else 0.0


# ─────────────────────── музыка или речь ───────────────────────

def _f0_track(x, sr, hop_s=0.02, win_s=0.04):
    """Дорожка основной частоты по кадрам (для вибрато)."""
    win, hop = int(sr * win_s), int(sr * hop_s)
    out = []
    lo, hi = int(sr / 400), int(sr / 70)
    for i in range(0, max(0, len(x) - win), hop):
        w = x[i:i + win]
        w = w - w.mean()
        if float(np.sqrt(np.mean(w ** 2))) < 0.01:
            out.append(0.0)
            continue
        nfft = 1 << int(np.ceil(np.log2(2 * len(w))))
        sp = np.fft.rfft(w, nfft)
        ac = np.fft.irfft(sp * np.conj(sp))[:len(w)]
        if hi >= len(ac) or lo >= hi:
            out.append(0.0)
            continue
        k = lo + int(np.argmax(ac[lo:hi]))
        out.append(sr / k if ac[k] > 0.3 * ac[0] else 0.0)
    return np.asarray(out, np.float32)


def vibrato(pcm16, sr: int = SR):
    """0..1 — насколько высота качается 4-7 раз в секунду.

    Певческое вибрато ставят специально и держат именно в этой полосе;
    в речи периодического качания нет вовсе."""
    x = np.asarray(pcm16, np.float32).ravel() / 32768.0
    f0 = _f0_track(x, sr)
    v = f0[f0 > 0]
    if v.size < 24:
        return 0.0
    # работаем в полутонах: качание на пол-тона внизу и вверху — одно и то же
    cents = 12.0 * np.log2(np.maximum(f0, 1e-6) / max(np.median(v), 1e-6))
    cents[f0 <= 0] = 0.0
    cents = cents - cents.mean()
    n = len(cents)
    sp = np.abs(np.fft.rfft(cents * np.hanning(n)))
    fr = np.fft.rfftfreq(n, 0.02)         # шаг дорожки 20мс
    band = (fr >= 4.0) & (fr <= 7.5)
    rest = (fr > 0.5) & (~band)
    if not band.any() or not rest.any():
        return 0.0
    r = float(sp[band].max() / (sp[rest].mean() + 1e-9))
    return float(np.clip((r - 2.0) / 6.0, 0.0, 1.0))


def beat(pcm16, sr: int = SR):
    """0..1 — есть ли ровный пульс 60-180 ударов в минуту.

    Классика анализа музыки: огибающая нарастаний (onset envelope), её
    автокорреляция, пик на периоде доли. У речи слоговой ритм плывёт и
    острого пика не даёт."""
    x = np.asarray(pcm16, np.float32).ravel() / 32768.0
    hop = int(sr * 0.01)
    if len(x) < sr:
        return 0.0
    m = len(x) // hop
    e = np.sqrt((x[:m * hop].reshape(m, hop) ** 2).mean(1))
    d = np.diff(e)
    d[d < 0] = 0.0                        # только нарастания
    d = d - d.mean()
    if d.size < 100 or float(np.std(d)) < 1e-6:
        return 0.0
    nfft = 1 << int(np.ceil(np.log2(2 * d.size)))
    sp = np.fft.rfft(d, nfft)
    ac = np.fft.irfft(sp * np.conj(sp))[:d.size]
    if ac[0] <= 0:
        return 0.0
    ac = ac / ac[0]
    lo = int(60.0 / 180 / 0.01)           # 180 BPM
    hi = int(60.0 / 60 / 0.01)            # 60 BPM
    hi = min(hi, len(ac) - 1)
    if lo >= hi:
        return 0.0
    peak = float(ac[lo:hi].max())
    base = float(np.median(ac[lo:hi]))
    return float(np.clip((peak - base) * 3.0, 0.0, 1.0))


def harmonicity(pcm16, sr: int = SR):
    """0..1 — доля «горизонтальных» линий в спектрограмме.

    Упрощённый HPSS: инструмент держит ноту секундами (линия вдоль
    времени), речь меняет спектр каждые 50-100мс. Медиана вдоль времени
    выделяет первое, медиана вдоль частоты — второе."""
    x = np.asarray(pcm16, np.float32).ravel() / 32768.0
    win, hop = 1024, 256
    if len(x) < win * 8:
        return 0.0
    frames = [np.abs(np.fft.rfft(x[i:i + win] * np.hanning(win)))
              for i in range(0, len(x) - win, hop)]
    S = np.stack(frames, 1)               # (частота, время)
    if S.shape[1] < 9:
        return 0.0
    k = 9
    pad = k // 2
    Sp = np.pad(S, ((0, 0), (pad, pad)), mode="edge")
    H = np.median(np.stack([Sp[:, i:i + S.shape[1]] for i in range(k)]), 0)
    Sf = np.pad(S, ((pad, pad), (0, 0)), mode="edge")
    P = np.median(np.stack([Sf[i:i + S.shape[0]] for i in range(k)]), 0)
    h, p = float((H ** 2).sum()), float((P ** 2).sum())
    if h + p < 1e-9:
        return 0.0
    return float(np.clip((h / (h + p) - 0.5) * 4.0, 0.0, 1.0))


def music_score(pcm16, sr: int = SR) -> dict:
    """Три свидетеля и общий балл 0..1. Порог решает вызывающий."""
    try:
        vb = vibrato(pcm16, sr)
        bt = beat(pcm16, sr)
        hm = harmonicity(pcm16, sr)
    except Exception as e:
        log.debug("детектор музыки споткнулся: %s", e)
        return {"vibrato": 0.0, "beat": 0.0, "harmonic": 0.0, "score": 0.0}
    # вибрато — самый специфичный признак (в речи его не бывает вовсе),
    # поэтому вес больше; доля и гармоничность подтверждают
    score = 0.45 * vb + 0.30 * bt + 0.25 * hm
    return {"vibrato": round(vb, 2), "beat": round(bt, 2),
            "harmonic": round(hm, 2), "score": round(float(score), 2)}


def dna(pcm16, sr: int = SR) -> dict:
    """Полный паспорт куска: чем он звучит и кто это может быть."""
    env = envelope(pcm16, sr)
    fmts = formants(pcm16, sr)
    return {"env": env, "formants": fmts, "tract_cm": tract_length(fmts),
            **music_score(pcm16, sr)}
