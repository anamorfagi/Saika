"""РЕГЛАМЕНТ РАБОТЫ РУКАМИ (2026-08-13). Подробности — в WORKFLOW.md.

ЗАЧЕМ. Владелец: «чем обычно пользуется человек за компом, какие действия
он выполняет, чтобы пройти от задачи к её выполнению? нам нужно описать
логику и отработать её во всех этих действиях».

Разбор показал вот что: НЕДОСТАЮЩЕГО ИНСТРУМЕНТА НЕТ НИ ОДНОГО. Руки
(запустить, набрать, нажать, кликнуть, прокрутить) и глаза (screen_read,
window_list, vision) на месте давно. Не хватало ПОРЯДКА ДЕЙСТВИЙ: человек
перед каждым шагом бесплатно смотрит на экран и после каждого шага
бесплатно проверяет результат — и потому не замечает, что делает это.
Модель без явного регламента эти два шага пропускает и выдаёт намерение за
результат («Закрываю Blender», ноль вызовов, три раза подряд).

Здесь — этот регламент. Не реплики (характер её собственный и в чужих
подсказках не нуждается), а последовательность: где посмотреть, чем
сделать, чем проверить, куда свернуть при отказе. Подкладывается в промпт
ТОЛЬКО под ту задачу, что сейчас на столе: полный свод из шести сценариев
съел бы контекст и утопил мелкую модель.
"""
import logging
