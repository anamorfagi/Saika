_RX = {k: re.compile(v[0], re.I) for k, v in PLAYBOOKS.items()}

# задачи руками вообще: если ни одного признака — регламент не нужен,
# это разговор, и грузить им контекст незачем
_HANDS = re.compile(
    r"запусти|открой|включи|закрой|выключи|сверни|разверни|подними|"
    r"переключ|напиши|набери|введи|впиши|отправ|найди|поищи|погугли|"
    r"прокрут|пролист|нажми|кликни|тыкни|файл|папк|сохран|переимен|"
    r"перемест|удали|музык|громк|тише|громче|пауз|игр|настройк|вкладк|"
    r"сайт|ссылк|покажи|поставь|сделай|помен|смени|настрой|убери|"
    r"создай|запиши|скачай|распечат|яркост|обои|громкост|заверши|"
    r"переключись|скопир|встав|отмени|перенес|перекин|перетащ|подним|верни|экран|монитор|вкладк|поменьше|побольше|уменьш|увелич|разверни|сверни", re.I)


def scenario(text: str) -> str:
    """Какой вид работы сейчас на столе. Пусто — значит разговор."""
    t = text or ""
    if not _HANDS.search(t):
        return ""
    best, hits = "", 0
    for name, rx in _RX.items():
        n = len(rx.findall(t))
        if n > hits:
            best, hits = name, n
    return best or "app"


def block(text: str) -> str:
    """Регламент под текущую задачу — для вставки в промпт. Пусто, если
    задача не про руки: в разговоре инструкция только мешает."""
    sc = scenario(text)
    if not sc:
        return ""
    tail = PLAYBOOKS.get(sc, ("", ""))[1]
    return CORE + "\n" + ("### Под эту задачу\n" + tail if tail else "")
