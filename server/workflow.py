log = logging.getLogger("saika.workflow")

# ЦИКЛ ЦЕЛИКОМ — общая часть, одинаковая для всех задач. Короткая
# намеренно: длинные инструкции мелкие модели читают через строчку.
CORE = (
    "### Порядок работы руками (регламент, не обсуждается)\n"
    "1) НАЙДИ МЕСТО — где это делается: какое окно, какое поле.\n"
    "2) ПОПАДИ туда: открыто — window_focus, закрыто — app_launch.\n"
    "3) ПОСМОТРИ перед действием (screen_read / window_list), а не гадай.\n"
    "4) СДЕЛАЙ инструментом. Слова о действии действием НЕ являются.\n"
    "5) ПОДТВЕРДИ, если нужно: набранный текст без Enter никуда не ушёл.\n"
    "6) ПРОВЕРЬ результат тем же способом, каким смотрела.\n"
    "7) НЕ ВЫШЛО — иди ДРУГИМ путём, не повторяй тот же вызов.\n"
    "8) Говори «сделала» только о проверенном. Иначе — «пробую» "
    "или честно, что помешало."
)

# сценарий -> (регекс задачи, конкретная цепочка под этот вид работы)
