"""Беймакс — «персональный помощник по здоровью» системы.

Не сухие логи, а живой персонаж внутри Сайки: осматривает модули, бормочет
себе под нос, беззлобно чертыхается, ставит оценки по десятибалльной (иногда
«в сурках») и сам чинит/подстраивает систему под текущий ПК. Его реплики
уходят в основной чат отдельными пузырями (тип сообщения "baymax").

Тексты собираются из шаблонов со случайными вариациями — Беймакс должен
работать и когда LLM лежит, поэтому его «речь» не зависит от нейросети.
"""
import random

from server import diagnostics

# как произносим оценку: обычно «N из 10», иногда с забавной единицей
_UNITS = ["из 10", "из 10", "из 10", "из 10",
          "сурков из 10", "бобров из 10", "по десятибалльной, ага",
          "из 10, но это неточно"]


def _score(n: int) -> str:
    return f"{n} {random.choice(_UNITS)}"


