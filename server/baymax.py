_FIXED = [
    "Фух, «{name}» ожил. {sc}, живём.",
    "Ну вот, починил «{name}». Я же говорил — {sc}.",
    "«{name}» снова в строю. {sc}. Работаем дальше.",
    "Оп, «{name}» поднялся. {sc}, красота.",
]

_SWITCH = [
    "Так, беру запасной, чтоб ты не молчал.",
    "Переключаюсь на рабочий, без паники.",
]


def line(component: str, error: str, action: str, diag: dict = None) -> dict:
    """Реплика Беймакса по событию подсистемы. Возвращает
    {text, score, mood: 'ok'|'bad'|'meh'}."""
    name = (component or "модуль").split(".")[-1]

    # пустая ошибка = восстановление/хорошая новость
    if not error:
        if "восстановлен" in (action or "") or "ожил" in (action or ""):
            n = random.randint(8, 10)
            return {"text": random.choice(_FIXED).format(name=name, sc=_score(n)),
                    "score": n, "mood": "ok"}
        return {"text": random.choice(_SWITCH), "score": 6, "mood": "meh"}

    d = diag or diagnostics.classify(component, error)
    cat = d.get("category", "unknown")
    n = diagnostics._BROKEN_SCORE.get(cat, 2)
    templ = _GRUMBLE.get(cat, _GRUMBLE["unknown"])
    return {"text": random.choice(templ).format(name=name, sc=_score(n)),
            "score": n, "mood": "bad"}


def greeting(stt_status: dict, tts_status: dict) -> dict:
    """Короткое приветствие при подключении вкладки: осмотрелся — как оно."""
    def bad(st):
        h = st.get("health", {})
        return sum(1 for v in h.values() if v == "broken")

    broken = bad(stt_status) + bad(tts_status)
    if broken == 0:
        n = random.randint(8, 10)
        txt = random.choice([
            f"Беймакс на связи. Осмотрелся — вроде всё живое, {_score(n)}.",
            f"Привет, я Беймакс. Système в норме, {_score(n)}. Если что упадёт — починю.",
        ])
        return {"text": txt, "score": n, "mood": "ok"}
    n = max(2, 7 - broken)
    return {"text": f"Беймакс на связи. Хм, вижу {broken} подраненных модуля(ей), "
                    f"{_score(n)}. Ща погляжу, что там.",
            "score": n, "mood": "meh"}
