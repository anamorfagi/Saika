# слова, при которых «открой X» — НЕ запуск программы (папки/файлы/страницы
# требуют решений — это работа модели, не спинного мозга)
_NOT_APPS = {"папку", "файл", "сайт", "страницу", "ссылку", "глаза",
             "окно", "настройки", "доску", "память"}

# «закрой ЭТО» — не имя программы, а указание на переднее окно; такие
# случаи и правда стоит отдать модели, у неё есть картина обстановки
# короткое согласие: имеет силу только при незакрытом вопросе «это оно?»
# СОГЛАСИЕ НА ЕЁ СОБСТВЕННЫЙ ВОПРОС. Разбираем по словам, а не регексом:
# в живой речи вокруг «да» всегда мусор, и перечислять его комбинации в
# одном выражении — путь к ошибкам вроде «Да, блин» -> не распознано.
_AGREE_WORDS = {"да", "дааа", "ага", "угу", "давай", "запускай", "запусти",
                "ок", "окей", "верно", "точно", "ясно", "именно"}
_ORDINAL = {"первое": 1, "первый": 1, "первая": 1, "1": 1,
            "второе": 2, "второй": 2, "вторая": 2, "2": 2,
            "третье": 3, "третий": 3, "третья": 3, "3": 3,
            "четвёртое": 4, "четвертое": 4, "четвёртый": 4, "4": 4}
_FILLER = {"ну", "блин", "бля", "блядь", "же", "уже", "конечно", "нафиг",
           "пожалуйста", "сайка", "это", "оно", "то", "самое", "и", "а"}


def _is_agree(text: str) -> bool:
    """Фраза целиком состоит из согласия и мусора вокруг него?"""
    words = [w for w in re.split(r"[^\wа-яё]+", (text or "").lower()) if w]
    if not words or len(words) > 4:
        return False
    hit = False
    for w in words:
        if w in _AGREE_WORDS or w in _ORDINAL:
            hit = True
        elif w not in _FILLER:
            return False          # есть постороннее слово — это не «да»
    return hit


_NOT_WINDOWS = {"это", "его", "её", "ее", "их", "всё", "все", "браузер",
                "вкладку", "глаза", "зрение", "звук", "музыку", "песню",
                "рот", "себя", "программу", "окно", "окна",
                # «выключи компьютер» — это выключение машины, а не окно
                "комп", "компьютер", "пк", "ноут", "ноутбук",
                "систему", "винду", "свет", "меня", "нас"}


# СВОИ РЕФЛЕКСЫ ИЗ КОНФИГА (2026-07-28): владелец добавляет правила без
# правки кода — reflex.extra в config.json:
#   [{"pattern": "стрим-режим", "tool": "minimize_all", "args": {}}]
# pattern — регекс по фразе, tool — любой из списка инструментов.
_extra_cache = {"src": None, "rules": []}


def _extra_rules():
    src = CFG.get("reflex.extra", []) or []
    if _extra_cache["src"] == src:
        return _extra_cache["rules"]
    rules = []
    for r in src:
        try:
            rules.append((re.compile(r["pattern"], re.I), r["tool"],
                          dict(r.get("args") or {})))
        except Exception as e:
            log.warning("рефлекс из конфига не собрался (%s): %s", r, e)
    _extra_cache.update(src=src, rules=rules)
    return rules


# ЦЕПОЧКИ КОМАНД (2026-07-28, практика Talon: команды идут связками без
# пауз). «Сверни всё и открой проводник» раньше уходило модели целиком —
# теперь фраза режется по связкам « и / потом / затем / а после », и если
# КАЖДЫЙ кусок — рефлекс, исполняется вся цепочка (до 3 действий). Если
# хоть один кусок рефлексом не ловится — вся фраза уходит модели, как
# раньше: полкоманды делать хуже, чем не делать вовсе.
_CHAIN_SPLIT = re.compile(r"\s*(?:,\s*)?(?:\bи\b|\bпотом\b|\bзатем\b|"
                          r"\bа после\b|\bпосле этого\b)\s+", re.I)


def match_chain(user_text: str) -> list:
    """[(имя, аргументы), ...] если ВСЯ фраза — цепочка рефлексов, иначе []."""
    t = (user_text or "").strip()
    if not t or len(t) > 120:
        return []
    parts = [p.strip() for p in _CHAIN_SPLIT.split(t) if p.strip()]
    if len(parts) < 2 or len(parts) > 3:
        return []
    hits = [match(p) for p in parts]
    return hits if all(hits) else []


# ═══ КОМАНДЫ, КОТОРЫЕ РАБОТАЮТ В ЛЮБОЙ ФРАЗЕ И ЛЮБОЙ ДЛИНЫ ═══
# 2026-08-14, живой разговор владельца. Двадцать минут «не получилось» на
# ровном месте, и вот почему рефлекс молчал:
#
#   «Да, но перейди просто в диск C.»              — начинается с «Да, но»,
#        а правило было привязано к НАЧАЛУ фразы.
#   «А, ты дискард услышала, да? Окей, давай ещё
#    раз зайди на диск C.»                          — 62 символа, а порог 60.
#
# Оба раза команда в тексте БЫЛА, чистая и однозначная. Порог в 60 символов
# придуман для другого: длинная фраза обычно про контекст, и решать её
# должна модель. Но «диск C» ни в каком контексте не значит ничего иного —
# в такой команде нечего решать. Поэтому эти правила проверяются ПЕРВЫМИ,
# ищутся ГДЕ УГОДНО в предложении и порога длины не знают.
#
# Что сюда можно класть: только то, у чего нет второго смысла. Диск, «Этот
# компьютер», «наверх». Всё остальное — в обычный список, под порог.
# Правила пишем ЯВНО, а не выводим из обычных: у сильного правила другая
# задача. Обычное разбирает фразу целиком («это точно команда и ничего
# больше»), сильное — выхватывает ЯДРО команды из чего угодно. Перечислять
# все возможные «да, но», «окей, давай ещё раз» бессмысленно: их бесконечно
# много. Ищем то, что нельзя понять двояко.
# ОДНОБУКВЕННЫЕ ПРЕДЛОГИ — НЕ БУКВЫ ДИСКА (2026-08-14, стенд: «у меня три
# диска В системе» уезжало в go_to «в»). Отличаем по хвосту: буква диска
# стоит в конце команды, а предлог тянет за собой существительное.
_AMBIG = {"в", "у", "о", "к", "а", "и", "я", "на", "из", "по", "за", "до"}


# «НАЙДИ НА ДИСКЕ C ИГРЫ» — ЭТО ОБЗОР, А НЕ ШАГ (2026-08-14, стенд).
# Сильное правило ищет «диск C» где угодно и потому перехватывало просьбу
# ПОИСКА. Отличаем по составу: есть глагол поиска И предмет поиска —
# значит человек просит найти, а не перейти.
_LOOKUP = re.compile(r"(?:найд|поищ|покаж|глянь|где)\w*[^.!?]{0,30}?"
                     r"(?:игр|game|программ|прог|софт)", re.I)


def _g_drive(m):
    if _LOOKUP.search(m.string):
        raise ValueError("это поиск по диску, а не переход")
    w = m.group(1).lower()
    if w in _AMBIG:
        tail = m.string[m.end(1):].strip()
        if tail and tail[0] not in ".,!?;:":
            raise ValueError("предлог, а не буква диска")
    return {"where": m.group(1)}


def _g_pc(m):
    return {"where": "пк"}


# «диск» ТОЛЬКО в единственном числе: «диски в компьютере» — это разговор
# о железе, а не команда, и «в» там не буква диска.
_D = r"диск(?:е|а|у|ом)?"
_STRONG_RULES = [
    # «ОТЛИЧНО. ЗАЙДИ В PROGRAM FILES X86» (2026-08-14, живой лог: рефлекс
    # промолчал из-за приставки «Отлично.», модель сказала «Захожу…» и не
    # сделала ничего). «Зайди в …» — слова про МЕСТО, второго смысла у них
    # нет, значит правилу здесь и место.
    (re.compile(r"(?:^|[,.!?]\s*|\bи\s+|\bа\s+|\bпотом\s+)"
                r"(?:а\s+|ну\s+|давай\s+|теперь\s+|просто\s+)*"
                r"(?:зайди|перейди|спустись|шагай)\s+(?:в|во|на)\s+"
                r"(?:папку\s+|директорию\s+)?"
                r"([a-zа-яё0-9 ()._/:-]{2,40}?)\s*[.!]?(?:$|[,;])", re.I),
     "go_to", lambda m: {"where": m.group(1).strip()}),
    # «ВЫВЕДИ ВПЕРЁД» БЕЗ ИМЕНИ — ЭТО ПРО ТО, ЧЕМ ЗАНЯТЫ (2026-08-14).
    # Живой лог: «выведи вперёд» -> window_focus без аргумента -> «ты не
    # указала, какое именно окно». Человек только что ходил по папкам;
    # переспрашивать «какое окно» после этого — издевательство.
    (re.compile(r"(?:^|[,.!?]\s*)(?:ну\s+|давай\s+|просто\s+)*"
                r"(?:вывед\w*|подним\w*|покажи)\s+"
                r"(?:его\s+|её\s+|ее\s+|окно\s+)?"
                r"(?:вперёд|вперед|наверх|поверх\s+всех|на\s+экран)"
                r"\s*[.!]?$", re.I),
     "window_focus", lambda m: {"match": "проводник"}),
    # «на диск C», «в диске E», «обратно на диск ц»
    (re.compile(r"(?:^|\W)(?:на|в|во)\s+" + _D + r"\s+([a-zа-яё]{1,2})"
                r"(?![\wа-яё])", re.I), "go_to", _g_drive),
    # «диск C» без предлога
    (re.compile(r"(?:^|\W)" + _D + r"\s+([a-zа-яё])(?![\wа-яё])", re.I),
     "go_to", _g_drive),
    # проводник и «Этот компьютер» в любой обёртке
    (re.compile(r"(?:^|\W)(?:открой|запусти|покажи|врубай|перейди|зайди|"
                r"вернись|давай|верни)\s+(?:мне\s+|просто\s+|снова\s+|"
                r"ещ[её]\s+раз\s+|в\s+|во\s+|на\s+)*проводник", re.I),
     "go_to", _g_pc),
    (re.compile(r"(?:^|\W)(?:открой|покажи|давай|верни(?:сь)?)\s+"
                r"(?:мне\s+|просто\s+)*(?:мой\s+|этот\s+)?"
                r"(?:компьютер|список\s+дисков)(?![\wа-яё])", re.I),
     "go_to", _g_pc),
]


def _strong_rules():
    return _STRONG_RULES


_STRONG = None


def match(user_text: str):
    """None или (имя_инструмента, аргументы). Стоит доли миллисекунды."""
    global _STRONG
    if not CFG.get("reflex.enabled", True):
        return None
    t = (user_text or "").strip()
    if not t:
        return None
    if _STRONG is None:
        _STRONG = _strong_rules()
    if len(t) <= 200:
        for rx, name, fn in _STRONG:
            m = rx.search(t)
            if not m:
                continue
            try:
                return name, fn(m)
            except Exception as e:
                log.debug("сильный рефлекс %s не разобрал: %s", name, e)
    if len(t) > 60:                   # длинная фраза = контекст, пусть думает
        return None
    for rx, name, args in _extra_rules():   # правила владельца — первыми
        if rx.search(t):
            return name, args
    for rx, name, args_fn in _RULES:
        m = rx.search(t)
        if not m:
            continue
        # у правила согласия скобок нет — group(1) там не существует
        _g1 = m.group(1) if m.re.groups else ""
        if name == "app_launch" and _g1 and _g1.lower() in _NOT_APPS:
            continue
        # ПРАВИЛО СОГЛАСИЯ — единственное без скобок в шаблоне, по этому и
        # узнаём его. Оно нарочно ловит любую короткую фразу, а решение
        # принимают две проверки: это действительно согласие И она
        # действительно только что спросила «это оно?». Без обеих — молчим,
        # иначе «привет» запускал бы программы.
        if name == "app_launch" and m.re.groups == 0:
            if not _is_agree(t):
                continue
            try:
                from server import app_memory as _mem
                if not _mem.pending():
                    continue
            except Exception:
                continue
        # НОМЕР ИМЕЕТ СИЛУ, ТОЛЬКО ПОКА ЕСТЬ СПИСОК (2026-08-14). Иначе
        # «пятый» посреди разговора о чём угодно дёргал бы прогулку, а
        # «да, третий» перехватывался бы у ответа на её же вопрос «это
        # оно?» — у того свой разбор и своя память.
        if name == "pick_number":
            try:
                from server import explorer as _ex
                from server import app_memory as _mem
                if _mem.pending() or not _ex.offer_alive():
                    continue
            except Exception:
                continue
        # «закрой это / закрой браузер / закрой глаза» — не имя окна,
        # а указание на обстановку: тут нужна её картина мира, не рефлекс
        if name in ("window_close", "window_minimize", "window_focus") \
                and _g1.lower().strip() in _NOT_WINDOWS:
            continue
        try:
            return name, args_fn(m)
        except Exception as e:
            log.debug("рефлекс %s не разобрал аргументы: %s", name, e)
    return None


def execute(hit, user_text: str) -> str:
    """Исполняет рефлекс через штатный tools.call (со всеми
    предохранителями). Возвращает результат для вставки в промпт."""
    name, args = hit
    from server.llm import tools as _tls
    _tls.LAST_USER["text"] = user_text     # предохранитель намерения
    res = _tls.call(name, args)
    log.info("Рефлекс: %s(%s) -> %s", name, args, str(res)[:120])
    return str(res or "сделано")
