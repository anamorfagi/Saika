"""Сторож генерации: ловит зависание LLM (лупы) и обрывает стрим.

Типовые залипания мелких моделей:
- фонема: «ааааааааааа...» — одна буква/символ бесконечно
- слово: «так так так так...» — 1-2 слова по кругу
- фраза: один и тот же кусок предложения повторяется блоками
- тихий бесконечный поток: генерация идёт минуты без остановки

Детект срабатывает за секунды (не ждём 3 минуты страданий), плюс два
предохранителя: общий таймаут и аварийный потолок токенов — на случай
лупа, который детектор по паттерну не поймал.

После обрыва main.py делает «recovery»-вызов: Сайке показывают её же
затуп, и она реагирует на него сама — с самоиронией, в характере.
"""
import re
import time


class LoopGuard:
    def __init__(self, hard_tokens=4000, max_seconds=180):
        self.hard_tokens = hard_tokens      # аварийный потолок токенов
        self.max_seconds = max_seconds      # общий таймаут генерации
        self.n = 0
        self.tail = ""                      # хвост текста для анализа
        self.t0 = time.monotonic()

    def feed(self, token: str):
        """None — всё нормально. Строка — причина обрыва."""
        self.n += 1
        self.tail = (self.tail + token)[-600:]

        if self.n >= self.hard_tokens:
            return f"аварийный потолок {self.hard_tokens} токенов"
        if time.monotonic() - self.t0 > self.max_seconds:
            return f"таймаут генерации ({self.max_seconds}с)"

        t = self.tail
        # --- одна буква/символ подряд («ааааааа», «!!!!!!!») ---
        packed = t[-80:].replace(" ", "")
        if len(packed) >= 50 and len(set(packed.lower())) <= 2:
            return "залипание на звуке"

        # --- 1-2 слова по кругу («так так так так ...») ---
        words = [w.strip(".,!?…—-:;()«»\"'").lower() for w in t.split()]
        words = [w for w in words if w]
        if len(words) >= 14 and len(set(words[-14:])) <= 2:
            return "залипание на слове"

        # --- повтор целой фразы блоками: ищем период p, которым хвост
        # повторяется подряд. Короткий период («да, да, да») требует больше
        # повторов, чем длинная фраза — чтобы не ловить living speech ---
        if len(t) >= 60:
            for p in range(8, 201):
                need = 5 if p < 20 else 3          # повторов для срабатывания
                if p * need > len(t):
                    break
                block = t[-p:]
                if all(t[-(i + 1) * p:-i * p or None] == block
                       for i in range(1, need)):
                    return "залипание на фразе"

        return None

    def trimmed(self, full_text: str) -> str:
        """Отрезать залипший хвост, вернуть осмысленную часть ответа."""
        text = full_text.rstrip()
        # срежем повторяющийся хвост грубо: последние 120 символов лупа
        cut = text[:-120] if len(text) > 160 else ""
        # и добьём до конца последнего законченного предложения
        m = re.search(r"^(.*[.!?…])", cut, re.S)
        return (m.group(1) if m else cut).strip()


RECOVERY_PROMPT = (
    "Служебное сообщение сторожевого скрипта: твоя генерация только что "
    "зависла ({reason}). Тебя пришлось оборвать, зациклившийся кусок "
    "выглядел так: «{glitch}». Это твой мелкий технический глюк — отреагируй "
    "на него сама, одной-двумя фразами, в своём характере: с самоиронией, "
    "без паники и без извинений на три абзаца. Если до зависания ты "
    "отвечала на вопрос — после шутки коротко и нормально договори мысль."
)
