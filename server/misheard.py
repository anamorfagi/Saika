"""ЛОГИКА ПРАВИЛЬНОГО НАПИСАНИЯ — ремонт ослышек и метка «шатко» (2026-08-15).

ПРОСЬБА ВЛАДЕЛЬЦА, дословно: «повысить точность и доработать логику
правильного написания», после живого случая, где половина слов в строке
оказалась выдумкой движка.

ЗДЕСЬ ДВЕ РАЗНЫЕ РАБОТЫ, и путать их нельзя:

  1. РЕМОНТ ПО СЛОВАРЮ ПРОЕКТА. Движок не знает наших слов: имени «Сайка»,
     имён голосов из карты, слов, на которых стоит рефлекс. Он честно пишет
     созвучное — «зайка», «гайка», «чайка». Это чинится детерминированно:
     фонетический ключ русского слова + словарь того, что у нас вообще
     бывает. Правило из CLAUDE.md: что можно решить правилом — решается
     правилом, модель последняя инстанция, а не первая.

  2. МЕТКА НЕДОВЕРИЯ. Часть строк движок выдумывает целиком — на шорохе, на
     обрывке слова, на чужом звуке из колонок. Признак у выдумки простой и
     измеримый: слов написано много, а звука было мало (или он был тише
     порога). Такую строку МЫ НЕ ВЫБРАСЫВАЕМ — молчаливый отказ запрещён, —
     а помечаем: интерфейс покажет её иначе, стенд слуха сохранит рядом с
     волной, и станет видно, где проходит настоящая граница.

ПОЧЕМУ НЕ ПРАВИМ ВСЁ ПОДРЯД. Автозамена по созвучию — оружие обоюдоострое:
она с той же лёгкостью испортит правильно расслышанное слово. Поэтому
замена происходит ТОЛЬКО в сторону словаря проекта, только для слов от
четырёх букв, никогда — для слов, которые и так есть в словаре, и каждая
замена уходит в лог и в поле heard_raw. Тихих правок текста здесь не бывает.
"""
import logging
import re

from server.config import CFG

log = logging.getLogger("saika.misheard")

_WORD = re.compile(r"[А-Яа-яЁё]+")

# Пары «звонкий → глухой» и стяжка безударных гласных: ровно те подмены,
# на которых распознаватель и путается. Ударение мы не знаем, поэтому
# сводим ВСЕ безударные и ударные к одному классу — ключ становится грубее,
# зато устойчив к тому, как человек проглотил окончание.
_MAP = str.maketrans({
    "ё": "и", "е": "и", "э": "и", "я": "а", "о": "а", "ы": "и", "ю": "у",
    "б": "п", "в": "ф", "г": "к", "д": "т", "ж": "ш", "з": "с",
    "щ": "ш", "ч": "ш", "ц": "с", "й": "и",
    "ъ": "", "ь": "",
})


def key(word: str) -> str:
    """Фонетический ключ русского слова: как оно звучит, а не как пишется."""
    s = (word or "").lower().translate(_MAP)
    out = []
    for ch in s:
        if not out or out[-1] != ch:
            out.append(ch)
    return "".join(out)


def _dist(a: str, b: str, cap: int = 2) -> int:
    """Левенштейн с потолком: считать точное расстояние между длинными
    словами тут незачем, нас интересует только «отличается на букву-две»."""
    if abs(len(a) - len(b)) > cap:
        return cap + 1
    prev = list(range(len(b) + 1))
    for i, ca in enumerate(a, 1):
        cur = [i] + [0] * len(b)
        for j, cb in enumerate(b, 1):
            cur[j] = min(prev[j] + 1, cur[j - 1] + 1,
                         prev[j - 1] + (ca != cb))
        if min(cur) > cap:
            return cap + 1
        prev = cur
    return prev[-1]


# ------------------------------------------------------------------ словарь
_CACHE = {"words": [], "ts": 0.0}


def vocab() -> list:
    """Слова, которых движок не знает, а у нас они есть.

    Собирается из живых источников, а не из статического списка: имена
    голосов меняются, стоп-слова правятся в конфиге, лорбук растёт. Кэш на
    минуту — этого хватает, чтобы не собирать словарь на каждую фразу."""
    import time
    if _CACHE["words"] and time.time() - _CACHE["ts"] < 60:
        return _CACHE["words"]
    words = set()
    try:
        words.add(str(CFG.get("assistant.name", "Сайка")))
    except Exception:
        pass
    words.add("Сайка")
    for w in (CFG.get("attention.stop_words", []) or []):
        words.add(str(w))
    for w in (CFG.get("stt.vocab", []) or []):
        words.add(str(w))
    # имена голосов из карты: человек назвал их сам, движок про них не знает
    try:
        from server import voiceprint as _vp
        for nm in (_vp.S.reg.speakers or {}):
            if nm and not str(nm).lower().startswith("голос"):
                words.add(str(nm))
    except Exception:
        pass
    out = []
    seen = set()
    for w in words:
        w = w.strip()
        if len(w) < 4:            # короче — слишком мало сигнала для созвучия
            continue
        k = key(w)
        if k in seen:
            continue
        seen.add(k)
        out.append((w, k))
    _CACHE["words"] = out
    _CACHE["ts"] = time.time()
    return out


# ------------------------------------------------------------------- ремонт
def repair(text: str):
    """-> (текст, [(было, стало)]). Пустой список правок = не тронули."""
    if not text or not CFG.get("stt.repair", True):
        return text, []
    voc = vocab()
    if not voc:
        return text, []
    # «Уже наше слово» — это совпадение ПО НАПИСАНИЮ, а не по звучанию.
    # Сравнивать здесь ключи было ошибкой ровно наоборот смыслу модуля:
    # у «зайки» и «Сайки» ключ один и тот же — на то и расчёт, — и проверка
    # по ключу объявляла ослышку «нашим словом» и оставляла её как есть.
    known = {w.lower() for w, _ in voc}
    fixes = []

    # ПОЧЕМУ ПО УМОЛЧАНИЮ ТОЛЬКО ТОЧНОЕ СОЗВУЧИЕ (расстояние 0).
    # Соблазн разрешить «отличается на букву» велик — так ловятся «чайка» и
    # «гайка» вместо «Сайка». Но ключ у русских слов короткий, и на
    # расстоянии в одну букву начинают сходиться совершенно разные слова:
    # ключ «молчи» — «малши», ключ «мальчик» — «малшик», разница ровно одна
    # буква. Живой «мальчик» превратился бы в команду «молчи» — это уже не
    # ремонт, а порча текста, причём молчаливая. Точное созвучие такой цены
    # не имеет: «зайка» и «Сайка» дают один и тот же ключ «саика», а
    # «мальчик» и «молчи» — разные. Кому нужно шире — stt.repair_fuzzy,
    # и тогда мягкое сравнение работает ТОЛЬКО для имён (их человек
    # произносит осознанно и ждёт, что его услышат).
    fuzzy = bool(CFG.get("stt.repair_fuzzy", False))
    names = {key(str(CFG.get("assistant.name", "Сайка"))), key("Сайка")}

    def one(m):
        w = m.group(0)
        if len(w) < 4:
            return w
        if w.lower() in known:        # написано верно — не трогаем
            return w
        k = key(w)
        best, bd = None, 99
        for word, wk in voc:
            cap = 1 if (fuzzy and wk in names) else 0
            d = _dist(k, wk, cap)
            if d <= cap and d < bd and abs(len(w) - len(word)) <= 1:
                best, bd = word, d
        if best is None or len(k) < 4:
            return w
        fixed = (best[:1].upper() + best[1:]) if w[:1].isupper() \
            else best.lower()
        fixes.append((w, fixed))
        return fixed

    out = _WORD.sub(one, text)
    if fixes:
        log.info("Написание: поправила по словарю проекта %s",
                 ", ".join(f"{a}→{b}" for a, b in fixes))
    return out, fixes


# ------------------------------------------------------- правдоподобие строки
def shaky(text: str, seconds: float, rms: float = 0.0):
    """Похоже ли, что движок выдумал строку. -> (bool, причина).

    Числа нарочно грубые и объяснимые вслух. Человек в разговоре выдаёт
    примерно 2-3 слова в секунду; пять слов на полсекунды звука — это не
    быстрая речь, это решётка гипотез, разошедшаяся на шуме. Второй признак —
    звук тише рабочего порога: там движку просто не из чего было брать слова.

    Мы НИЧЕГО не выбрасываем: строка идёт дальше как обычно, просто с
    честной меткой. Молчаливо съеденная фраза дороже лишней пометки."""
    if not text or not CFG.get("stt.shaky_mark", True):
        return False, ""
    n = len(_WORD.findall(text))
    if not n or seconds <= 0:
        return False, ""
    rate = n / float(seconds)
    lim = float(CFG.get("stt.shaky_words_per_s", 4.5))
    if rate > lim and n >= 3:
        return True, f"{n} слов на {seconds:.1f}с — {rate:.1f} слов/с"
    floor = float(CFG.get("stt.shaky_rms", 0.006))
    if rms and rms < floor and n >= 3:
        return True, f"звук был тихий (rms {rms:.4f})"
    return False, ""


# ------------------------------------------------------- растяжка по звуку
# (2026-08-15, владелец: «если я затяну слово — "наприиииимер" — транскриб
# должен уметь это правильно писать, по времени продления, буквально по
# буквам».) Движки нормализуют: тянутое «наприиииимер» приезжает как
# «например», и следа растяжки в тексте нет. А в ЗВУКЕ след есть — плато
# огибающей: долгий почти неизменный кусок там, где тянулась гласная или
# шипящая. Восстанавливаем честно: находим плато, отображаем его центр на
# позицию буквы в слове, размножаем ближайшую ТЯНУЩУЮСЯ букву — по букве
# за каждые ~120мс сверх обычной длины звука.

_STRETCHABLE = set("аеёиоуыэюяржзсшщфвмнлх")


def _plateau(x, sr):
    """Самый долгий ровный кусок: (центр_сек, длительность_сек) или None.
    Ровный = огибающая держится выше 55% пика без провалов дольше 60мс."""
    import numpy as _np
    hop = max(1, int(sr * 0.02))
    env = _np.abs(_np.asarray(x, _np.float32))
    n = len(env) // hop
    if n < 4:
        return None
    # СРЕДНЕЕ, НЕ МАКСИМУМ, и сглаживание (поймано стендом: у шипящих
    # огибающая по максимумам дрожит, плато «тсссс» рассыпалось на куски
    # по 120мс). Средняя энергия шума ровная — её и меряем.
    env = env[:n * hop].reshape(n, hop).mean(1)
    if n >= 3:
        env = _np.convolve(env, _np.ones(3) / 3, mode="same")
    thr = float(env.max()) * 0.45
    best = (0, 0)          # (старт, длина) в кадрах
    i = 0
    while i < n:
        if env[i] >= thr:
            j = i
            gap = 0
            while j < n and gap <= 5:
                gap = gap + 1 if env[j] < thr else 0
                j += 1
            if j - i > best[1]:
                best = (i, j - i)
            i = j
        else:
            i += 1
    if not best[1]:
        return None
    c = (best[0] + best[1] / 2) * hop / sr
    return c, best[1] * hop / sr


def stretch(text: str, pcm16, sr: int, words=None):
    """Вернуть текст с восстановленной растяжкой (или как есть).

    words — пословные времена от whisper [{'w','t0','t1'},...]; без них
    работаем, только если фраза из одного-двух слов: на длинной фразе без
    таймингов честно понять, какое слово тянулось, нельзя."""
    if not text or not CFG.get("stt.stretch", True):
        return text
    try:
        import numpy as _np
        x = _np.asarray(pcm16, _np.float32) / 32768.0
        sec = len(x) / float(sr or 16000)
        per_letter = 0.075          # обычная цена буквы русской речи
        step = float(CFG.get("stt.stretch_step_s", 0.12))
        cap = int(CFG.get("stt.stretch_max", 10))

        def _do(word, w_x):
            w_sec = len(w_x) / float(sr)
            need = per_letter * max(3, len(word)) + 0.15
            if w_sec < need * 1.7:
                return word          # обычная длительность — не трогаем
            pl = _plateau(w_x, sr)
            if not pl:
                return word
            c, dur = pl
            extra = max(0.0, dur - 2 * per_letter)
            k = min(cap, int(extra / step))
            if k < 2:
                return word
            idx = min(len(word) - 1, int(c / w_sec * len(word)))
            # ближайшая тянущаяся буква к центру плато. При равной близости
            # ГЛАСНАЯ главнее согласной: плато почти всегда живёт на
            # гласной, а сосед-согласный («р» рядом с «и») просто попадает
            # под грубость отображения времени в буквы (поймано стендом:
            # «напррррример» вместо «наприиимер»).
            vowels = set("аеёиоуыэюя")
            # гласная в шаге от плато главнее согласной НА самом плато:
            # тянется почти всегда гласная, а согласный сосед попадает под
            # грубость пересчёта времени в буквы. Штраф согласной 1.1 —
            # гласная перевешивает на расстоянии 1, но не дальше (в «тссс»
            # гласных нет вовсе, и там честно тянется «с»).
            order = sorted(range(len(word)),
                           key=lambda i: abs(i - idx)
                           + (0.0 if word[i].lower() in vowels else 1.1))
            for i in order:
                if word[i].lower() in _STRETCHABLE:
                    return word[:i + 1] + word[i].lower() * k + word[i + 1:]
            return word

        ws = [w for w in (words or [])
              if w.get("t0") is not None and w.get("t1") is not None]
        if ws:
            out = []
            for w in ws:
                a = int(float(w["t0"]) * sr)
                b = int(float(w["t1"]) * sr)
                out.append(_do(w["w"], x[max(0, a):min(len(x), b)]))
            return " ".join(out)
        toks = text.split()
        if len(toks) <= 2 and sec > 0.8:
            # без таймингов: одно-два слова — плато ищем по всему куску
            return " ".join(_do(t, x) for t in toks)
        return text
    except Exception:
        return text


# ------------------------------------------- притяжка к предложенной фразе
# (2026-08-15, живой случай: Сайка пишет «Скажи "подключись к моему
# хрому"» — владелец повторяет ровно это, а движок пишет «подключись к
# новому хозяину», и команда не срабатывает.)
#
# ПОЧЕМУ ЭТО ЧИНИТСЯ ТОЧНО, А НЕ ГАДАНИЕМ. Обычная ослышка неисправима:
# мы не знаем, что человек хотел сказать. Но здесь знаем — фразу ПРЕДЛОЖИЛА
# САМА СИСТЕМА минуту назад и сама поставила её в кавычки. Это не догадка
# по созвучию вообще, а проверка одной конкретной гипотезы: «не эту ли
# фразу он повторил?» Окно узкое (минута), кандидат один-два — цена ошибки
# копеечная, а выигрыш большой: команды, которые она сама же и подсказала,
# перестают отваливаться на распознавании.

def snap_to_expected(text: str, expected):
    """-> (текст, что_подтянули) или (текст, ""). expected — список фраз,
    которые система недавно предложила сказать."""
    if not text or not expected or not CFG.get("stt.snap_expected", True):
        return text, ""
    tk = key(re.sub(r"[^А-Яа-яЁёA-Za-z ]", " ", text))
    if len(tk) < 8:
        return text, ""
    lim = float(CFG.get("stt.snap_max_rel", 0.42))
    best, bd = "", 1.0
    for ph in expected:
        pk = key(re.sub(r"[^А-Яа-яЁёA-Za-z ]", " ", str(ph)))
        if not pk or abs(len(pk) - len(tk)) > max(6, len(pk) * 0.4):
            continue
        d = _dist(tk, pk, cap=max(len(pk), len(tk)))
        rel = d / max(1, len(pk))
        if rel < bd:
            best, bd = str(ph), rel
    if best and bd <= lim:
        log.info("Написание: услышанное %r притянуто к тому, что сама же "
                 "предложила: %r (расхождение %.0f%%)",
                 text[:50], best[:50], bd * 100)
        return best, text
    return text, ""
